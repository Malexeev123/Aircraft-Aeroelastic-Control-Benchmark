function digest = get_phase18c_lqr_file_hash(path)
    engine = javaMethod("getInstance", ...
        "java.security.MessageDigest", "SHA-256");
    fileId = fopen(path, "rb");
    assert(fileId >= 0, 'LQRConfig:HashOpen', ...
        'Cannot read the LQR artifact: %s', path);
    cleanup = onCleanup(@() fclose(fileId));
    while ~feof(fileId)
        buffer = fread(fileId, 1024 * 1024, "*uint8");
        if isempty(buffer)
            break
        end
        engine.update(typecast(buffer(:), "int8"));
    end
    bytes = typecast(engine.digest(), "uint8");
    digest = lower(string(reshape(dec2hex(bytes, 2).', 1, [])));
    clear cleanup
end

function selection = configureExactSourceLqrGainBank(configDir, request, baselineDesign, baselinePath, baselineHash, hashFcn, cfg)
%CONFIGUREEXACTSOURCELQRGAINBANK Select a hash-bound V17 or V17A artifact.
selection = struct('design',baselineDesign,'artifactPath',baselinePath, ...
    'artifactSha256',string(baselineHash),'info',struct( ...
    'enable',false,'auditOnly',true,'selectedSourceId',"", ...
    'manifestPath',"",'manifestSha256',"",'modelRevision',"V17", ...
    'registrySha256',string(baselineDesign.registrySha256), ...
    'sourcePackageSha256',""));
if ~isfield(request,'enable') || ~logical(request.enable)
    return
end
assert(isfield(request,'auditOnly') && logical(request.auditOnly), ...
    'LQRConfig:GainBankAuditOnly', ...
    'The source-specific gain bank is available only for an audit request.');
assert(isfield(request,'sourceId') && strlength(string(request.sourceId)) > 0, ...
    'LQRConfig:GainBankSourceId', ...
    'An enabled source-specific gain-bank request requires sourceId.');
assert(isfield(request,'expectedManifestSha256') && ...
    strlength(string(request.expectedManifestSha256)) == 64, ...
    'LQRConfig:GainBankManifestHash', ...
    'An enabled source-specific gain-bank request requires a manifest SHA-256 binding.');
if isfield(request,'manifestPath') && ~isempty(request.manifestPath)
    manifestPath = char(request.manifestPath);
else
    manifestPath = fullfile(configDir, 'control', ...
        'phase18c_v17_longitudinal_lqr_gain_bank_v1.json');
end
assert(isfile(manifestPath), 'LQRConfig:GainBankManifest', ...
    'The source-specific gain-bank manifest is missing: %s', manifestPath);
manifestHash = hashFcn(manifestPath);
assert(manifestHash == string(request.expectedManifestSha256), ...
    'LQRConfig:GainBankManifestHash', ...
    'The source-specific gain-bank manifest SHA-256 does not match.');
manifest = jsondecode(fileread(manifestPath));
assert(isfield(manifest,'registrySha256'), ...
    'LQRConfig:GainBankRegistry', ...
    'The source-specific gain bank has no registry binding.');
registryHash = string(manifest.registrySha256);
v17Hash = "2702cd0dcdae15c13f6bcbc2c59d8b4f899054c63a5df607dcacd0d282ac473f";
v17aHash = "c3dcb391b61caf163bcc6781e239be94992e9ef651a56040c17a2aec86c62c2c";
assert(registryHash==v17Hash || registryHash==v17aHash, ...
    'LQRConfig:GainBankRegistry', ...
    'The source-specific gain bank is not bound to immutable V17 or promoted V17A.');
repositoryRoot = fileparts(fileparts(configDir));
if registryHash == v17Hash
    modelRevision = "V17";
    registryPath = fullfile(repositoryRoot,'context','audits', ...
        'phase18b-kkt-path-closure','static-feedback-source-placement-v1', ...
        'V17_PRODUCTION_SOURCE_REGISTRY_V1.json');
    expectedModelId = "V17_PRODUCTION_LOCKED";
else
    modelRevision = "V17A";
    registryPath = fullfile(repositoryRoot,'context','audits', ...
        'phase18c-control-validation','plant', ...
        'V17A_DIMENSIONAL_STEADY_FORCE_PRODUCTION_SOURCE_REGISTRY_V1.json');
    expectedModelId = "V17A_DIMENSIONAL_STEADY_FORCE_LOCKED";
    assert(isfield(manifest,'modelRevision') && ...
        string(manifest.modelRevision)==modelRevision, ...
        'LQRConfig:GainBankModelRevision', ...
        'The V17A gain-bank manifest has an inconsistent model revision.');
end
assert(isfile(registryPath) && hashFcn(registryPath)==registryHash, ...
    'LQRConfig:GainBankRegistry', ...
    'The bound production registry is missing or has changed.');
assert(isfield(manifest,'selectionPolicy') && ...
    manifest.selectionPolicy.exactSourceOnly && ...
    manifest.selectionPolicy.noExtrapolation && ...
    ~manifest.selectionPolicy.rawGainInterpolationAllowed && ...
    ~manifest.selectionPolicy.absoluteTrimInterpolationAllowed && ...
    ~manifest.selectionPolicy.enabledByDefault, ...
    'LQRConfig:GainBankPolicy', ...
    'The source-specific gain bank does not retain its audit-only policy.');
sourceId = string(request.sourceId);
matches = find(string({manifest.entries.sourceId}) == sourceId);
assert(isscalar(matches), 'LQRConfig:GainBankSource', ...
    'The requested source must occur exactly once in the gain bank: %s', sourceId);
entry = manifest.entries(matches);
assert(startsWith(string(entry.status), "PASS"), ...
    'LQRConfig:GainBankEntryStatus', ...
    'The selected gain-bank entry is not an accepted audit entry: %s', sourceId);
artifactPath = fullfile(repositoryRoot, char(entry.artifactPath));
assert(isfile(artifactPath), 'LQRConfig:GainBankArtifact', ...
    'The selected gain-bank artifact is missing: %s', artifactPath);
artifactHash = hashFcn(artifactPath);
assert(artifactHash == string(entry.artifactSha256), ...
    'LQRConfig:GainBankArtifactHash', ...
    'The selected gain-bank artifact SHA-256 does not match.');
design = jsondecode(fileread(artifactPath));
assert(design.auditOnly && ~design.enabledByDefault && ...
    string(design.registrySha256) == string(manifest.registrySha256) && ...
    string(design.sourceId) == sourceId && ...
    string(design.sourcePackageSha256) == string(entry.sourcePackageSha256) && ...
    string(design.modelId) == expectedModelId, ...
    'LQRConfig:GainBankArtifactBinding', ...
    'The selected gain-bank artifact does not match its manifest entry.');
sourcePackagePath = fullfile(repositoryRoot,char(entry.sourcePackagePath));
assert(isfile(sourcePackagePath) && ...
    hashFcn(sourcePackagePath)==string(entry.sourcePackageSha256), ...
    'LQRConfig:GainBankPackageHash', ...
    'The selected gain-bank source package is missing or has changed.');
if modelRevision=="V17A"
    assert(isfield(entry,'sourceCertificateSha256') && ...
        isfield(design,'sourceCertificatePath') && ...
        isfield(design,'sourceCertificateSha256') && ...
        string(design.sourceCertificateSha256)== ...
            string(entry.sourceCertificateSha256), ...
        'LQRConfig:GainBankCertificateBinding', ...
        'The V17A source certificate binding is incomplete or inconsistent.');
    sourceCertificatePath = fullfile(repositoryRoot, ...
        char(design.sourceCertificatePath));
    assert(isfile(sourceCertificatePath) && ...
        hashFcn(sourceCertificatePath)==string(entry.sourceCertificateSha256), ...
        'LQRConfig:GainBankCertificateHash', ...
        'The selected V17A source certificate is missing or has changed.');
end
assert(abs(cfg.flight.U_inf - design.sourceCoordinate(1)) <= ...
    design.flightCheckTolerance && ...
    abs(cfg.flight.aoa_deg - design.sourceCoordinate(2)) <= ...
    design.flightCheckTolerance, 'LQRConfig:GainBankFlightPoint', ...
    'The active flight coordinate differs from the requested exact-source gain-bank entry.');
selection.design = design;
selection.artifactPath = artifactPath;
selection.artifactSha256 = artifactHash;
selection.info = struct('enable',true,'auditOnly',true, ...
    'selectedSourceId',char(sourceId),'manifestPath',manifestPath, ...
    'manifestSha256',char(manifestHash),'sourcePackageSha256', ...
    char(entry.sourcePackageSha256),'modelRevision',char(modelRevision), ...
    'registrySha256',char(registryHash));
end

function selection = configureStructuredOuterAudit(defaultSelection, request, hashFcn, cfg, trim, gainBankInfo)
%CONFIGURESTRUCTUREDOUTERAUDIT Permit only explicit hash-bound audit opt-in.
selection = defaultSelection;
if ~isfield(request,'enable') || ~logical(request.enable)
    return
end

assert(isfield(request,'expectedArtifactSha256') && ...
    strlength(string(request.expectedArtifactSha256)) == 64, ...
    'LQRConfig:StructuredOuterExpectedHash', ...
    'An enabled structured-outer audit requires a SHA-256 binding.');
if isfield(request,'artifactPath') && ~isempty(request.artifactPath)
    artifactPath = char(request.artifactPath);
else
    artifactPath = defaultSelection.artifactPath;
end
assert(isfile(artifactPath), 'LQRConfig:StructuredOuterArtifact', ...
    'The structured-outer audit artifact is missing: %s', artifactPath);
artifactSha256 = hashFcn(artifactPath);
assert(artifactSha256 == string(request.expectedArtifactSha256), ...
    'LQRConfig:StructuredOuterArtifactHash', ...
    'The structured-outer audit artifact SHA-256 does not match.');
design = jsondecode(fileread(artifactPath));
assert(isfield(design,'registrySha256') && string(design.registrySha256) == ...
    "2702cd0dcdae15c13f6bcbc2c59d8b4f899054c63a5df607dcacd0d282ac473f", ...
    'LQRConfig:StructuredOuterRegistryHash', ...
    'The structured-outer audit artifact is not bound to V17.');
assert(isfield(design,'auditOnly') && logical(design.auditOnly) && ...
    isfield(design,'enabledByDefault') && ~logical(design.enabledByDefault), ...
    'LQRConfig:StructuredOuterScope', ...
    'The structured-outer artifact is not an audit-only disabled-default design.');
if isfield(design, 'sourceId')
    required = {'sourceId','sourcePackageSha256','sourceCoordinate'};
    for field = required
        assert(isfield(request, field{1}), 'LQRConfig:StructuredOuterSourceRequest', ...
            'A source-specific structured-outer audit requires %s.', field{1});
    end
    assert(string(request.sourceId) == string(design.sourceId) && ...
        string(request.sourcePackageSha256) == string(design.sourcePackageSha256), ...
        'LQRConfig:StructuredOuterSourceBinding', ...
        'The structured-outer request does not match the source-bound artifact.');
    coordinate = request.sourceCoordinate(:).';
    assert(isequal(size(coordinate), [1, 2]) && ...
        norm(coordinate - design.sourceCoordinate(:).', inf) <= 1e-12 && ...
        abs(cfg.flight.U_inf - design.sourceCoordinate(1)) <= 1e-12 && ...
        abs(cfg.flight.aoa_deg - design.sourceCoordinate(2)) <= 1e-12, ...
        'LQRConfig:StructuredOuterFlightPoint', ...
        'The active flight coordinate does not match the exact structured-outer source.');
    assert(isfield(gainBankInfo, 'enable') && gainBankInfo.enable && ...
        string(gainBankInfo.selectedSourceId) == string(design.sourceId) && ...
        string(gainBankInfo.sourcePackageSha256) == string(design.sourcePackageSha256), ...
        'LQRConfig:StructuredOuterGainBank', ...
        'A source-specific structured-outer audit requires the same exact-source LQR gain bank.');
    assert(isfield(design, 'sourceFlexibleTrim') && ...
        numel(design.sourceFlexibleTrim) == numel(trim.states) && ...
        norm(design.sourceFlexibleTrim(:) - trim.states(:), inf) <= 1e-12 && ...
        abs(design.sourceElevatorTrimRad - trim.deltaElev) <= 1e-12 && ...
        abs(design.sourceThrustTrimN - trim.thrust) <= 1e-12, ...
        'LQRConfig:StructuredOuterTrim', ...
        'The active trim does not match the exact structured-outer source artifact.');
end
selection = struct('enable',true,'auditOnly',true, ...
    'artifactPath',artifactPath,'artifactSha256',char(artifactSha256), ...
    'expectedArtifactSha256',char(request.expectedArtifactSha256), ...
    'design',design);
end

