function T = getfield_safe_trim_thrust(cfg, trim)
    if exist('trim','var') && isstruct(trim) && isfield(trim,'thrust')
        T = trim.thrust;
    elseif isfield(cfg,'trim') && isfield(cfg.trim,'thrust')
        T = cfg.trim.thrust;
    else
        T = 0;
    end
end

