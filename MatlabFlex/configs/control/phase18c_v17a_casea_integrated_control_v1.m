function [cfg,measurement,profile] = ...
        phase18c_v17a_casea_integrated_control_v1(cfg,source)
%PHASE18C_V17A_CASEA_INTEGRATED_CONTROL_V1 Qualified Case-A control profile.
%   Applies the source-bound offline benchmark configuration that passed the
%   five-second V17A Case-A integration. Global GLA and SQP defaults are not
%   changed. The physical-output contract represents ideal simulated
%   measurements and is not a calibrated flight-sensor specification.

arguments
    cfg struct
    source struct
end

required = ["beam","base","trim","p5","sourceId", ...
    "registryPath","packagePath","certificatePath", ...
    "packageSha256","certificateSha256"];
for field = required
    assert(isfield(source,field), ...
        "AeroFlex:CaseAProfileSource", ...
        "The Case-A profile source is missing %s.",field);
end

expectedRegistryHash = ...
    "c3dcb391b61caf163bcc6781e239be94992e9ef651a56040c17a2aec86c62c2c";
assert(isfile(source.registryPath), ...
    "AeroFlex:CaseAProfileRegistry", ...
    "The V17A production registry is unavailable.");
assert(localFileHash(source.registryPath) == expectedRegistryHash, ...
    "AeroFlex:CaseAProfileRegistry", ...
    "The V17A production registry hash changed.");
assert(isfile(source.packagePath) && ...
    localFileHash(source.packagePath) == string(source.packageSha256), ...
    "AeroFlex:CaseAProfilePackage", ...
    "The V17A Case-A source package hash changed.");
assert(isfile(source.certificatePath) && ...
    localFileHash(source.certificatePath) == ...
        string(source.certificateSha256), ...
    "AeroFlex:CaseAProfileCertificate", ...
    "The V17A Case-A source certificate hash changed.");
assert(string(source.sourceId) == "CASEA_U040_ALPHA_P01", ...
    "AeroFlex:CaseAProfileSource", ...
    "The Case-A profile requires source CASEA_U040_ALPHA_P01.");
assert(isfield(source.p5,"mu") && numel(source.p5.mu) == 2 && ...
    norm(double(source.p5.mu(:).')-[40,1],inf) <= 1e-12, ...
    "AeroFlex:CaseAProfileCoordinate", ...
    "The Case-A profile requires the exact [40 m/s, 1 deg] source.");
assert(isfield(source.trim,"thrust") && isfinite(source.trim.thrust) && ...
    source.trim.thrust >= 0, ...
    "AeroFlex:CaseAProfileThrust", ...
    "The Case-A profile requires finite nonnegative trim thrust.");

bodyCase = "";
if isfield(cfg,"sim") && isfield(cfg.sim,"bodyCase")
    bodyCase = lower(erase(string(cfg.sim.bodyCase),"_"));
elseif isfield(cfg,"sim") && isfield(cfg.sim,"body_case")
    bodyCase = lower(erase(string(cfg.sim.body_case),"_"));
end
assert(bodyCase == "wingonly", ...
    "AeroFlex:CaseAProfileBodyCase", ...
    "The qualified Case-A profile is restricted to clamped wing-only use.");
assert(isfield(cfg.ctrl,"Ts") && abs(cfg.ctrl.Ts-0.01) <= 1e-14, ...
    "AeroFlex:CaseAProfileSampleTime", ...
    "The qualified Case-A control sample is 0.01 s.");
assert(isfield(cfg.sim,"dt") && abs(cfg.sim.dt-0.000625) <= 1e-14, ...
    "AeroFlex:CaseAProfilePlantStep", ...
    "The qualified Case-A plant step is 0.000625 s.");

cfg.ctrl.mheSolver = "custom_sqp";
cfg.ctrl.mheSqp.HessianMode = "gauss_newton";
cfg.ctrl.mheSqp.MaxIterations = 20;
cfg.ctrl.mheSqp.LineSearchStrategy = "safeguarded_hybrid";
cfg.ctrl.mheSqp.UseValueOnlyMeritEvaluation = true;
cfg.ctrl.mpcSolver = "custom_sqp";
cfg.ctrl.sqp.HessianMode = "gauss_newton";
cfg.ctrl.sqp.MaxIterations = 5;
cfg.ctrl.sqp.LineSearchStrategy = "l1_merit";
cfg.ctrl.sqp.LineSearchUpdate = "fixed_beta";
cfg.ctrl.sqp.UseValueOnlyMeritEvaluation = true;
cfg.ctrl.sqp.SecondOrderCorrectionEnabled = false;
packageOutputEnabled = false;
if isfield(cfg.ctrl,"packageOwnedPhysicalOutputs") && ...
        isstruct(cfg.ctrl.packageOwnedPhysicalOutputs) && ...
        isfield(cfg.ctrl.packageOwnedPhysicalOutputs,"enabled")
    packageOutputEnabled = logical( ...
        cfg.ctrl.packageOwnedPhysicalOutputs.enabled);
end
assert(isscalar(packageOutputEnabled), ...
    "AeroFlex:CaseAProfileOutputPolicy", ...
    "The package-owned physical-output switch must be scalar.");
measurementSource = source;
outputPolicy = "legacy_casea_closed_checkpoint";
cfg.ctrl.nmpcWingtipOutput = struct( ...
    "enabled",true,"stageWeight",1e4,"terminalWeight",0, ...
    "ownerPolicy",outputPolicy, ...
    "profile","phase18c_v17a_casea_integrated_control_v1");
if packageOutputEnabled
    candidateOptions = cfg.ctrl.packageOwnedPhysicalOutputs;
    assert(isfield(source,"packageOwnedScheduleStateCoordinate"), ...
        "AeroFlex:CaseAProfileOutputPolicy", ...
        "The candidate output path requires the active package chart.");
    measurementSource.scheduleStateCoordinate = ...
        source.packageOwnedScheduleStateCoordinate;
    outputContract = ...
        AeroFlex.sensor.buildSignedWingtipOutput(measurementSource);
    outputPolicy = outputContract.ownerPolicy;
    cfg.ctrl.nmpcWingtipOutput.ownerPolicy = outputPolicy;
    cfg.ctrl.nmpcWingtipOutput.gradient = ...
        outputContract.symmetricGradient;
    if isfield(cfg.ctrl.packageOwnedPhysicalOutputs, ...
            "candidateMpcMaxIterations")
        candidateIterations = double( ...
            cfg.ctrl.packageOwnedPhysicalOutputs.candidateMpcMaxIterations);
        assert(ismember(candidateIterations,[5,10]), ...
            "AeroFlex:CaseAProfileOutputPolicy", ...
            "The bounded candidate nMPC budget must be 5 or 10 iterations.");
        cfg.ctrl.sqp.MaxIterations = candidateIterations;
    end
    if isfield(cfg.ctrl.packageOwnedPhysicalOutputs, ...
            "candidateLineSearchStrategy")
        candidateStrategy = lower(string( ...
            candidateOptions.candidateLineSearchStrategy));
        assert(isscalar(candidateStrategy) && ismember( ...
            candidateStrategy,["l1_merit","filter", ...
                "safeguarded_hybrid"]), ...
            "AeroFlex:CaseAProfileOutputPolicy", ...
            "Unsupported bounded candidate nMPC line-search strategy.");
        cfg.ctrl.sqp.LineSearchStrategy = candidateStrategy;
        cfg.ctrl.sqp.UseValueOnlyMeritEvaluation = ...
            candidateStrategy ~= "filter";
    end
    if isfield(cfg.ctrl.packageOwnedPhysicalOutputs, ...
            "candidateLineSearchUpdate")
        candidateUpdate = lower(string( ...
            candidateOptions.candidateLineSearchUpdate));
        assert(isscalar(candidateUpdate) && ismember( ...
            candidateUpdate,["fixed_beta","quadratic_safeguarded"]), ...
            "AeroFlex:CaseAProfileOutputPolicy", ...
            "Unsupported bounded candidate nMPC line-search update.");
        cfg.ctrl.sqp.LineSearchUpdate = candidateUpdate;
    end
    if isfield(cfg.ctrl.packageOwnedPhysicalOutputs,"candidateAuditCapture")
        candidateAuditCapture = logical( ...
            cfg.ctrl.packageOwnedPhysicalOutputs.candidateAuditCapture);
        assert(isscalar(candidateAuditCapture), ...
            "AeroFlex:CaseAProfileOutputPolicy", ...
            "The candidate audit-capture switch must be scalar.");
        cfg.ctrl.sqp.AuditCapture = candidateAuditCapture;
    end
    if isfield(candidateOptions,"candidateSecondOrderCorrection")
        candidateSoc = logical( ...
            candidateOptions.candidateSecondOrderCorrection);
        assert(isscalar(candidateSoc), ...
            "AeroFlex:CaseAProfileOutputPolicy", ...
            "The candidate second-order-correction switch must be scalar.");
        cfg.ctrl.sqp.SecondOrderCorrectionEnabled = candidateSoc;
    end
end
cfg.ctrl.caseAEndpointRealization = struct( ...
    "enabled",true,"normalizeEndpointRateEquality",true, ...
    "fallback","preceding_accepted_endpoint");
cfg.caseAcceptance.minimumSolveSuccessRate = 0.975;
cfg.sim.commandsAreTrimIncrements = true;
cfg.fusion.enable = true;
cfg.fusion.omega_c = 2.5;
cfg.fusion.innerIsDeviation = false;
cfg.actuator.enable = true;
cfg.actuator.omega = 40;
cfg.actuator.deltaL = cfg.uL;
cfg.actuator.deltaU = cfg.uU;
cfg.actuator.rateL = cfg.urateL;
cfg.actuator.rateU = cfg.urateU;

[cfg,measurement] = ...
    AeroFlex.sensor.buildLongitudinalPhysicalOutputAudit( ...
        cfg,measurementSource,"imu_attitude_airdata");
measurement.detail.type = ...
    "qualified ideal symmetric-longitudinal benchmark measurement suite";
measurement.detail.benchmarkProfileEligible = true;
measurement.detail.hardwareProductionEligible = false;

profile = struct( ...
    "name","phase18c_v17a_casea_integrated_control_v1", ...
    "modelRevision","V17A", ...
    "sourceId","CASEA_U040_ALPHA_P01", ...
    "sourceCoordinate",[40,1], ...
    "registrySha256",expectedRegistryHash, ...
    "measurementContract","ideal_imu_attitude_airdata", ...
    "physicalOutputOwnerPolicy",outputPolicy, ...
    "nmpcLineSearchStrategy",string(cfg.ctrl.sqp.LineSearchStrategy), ...
    "nmpcLineSearchUpdate",string(cfg.ctrl.sqp.LineSearchUpdate), ...
    "nmpcMaximumIterations",cfg.ctrl.sqp.MaxIterations, ...
    "nmpcSecondOrderCorrectionEnabled", ...
        logical(cfg.ctrl.sqp.SecondOrderCorrectionEnabled), ...
    "closedCheckpointFallback", ...
        "phase18c_v17a_casea_integrated_control_v1", ...
    "minimumSolveSuccessRate",0.975, ...
    "offlineOnly",true, ...
    "hardwareSensorClaim",false);
end

function value = localFileHash(path)
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
fileId = fopen(path,"rb");
assert(fileId >= 0,"AeroFlex:CaseAProfileHash", ...
    "Unable to read %s.",path);
cleanup = onCleanup(@() fclose(fileId));
while ~feof(fileId)
    buffer = fread(fileId,1024*1024,"*uint8");
    if isempty(buffer)
        break
    end
    engine.update(typecast(buffer(:),"int8"));
end
bytes = typecast(engine.digest(),"uint8");
value = lower(string(reshape(dec2hex(bytes,2).',1,[])));
clear cleanup
end
