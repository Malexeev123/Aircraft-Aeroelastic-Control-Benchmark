function profile = localSupportedSpeedProfile(cfg,source)
profile = struct("enabled",false);
if ~isfield(cfg,"benchmark") || ~isstruct(cfg.benchmark) || ...
        ~isfield(cfg.benchmark,"caseB") || ...
        ~isstruct(cfg.benchmark.caseB) || ...
        ~isfield(cfg.benchmark.caseB,"supportedSpeedCorridor")
    return
end
request = cfg.benchmark.caseB.supportedSpeedCorridor;
if ~isstruct(request) || ~isfield(request,"enable") || ...
        ~logical(request.enable)
    return
end
required = ["auditOnly","changeId","manifestPath","manifestSha256", ...
    "initialQuery","initializationSeedId", ...
    "gainCertificatePath","gainCertificateSha256"];
expectedManifestHash = ...
    "824ae574638af47b2a42f128afa63944bfa6b283537fd22c65efbf299a2fd329";
expectedGainHash = ...
    "bed5710aeb31a77b65f61ef16e68ad3b253da3cbefd13d8dfb1228af25268f72";
assert(all(isfield(request,required)) && logical(request.auditOnly) && ...
    string(request.changeId)== ...
        "phase18c-v17a-caseb-supported-speed-corridor-rebase-v1" && ...
    string(request.manifestSha256)==expectedManifestHash && ...
    localFileHash(request.manifestPath)==expectedManifestHash && ...
    string(request.gainCertificateSha256)==expectedGainHash && ...
    localFileHash(request.gainCertificatePath)==expectedGainHash && ...
    string(request.initializationSeedId)=="STATICFB_CASEB_AB_MID", ...
    "AeroFlex:CaseBV2ProfileRequest", ...
    "The supported-speed Case-B request is incomplete or changed.");
manifest = jsondecode(fileread(request.manifestPath));
initialQuery = double(request.initialQuery(:).');
assert(logical(manifest.userApproval) && ...
    string(manifest.status)=="APPROVED_AUDIT_ONLY" && ...
    norm(initialQuery-double( ...
        manifest.caseB.initialScheduledQuery(:).'),inf)<=1e-12 && ...
    string(source.manifestSha256)==expectedManifestHash && ...
    string(source.initializationSeedId)=="STATICFB_CASEB_AB_MID", ...
    "AeroFlex:CaseBV2ProfileManifest", ...
    "The V2 profile source does not match its approved manifest.");
profile = struct("enabled",true,"initialQuery",initialQuery, ...
    "manifestPath",string(request.manifestPath), ...
    "manifestSha256",expectedManifestHash, ...
    "gainCertificatePath",string(request.gainCertificatePath), ...
    "gainCertificateSha256",expectedGainHash, ...
    "definition",struct( ...
        "initialSpeed",double(manifest.caseB.speedReference. ...
            initialMetersPerSecond), ...
        "targetSpeed",double(manifest.caseB.speedReference. ...
            targetMetersPerSecond), ...
        "onset",double(manifest.caseB.speedReference.onsetSeconds), ...
        "duration",double(manifest.caseB.speedReference.durationSeconds), ...
        "alphaOffsetDegrees",25));
end

function reference = localSupportedSpeedReference(t,~,definition)
phase = min(max((double(t)-definition.onset)/definition.duration,0),1);
speedRange = definition.targetSpeed-definition.initialSpeed;
speed = definition.initialSpeed+0.5*speedRange*(1-cos(pi*phase));
speedRate = 0.5*speedRange*pi/definition.duration*sin(pi*phase);
alphaDegrees = definition.alphaOffsetDegrees-speed;
alpha = deg2rad(alphaDegrees);
assert(speed>=definition.initialSpeed-1e-10 && ...
    speed<=definition.targetSpeed+1e-10, ...
    "AeroFlex:CaseBV2ScheduleDomain", ...
    "The V2 reference schedule left its locked source corridor.");
reference = struct( ...
    "v_B_ref",[speed*cos(alpha);0;speed*sin(alpha)], ...
    "speedReferenceRateMps2",speedRate, ...
    "euler_ref",[0;alpha;0],"omega_B_ref",zeros(3,1), ...
    "scheduleUInfMps",speed, ...
    "scheduleAlphaDeg",alphaDegrees);
end

function reference = localCaseBReference(t,rb)
startSeconds = 1;
durationSeconds = 20;
phase = min(max((double(t)-startSeconds)/durationSeconds,0),1);
speed = 15+2.5*(1-cos(pi*phase));
speedRate = (2.5*pi/durationSeconds)*sin(pi*phase);
alphaDegrees = 25-speed;
alpha = deg2rad(alphaDegrees);
assert(isstruct(rb) && isfield(rb,"v_B") && ...
    isnumeric(rb.v_B) && isreal(rb.v_B) && numel(rb.v_B) == 3 && ...
    all(isfinite(rb.v_B(:))), ...
    "AeroFlex:CaseBScheduleMeasuredSpeed", ...
    "The Case-B scheduler requires a finite measured rigid-body velocity.");
scheduleSpeed = norm(double(rb.v_B(:)));
assert(isfinite(scheduleSpeed) && scheduleSpeed > 0, ...
    "AeroFlex:CaseBScheduleMeasuredSpeed", ...
    "The Case-B measured scheduling speed must be positive and finite.");
scheduleAlphaDegrees = 25-scheduleSpeed;
reference = struct( ...
    "v_B_ref",[speed*cos(alpha);0;speed*sin(alpha)], ...
    "speedReferenceRateMps2",speedRate, ...
    "euler_ref",[0;alpha;0], ...
    "omega_B_ref",zeros(3,1), ...
    "scheduleUInfMps",scheduleSpeed, ...
    "scheduleAlphaDeg",scheduleAlphaDegrees);
end

function value = localFileHash(path)
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
fileId = fopen(path,"rb");
assert(fileId >= 0,"AeroFlex:CaseBProfileHash","Unable to read %s.",path);
cleanup = onCleanup(@() fclose(fileId));
while ~feof(fileId)
    buffer = fread(fileId,1024*1024,"*uint8");
    if isempty(buffer), break, end
    engine.update(typecast(buffer(:),"int8"));
end
bytes = typecast(engine.digest(),"uint8");
value = lower(string(reshape(dec2hex(bytes,2).',1,[])));
clear cleanup
end
