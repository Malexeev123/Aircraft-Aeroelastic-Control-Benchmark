function [result,plan] = runPazyModelWorkflow(options)
%RUNPAZYMODELWORKFLOW Prepare or execute the general Pazy model workflow.
%   This entry point retains the established sim_init/sim_run path for
%   wing-only and coupled-full development cases. It is separate from the
%   formally qualified A/B benchmark facade.
%
%   Use Execute=false to inspect the setup request without reading SHARPy
%   products, constructing the model, or creating output files.

arguments
    options.BodyCase (1,1) string ...
        {mustBeMember(options.BodyCase,["wingOnly","coupledFull"])} = ...
        "wingOnly"
    options.SimulationMode (1,1) string ...
        {mustBeMember(options.SimulationMode,["openloop","nmhe_nmpc"])} = ...
        "openloop"
    options.GustEnabled (1,1) logical = true
    options.Execute (1,1) logical = false
    options.PrepareSetup (1,1) logical = true
    options.SetupDirectory (1,1) string = ""
    options.SharpyRoot (1,1) string = ""
    options.CaseName (1,1) string = "pazy_krylov_ROM"
    options.DurationSeconds (1,1) double = nan
    options.TargetSpeedMps (1,1) double = nan
    options.TargetAngleOfAttackDeg (1,1) double = nan
    options.LibraryMode (1,1) string {mustBeMember(options.LibraryMode, ...
        ["auto","supplied_source","production"])} = "auto"
    options.InitializationMode (1,1) string {mustBeMember( ...
        options.InitializationMode,["auto","recompute_trim", ...
        "qualified_source_trim"])} = "auto"
    options.RunId (1,1) string = "auto"
    options.Debug (1,1) logical = false
    options.FiguresVisible (1,1) logical = false
end

repositoryRoot = string(fileparts(fileparts(mfilename("fullpath"))));
assert(isnan(options.DurationSeconds) || ...
    (isfinite(options.DurationSeconds) && options.DurationSeconds>0), ...
    "AeroFlex:ModelWorkflowDuration", ...
    "DurationSeconds must be positive and finite when specified.");
explicitOperatingPoint = ~isnan(options.TargetSpeedMps) || ...
    ~isnan(options.TargetAngleOfAttackDeg);
assert(~explicitOperatingPoint || ...
    (isfinite(options.TargetSpeedMps) && options.TargetSpeedMps>0 && ...
    isfinite(options.TargetAngleOfAttackDeg)), ...
    "AeroFlex:ModelWorkflowOperatingPoint", ...
    "Specify both TargetSpeedMps and TargetAngleOfAttackDeg, or leave " + ...
    "both unset to use the resolved library default.");
libraryMode = localLibraryMode(options.LibraryMode,options.BodyCase, ...
    explicitOperatingPoint);
initializationMode = localInitializationMode( ...
    options.InitializationMode,libraryMode);
[planSpeedMps,planAlphaDeg] = localPlanOperatingPoint( ...
    options.TargetSpeedMps,options.TargetAngleOfAttackDeg, ...
    options.BodyCase,libraryMode);
sharpyRoot = options.SharpyRoot;
if strlength(sharpyRoot)==0
    sharpyRoot = fullfile(repositoryRoot,"TestBenchPazy");
end
runId = options.RunId;
if runId=="auto"
    runId = lower(options.BodyCase)+"_"+options.SimulationMode+"_" + ...
        string(datetime("now","TimeZone","UTC", ...
        "Format","yyyyMMdd'T'HHmmss'Z'"));
end

plan = struct( ...
    "schemaVersion","pazy-general-model-workflow-v1", ...
    "bodyCase",options.BodyCase, ...
    "simulationMode",options.SimulationMode, ...
    "gustEnabled",options.GustEnabled, ...
    "caseName",options.CaseName, ...
    "durationSeconds",options.DurationSeconds, ...
    "targetSpeedMps",planSpeedMps, ...
    "targetAngleOfAttackDeg",planAlphaDeg, ...
    "operatingPointPolicy",localOperatingPointPolicy( ...
        explicitOperatingPoint,libraryMode), ...
    "libraryMode",libraryMode, ...
    "initializationMode",initializationMode, ...
    "sharpyRoot",sharpyRoot, ...
    "prepareSetup",options.PrepareSetup, ...
    "setupDirectory",options.SetupDirectory, ...
    "runId",runId, ...
    "rateProjectionEnabled",options.BodyCase=="coupledFull", ...
    "figuresVisible",options.FiguresVisible, ...
    "formalBenchmarkCase",false, ...
    "executed",false);
result = struct("status","PLAN_ONLY","success",false, ...
    "setup",struct(),"history",struct(),"plan",plan);
if ~options.Execute
    return
end

% Setup generation and simulation are deliberately separate. A prepared
% setup can be reused without charging model construction to online timing.
workflowTimer = tic;
setupProject(ValidateEntryPoints=true);
modelAssets = AeroFlex.benchmark.verifyGeneralModelAssets(repositoryRoot);
assert(modelAssets.passed,"AeroFlex:ModelWorkflowAssets", ...
    "The shared model-data payload is missing or changed. Run " + ...
    "verifyBenchmarkInstallation for the exact file and hash status.");
[targetSpeedMps,targetAngleOfAttackDeg] = localOperatingPoint( ...
    repositoryRoot,planSpeedMps,planAlphaDeg);
plan.targetSpeedMps = targetSpeedMps;
plan.targetAngleOfAttackDeg = targetAngleOfAttackDeg;
setupDirectory = options.SetupDirectory;
setup = struct();
setupTimer = tic;
if options.PrepareSetup
    if libraryMode=="production"
        assert(initializationMode=="qualified_source_trim", ...
            "AeroFlex:ModelWorkflowProductionInitialization", ...
            "Production-library execution requires the qualified source " + ...
            "trim. Use the explicit rebuild workflow to recompute trims.");
        setup = AeroFlex.benchmark.prepareProductionModelSetup( ...
            RepositoryRoot=repositoryRoot,SharpyRoot=sharpyRoot, ...
            CaseName=options.CaseName,BodyCase=options.BodyCase, ...
            SimulationMode=options.SimulationMode, ...
            GustEnabled=options.GustEnabled, ...
            DurationSeconds=options.DurationSeconds, ...
            OperatingPoint=[targetSpeedMps,targetAngleOfAttackDeg], ...
            RunId=runId);
        setupPassed = true;
    else
        assert(initializationMode=="recompute_trim", ...
            "AeroFlex:ModelWorkflowSourceInitialization", ...
            "The supplied SHARPy source workflow currently owns explicit " + ...
            "trim reconstruction.");
        [setup,setupPassed] = sim_init(sharpyRoot, ...
            'case_name',options.CaseName, ...
            'body_case',options.BodyCase, ...
            'sim_case',options.SimulationMode, ...
            'runner','PlantROM', ...
            'gustOn',options.GustEnabled, ...
            'durationSeconds',options.DurationSeconds, ...
            'targetUInf',targetSpeedMps, ...
            'targetAoADeg',targetAngleOfAttackDeg, ...
            'debug',options.Debug, ...
            'overwrite',false, ...
            'date_only_runs',false, ...
            'run_id',runId);
    end
    assert(setupPassed,"AeroFlex:ModelWorkflowSetup", ...
        "The requested model setup did not complete successfully.");
    setupDirectory = string(setup.paths.run_dir);
else
    assert(strlength(setupDirectory)>0 && isfolder(setupDirectory), ...
        "AeroFlex:ModelWorkflowSetupDirectory", ...
        "Provide an existing SetupDirectory when PrepareSetup=false.");
end
preparationSeconds = toc(setupTimer);

oldVisibility = get(groot,"DefaultFigureVisible");
initialFigures = findall(groot,"Type","figure");
set(groot,"DefaultFigureVisible",localVisibility(options.FiguresVisible));
figureCleanup = onCleanup(@()localRestoreFigures( ...
    oldVisibility,initialFigures));
simulationTimer = tic;
[simulationPassed,history] = sim_run(options.CaseName,options.BodyCase, ...
    'setup_dir',setupDirectory, ...
    'date_only_runs',false, ...
    'overwrite',false);
simulationAndPostSeconds = toc(simulationTimer);
assert(simulationPassed,"AeroFlex:ModelWorkflowSimulation", ...
    "The requested model workflow did not complete successfully.");

plan.setupDirectory = setupDirectory;
plan.executed = true;
outputs = localWorkflowOutputs(history);
timing = localWorkflowTiming(history,preparationSeconds, ...
    simulationAndPostSeconds,toc(workflowTimer));
metrics = localWorkflowMetrics(outputs);
physicalGate = localPhysicalStartupGate(history,plan);
assert(physicalGate.passed,"AeroFlex:ModelWorkflowPhysicalGate", ...
    "The shared workflow completed mechanically but failed its physical " + ...
    "startup gate: %s",physicalGate.reason);
result = struct("status","PASS_COMPLETED_MODEL_WORKFLOW", ...
    "success",true,"setup",setup,"history",history,"plan",plan, ...
    "timing",timing,"metrics",metrics,"outputs",outputs, ...
    "physicalGate",physicalGate,"modelAssets",modelAssets);

% Keep the compact run summary beside the established sim_run products.
% The full state history is already owned by the serialized run bundle.
workflowSummary = rmfield(result,["setup","history"]);
summaryPath = fullfile(outputs.runRoot,"model_workflow_summary.mat");
save(summaryPath,"workflowSummary","-v7");
result.outputs.summaryMat = string(summaryPath);
clear figureCleanup
end

function mode = localLibraryMode(requested,bodyCase,explicitPoint)
mode = requested;
if mode~="auto"
    return
end
if bodyCase=="coupledFull" || explicitPoint
    mode = "production";
else
    mode = "supplied_source";
end
end

function mode = localInitializationMode(requested,libraryMode)
mode = requested;
if mode~="auto"
    return
end
if libraryMode=="production"
    mode = "qualified_source_trim";
else
    mode = "recompute_trim";
end
end

function [speedMps,alphaDeg] = localPlanOperatingPoint( ...
        speedMps,alphaDeg,bodyCase,libraryMode)
if ~isnan(speedMps) || libraryMode~="production"
    return
end
if bodyCase=="coupledFull"
    speedMps = 15;
    alphaDeg = 10;
else
    speedMps = 40;
    alphaDeg = 1;
end
end

function policy = localOperatingPointPolicy(isExplicit,libraryMode)
if isExplicit
    policy = "explicit";
elseif libraryMode=="production"
    policy = "production_default";
else
    policy = "supplied_source";
end
end

function [speedMps,alphaDeg] = localOperatingPoint( ...
        repositoryRoot,speedMps,alphaDeg)
%LOCALOPERATINGPOINT Use the supplied source metadata unless overridden.

if ~isnan(speedMps)
    return
end
metadataPath = fullfile(repositoryRoot,"TestBenchPazy","output", ...
    "pazy_krylov_ROM","linear_results","simulation_parameters.mat");
metadata = load(metadataPath,"u_inf","aoa_deg");
assert(isfield(metadata,"u_inf") && isscalar(metadata.u_inf) && ...
    isfinite(metadata.u_inf) && metadata.u_inf>0 && ...
    isfield(metadata,"aoa_deg") && isscalar(metadata.aoa_deg) && ...
    isfinite(metadata.aoa_deg), ...
    "AeroFlex:ModelWorkflowSourceOperatingPoint", ...
    "The supplied source operating-point metadata is incomplete.");
speedMps = double(metadata.u_inf);
alphaDeg = double(metadata.aoa_deg);
end

function value = localVisibility(isVisible)
if isVisible
    value = "on";
else
    value = "off";
end
end

function localRestoreFigures(oldVisibility,initialFigures)
currentFigures = findall(groot,"Type","figure");
newFigures = setdiff(currentFigures,initialFigures);
if ~isempty(newFigures)
    delete(newFigures);
end
set(groot,"DefaultFigureVisible",oldVisibility);
end

function outputs = localWorkflowOutputs(history)
if isfield(history,"paths") && isfield(history.paths,"run_dir")
    paths = history.paths;
elseif isfield(history,"cfg") && isfield(history.cfg,"paths") && ...
        isfield(history.cfg.paths,"run_dir")
    paths = history.cfg.paths;
else
    paths = struct();
end
assert(isfield(paths,"run_dir"), ...
    "AeroFlex:ModelWorkflowOutputRoot", ...
    "The completed run did not report its output directory.");
runRoot = string(paths.run_dir);
plotsRoot = localPathField(paths,"plots",fullfile(runRoot,"plots"));
postMat = localPathField(paths,"for_matlab", ...
    fullfile(runRoot,"for_matlab"));
postMat = fullfile(postMat,"post_out.mat");
plotFiles = strings(0,1);
if isfolder(plotsRoot)
    listing = [dir(fullfile(plotsRoot,"*.png")); ...
        dir(fullfile(plotsRoot,"*.pdf"))];
    plotFiles = string(fullfile({listing.folder},{listing.name})).';
end
outputs = struct("runRoot",runRoot,"plotsRoot",string(plotsRoot), ...
    "postProcessMat",string(postMat),"plotFiles",plotFiles, ...
    "summaryMat","");
end

function timing = localWorkflowTiming(history,preparationSeconds, ...
        simulationAndPostSeconds,totalEntrySeconds)
simulatedSeconds = nan;
if isfield(history,"t") && ~isempty(history.t)
    simulatedSeconds = max(history.t)-min(history.t);
end
timing = struct( ...
    "preparationSeconds",preparationSeconds, ...
    "simulationAndPostProcessingSeconds",simulationAndPostSeconds, ...
    "totalEntrySeconds",totalEntrySeconds, ...
    "simulatedSeconds",simulatedSeconds, ...
    "conservativeRealTimeFactor", ...
        simulatedSeconds/max(simulationAndPostSeconds,eps), ...
    "onlineComponentTiming",localComponentTiming(history));
end

function distributions = localComponentTiming(history)
distributions = struct();
if ~isfield(history,"log") || ~isfield(history.log,"diag")
    return
end
diagnostics = history.log.diag;
fields = ["scheduleTime","senseTime","mheTime","mpcTime", ...
    "allocationTime","fusionTime","actuatorTime","plantTime"];
labels = ["scheduling","sensing","nMhe","nMpc", ...
    "allocation","fusion","actuator","plant"];
for index = 1:numel(fields)
    if ~isfield(diagnostics,fields(index))
        continue
    end
    values = diagnostics.(fields(index));
    values = values(isfinite(values) & values>=0);
    if isempty(values)
        continue
    end
    distributions.(labels(index)) = struct( ...
        "meanSeconds",mean(values), ...
        "p95Seconds",prctile(values,95), ...
        "maximumSeconds",max(values), ...
        "sampleCount",numel(values));
end
end

function metrics = localWorkflowMetrics(outputs)
metrics = struct();
if ~isfile(outputs.postProcessMat)
    return
end
saved = load(outputs.postProcessMat,"out");
if isfield(saved,"out") && isfield(saved.out,"metrics")
    metrics = saved.out.metrics;
end
end

function gate = localPhysicalStartupGate(history,plan)
% Fail closed when a certified source trim is serialized in the wrong chart.
gate = struct("applicable",false,"passed",true,"reason","not_applicable", ...
    "flexibleFirstStepInfinity",nan,"rigidFirstStepInfinity",nan, ...
    "minimumThrustNewtons",nan);
if plan.bodyCase~="coupledFull" || plan.simulationMode~="openloop" || ...
        plan.libraryMode~="production" || plan.gustEnabled
    return
end

gate.applicable = true;
gate.reason = "pass";
assert(isfield(history,"x") && size(history.x,2)>=2, ...
    "AeroFlex:ModelWorkflowPhysicalHistory", ...
    "The coupled startup gate requires two flexible-state samples.");
gate.flexibleFirstStepInfinity = norm( ...
    history.x(:,2)-history.x(:,1),inf);

if isfield(history,"log") && isfield(history.log,"rb") && ...
        isfield(history.log.rb,"state") && ...
        size(history.log.rb.state,2)>=2
    gate.rigidFirstStepInfinity = norm( ...
        history.log.rb.state(4:12,2)-history.log.rb.state(4:12,1),inf);
end
if isfield(history,"trim") && isfield(history.trim,"thrust")
    gate.minimumThrustNewtons = double(history.trim.thrust);
end

finiteGate = isfinite(gate.flexibleFirstStepInfinity) && ...
    isfinite(gate.rigidFirstStepInfinity) && ...
    isfinite(gate.minimumThrustNewtons);
gate.passed = finiteGate && gate.flexibleFirstStepInfinity<=1e-4 && ...
    gate.rigidFirstStepInfinity<=1e-4 && ...
    gate.minimumThrustNewtons>=0;
if ~gate.passed
    gate.reason = sprintf([ ...
        "flexible first-step %.6g, rigid first-step %.6g, thrust %.6g N"], ...
        gate.flexibleFirstStepInfinity,gate.rigidFirstStepInfinity, ...
        gate.minimumThrustNewtons);
end
end

function value = localPathField(paths,name,fallback)
if isfield(paths,name) && ~isempty(paths.(name))
    value = string(paths.(name));
else
    value = string(fallback);
end
end
