function status = verifyBenchmarkInstallation(options)
%VERIFYBENCHMARKINSTALLATION Check the benchmark runtime and toolchain.
%   STATUS = VERIFYBENCHMARKINSTALLATION() verifies MATLAB path authority,
%   the Beam/Aero/Core/Base integration chain, control components, the locked
%   source registry, and compatible native caches. It does not run a model.

arguments
    options.RequireNativeKernels (1,1) logical = false
    options.PrintSummary (1,1) logical = true
    options.ProjectInfo (1,1) struct = struct()
end

if isempty(fieldnames(options.ProjectInfo))
    project = setupProject(ValidateEntryPoints=true);
else
    project = options.ProjectInfo;
end
root = string(project.repositoryRoot);
entryPoints = [ ...
    "AeroFlex.beam.BeamModel"
    "AeroFlex.aero.AeroROM"
    "AeroFlex.core.build_xi_coupling"
    "AeroFlex.core.assemble_L_matrix"
    "AeroFlex.sim.ROMIntegrator"
    "AeroFlex.sim.PlantRunTime"
    "AeroFlex.sim.SimRunner"
    "AeroFlex.sched.evalLibrary"
    "AeroFlex.ctrl.nMHEv2"
    "AeroFlex.ctrl.nMPC"
    "AeroFlex.ctrl.OuterLQR"
    "AeroFlex.ctrl.ComplementaryCommandFusion"
    "AeroFlex.ctrl.ActuatorChain"
    "RigidBody.methods.CoupledTrim.TrimRBwFlex"
    "sim_init"
    "sim_run"
    "runPazyModelWorkflow"
    "runBenchmarkCase"
    "AeroFlex.benchmark.runtime." + ...
        "run_phase18c_v17a_formal_casea_freeflight_attitude_hold_v1"
    "AeroFlex.benchmark.runtime." + ...
        "run_phase18c_v17a_caseb_integrated_profile_v1"
    "AeroFlex.benchmark.runtime.casea." + ...
        "run_phase18c_v17a_reciprocal_formal_casea_member_v1"
    "AeroFlex.benchmark.customCaseDefinition"
    "runCustomBenchmarkCase"
    "AeroFlex.sched.buildLibraryFromSetups"];
resolved = strings(size(entryPoints));
unique = false(size(entryPoints));
for index = 1:numel(entryPoints)
    matches = string(which(entryPoints(index),"-all"));
    matches(matches=="") = [];
    if ~isempty(matches)
        resolved(index) = matches(1);
    end
    unique(index) = isscalar(matches) && ...
        startsWith(localNormalize(resolved(index)),localNormalize(root));
end

registryPath = fullfile(root,"context","audits", ...
    "phase18b-kkt-path-closure","static-feedback-source-placement-v1", ...
    "V17_PRODUCTION_SOURCE_REGISTRY_V1.json");
expectedRegistryHash = ...
    "2702cd0dcdae15c13f6bcbc2c59d8b4f899054c63a5df607dcacd0d282ac473f";
registryHash = "";
if isfile(registryPath)
    registryHash = localFileHash(registryPath);
end
registryPassed = registryHash==expectedRegistryHash;
native = buildBenchmarkTools(Action="check",ProjectInfo=project);
generalModelAssets = AeroFlex.benchmark.verifyGeneralModelAssets(root);
releaseRuntimeAssets = prepareBenchmarkReleaseAssets(Action="check", ...
    ProjectInfo=project,PrintSummary=false);
products = struct( ...
    "controlSystemToolbox",~isempty(ver("control")), ...
    "optimizationToolbox",~isempty(ver("optim")), ...
    "matlabCoder",~isempty(which("coder.config")), ...
    "hdf5Interface",~isempty(which("h5read")) && ...
        ~isempty(which("h5write")));
qualifiedPlatform = ismember(string(version("-release")), ...
    ["2023b","2024a","2024b","2025a","2025b"]) && ...
    string(computer("arch"))=="win64";
runtimeDependenciesPassed = qualifiedPlatform && ...
    products.controlSystemToolbox && products.optimizationToolbox && ...
    products.hdf5Interface;

status = struct( ...
    "schemaVersion","pazy-installation-verification-v1", ...
    "generatedUtc",string(datetime("now","TimeZone","UTC", ...
        "Format","yyyy-MM-dd'T'HH:mm:ss.SSS'Z'")), ...
    "passed",all(unique) && registryPassed && generalModelAssets.passed && ...
        releaseRuntimeAssets.passed && ...
        runtimeDependenciesPassed && ...
        (~options.RequireNativeKernels || native.passed), ...
    "matlabRelease",project.matlabRelease, ...
    "matlabVersion",project.matlabVersion, ...
    "architecture",string(computer("arch")), ...
    "repositoryRoot",root, ...
    "dependencies",struct("qualifiedPlatform",qualifiedPlatform, ...
        "runtimePassed",runtimeDependenciesPassed, ...
        "products",products, ...
        "cppCompilerSelected",logical( ...
            native.environment.cppCompilerSelected), ...
        "sharpyXbeam", ...
            "external WSL generation dependency; immutable and not executed"), ...
    "entryPoints",table(entryPoints,resolved,unique), ...
    "generalWorkflows",struct( ...
        "modelAssets",generalModelAssets, ...
        "sourceLibraryAssembly",unique(24), ...
        "wingOnlyOpenLoop",all(unique([15,16,17])) && ...
            generalModelAssets.passed, ...
        "wingOnlyClosedLoop",all(unique([15,16,17])) && ...
            generalModelAssets.passed, ...
        "coupledOpenLoopNoGust",all(unique([15,16,17])) && ...
            generalModelAssets.passed), ...
    "releaseRuntimeAssets",releaseRuntimeAssets, ...
    "customCaseInterface",struct( ...
        "definition",unique(22),"plan",unique(23), ...
        "passed",all(unique(22:23))), ...
    "productionCaseRunners",struct( ...
        "formalCaseA",all(unique([19,21])), ...
        "scheduledCaseB",unique(20), ...
        "passed",all(unique(19:21))), ...
    "registry",struct("path",registryPath,"expectedSha256", ...
        expectedRegistryHash,"actualSha256",registryHash, ...
        "passed",registryPassed), ...
    "nativeTools",native, ...
    "nativeRequired",options.RequireNativeKernels);

if options.PrintSummary
    fprintf("\nPazy benchmark installation verification\n");
    fprintf("  MATLAB release       : %s\n",status.matlabRelease);
    fprintf("  Runtime dependencies : %s\n", ...
        localPassFail(runtimeDependenciesPassed));
    fprintf("  MATLAB Coder         : %s (native build)\n", ...
        localPassFail(products.matlabCoder));
    fprintf("  C++ compiler         : %s (native build)\n", ...
        localPassFail(native.environment.cppCompilerSelected));
    fprintf("  Beam/Aero/Core/Base  : %s\n",localPassFail(all(unique(1:4))));
    fprintf("  Plant and scheduling : %s\n",localPassFail(all(unique(5:8))));
    fprintf("  Control chain        : %s\n",localPassFail(all(unique(9:13))));
    fprintf("  Coupled trim         : %s\n",localPassFail(unique(14)));
    fprintf("  Shared model data    : %s (%d files)\n", ...
        localPassFail(generalModelAssets.passed), ...
        generalModelAssets.assetCount);
    fprintf("  Dynamic runtime data : %s (%d files)\n", ...
        localPassFail(releaseRuntimeAssets.passed), ...
        releaseRuntimeAssets.assetCount);
    fprintf("  General workflows    : %s\n",localPassFail( ...
        all(unique(15:17)) && generalModelAssets.passed));
    fprintf("  Library regeneration : %s\n",localPassFail(unique(24)));
    fprintf("  Benchmark facade     : %s\n",localPassFail(unique(18)));
    fprintf("  Production runners   : %s\n",localPassFail(all(unique(19:21))));
    fprintf("  Custom-case planning : %s\n",localPassFail(all(unique(22:23))));
    fprintf("  Production registry  : %s\n",localPassFail(registryPassed));
    fprintf("  Native kernels       : %s%s\n",localPassFail(native.passed), ...
        localRecommendedSuffix(options.RequireNativeKernels));
    fprintf("  Overall              : %s\n\n",localPassFail(status.passed));
end
end

function value = localNormalize(path)
value = lower(replace(string(path),"\","/"));
end

function value = localFileHash(path)
file = fopen(path,"rb");
assert(file>=0,"AeroFlex:InstallationHashRead", ...
    "Cannot read %s for hashing.",path);
cleanup = onCleanup(@()fclose(file));
engine = java.security.MessageDigest.getInstance("SHA-256");
while ~feof(file)
    bytes = fread(file,1024*1024,"*uint8");
    if isempty(bytes), break, end
    engine.update(bytes);
end
value = lower(string(sprintf("%02x",typecast( ...
    engine.digest(),"uint8"))));
clear cleanup
end

function value = localPassFail(flag)
if flag, value = "PASS"; else, value = "NOT READY"; end
end

function value = localRecommendedSuffix(required)
if required, value = " (required)"; else, value = " (recommended)"; end
end
