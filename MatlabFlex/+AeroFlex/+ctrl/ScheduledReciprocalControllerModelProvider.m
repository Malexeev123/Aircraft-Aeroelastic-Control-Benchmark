classdef ScheduledReciprocalControllerModelProvider < handle
%SCHEDULEDRECIPROCALCONTROLLERMODELPROVIDER Source-local reciprocal bank.
%   The public state remains the native Artola state followed by deterministic
%   source-local memories. Scheduler weights blend corrections only after
%   every member is represented in the active native and physical-output
%   coordinates. No latent state or latent matrix is interpolated.

    properties (SetAccess = private)
        model
        members struct
        idx struct
        nativeStateCount (1,1) double
        hiddenStateCount (1,1) double
        stateCount (1,1) double
        queryTrim struct
        hiddenOffsets double
        aggregateRuntimeRequested (1,1) logical = false
        aggregateRuntimeActive (1,1) logical = false
        aggregateCandidate struct = struct()
        aggregateWeights double = []
        aggregatePacketSignature string = ""
        aggregateVerified (1,1) logical = false
        aggregateStateTolerance (1,1) double = 2e-11
        aggregateJacobianTolerance (1,1) double = 2e-8
        aggregateWrenchTolerance (1,1) double = 2e-9
        aggregateRuntimeFromNative double = []
        aggregateRuntimeFromRigid double = []
        aggregateCorrectionToNative double = []
        aggregateCallCount (1,1) double = 0
        aggregateParityCount (1,1) double = 0
        aggregateFallbackCount (1,1) double = 0
        aggregateDiagnosticFallbackCount (1,1) double = 0
        aggregateLastFallback string = ""
        scheduledCompiledRequested (1,1) logical = false
        scheduledCompiledActive (1,1) logical = false
        scheduledCompiledVerified (1,1) logical = false
        scheduledCompiledKernel function_handle = function_handle.empty
        scheduledCompiledPacket struct = struct()
        scheduledCompiledPacketSignature string = ""
        scheduledCompiledCallCount (1,1) double = 0
        scheduledCompiledFallbackCount (1,1) double = 0
        scheduledCompiledLastFallback string = ""
        scheduledCompiledIdentity string = "disabled"
        scheduledSensitivityStencilRequested (1,1) logical = false
        scheduledSensitivitySourceMask logical = true(14,1)
        validatedPacketCacheRequested (1,1) logical = false
        validatedPacketCacheActive (1,1) logical = false
        validatedPacketCacheChangeId string = ""
        validatedPacketCacheProfile string = ""
        validatedPacketCacheMaxEntries (1,1) double = 0
        validatedPacketCacheEntries struct = struct( ...
            'key',{},'members',{},'queryTrim',{}, ...
            'aggregateCandidate',{},'aggregateWeights',{}, ...
            'aggregatePacketSignature',{},'aggregateRuntimeActive',{}, ...
            'aggregateRuntimeFromNative',{},'aggregateRuntimeFromRigid',{}, ...
            'aggregateCorrectionToNative',{},'aggregateVerified',{}, ...
            'scheduledCompiledPacket',{}, ...
            'scheduledCompiledPacketSignature',{}, ...
            'scheduledCompiledActive',{},'scheduledCompiledVerified',{}, ...
            'lastUse',{})
        validatedPacketCacheCurrentKey struct = struct()
        validatedPacketCacheClock (1,1) double = 0
        validatedPacketCacheHitCount (1,1) double = 0
        validatedPacketCacheMissCount (1,1) double = 0
        validatedPacketCacheEvictionCount (1,1) double = 0
        validatedPacketCacheInvalidationCount (1,1) double = 0
        validatedPacketCacheLastAction string = "disabled"
    end

    methods
        function obj = ScheduledReciprocalControllerModelProvider( ...
                model,members,queryTrim)
            arguments
                model
                members (:,1) struct
                queryTrim (1,1) struct
            end
            assert(isprop(model,'idx') && isprop(model,'L') && ...
                isprop(model,'dt'), ...
                'ScheduledReciprocalControllerModelProvider:NativeModel', ...
                'The native model must expose idx, L, and dt.');
            requiredTrim = {'wing','elevator','thrust'};
            assert(all(isfield(queryTrim,requiredTrim)) && ...
                numel(queryTrim.wing)==4 && isscalar(queryTrim.elevator) && ...
                isscalar(queryTrim.thrust) && queryTrim.thrust>=0 && ...
                all(isfinite([queryTrim.wing(:);queryTrim.elevator; ...
                    queryTrim.thrust])), ...
                'ScheduledReciprocalControllerModelProvider:QueryTrim', ...
                'The active query trim is incomplete or invalid.');
            assert(~isempty(members), ...
                'ScheduledReciprocalControllerModelProvider:Members', ...
                'At least one reciprocal source member is required.');

            obj.model = model;
            obj.idx = model.idx;
            obj.nativeStateCount = size(model.L,1);
            obj.queryTrim = localTrim(queryTrim);
            counts = zeros(numel(members),1);
            validated = repmat(obj.validateMember(members(1)), ...
                numel(members),1);
            for memberIndex = 1:numel(members)
                if memberIndex>1
                    validated(memberIndex) = obj.validateMember( ...
                        members(memberIndex));
                end
                counts(memberIndex) = ...
                    double(validated(memberIndex).candidate.hidden.count);
            end
            obj.members = validated;
            obj.hiddenOffsets = [0;cumsum(counts)];
            obj.hiddenStateCount = sum(counts);
            obj.stateCount = obj.nativeStateCount+obj.hiddenStateCount;
        end

        function applyScheduledPacket(obj,model,packet)
            required = {'members','queryTrim','sourceIds','schedule'};
            assert(isstruct(packet) && isscalar(packet) && ...
                all(isfield(packet,required)) && ...
                isprop(model,'idx') && isprop(model,'L') && ...
                isprop(model,'dt') && size(model.L,1)==obj.nativeStateCount && ...
                isequal(model.idx,obj.idx) && ...
                abs(double(model.dt)-double(obj.model.dt))<=1e-14, ...
                'ScheduledReciprocalControllerModelProvider:Packet', ...
                'The scheduled reciprocal packet is incompatible.');
            sourceIds = string(packet.sourceIds(:));
            currentIds = string({obj.members.sourceId}).';
            packetIds = string({packet.members.sourceId}).';
            assert(isequal(sourceIds,currentIds) && ...
                isequal(packetIds,currentIds) && ...
                numel(packet.schedule.weights)==numel(currentIds), ...
                'ScheduledReciprocalControllerModelProvider:PacketSources', ...
                ['A scheduled packet must preserve source order so the ', ...
                 'external hidden-memory state remains causal.']);
            cacheKey = struct();
            if obj.validatedPacketCacheActive
                schedule = obj.validateSchedule(packet.schedule);
                validatedTrim = localTrim(packet.queryTrim);
                cacheKey = obj.validatedPacketBindingKey( ...
                    model,packet,sourceIds,packetIds,schedule,validatedTrim);
                obj.commitCurrentValidatedPacketCacheState();
                cacheIndex = obj.findValidatedPacketCacheEntry(cacheKey);
                if cacheIndex>0
                    obj.restoreValidatedPacketCacheEntry( ...
                        cacheIndex,model);
                    obj.validatedPacketCacheHitCount = ...
                        obj.validatedPacketCacheHitCount+1;
                    obj.validatedPacketCacheLastAction = "hit";
                    return
                end
                obj.validatedPacketCacheMissCount = ...
                    obj.validatedPacketCacheMissCount+1;
                obj.validatedPacketCacheLastAction = "miss";
            end
            newMembers = repmat(obj.validateMember(packet.members(1)), ...
                numel(packet.members),1);
            counts = zeros(numel(packet.members),1);
            for memberIndex = 1:numel(packet.members)
                if memberIndex>1
                    newMembers(memberIndex) = obj.validateMember( ...
                        packet.members(memberIndex));
                end
                counts(memberIndex) = double( ...
                    newMembers(memberIndex).candidate.hidden.count);
            end
            assert(isequal([0;cumsum(counts)],obj.hiddenOffsets), ...
                'ScheduledReciprocalControllerModelProvider:PacketMemory', ...
                'A scheduled packet changed the hidden-memory partition.');
            obj.model = model;
            obj.members = newMembers;
            obj.queryTrim = localTrim(packet.queryTrim);
            if obj.aggregateRuntimeRequested
                assert(isfield(packet,'plantCandidate') && ...
                    isfield(packet,'queryPackageHash'), ...
                    ['ScheduledReciprocalControllerModelProvider:', ...
                     'AggregatePacket'], ...
                    ['The aggregate runtime requires the packet-owned ', ...
                     'common-coordinate realization and package hash.']);
                candidate = obj.validateAggregateCandidate( ...
                    packet.plantCandidate);
                signature = localAggregateSignature(packet);
                if signature~=obj.aggregatePacketSignature
                    obj.aggregateVerified = false;
                end
                obj.aggregateCandidate = candidate;
                obj.aggregateWeights = double(packet.schedule.weights(:));
                obj.aggregatePacketSignature = signature;
                obj.aggregateRuntimeActive = true;
                [obj.aggregateRuntimeFromNative, ...
                    obj.aggregateRuntimeFromRigid, ...
                    obj.aggregateCorrectionToNative] = ...
                    obj.aggregateCoordinateMaps(candidate);
            end
            if obj.scheduledCompiledRequested && ...
                    ~isempty(obj.scheduledCompiledKernel)
                signature = localAggregateSignature(packet);
                if signature~=obj.scheduledCompiledPacketSignature
                    obj.scheduledCompiledPacket = ...
                        AeroFlex.ctrl. ...
                        buildScheduledReciprocalIntervalPacketAudit( ...
                            model,packet);
                    obj.scheduledCompiledPacket.sensitivitySourceMask = ...
                        obj.scheduledSensitivitySourceMask;
                    obj.scheduledCompiledPacketSignature = signature;
                end
                obj.scheduledCompiledActive = true;
            end
            if obj.validatedPacketCacheActive
                obj.storeValidatedPacketCacheEntry(cacheKey);
            end
        end

        function state = initialize(obj,nativeState)
            nativeState = obj.validateNativeState(nativeState);
            hiddenState = zeros(obj.hiddenStateCount,1);
            for memberIndex = 1:numel(obj.members)
                indices = obj.hiddenOffsets(memberIndex)+ ...
                    (1:obj.members(memberIndex).candidate.hidden.count);
                hiddenState(indices) = ...
                    obj.members(memberIndex).queryHiddenEquilibrium;
            end
            state = [nativeState;hiddenState];
        end

        function [nativeState,hiddenState] = splitState(obj,state)
            state = obj.validateState(state);
            nativeState = state(1:obj.nativeStateCount);
            hiddenState = state(obj.nativeStateCount+1:end);
        end

        function [stateNext,jacobian,diagnostic] = step(obj,state, ...
                wingTotal,sourceInput,rigidState,schedule,needJacobian)
            if nargin < 7 || isempty(needJacobian), needJacobian = false; end
            [nativeState,hiddenState] = obj.splitState(state);
            wingTotal = wingTotal(:); sourceInput = sourceInput(:);
            rigidState = rigidState(:);
            assert(numel(wingTotal)==4 && numel(sourceInput)==7 && ...
                numel(rigidState)==9 && ...
                all(isfinite([wingTotal;sourceInput;rigidState])), ...
                'ScheduledReciprocalControllerModelProvider:Input', ...
                'The scheduled reciprocal input context is invalid.');
            schedule = obj.validateSchedule(schedule);
            assert(norm(wingTotal-(obj.queryTrim.wing+sourceInput(2:5)),inf) ...
                <=100*eps(max(1,norm(wingTotal,inf))), ...
                'ScheduledReciprocalControllerModelProvider:WingOwner', ...
                'The query total and trim-relative wing commands disagree.');

            sensitivity0 = [];
            if needJacobian
                sensitivity0 = [eye(obj.nativeStateCount), ...
                    zeros(obj.nativeStateCount,5)];
            end
            [nativeNext,nativeSensitivity] = obj.model.step( ...
                nativeState,wingTotal,sourceInput(1),sensitivity0,needJacobian);

            correction = zeros(obj.nativeStateCount,1);
            hiddenNext = zeros(obj.hiddenStateCount,1);
            rootWrench = zeros(6,1);
            sourceDiagnostics = repmat(struct(),numel(obj.members),1);
            if needJacobian
                correctionState = zeros(obj.nativeStateCount,obj.stateCount);
                correctionInput = zeros(obj.nativeStateCount,7);
                correctionRigid = zeros(obj.nativeStateCount,9);
                hiddenStateJacobian = zeros(obj.hiddenStateCount,obj.stateCount);
                hiddenInputJacobian = zeros(obj.hiddenStateCount,7);
                hiddenRigidJacobian = zeros(obj.hiddenStateCount,9);
            end

            actualElevator = obj.queryTrim.elevator+sourceInput(6);
            actualThrust = obj.queryTrim.thrust+sourceInput(7);
            assert(actualThrust>=0, ...
                'ScheduledReciprocalControllerModelProvider:Thrust', ...
                'The scheduled reciprocal context violates T >= 0.');
            for memberIndex = 1:numel(obj.members)
                member = obj.members(memberIndex);
                weight = schedule.weights(memberIndex);
                hiddenIndices = obj.hiddenOffsets(memberIndex)+ ...
                    (1:member.candidate.hidden.count);
                localHidden = hiddenState(hiddenIndices);
                queryToSource = member.queryToSourceNative;
                sourceToQueryCorrection = member.sourceToQueryCorrection;
                sourceNative = queryToSource*nativeState;
                runtimeState = member.runtimeFromNative*sourceNative+ ...
                    member.runtimeFromRigid*rigidState;
                runtimeDeparture = runtimeState- ...
                    member.candidate.base.correctionStateEquilibrium(:);
                localInput = [sourceInput(1); ...
                    wingTotal-member.trim.wing; ...
                    actualElevator-member.trim.elevator; ...
                    actualThrust-member.trim.thrust];
                inputDeparture = localInput- ...
                    member.candidate.base.inputEquilibrium(:);
                runtimeDeviation = runtimeDeparture- ...
                    member.queryRuntimeDeparture;
                inputDeviation = inputDeparture- ...
                    member.queryInputDeparture;
                visibleCorrection = ...
                    member.candidate.correction.deltaAFullState* ...
                        runtimeDeviation+ ...
                    member.candidate.partition.Avh*localHidden+ ...
                    member.candidate.correction.deltaBv*inputDeviation;
                localHiddenNext = ...
                    member.candidate.partition.hiddenFromFullState* ...
                        runtimeDeviation+ ...
                    member.candidate.partition.Ahh*localHidden+ ...
                    member.candidate.partition.Bh*inputDeviation;
                hiddenNext(hiddenIndices) = localHiddenNext;
                correction = correction+weight* ...
                    sourceToQueryCorrection*(visibleCorrection- ...
                        member.queryVisibleCorrection);
                localWrench = member.candidate.rootWrenchOutput.equilibrium(:)+ ...
                    member.candidate.rootWrenchOutput.runtimeStateMap* ...
                        [runtimeDeparture;localHidden]+ ...
                    member.candidate.rootWrenchOutput.runtimeInputMap* ...
                        inputDeparture;
                rootWrench = rootWrench+weight*localWrench;

                if needJacobian
                    runtimeNative = member.runtimeFromNative*queryToSource;
                    localVisibleState = member.candidate.correction. ...
                        deltaAFullState*runtimeNative;
                    localHiddenState = member.candidate.partition. ...
                        hiddenFromFullState*runtimeNative;
                    correctionState(:,1:obj.nativeStateCount) = ...
                        correctionState(:,1:obj.nativeStateCount)+weight* ...
                        sourceToQueryCorrection*localVisibleState;
                    correctionState(:,obj.nativeStateCount+hiddenIndices) = ...
                        correctionState(:,obj.nativeStateCount+hiddenIndices)+ ...
                        weight*sourceToQueryCorrection* ...
                        member.candidate.partition.Avh;
                    correctionInput = correctionInput+weight* ...
                        sourceToQueryCorrection* ...
                        member.candidate.correction.deltaBv;
                    correctionRigid = correctionRigid+weight* ...
                        sourceToQueryCorrection* ...
                        member.candidate.correction.deltaAFullState* ...
                        member.runtimeFromRigid;
                    hiddenStateJacobian(hiddenIndices, ...
                        1:obj.nativeStateCount) = localHiddenState;
                    hiddenStateJacobian(hiddenIndices, ...
                        obj.nativeStateCount+hiddenIndices) = ...
                        member.candidate.partition.Ahh;
                    hiddenInputJacobian(hiddenIndices,:) = ...
                        member.candidate.partition.Bh;
                    hiddenRigidJacobian(hiddenIndices,:) = ...
                        member.candidate.partition.hiddenFromFullState* ...
                        member.runtimeFromRigid;
                end
                sourceDiagnostics(memberIndex).sourceId = member.sourceId;
                sourceDiagnostics(memberIndex).weight = weight;
                sourceDiagnostics(memberIndex).hiddenStateInfinity = ...
                    norm(localHiddenNext,inf);
                sourceDiagnostics(memberIndex).runtimeDepartureInfinity = ...
                    norm(runtimeDeparture,inf);
                sourceDiagnostics(memberIndex).inputDepartureInfinity = ...
                    norm(inputDeparture,inf);
                sourceDiagnostics(memberIndex).runtimeDeviationInfinity = ...
                    norm(runtimeDeviation,inf);
                sourceDiagnostics(memberIndex).inputDeviationInfinity = ...
                    norm(inputDeviation,inf);
                sourceDiagnostics(memberIndex).visibleCorrectionInfinity = ...
                    norm(visibleCorrection,inf);
                sourceDiagnostics(memberIndex).rootWrench = localWrench;
            end
            nativeNext = nativeNext+correction;
            stateNext = [nativeNext;hiddenNext];
            assert(all(isfinite(stateNext)), ...
                'ScheduledReciprocalControllerModelProvider:FiniteState', ...
                'The scheduled reciprocal transition is nonfinite.');

            jacobian = struct();
            if needJacobian
                nativeA = nativeSensitivity(:,1:obj.nativeStateCount);
                nativeInput = zeros(obj.nativeStateCount,7);
                nativeInput(:,1:5) = nativeSensitivity(:, ...
                    obj.nativeStateCount+(1:5));
                jacobian.state = [nativeA, ...
                    zeros(obj.nativeStateCount,obj.hiddenStateCount); ...
                    zeros(obj.hiddenStateCount,obj.nativeStateCount), ...
                    zeros(obj.hiddenStateCount)] + ...
                    [correctionState;hiddenStateJacobian];
                jacobian.input = [nativeInput+correctionInput; ...
                    hiddenInputJacobian];
                jacobian.rigid = [correctionRigid;hiddenRigidJacobian];
            end
            diagnostic = struct('weights',schedule.weights, ...
                'sourceRootWrench',rootWrench, ...
                'sourceDiagnostics',sourceDiagnostics, ...
                'plantHiddenStateRead',false);
        end

        function [state,sensitivity,diagnostics] = propagateInterval( ...
                obj,state,disturbance,context,needJacobian)
            if nargin < 5 || isempty(needJacobian), needJacobian = false; end
            diagnosticsRequested = nargout>=3;
            context = obj.activateScheduledContext(context);
            context = obj.validateIntervalContext(context,true);
            count = size(context.wingTotal,2);
            if obj.compiledIntervalEligible( ...
                    context.scheduledReciprocal,diagnosticsRequested,count)
                [state,sensitivity] = obj.propagateCompiledInterval( ...
                    state,disturbance,context.wingTotal, ...
                    context.wingIncrement,context.elevatorIncrement, ...
                    context.thrustIncrement,context.rigidState, ...
                    context.scheduledReciprocal,needJacobian,false);
                diagnostics = [];
                return
            end
            [state,sensitivity,diagnostics] = obj.propagate( ...
                state,disturbance,context.wingTotal,context.wingIncrement, ...
                context.elevatorIncrement,context.thrustIncrement, ...
                context.rigidState,context.scheduledReciprocal, ...
                needJacobian,false,count,diagnosticsRequested);
        end

        function [state,sensitivity,diagnostics] = propagateControlInterval( ...
                obj,state,disturbance,wingIncrement,context,needJacobian)
            if nargin < 6 || isempty(needJacobian), needJacobian = false; end
            diagnosticsRequested = nargout>=3;
            context = obj.activateScheduledContext(context);
            context = obj.validateIntervalContext(context,false);
            count = size(context.rigidState,2);
            wingIncrement = wingIncrement(:);
            assert(numel(wingIncrement)==4 && all(isfinite(wingIncrement)), ...
                'ScheduledReciprocalControllerModelProvider:ControlInput', ...
                'The nMPC wing input must contain four finite coordinates.');
            wingTotal = repmat(obj.queryTrim.wing+wingIncrement,1,count);
            wingHistory = repmat(wingIncrement,1,count);
            if obj.compiledIntervalEligible( ...
                    context.scheduledReciprocal,diagnosticsRequested,count)
                [state,sensitivity] = obj.propagateCompiledInterval( ...
                    state,disturbance,wingTotal,wingHistory, ...
                    context.elevatorIncrement,context.thrustIncrement, ...
                    context.rigidState,context.scheduledReciprocal, ...
                    needJacobian,true);
                diagnostics = [];
                return
            end
            [state,sensitivity,diagnostics] = obj.propagate( ...
                state,disturbance,wingTotal,wingHistory, ...
                context.elevatorIncrement,context.thrustIncrement, ...
                context.rigidState,context.scheduledReciprocal, ...
                needJacobian,true,count,diagnosticsRequested);
        end

        function audit = evaluateControlIntervalSourceDomain( ...
                obj,state,disturbance,wingIncrement,context)
        %EVALUATECONTROLINTERVALSOURCEDOMAIN Audit the applied-plant domain.
        %   This is deliberately read-only.  It evaluates the same
        %   query-relative source envelope as PlantRunTime at every plant
        %   substep of a proposed nMPC interval.
            context = obj.activateScheduledContext(context);
            context = obj.validateIntervalContext(context,false);
            state = obj.validateState(state);
            wingIncrement = wingIncrement(:);
            validateattributes(disturbance,{'numeric'}, ...
                {'scalar','real','finite'});
            assert(numel(wingIncrement)==4 && all(isfinite(wingIncrement)), ...
                'ScheduledReciprocalControllerModelProvider:DomainInput', ...
                'The source-domain audit requires four finite wing increments.');
            count = size(context.rigidState,2);
            template = struct('accepted',true,'reason',"", ...
                'details',repmat(struct('sourceId',"", ...
                'inputRatio',0,'visibleRatio',0,'hiddenRatio',0, ...
                'pulseHiddenRatio',0,'memoryOwner',"one_step_pulse", ...
                'rootWrenchRatio',0,'accepted',true),0,1));
            substeps = repmat(template,count,1);
            for stepIndex = 1:count
                sourceInput = [double(disturbance);wingIncrement; ...
                    context.elevatorIncrement(stepIndex); ...
                    context.thrustIncrement(stepIndex)];
                wingTotal = obj.queryTrim.wing+wingIncrement;
                substeps(stepIndex) = obj.evaluateSourceDomainAtState( ...
                    state,wingTotal,sourceInput, ...
                    context.rigidState(:,stepIndex), ...
                    context.scheduledReciprocal{stepIndex});
                if ~substeps(stepIndex).accepted
                    break
                end
                state = obj.step(state,wingTotal,sourceInput, ...
                    context.rigidState(:,stepIndex), ...
                    context.scheduledReciprocal{stepIndex},false);
            end
            accepted = [substeps.accepted];
            firstRejected = find(~accepted,1,'first');
            audit = struct('accepted',all(accepted), ...
                'firstRejectedSubstep',firstRejected, ...
                'substeps',substeps);
        end

        function configureFixedIntervalKernelAudit(obj,request)
            obj.invalidateValidatedPacketCacheEntries();
            assert(isstruct(request) && isscalar(request) && ...
                isfield(request,'enabled'), ...
                'ScheduledReciprocalControllerModelProvider:CompiledKernel', ...
                'The scheduled compiled-kernel request is incomplete.');
            if ~logical(request.enabled)
                obj.scheduledCompiledRequested = false;
                obj.scheduledCompiledActive = false;
                obj.scheduledCompiledVerified = false;
                obj.scheduledCompiledKernel = function_handle.empty;
                obj.scheduledCompiledPacket = struct();
                obj.scheduledCompiledPacketSignature = "";
                obj.scheduledCompiledCallCount = 0;
                obj.scheduledCompiledFallbackCount = 0;
                obj.scheduledCompiledLastFallback = "";
                obj.scheduledCompiledIdentity = "disabled";
                obj.scheduledSensitivityStencilRequested = false;
                obj.scheduledSensitivitySourceMask = true(14,1);
                return
            end
            required = {'enabled','auditOnly','changeId'};
            assert(all(isfield(request,required)) && ...
                logical(request.auditOnly) && string(request.changeId)== ...
                "phase18c-v17a-casebc-scheduled-compiled-interval-kernel-audit-v1", ...
                'ScheduledReciprocalControllerModelProvider:CompiledApproval', ...
                'The scheduled compiled-kernel request is unauthorized.');
            functionName = ...
                'AeroFlex_ctrl_scheduledReciprocalIntervalKernelAudit_mex';
            obj.scheduledCompiledRequested = true;
            obj.scheduledCompiledActive = false;
            obj.scheduledCompiledVerified = false;
            obj.scheduledCompiledKernel = function_handle.empty;
            % The first completed/future interval owns both the scheduled
            % packet and the ROMIntegrator built from its package. Do not
            % bind compiled matrices to the constructor's base integrator.
            obj.scheduledCompiledPacket = struct();
            obj.scheduledCompiledPacketSignature = "";
            obj.scheduledCompiledCallCount = 0;
            obj.scheduledCompiledFallbackCount = 0;
            obj.scheduledCompiledLastFallback = "";
            obj.scheduledCompiledIdentity = "unavailable";
            obj.scheduledSensitivityStencilRequested = false;
            obj.scheduledSensitivitySourceMask = true(14,1);
            if isfield(request,'activeStencilSensitivityEnabled') && ...
                    logical(request.activeStencilSensitivityEnabled)
                assert(isfield(request,'sensitivityChangeId') && ...
                    string(request.sensitivityChangeId)== ...
                    "phase18c-v17a-casebc-active-stencil-scheduled-sensitivity-condensation-v1", ...
                    ['ScheduledReciprocalControllerModelProvider:', ...
                     'SensitivityStencilApproval'], ...
                    'The active-stencil sensitivity request is unauthorized.');
                obj.scheduledSensitivityStencilRequested = true;
            end
            if isempty(which(functionName))
                obj.scheduledCompiledFallbackCount = 1;
                obj.scheduledCompiledLastFallback = ...
                    "compiled kernel unavailable; exact MATLAB aggregate active";
                return
            end
            kernelPath = string(which(functionName));
            obj.scheduledCompiledKernel = str2func(functionName);
            obj.scheduledCompiledIdentity = functionName+"|"+ ...
                localFileHash(kernelPath)+"|"+string(computer('arch'))+ ...
                "|"+string(mexext);
            obj.scheduledCompiledActive = true;
        end

        function configureHorizonSensitivityStencilAudit(obj,contexts)
        %CONFIGUREHORIZONSENSITIVITYSTENCILAUDIT Bind the exact source union.
            if ~obj.scheduledSensitivityStencilRequested
                return
            end
            assert(iscell(contexts) && ~isempty(contexts), ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'SensitivityStencilContext'], ...
                'The active-stencil path requires a nonempty context horizon.');
            sourceMask = false(14,1);
            for interval = 1:numel(contexts)
                context = contexts{interval};
                assert(isstruct(context) && isscalar(context) && ...
                    isfield(context,'scheduledPacket') && ...
                    isfield(context.scheduledPacket,'schedule') && ...
                    isfield(context.scheduledPacket.schedule,'weights'), ...
                    ['ScheduledReciprocalControllerModelProvider:', ...
                     'SensitivityStencilContext'], ...
                    'Scheduled context %d has no interpolation weights.', ...
                    interval);
                weights = double( ...
                    context.scheduledPacket.schedule.weights(:));
                assert(numel(weights)==14 && all(isfinite(weights)) && ...
                    all(weights>=-1e-14) && abs(sum(weights)-1)<=1e-12, ...
                    ['ScheduledReciprocalControllerModelProvider:', ...
                     'SensitivityStencilWeights'], ...
                    'Scheduled context %d has invalid interpolation weights.', ...
                    interval);
                sourceMask = sourceMask | weights>0;
            end
            assert(any(sourceMask), ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'SensitivityStencilEmpty'], ...
                'The scheduled sensitivity source union is empty.');
            if ~isequal(sourceMask,obj.scheduledSensitivitySourceMask)
                obj.invalidateValidatedPacketCacheEntries();
                obj.scheduledCompiledVerified = false;
            end
