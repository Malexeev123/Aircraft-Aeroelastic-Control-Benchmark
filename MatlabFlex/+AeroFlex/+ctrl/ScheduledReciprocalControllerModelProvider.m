    all(isfinite([trim.wing;trim.elevator;trim.thrust])), ...
    'ScheduledReciprocalControllerModelProvider:SourceTrim', ...
    'A source trim is incomplete or violates T >= 0.');
end

function value = localAggregateSignature(packet)
weights = double(packet.schedule.weights(:));
