        function [state,sensitivity,diagnostics] = propagate(obj,state, ...
                disturbance,wingTotal,wingIncrement,elevator,thrust,rigid, ...
                schedules,needJacobian,control,count,diagnosticsRequested)
            state = obj.validateState(state);
            diagnostics = [];
            if diagnosticsRequested, diagnostics = cell(1,count); end
            if needJacobian
                stateSensitivity = eye(obj.stateCount);
                disturbanceSensitivity = zeros(obj.stateCount,1);
                wingSensitivity = zeros(obj.stateCount,4);
            end
            for substep = 1:count
                sourceInput = [disturbance;wingIncrement(:,substep); ...
                    elevator(substep);thrust(substep)];
                schedule = obj.validateSchedule(schedules{substep});
                useAggregate = obj.aggregateEligible( ...
                    schedule,diagnosticsRequested);
                if useAggregate
                    [state,jacobian] = obj.stepAggregateWithParity( ...
                        state,wingTotal(:,substep),sourceInput, ...
                        rigid(:,substep),schedule,needJacobian);
                elseif diagnosticsRequested
                    [state,jacobian,diagnostics{substep}] = obj.step( ...
                        state,wingTotal(:,substep),sourceInput, ...
                        rigid(:,substep),schedule,needJacobian);
                else
                    [state,jacobian] = obj.step( ...
                        state,wingTotal(:,substep),sourceInput, ...
                        rigid(:,substep),schedule,needJacobian);
                end
                if needJacobian
                    disturbanceSensitivity = jacobian.state* ...
                        disturbanceSensitivity+jacobian.input(:,1);
                    if control
                        wingSensitivity = jacobian.state*wingSensitivity+ ...
                            jacobian.input(:,2:5);
                    end
                    stateSensitivity = jacobian.state*stateSensitivity;
                end
            end
            sensitivity = [];
            if needJacobian
                sensitivity = [stateSensitivity,disturbanceSensitivity];
                if control, sensitivity = [sensitivity,wingSensitivity]; end
            end
        end

        function eligible = compiledIntervalEligible(obj,schedules, ...
                diagnosticsRequested,count)
            eligible = obj.scheduledCompiledRequested && ...
                obj.scheduledCompiledActive && ...
                obj.aggregateRuntimeRequested && ...
                obj.aggregateRuntimeActive && count==14 && ...
                ~isempty(fieldnames(obj.scheduledCompiledPacket));
            if ~eligible
                return
            end
            if diagnosticsRequested
                obj.scheduledCompiledFallbackCount = ...
                    obj.scheduledCompiledFallbackCount+1;
                obj.scheduledCompiledLastFallback = ...
                    "per-source diagnostics requested";
                eligible = false;
                return
            end
            for substep = 1:count
                schedule = obj.validateSchedule(schedules{substep});
                if numel(schedule.weights)~=numel(obj.aggregateWeights) || ...
                        norm(schedule.weights-obj.aggregateWeights,inf)>1e-13
                    obj.scheduledCompiledFallbackCount = ...
                        obj.scheduledCompiledFallbackCount+1;
                    obj.scheduledCompiledLastFallback = ...
                        "substep weights differ from compiled packet";
                    eligible = false;
                    return
                end
            end
        end

        function [stateNext,sensitivity] = propagateCompiledInterval( ...
                obj,state,disturbance,wingTotal,wingIncrement,elevator, ...
                thrust,rigid,schedules,needJacobian,control)
            state = obj.validateState(state);
            schedule = obj.validateSchedule(schedules{1});
            if ~obj.aggregateVerified
                sourceInput = [disturbance;wingIncrement(:,1); ...
                    elevator(1);thrust(1)];
                obj.stepAggregateWithParity(state,wingTotal(:,1), ...
                    sourceInput,rigid(:,1),schedule,true);
            end
            if ~obj.aggregateVerified || ~obj.aggregateRuntimeActive
                obj.scheduledCompiledActive = false;
                obj.scheduledCompiledFallbackCount = ...
                    obj.scheduledCompiledFallbackCount+1;
                obj.scheduledCompiledLastFallback = ...
                    "aggregate packet parity unavailable";
                [stateNext,sensitivity] = obj.propagate(state,disturbance, ...
                    wingTotal,wingIncrement,elevator,thrust,rigid,schedules, ...
                    needJacobian,control,14,false);
                return
            end
            try
                [compiledState,compiledSensitivity] = ...
                    obj.scheduledCompiledKernel(state,disturbance, ...
                        wingTotal,wingIncrement,elevator,thrust,rigid, ...
                        needJacobian,obj.scheduledCompiledPacket);
                if ~obj.scheduledCompiledVerified
                    fullPacket = obj.scheduledCompiledPacket;
                    fullPacket.sensitivitySourceMask = true(14,1);
                    [matlabState,fullMatlabSensitivity] = ...
                        AeroFlex.ctrl. ...
                        scheduledReciprocalIntervalKernelAudit( ...
                            state,disturbance,wingTotal,wingIncrement, ...
                            elevator,thrust,rigid,needJacobian, ...
                            fullPacket);
                    matlabSensitivity = localStencilSensitivity( ...
                        fullMatlabSensitivity, ...
                        obj.scheduledCompiledPacket);
                    stateError = norm(compiledState-matlabState,inf);
                    sensitivityError = norm( ...
                        compiledSensitivity-matlabSensitivity,inf);
                    if stateError>obj.aggregateStateTolerance || ...
                            sensitivityError>obj.aggregateJacobianTolerance
                        error(['ScheduledReciprocalControllerModelProvider:', ...
                            'CompiledParity'], ...
                            ['Scheduled compiled parity failed: state %.3e, ', ...
                             'sensitivity %.3e.'],stateError,sensitivityError);
                    end
                    obj.scheduledCompiledVerified = true;
                end
                stateNext = compiledState;
                if needJacobian
                    if control
                        sensitivity = compiledSensitivity;
                    else
                        sensitivity = compiledSensitivity(:,1:621);
                    end
                else
                    sensitivity = [];
                end
                obj.scheduledCompiledCallCount = ...
                    obj.scheduledCompiledCallCount+1;
            catch exception
                obj.scheduledCompiledActive = false;
                obj.scheduledCompiledFallbackCount = ...
                    obj.scheduledCompiledFallbackCount+1;
                obj.scheduledCompiledLastFallback = string(exception.message);
                [stateNext,sensitivity] = obj.propagate(state,disturbance, ...
                    wingTotal,wingIncrement,elevator,thrust,rigid,schedules, ...
                    needJacobian,control,14,false);
            end
        end

        function eligible = aggregateEligible(obj,schedule,diagnosticsRequested)
            eligible = obj.aggregateRuntimeRequested && ...
                obj.aggregateRuntimeActive && ...
                ~isempty(obj.aggregateCandidate);
            if ~eligible
                return
            end
            if diagnosticsRequested
                obj.aggregateDiagnosticFallbackCount = ...
                    obj.aggregateDiagnosticFallbackCount+1;
                obj.aggregateLastFallback = ...
                    "per-source diagnostics requested";
                eligible = false;
                return
            end
            if numel(schedule.weights)~=numel(obj.aggregateWeights) || ...
                    norm(schedule.weights-obj.aggregateWeights,inf)>1e-13
                obj.aggregateFallbackCount = obj.aggregateFallbackCount+1;
                obj.aggregateLastFallback = ...
                    "substep weights differ from packet aggregate";
                eligible = false;
            end
        end

        function [stateNext,jacobian] = stepAggregateWithParity(obj,state, ...
                wingTotal,sourceInput,rigidState,schedule,needJacobian)
            if obj.aggregateVerified
                [stateNext,jacobian] = obj.aggregateStep( ...
                    state,wingTotal,sourceInput,rigidState,needJacobian);
                obj.aggregateCallCount = obj.aggregateCallCount+1;
                return
            end

            [aggregateState,aggregateJacobian,aggregateWrench] = ...
                obj.aggregateStep(state,wingTotal,sourceInput, ...
                    rigidState,true);
            [bankState,bankJacobian,bankDiagnostic] = obj.step( ...
                state,wingTotal,sourceInput,rigidState,schedule,true);
            stateError = norm(aggregateState-bankState,inf);
            jacobianError = max([ ...
                norm(aggregateJacobian.state-bankJacobian.state,inf), ...
                norm(aggregateJacobian.input-bankJacobian.input,inf), ...
                norm(aggregateJacobian.rigid-bankJacobian.rigid,inf)]);
            wrenchError = norm(aggregateWrench- ...
                bankDiagnostic.sourceRootWrench,inf);
            if stateError<=obj.aggregateStateTolerance && ...
                    jacobianError<=obj.aggregateJacobianTolerance && ...
                    wrenchError<=obj.aggregateWrenchTolerance
                obj.aggregateVerified = true;
                obj.aggregateParityCount = obj.aggregateParityCount+1;
                obj.aggregateCallCount = obj.aggregateCallCount+1;
                stateNext = aggregateState;
                if needJacobian
                    jacobian = aggregateJacobian;
                else
                    jacobian = struct();
                end
                return
            end

            obj.aggregateRuntimeActive = false;
            obj.aggregateFallbackCount = obj.aggregateFallbackCount+1;
            obj.aggregateLastFallback = sprintf( ...
                ['packet parity failed: state %.3e, Jacobian %.3e, ', ...
                 'root wrench %.3e'],stateError,jacobianError,wrenchError);
            stateNext = bankState;
            if needJacobian
                jacobian = bankJacobian;
            else
                jacobian = struct();
            end
        end

        function [stateNext,jacobian,rootWrench] = aggregateStep(obj,state, ...
                wingTotal,sourceInput,rigidState,needJacobian)
            state = obj.validateState(state);
            nativeState = state(1:obj.nativeStateCount);
            hiddenState = state(obj.nativeStateCount+1:end);
            wingTotal = double(wingTotal(:));
            sourceInput = double(sourceInput(:));
            rigidState = double(rigidState(:));
            assert(numel(wingTotal)==4 && numel(sourceInput)==7 && ...
                numel(rigidState)==9 && ...
                all(isfinite([wingTotal;sourceInput;rigidState])), ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'AggregateInput'], ...
                'The aggregate scheduled input context is invalid.');
            assert(norm(wingTotal-(obj.queryTrim.wing+ ...
                sourceInput(2:5)),inf)<= ...
                100*eps(max(1,norm(wingTotal,inf))), ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'AggregateWingOwner'], ...
                'The aggregate total and trim-relative wing commands disagree.');
            assert(obj.queryTrim.thrust+sourceInput(7)>=0, ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'AggregateThrust'], ...
                'The aggregate scheduled context violates T >= 0.');

            candidate = obj.aggregateCandidate;
            runtimeDeparture = obj.aggregateRuntimeFromNative*nativeState+ ...
                obj.aggregateRuntimeFromRigid*rigidState- ...
                candidate.base.correctionStateEquilibrium(:);
            inputDeparture = sourceInput- ...
                candidate.base.inputEquilibrium(:);
            visibleCorrection = candidate.correction.deltaAFullState* ...
                runtimeDeparture+candidate.partition.Avh*hiddenState+ ...
                candidate.correction.deltaBv*inputDeparture;
            hiddenNext = candidate.partition.hiddenFromFullState* ...
                runtimeDeparture+candidate.partition.Ahh*hiddenState+ ...
                candidate.partition.Bh*inputDeparture;

            sensitivity0 = [];
            if needJacobian
                sensitivity0 = [eye(obj.nativeStateCount), ...
                    zeros(obj.nativeStateCount,5)];
            end
            [nativeNext,nativeSensitivity] = obj.model.step( ...
                nativeState,wingTotal,sourceInput(1), ...
                sensitivity0,needJacobian);
            nativeNext = nativeNext+ ...
                obj.aggregateCorrectionToNative*visibleCorrection;
            stateNext = [nativeNext;hiddenNext];
            assert(all(isfinite(stateNext)), ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'AggregateFiniteState'], ...
                'The aggregate scheduled transition is nonfinite.');

            jacobian = struct();
            if needJacobian
                nativeA = nativeSensitivity(:,1:obj.nativeStateCount);
                nativeInput = nativeSensitivity(:, ...
                    obj.nativeStateCount+(1:5));
                correctionA = candidate.correction.deltaAFullState;
                hiddenA = candidate.partition.hiddenFromFullState;
                jacobian.state = [ ...
                    nativeA+obj.aggregateCorrectionToNative*correctionA* ...
                        obj.aggregateRuntimeFromNative, ...
                    obj.aggregateCorrectionToNative* ...
                        candidate.partition.Avh; ...
                    hiddenA*obj.aggregateRuntimeFromNative, ...
                    candidate.partition.Ahh];
                nativeSourceInput = zeros(obj.nativeStateCount,7);
                nativeSourceInput(:,1:5) = nativeInput;
                jacobian.input = [nativeSourceInput+ ...
                    obj.aggregateCorrectionToNative* ...
                        candidate.correction.deltaBv; ...
                    candidate.partition.Bh];
                jacobian.rigid = [ ...
                    obj.aggregateCorrectionToNative*correctionA* ...
                        obj.aggregateRuntimeFromRigid; ...
                    hiddenA*obj.aggregateRuntimeFromRigid];
            end
            rootWrench = candidate.rootWrenchOutput.equilibrium(:)+ ...
                candidate.rootWrenchOutput.runtimeStateMap* ...
                    [runtimeDeparture;hiddenState]+ ...
                candidate.rootWrenchOutput.runtimeInputMap*inputDeparture;
        end

        function candidate = validateAggregateCandidate(obj,candidate)
            required = {'runtimeEligible','runtimeState','visible','input', ...
                'hidden','base','correction','partition','rootWrenchOutput'};
            assert(isstruct(candidate) && isscalar(candidate) && ...
                all(isfield(candidate,required)) && ...
                logical(candidate.runtimeEligible) && ...
                candidate.runtimeState.count==83 && ...
                candidate.visible.count==69 && candidate.input.count==7 && ...
                candidate.hidden.count==obj.hiddenStateCount, ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'AggregateCandidate'], ...
                'The packet aggregate has an incompatible state contract.');
            runtimeCount = double(candidate.runtimeState.count);
            visibleCount = double(candidate.visible.count);
            hiddenCount = double(candidate.hidden.count);
            inputCount = double(candidate.input.count);
            dimensions = [ ...
                isequal(size(candidate.correction.deltaAFullState), ...
                    [visibleCount,runtimeCount]), ...
                isequal(size(candidate.correction.deltaBv), ...
                    [visibleCount,inputCount]), ...
                isequal(size(candidate.partition.Avh), ...
                    [visibleCount,hiddenCount]), ...
                isequal(size(candidate.partition.hiddenFromFullState), ...
                    [hiddenCount,runtimeCount]), ...
                isequal(size(candidate.partition.Ahh), ...
                    [hiddenCount,hiddenCount]), ...
                isequal(size(candidate.partition.Bh), ...
                    [hiddenCount,inputCount]), ...
                isequal(size(candidate.rootWrenchOutput.runtimeStateMap), ...
                    [6,runtimeCount+hiddenCount]), ...
                isequal(size(candidate.rootWrenchOutput.runtimeInputMap), ...
                    [6,inputCount])];
            assert(all(dimensions), ...
                ['ScheduledReciprocalControllerModelProvider:', ...
                 'AggregateDimensions'], ...
                'The packet aggregate matrix dimensions changed.');
        end

        function [runtimeFromNative,runtimeFromRigid,correctionToNative] = ...
                aggregateCoordinateMaps(obj,candidate)
            runtimeFromNative = zeros( ...
                candidate.runtimeState.count,obj.nativeStateCount);
            runtimeFromNative(candidate.runtimeState.sourceVisible(1:60), ...
                [obj.idx.q1(:);obj.idx.q2(:);obj.idx.qGam(:)]) = eye(60);
            runtimeFromNative(candidate.runtimeState.qxi,obj.idx.qxi) = ...
                eye(numel(obj.idx.qxi));
            runtimeFromNative(candidate.runtimeState.chi,obj.idx.chi) = ...
                eye(numel(obj.idx.chi));
            runtimeFromRigid = zeros(candidate.runtimeState.count,9);
            runtimeFromRigid(candidate.visible.rigid,:) = eye(9);
            correctionToNative = zeros( ...
                obj.nativeStateCount,candidate.visible.count);
            correctionToNative(obj.idx.q1,candidate.visible.q1) = ...
                eye(numel(obj.idx.q1));
            correctionToNative(obj.idx.q2,candidate.visible.q2) = ...
                eye(numel(obj.idx.q2));
            correctionToNative(obj.idx.qGam,candidate.visible.qGam) = ...
                eye(numel(obj.idx.qGam));
        end

