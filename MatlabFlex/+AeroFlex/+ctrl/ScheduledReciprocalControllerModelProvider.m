    string(sprintf('%.17g,',weights));
end

function reduced = localStencilSensitivity(fullSensitivity,packet)
mask = logical(packet.sensitivitySourceMask(:));
counts = double(packet.hiddenStateCounts(:));
if all(mask)
    reduced = fullSensitivity;
    return
end
offsets = [0;cumsum(counts)];
hidden = zeros(sum(counts(mask)),1);
cursor = 0;
for source = 1:numel(mask)
    if mask(source)
        count = counts(source);
        hidden(cursor+(1:count)) = offsets(source)+(1:count);
        cursor = cursor+count;
    end
end
active = [reshape(1:74,[],1);74+hidden];
reduced = zeros(size(fullSensitivity));
reduced(active,active) = fullSensitivity(active,active);
reduced(active,621:625) = fullSensitivity(active,621:625);
end

function digest = localFileHash(path)
path = string(path);
assert(isscalar(path) && isfile(path), ...
    'ScheduledReciprocalControllerModelProvider:KernelIdentity', ...
    'The compiled-kernel identity path is unavailable.');
file = fopen(path,'rb');
assert(file>=0, ...
    'ScheduledReciprocalControllerModelProvider:KernelIdentity', ...
    'The compiled-kernel identity file cannot be opened.');
cleanup = onCleanup(@()fclose(file));
bytes = fread(file,Inf,'*uint8');
engine = javaMethod( ...
    'getInstance','java.security.MessageDigest','SHA-256');
engine.update(typecast(bytes,'int8'));
raw = mod(double(engine.digest()),256);
digest = lower(string(reshape(dec2hex(raw,2).',1,[])));
clear cleanup
end
