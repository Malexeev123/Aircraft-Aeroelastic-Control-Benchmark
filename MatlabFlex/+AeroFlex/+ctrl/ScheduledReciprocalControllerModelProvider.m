        function index = findValidatedPacketCacheEntry(obj,key)
            index = 0;
            for candidateIndex = 1:numel( ...
                    obj.validatedPacketCacheEntries)
                if isequaln(obj.validatedPacketCacheEntries( ...
                        candidateIndex).key,key)
                    index = candidateIndex;
                    return
                end
            end
        end

        function commitCurrentValidatedPacketCacheState(obj)
            if isempty(fieldnames(obj.validatedPacketCacheCurrentKey))
                return
            end
            index = obj.findValidatedPacketCacheEntry( ...
                obj.validatedPacketCacheCurrentKey);
            if index==0
                return
            end
            obj.validatedPacketCacheEntries(index).aggregateVerified = ...
                obj.aggregateVerified;
            obj.validatedPacketCacheEntries(index). ...
                scheduledCompiledVerified = obj.scheduledCompiledVerified;
        end

