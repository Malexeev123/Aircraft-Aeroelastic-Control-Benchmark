        function [appliedEndpointTarget,info] = computeLexicographic( ...
                obj,plant,package,fusion,actuator,controller,xFlexible, ...
                uPrevious,uOuter,rigidCommand,rigidReference,gustHorizon, ...
                timeSeconds,nmpcCandidateHorizon)
        %COMPUTELEXICOGRAPHIC Allocate the shared wing after the nMPC solve.
        %   The dedicated rigid channels in rigidCommand are held fixed.  This
        %   audit-only method chooses only the symmetric wing correction.  Its
        %   default three-interval form is retained; the source-bound
        %   ten-interval dynamic-nullspace request reuses this same nonlinear
        %   realization with a longer wing-only decision sequence.
            solveTimer = tic;
            obj.callCount = obj.callCount+1;
            gustHorizon = obj.normalizeGustHorizon(gustHorizon);
            obj.validateRuntime(plant,fusion,actuator,controller, ...
                xFlexible,uPrevious,uOuter,rigidCommand,rigidReference, ...
                gustHorizon,timeSeconds);
            nSurface = obj.cfg.ctrl.n_surf;
            nDecision = nSurface*obj.nInterval;
            assert(isnumeric(nmpcCandidateHorizon) && ...
                size(nmpcCandidateHorizon,1)==2*nSurface && ...
                size(nmpcCandidateHorizon,2)>=obj.nInterval && ...
                all(isfinite(nmpcCandidateHorizon(:,1:obj.nInterval)),"all"), ...
                "CoupledRtiAllocatorAudit:LexicographicCandidate", ...
                "The nMPC candidate horizon must contain finite endpoint/rate rows.");

            nominalRates = zeros(nSurface,obj.nInterval);
            [nominalResponse,nominal] = obj.rollout(plant,package, ...
                fusion,actuator,xFlexible,uPrevious,uOuter, ...
                rigidCommand,gustHorizon,nominalRates);
            outputReference = obj.outputReference(plant,xFlexible,nominal.tip);
            [nominalFlexible,nominalRigid] = obj.residuals( ...
                controller,nominal,outputReference,rigidReference);

            responseJacobian = zeros(numel(nominalResponse),nDecision);
            rigidJacobian = zeros(numel(nominalRigid),nDecision);
            step = obj.finiteDifferenceStep;
            for decisionIndex = 1:nDecision
                plusRates = nominalRates;
                minusRates = nominalRates;
                plusRates(decisionIndex) = plusRates(decisionIndex)+step;
                minusRates(decisionIndex) = minusRates(decisionIndex)-step;
                [plusResponse,plus] = obj.rollout(plant,package, ...
                    fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    rigidCommand,gustHorizon,plusRates);
                [minusResponse,minus] = obj.rollout(plant,package, ...
                    fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    rigidCommand,gustHorizon,minusRates);
                [~,plusRigid] = obj.residuals( ...
                    controller,plus,outputReference,rigidReference);
                [~,minusRigid] = obj.residuals( ...
                    controller,minus,outputReference,rigidReference);
                responseJacobian(:,decisionIndex) = ...
                    (plusResponse-minusResponse)/(2*step);
                rigidJacobian(:,decisionIndex) = ...
                    (plusRigid-minusRigid)/(2*step);
            end

            rateScale = min(abs([actuator.rateL(:), ...
                actuator.rateU(:)]),[],2);
            decisionScale = repmat(rateScale,obj.nInterval,1);
            scaledRigidJacobian = rigidJacobian.*decisionScale.';
            regularization = 1e-10*max( ...
                trace(scaledRigidJacobian.'*scaledRigidJacobian)/nDecision,1);
            primaryHessian = scaledRigidJacobian.'*scaledRigidJacobian + ...
                regularization*eye(nDecision);
            primaryHessian = 0.5*(primaryHessian+primaryHessian.');
            primaryGradient = scaledRigidJacobian.'*nominalRigid;
            [Aphysical,bphysical] = obj.physicalConstraints( ...
                actuator,uPrevious,nominalRates,rateScale);
            options = optimoptions("fmincon","Algorithm","sqp", ...
                "Display","none","MaxIterations",50, ...
                "OptimalityTolerance",1e-8,"ConstraintTolerance",1e-9);
            primaryObjective = @(z) 0.5*z.'*primaryHessian*z + ...
                primaryGradient.'*z;
            zero = zeros(nDecision,1);
            [primaryStep,primaryValue,primaryExitflag,primaryOutput] = ...
                fmincon(primaryObjective,zero,Aphysical,bphysical, ...
                [],[],[],[],[],options);
            primaryAccepted = primaryExitflag > 0 && ...
                all(isfinite(primaryStep)) && isfinite(primaryValue);
            % The second stage is constrained by the first-stage optimum.
            % Its numerical allowance follows the declared SQP feasibility
            % tolerance, never a tracking or load tuning weight.
            primaryTolerance = max(100*options.ConstraintTolerance, ...
                256*eps(max(1,abs(primaryValue))));

            candidateRates = nmpcCandidateHorizon(nSurface+(1:nSurface), ...
                1:obj.nInterval);
            candidateScaledRates = candidateRates(:)./decisionScale;
            secondaryObjective = @(z) 0.5*sum((z-candidateScaledRates).^2) + ...
                0.5*regularization*(z.'*z);
            primaryConstraint = @(z) deal( ...
                primaryObjective(z)-primaryValue-primaryTolerance,[]);
            if primaryAccepted
                [secondaryStep,secondaryValue,secondaryExitflag, ...
                    secondaryOutput] = fmincon(secondaryObjective,primaryStep, ...
                    Aphysical,bphysical,[],[],[],[],primaryConstraint,options);
            else
                secondaryStep = zero;
                secondaryValue = nan;
                secondaryExitflag = -inf;
                secondaryOutput = struct();
            end
            secondaryAccepted = primaryAccepted && secondaryExitflag > 0 && ...
                all(isfinite(secondaryStep)) && isfinite(secondaryValue) && ...
                primaryObjective(secondaryStep) <= primaryValue + ...
                primaryTolerance;

            selected = nominal;
            selectedFlexible = nominalFlexible;
            selectedRigid = nominalRigid;
            selectedRates = nominalRates;
            hardChecks = obj.lexicographicHardChecks( ...
                plant.trimThrust+rigidCommand.thrust,nominal);
            if secondaryAccepted
                proposedRates = reshape(decisionScale.*secondaryStep, ...
                    nSurface,obj.nInterval);
                [~,trial] = obj.rollout(plant,package,fusion,actuator, ...
                    xFlexible,uPrevious,uOuter,rigidCommand,gustHorizon, ...
                    proposedRates);
                [trialFlexible,trialRigid] = obj.residuals( ...
                    controller,trial,outputReference,rigidReference);
                trialChecks = obj.lexicographicHardChecks( ...
                    plant.trimThrust+rigidCommand.thrust,trial);
                if all(structfun(@logical,trialChecks))
                    selected = trial;
                    selectedFlexible = trialFlexible;
                    selectedRigid = trialRigid;
                    selectedRates = proposedRates;
                    hardChecks = trialChecks;
                else
                    secondaryAccepted = false;
                end
            end

            if secondaryAccepted
                appliedEndpointTarget = selected.endpoint(:,1);
                obj.warmRates = selectedRates;
                obj.initialized = true;
                exitflag = 1;
                message = "Accepted lexicographic shared-wing nonlinear replay.";
            else
                % Retain only the prior wing endpoint. The caller continues to
                % apply the current independent elevator/thrust LQR command.
                appliedEndpointTarget = uPrevious(:);
                obj.warmRates(:) = 0;
                obj.initialized = false;
                exitflag = 0;
                message = "Retained prior wing endpoint after lexicographic replay rejection.";
            end
            assert(numel(appliedEndpointTarget)==2*nSurface && ...
                all(isfinite(appliedEndpointTarget)), ...
                "CoupledRtiAllocatorAudit:LexicographicOutput", ...
                "The lexicographic endpoint target is invalid.");

            selectedCost = obj.costSummary(selectedFlexible,selectedRigid);
            info = struct("cost",selectedCost.combined,"exitflag",exitflag, ...
                "accepted",secondaryAccepted,"solveAttempted",true, ...
                "uHorizon",obj.padHorizon(selected.endpoint, ...
                appliedEndpointTarget,controller.Nc), ...
                "candidateUHorizon",nmpcCandidateHorizon, ...
                "candidateFirstCommand",nmpcCandidateHorizon(:,1), ...
                "wHorizon",obj.padGustHorizon(gustHorizon,controller.Nc), ...
                "continuity",0,"continuityTwoNorm",0, ...
                "constraintViolationInf",obj.constraintViolation(hardChecks), ...
                "terminalSetValue",nan,"terminalSetSatisfied",false, ...
                "output",struct("iterations",safeField(secondaryOutput, ...
                "iterations",nan),"message",message,"auditCapture",struct( ...
                "schemaVersion","phase18c-v17a-lexicographic-shared-wing-allocation-v1", ...
                "sample",obj.callCount,"timeSeconds",timeSeconds, ...
                "primaryExitflag",primaryExitflag, ...
                "primaryValue",primaryValue, ...
                "primaryTolerance",primaryTolerance, ...
                "primaryIterations",safeField(primaryOutput,"iterations",nan), ...
                "secondaryExitflag",secondaryExitflag, ...
                "secondaryValue",secondaryValue, ...
                "secondaryIterations",safeField(secondaryOutput,"iterations",nan), ...
                "primaryConstraintValue",primaryObjective(secondaryStep)-primaryValue, ...
                "primaryConstraintSatisfied",secondaryAccepted, ...
                "hardChecks",hardChecks, ...
                "rigidReference",rigidReference(:), ...
                "nominalRigidCost",0.5*(nominalRigid.'*nominalRigid), ...
                "selectedRigidCost",0.5*(selectedRigid.'*selectedRigid), ...
                "nominalFlexibleCost",0.5*(nominalFlexible.'*nominalFlexible), ...
                "selectedFlexibleCost",0.5*(selectedFlexible.'*selectedFlexible), ...
                "candidateRates",candidateRates, ...
                "selectedRates",selectedRates, ...
                "responseJacobianCondition",cond(responseJacobian), ...
                "rigidJacobianCondition",cond(scaledRigidJacobian), ...
                "dedicatedRigidCommand",rigidCommand, ...
                "fallbackWingOnly",~secondaryAccepted)), ...
                "priority",struct("enabled",true,"stageOne", ...
                "rigid_trajectory","stageTwo", ...
                "nmpc_candidate_proximity"), ...
                "solverSeconds",toc(solveTimer));
            obj.lastPrediction = obj.firstIntervalPrediction( ...
                selected,package,timeSeconds,secondaryAccepted);
            obj.lastPrediction.initialFlexibleStateErrorInfinity = ...
                norm(xFlexible(:)-plant.xFlex(:),inf);
        end

        function [appliedEndpointTarget,info] = computeDynamicNullspaceWing( ...
                obj,plant,package,fusion,actuator,controller,xFlexible, ...
                uPrevious,uOuter,rigidCommand,rigidReference,gustHorizon, ...
                timeSeconds,nmpcCandidateHorizon)
        %COMPUTEDYNAMICNULLSPACEWING Preserve the complete outer baseline.
        %   This source-bound audit computes a symmetric wing correction in
        %   the numerical null space of the finite-horizon rigid-output map.
        %   Unlike COMPUTELEXICOGRAPHIC, its primary residual is the change
        %   from the matched outer-wing/tail/thrust trajectory, never the
        %   departure of that nominal trajectory from guidance.
            assert(obj.dynamicNullspaceWingOnlyEnabled && obj.nInterval == 10 && ...
                ~obj.fullChannelLexicographicEnabled, ...
                "CoupledRtiAllocatorAudit:DynamicNullspaceMode", ...
                "The dynamic-nullspace method requires its explicit wing-only mode.");
            solveTimer = tic;
            obj.callCount = obj.callCount + 1;
            gustHorizon = obj.normalizeGustHorizon(gustHorizon);
            obj.validateRuntime(plant,fusion,actuator,controller,xFlexible, ...
                uPrevious,uOuter,rigidCommand,rigidReference,gustHorizon,timeSeconds);
            nSurface = obj.cfg.ctrl.n_surf;
            assert(size(nmpcCandidateHorizon,1) == 2*nSurface && ...
                size(nmpcCandidateHorizon,2) >= obj.nInterval && ...
                all(isfinite(nmpcCandidateHorizon(:,1:obj.nInterval)),"all"), ...
                "CoupledRtiAllocatorAudit:DynamicNullspaceCandidate", ...
                "The dynamic-nullspace audit requires a finite nMPC horizon.");
            nominalRates = zeros(nSurface,obj.nInterval);
            [~,nominal] = obj.rollout(plant,package,fusion,actuator,xFlexible, ...
                uPrevious,uOuter,rigidCommand,gustHorizon,nominalRates);
            selectedDetail = nominal;
            [nominalFlexible,nominalRigid] = obj.residuals(controller,nominal, ...
                struct(),rigidReference,obj.nInterval);
            nDecision = obj.nInterval;
            rateScale = min(abs([actuator.rateL(:),actuator.rateU(:)]),[],2);
            assert(norm(rateScale-rateScale(1),inf) <= 100*eps(max(rateScale)), ...
                "CoupledRtiAllocatorAudit:DynamicNullspaceSymmetricRate", ...
                "The symmetric wing rate limits are inconsistent.");
            responseJacobian = zeros(numel(nominalRigid),nDecision);
            flexibleJacobian = zeros(numel(nominalFlexible),nDecision);
            step = obj.finiteDifferenceStep;
            for decisionIndex = 1:nDecision
                plusRates = nominalRates; minusRates = nominalRates;
                plusRates(:,decisionIndex) = plusRates(:,decisionIndex) + step*rateScale(1);
                minusRates(:,decisionIndex) = minusRates(:,decisionIndex) - step*rateScale(1);
                [~,plus] = obj.rollout(plant,package,fusion,actuator,xFlexible, ...
                    uPrevious,uOuter,rigidCommand,gustHorizon,plusRates);
                [~,minus] = obj.rollout(plant,package,fusion,actuator,xFlexible, ...
                    uPrevious,uOuter,rigidCommand,gustHorizon,minusRates);
                [plusFlexible,plusRigid] = obj.residuals(controller,plus, ...
                    struct(),rigidReference,obj.nInterval);
                [minusFlexible,minusRigid] = obj.residuals(controller,minus, ...
                    struct(),rigidReference,obj.nInterval);
                responseJacobian(:,decisionIndex) = (plusRigid-minusRigid)/(2*step);
                flexibleJacobian(:,decisionIndex) = (plusFlexible-minusFlexible)/(2*step);
            end
            [~,singularValues,V] = svd(responseJacobian,"econ");
            singularValues = diag(singularValues);
            rankTolerance = max(size(responseJacobian))*eps(max([1;singularValues]));
            rigidRank = sum(singularValues > rankTolerance);
            nullBasis = V(:,rigidRank+1:end);
            if obj.baselineRelativeRigidTubeEnabled
                % The tube audit intentionally admits all symmetric-rate
                % directions, then accepts only nonlinear replays whose
                % rigid RMS remains within a declared baseline-relative tube.
                nullBasis = eye(nDecision);
            end
            candidateRates = mean(nmpcCandidateHorizon(nSurface+(1:nSurface), ...
                1:obj.nInterval),1).'/rateScale(1);
            selectedRates = nominalRates;
            accepted = false; exitflag = 0; solverOutput = struct();
            tubeFractionsPassed = zeros(0,1);
            primaryValue = nan; primaryExitflag = nan; hardChecks = ...
                obj.lexicographicHardChecks(plant.trimThrust+rigidCommand.thrust,nominal);
            rigidGuard = obj.rigidPreservationCheck(nominal,nominal,rigidReference);
            if ~isempty(nullBasis)
                projectedFlexible = flexibleJacobian*nullBasis;
                hessian = projectedFlexible.'*projectedFlexible;
                hessian = 0.5*(hessian+hessian.') + 1e-12*eye(size(hessian));
                gradient = projectedFlexible.'*nominalFlexible;
                objective = @(z) 0.5*z.'*hessian*z + gradient.'*z;
                bounds = ones(size(nullBasis,2),1);
                options = optimoptions("fmincon","Algorithm","sqp", ...
                    "Display","none","MaxIterations",50, ...
                    "OptimalityTolerance",1e-8,"ConstraintTolerance",1e-9);
                [z,primaryValue,primaryExitflag,solverOutput] = fmincon( ...
                    objective,zeros(size(bounds)),[],[],[],[],-bounds,bounds,[],options);
                primaryTolerance = max(100*options.ConstraintTolerance, ...
                    256*eps(max(1,abs(primaryValue))));
                if primaryExitflag > 0
                    secondaryObjective = @(value) 0.5*norm( ...
                        nullBasis*value-candidateRates)^2;
                    primaryConstraint = @(value) deal( ...
                        objective(value)-primaryValue-primaryTolerance,[]);
                    [z,~,secondaryExitflag,secondaryOutput] = fmincon( ...
                        secondaryObjective,z,[],[],[],[],-bounds,bounds, ...
                        primaryConstraint,options);
                    if secondaryExitflag <= 0
                        z = zeros(size(bounds));
                    end
                else
                    secondaryExitflag = nan; secondaryOutput = struct();
                end
                proposedNormalizedRates = nullBasis*z;
                proposedRates = repmat(rateScale(1)*proposedNormalizedRates.',nSurface,1);
                [~,candidate] = obj.rollout(plant,package,fusion,actuator, ...
                    xFlexible,uPrevious,uOuter,rigidCommand,gustHorizon,proposedRates);
                hardChecks = obj.lexicographicHardChecks( ...
                    plant.trimThrust+rigidCommand.thrust,candidate);
                rigidGuard = obj.rigidPreservationCheck(nominal,candidate,rigidReference);
                componentPass = all(structfun(@(entry) logical(entry.passed), ...
                    rigidGuard.components));
                tubeFractionsPassed = zeros(0,1);
                if obj.baselineRelativeRigidTubeEnabled
                    baseline = [nominal.uBody(:),nominal.wBody(:), ...
                        nominal.theta(:),nominal.pitchRate(:)];
                    replay = [candidate.uBody(:),candidate.wBody(:), ...
                        candidate.theta(:),candidate.pitchRate(:)];
                    baselineRms = sqrt(mean(baseline.^2,1));
                    replayRms = sqrt(mean(replay.^2,1));
                    tubeFractionsPassed = obj.baselineRelativeRigidTubeFractions( ...
                        arrayfun(@(fraction) all(replayRms <= ...
                        (1+fraction)*baselineRms + 100*eps(max([1,baselineRms]))), ...
                        obj.baselineRelativeRigidTubeFractions));
                    componentPass = ~isempty(tubeFractionsPassed);
                end
                accepted = primaryExitflag > 0 && all(structfun(@logical,hardChecks)) && ...
                    componentPass;
                if accepted
                    selectedRates = proposedRates;
                    selectedDetail = candidate;
                    appliedEndpointTarget = candidate.endpoint(:,1);
                    exitflag = 1;
                end
            end
            if ~accepted
                appliedEndpointTarget = uPrevious(:);
            end
            obj.warmRates = selectedRates;
            obj.initialized = accepted;
            obj.lastPrediction = obj.firstIntervalPrediction( ...
                selectedDetail,package,timeSeconds,accepted);
            obj.lastPrediction.initialFlexibleStateErrorInfinity = ...
                norm(xFlexible(:)-plant.xFlex(:),inf);
            info = struct("accepted",accepted,"solveAttempted",true, ...
                "exitflag",exitflag,"solverSeconds",toc(solveTimer), ...
                "uHorizon",obj.padHorizon([appliedEndpointTarget, ...
                repmat(appliedEndpointTarget,1,obj.nInterval-1)], ...
                appliedEndpointTarget,controller.Nc),"continuity",0, ...
                "output",struct("iterations",safeField(solverOutput, ...
                "iterations",nan),"auditCapture",struct( ...
                "schemaVersion","phase18c-v17a-dynamic-nullspace-wing-only-v1", ...
                "rigidRank",rigidRank, ...
                "exactNullity",nDecision-rigidRank, ...
                "activeDecisionDimension",size(nullBasis,2), ...
                "rankTolerance",rankTolerance,"singularValues",singularValues, ...
                "primaryExitflag",primaryExitflag,"primaryValue",primaryValue, ...
                "secondaryExitflag",secondaryExitflag, ...
                "secondaryIterations",safeField(secondaryOutput,"iterations",nan), ...
                "candidateSymmetricRates",candidateRates, ...
                "selectedRates",selectedRates,"hardChecks",hardChecks, ...
                "tubeFractionsPassed",tubeFractionsPassed, ...
                "rigidBaselineCost",0.5*(nominalRigid.'*nominalRigid), ...
                "rigidPreservation",rigidGuard,"fallbackWingOnly",~accepted)));
        end

        function realized = recordRealized(obj,plant,actualTrajectory)
        %RECORDREALIZED Compare the last first-interval prediction to runtime.
            if nargin < 3
                actualTrajectory = struct();
            end
            if ~isfield(obj.lastPrediction,"valid") || ...
                    ~obj.lastPrediction.valid
                realized = struct("valid",false);
                obj.lastRealized = realized;
                return
            end
            prediction = obj.lastPrediction;
            actualRigid = obj.rigidState(plant.rb);
            actualTip = obj.tipValue(plant.xFlex,prediction.tip);
            realized = struct( ...
                "valid",true,"timeSeconds",plant.t, ...
                "initialFlexibleStateErrorInfinity", ...
                    prediction.initialFlexibleStateErrorInfinity, ...
                "flexibleStateInfinity",norm(plant.xFlex- ...
                    prediction.flexible,inf), ...
                "rigidStateInfinity",norm(actualRigid-prediction.rigid,inf), ...
                "flexibleStateDifference",plant.xFlex- ...
                    prediction.flexible, ...
                "rigidStateDifference",actualRigid-prediction.rigid, ...
                "speedAbsolute",abs(norm(plant.rb.v_B)- ...
                    prediction.speed), ...
                "pitchRateAbsolute",abs(plant.rb.omega_B(2)- ...
                    prediction.pitchRate), ...
                "wingtipAbsolute",abs(actualTip-prediction.wingtip), ...
                "centeredFzAbsolute",abs(plant.last.Clamp6(3)- ...
                    prediction.clampFz), ...
                "centeredMyAbsolute",abs(plant.last.Clamp6(5)- ...
                    prediction.clampMy), ...
                "totalFzAbsolute",abs(plant.last.Ftot_B(3)- ...
                    prediction.totalFz), ...
                "totalMyAbsolute",abs(plant.last.Mtot_B(2)- ...
                    prediction.totalMy));
            predictedTrajectory = safeField(prediction,"trajectory",struct());
            names = ["wingtip","clampFz","clampMy","totalFz", ...
                "totalMy","speed","pitchRate"];
            for name = names
                field = char(name+"TrajectoryInfinity");
                if isfield(actualTrajectory,name) && ...
                        isfield(predictedTrajectory,name)
