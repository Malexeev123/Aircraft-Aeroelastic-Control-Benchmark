        function [A,b,info] = removeTrustBoxRedundantRows(~,A,b)
        %REMOVETRUSTBOXREDUNDANTROWS Remove rows implied by the trust box.
            nDecision = size(A,2);
            nTrustRows = 2*nDecision;
            bound = b(1);
            assert(size(A,1)>=nTrustRows && isfinite(bound) && bound>0 && ...
                norm(A(1:nDecision,:)-eye(nDecision),inf)==0 && ...
                norm(A(nDecision+(1:nDecision),:)+eye(nDecision),inf)==0 && ...
                all(b(1:nTrustRows)==bound), ...
                "CoupledRtiAllocatorAudit:GuardedTrustBox", ...
                "The guarded QCQP does not begin with its exact trust box.");
            remove = false(size(b));
            rows = (nTrustRows+1:numel(b)).';
            remove(rows) = bound*sum(abs(A(rows,:)),2)<=b(rows);
            info = struct("removed",nnz(remove),"retained",nnz(~remove));
            A = A(~remove,:);
            b = b(~remove);
        end

        function [A,b,capture,data] = objectiveNondegradationConstraints( ...
