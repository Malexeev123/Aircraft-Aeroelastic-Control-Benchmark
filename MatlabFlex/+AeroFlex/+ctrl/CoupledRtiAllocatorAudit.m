                    ~isempty(ownerReciprocal.hiddenState) && ...
                    all(isfinite(ownerReciprocal.hiddenState(:))) && ...
                    isfield(ownerReciprocal,"candidate") && ...
                    isstruct(ownerReciprocal.candidate), ...
