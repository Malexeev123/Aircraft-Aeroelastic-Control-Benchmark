        function checks = replayChecks(obj,totalThrust,nominal,candidate, ...
                nominalFlexible,nominalRigid,candidateFlexible, ...
                candidateRigid,reference,limits,rigidReference,requireImprovement)
            nominalFlexibleCost = 0.5*(nominalFlexible.'*nominalFlexible);
            nominalRigidCost = 0.5*(nominalRigid.'*nominalRigid);
            candidateFlexibleCost = ...
                0.5*(candidateFlexible.'*candidateFlexible);
            candidateRigidCost = 0.5*(candidateRigid.'*candidateRigid);
            outputPass = true;
            protectedNames = ["wingtip","clampFz","clampMy"];
            if ~isempty(fieldnames(limits.robustEnvelope))
                protectedNames = [protectedNames,"totalFz","totalMy", ...
                    "pitchRate"];
            end
            for name = protectedNames
                if isfield(limits.(name),"absoluteLimit")
                    outputPass = outputPass && max(abs(candidate.(name))) <= ...
                        limits.(name).absoluteLimit + ...
                        100*eps(max(1,limits.(name).absoluteLimit));
                else
                    departure = max(abs(candidate.(name)-reference.(name)));
                    outputPass = outputPass && departure <= ...
                        limits.(name).departureLimit+ ...
                        100*eps(max(1,departure));
                end
            end
            outputPass = outputPass && ...
                all(candidate.speed >= limits.speed.lower- ...
                    limits.speed.tolerance) && ...
                all(candidate.speed <= limits.speed.upper+ ...
                    limits.speed.tolerance);
            rigidImproved = true; combinedImproved = true;
            flexiblePrimaryGuard = true;
            robustProtectedOutputImproved = true;
            robustSpeed = true;
            physicalOutputImproved = true;
            physicalOutputNondegradation = true;
            sourceRootQualified = true;
            rigidPreservation = obj.rigidPreservationCheck( ...
                nominal,candidate,rigidReference);
            if requireImprovement
                if obj.sourceNormalizedPhysicalOutputObjectiveEnabled
                    nominalPhysical = obj.sourceNormalizedPhysicalResidual( ...
                        nominal,reference);
                    candidatePhysical = obj.sourceNormalizedPhysicalResidual( ...
                        candidate,reference);
                    nominalPhysicalCost = 0.5*(nominalPhysical.'*nominalPhysical);
                    candidatePhysicalCost = 0.5*(candidatePhysical.'*candidatePhysical);
                    physicalTolerance = 256*eps(max(1,nominalPhysicalCost));
                    rigidTolerance = 256*eps(max(1,nominalRigidCost));
                    rigidImproved = candidateRigidCost <= ...
                        nominalRigidCost+rigidTolerance;
                    combinedImproved = candidatePhysicalCost < ...
                        nominalPhysicalCost-physicalTolerance;
                    physicalOutputImproved = combinedImproved;
                    nominalMetrics = obj.physicalOutputMetrics( ...
                        nominal,reference.wingtip);
                    candidateMetrics = obj.physicalOutputMetrics( ...
                        candidate,reference.wingtip);
                    metricNames = string(fieldnames(nominalMetrics));
                    for metricName = metricNames.'
                        tolerance = 256*eps(max(1, ...
                            nominalMetrics.(metricName)));
                        physicalOutputNondegradation = ...
                            physicalOutputNondegradation && ...
                            candidateMetrics.(metricName) <= ...
                            nominalMetrics.(metricName)+tolerance;
                    end
                    sourceRootQualified = nominal.sourceRootQualified && ...
                        candidate.sourceRootQualified;
                else
                    rigidImproved = candidateRigidCost < nominalRigidCost;
                    combinedImproved = candidateFlexibleCost+ ...
                        candidateRigidCost < nominalFlexibleCost+nominalRigidCost;
                end
                % The coupled predictor has a joint rigid-flexible objective.
                % Its physical flexible outputs remain hard constrained above;
                % do not recast a weighted flexible cost as a per-sample hard
                % veto when the coupled objective is reduced.
                flexiblePrimaryGuard = obj.coupledNmpcPredictorEnabled || ...
                    candidateFlexibleCost <= 1.001*nominalFlexibleCost+1e-12;
                if ~isempty(fieldnames(limits.robustEnvelope))
                    for name = ["clampFz","clampMy","totalFz", ...
                            "totalMy","pitchRate"]
                        nominalPeak = max(abs( ...
                            nominal.(name)-reference.(name)));
                        candidatePeak = max(abs( ...
                            candidate.(name)-reference.(name)));
                        margin = limits.robustEnvelope.(name);
                        robustProtectedOutputImproved = ...
                            robustProtectedOutputImproved && ...
                            candidatePeak+margin <= nominalPeak;
                    end
                    margin = limits.robustEnvelope.speed;
                    nominalInside = all(nominal.speed >= ...
                        limits.speed.corridorLower+margin) && ...
                        all(nominal.speed <= ...
                        limits.speed.corridorUpper-margin);
                    if nominalInside
                        robustSpeed = all(candidate.speed >= ...
                            limits.speed.corridorLower+margin) && ...
                            all(candidate.speed <= ...
                            limits.speed.corridorUpper-margin);
                    else
                        robustSpeed = max(abs(candidate.speed- ...
                            mean([limits.speed.corridorLower, ...
                            limits.speed.corridorUpper]))) <= ...
                            max(abs(nominal.speed-mean([ ...
                            limits.speed.corridorLower, ...
                            limits.speed.corridorUpper])));
                    end
                end
            end
            checks = struct( ...
                "finite",all(isfinite([candidate.flexibleNodes(:); ...
                    candidate.rigidNodes(:);candidate.endpoint(:); ...
                    candidate.wingtip;candidate.clampFz;candidate.clampMy; ...
                    candidate.totalFz;candidate.totalMy;candidate.speed; ...
                    candidate.pitchRate])), ...
                "endpointEquality",candidate.maximumEndpointEquality <= 1e-12, ...
                "fusionInverse",candidate.maximumFusionInverseError <= 1e-12, ...
                "actuatorBounds",candidate.minimumActuatorMargin >= 0, ...
                "nonnegativeThrust",totalThrust >= 0, ...
                "outputEnvelope",outputPass, ...
                "flexiblePrimaryGuard",flexiblePrimaryGuard, ...
                "robustProtectedOutputImproved", ...
                    robustProtectedOutputImproved, ...
                "robustSpeed",robustSpeed, ...
                "rigidPreservation",rigidPreservation.passed, ...
                "sourceRootQualified",sourceRootQualified, ...
                "physicalOutputImproved",physicalOutputImproved, ...
                "physicalOutputNondegradation", ...
                    physicalOutputNondegradation, ...
                "rigidTrackingImproved",rigidImproved, ...
                "combinedObjectiveImproved",combinedImproved);
        end

        function guard = rigidPreservationCheck(obj,nominal,candidate, ...
                rigidReference)
        %RIGIDPRESERVATIONCHECK Compare a correction with outer-only replay.
        % The audit baseline is zero inner-wing rate correction.  Tolerances
        % are machine-scale numerical allowances, never fitted tracking slack.
            rigidReference = rigidReference(:);
            names = ["u","w","theta","pitchRate"];
            reference = [rigidReference(1),rigidReference(3), ...
                rigidReference(5),rigidReference(8)];
            baseline = {nominal.uBody-reference(1), ...
                nominal.wBody-reference(2), ...
                obj.angleDifference(nominal.theta,reference(3)), ...
                nominal.pitchRate-reference(4)};
            candidateDeparture = {candidate.uBody-reference(1), ...
                candidate.wBody-reference(2), ...
                obj.angleDifference(candidate.theta,reference(3)), ...
                candidate.pitchRate-reference(4)};
            values = struct();
            passed = true;
            for index = 1:numel(names)
                name = names(index);
                baselineDeparture = baseline{index}(:);
                trialDeparture = candidateDeparture{index}(:);
                scale = max([1;abs(baselineDeparture); ...
                    abs(reference(index))]);
                tolerance = 128*eps(scale);
                values.(name) = struct( ...
                    "baselinePeak",max(abs(baselineDeparture)), ...
                    "candidatePeak",max(abs(trialDeparture)), ...
                    "tolerance",tolerance, ...
                    "passed",all(abs(trialDeparture) <= ...
                    abs(baselineDeparture)+tolerance));
                passed = passed && values.(name).passed;
            end
            alphaReference = atan2(reference(2),reference(1));
            alphaBaseline = obj.angleDifference( ...
                atan2(nominal.wBody,nominal.uBody),alphaReference);
            alphaCandidate = obj.angleDifference( ...
                atan2(candidate.wBody,candidate.uBody),alphaReference);
            alphaScale = max([1;abs(alphaBaseline(:));abs(alphaReference)]);
            values.alphaBody = struct( ...
                "baselinePeak",max(abs(alphaBaseline)), ...
                "candidatePeak",max(abs(alphaCandidate)), ...
                "tolerance",128*eps(alphaScale), ...
                "passed",all(abs(alphaCandidate) <= ...
                abs(alphaBaseline)+128*eps(alphaScale)));
            guard = struct("enabled",obj.rigidPreservationGuardEnabled, ...
                "baseline","outer_only_zero_inner_rate", ...
                "passed",~obj.rigidPreservationGuardEnabled || passed, ...
                "components",values);
        end

