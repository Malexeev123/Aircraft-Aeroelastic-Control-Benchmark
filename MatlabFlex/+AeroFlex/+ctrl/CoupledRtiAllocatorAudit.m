        function endpointTargets = fullChannelJointEndpointTargets(obj, ...
                nmpcCandidateHorizon,uPrevious,innerRateCorrection,nPreview)
        %FULLCHANNELJOINTENDPOINTTARGETS Expand runtime nMPC targets at 100 Hz.
            nSurface = obj.cfg.ctrl.n_surf;
            innerSteps = round(obj.cfg.ctrl.outerTs/obj.cfg.ctrl.Ts);
            assert(isequal(size(nmpcCandidateHorizon,1),2*nSurface) && ...
                all(isfinite(nmpcCandidateHorizon),'all') && ...
                numel(uPrevious)==2*nSurface && ...
                numel(innerRateCorrection)==obj.nInterval && ...
                nPreview>=obj.nInterval, ...
                'CoupledRtiAllocatorAudit:JointEndpointTargets', ...
                'The joint coordinator requires finite native nMPC endpoint targets.');
            nStep = nPreview*innerSteps;
            endpointTargets = zeros(2*nSurface,nStep);
            cumulativePositionCorrection = 0;
            for stepIndex = 1:nStep
                sourceIndex = min(stepIndex,size(nmpcCandidateHorizon,2));
                outerInterval = min(ceil(stepIndex/innerSteps),obj.nInterval);
                rateCorrection = innerRateCorrection(outerInterval);
                cumulativePositionCorrection = cumulativePositionCorrection + ...
                    obj.cfg.ctrl.Ts*rateCorrection;
                endpointTargets(:,stepIndex) = nmpcCandidateHorizon(:,sourceIndex);
                endpointTargets(1:nSurface,stepIndex) = ...
                    endpointTargets(1:nSurface,stepIndex) + cumulativePositionCorrection;
                endpointTargets(nSurface+(1:nSurface),stepIndex) = ...
                    endpointTargets(nSurface+(1:nSurface),stepIndex) + rateCorrection;
            end
        end

        function [A,b,diagnostic] = fullChannelConstraints(obj,actuator,plant,nominal, ...
                responseJacobian,scale,nominalRates,nominalCommands, ...
                trustRegionBound,outputReference)
        %FULLCHANNELCONSTRAINTS Linearized hard physical constraints.
            n = obj.nInterval; nSurface = obj.cfg.ctrl.n_surf;
            nPreview = size(nominal.endpoint,2);
            assert(nPreview == obj.fullChannelPreviewIntervals(), ...
                "CoupledRtiAllocatorAudit:FeasibilityTailPreview", ...
                "The full-channel candidate does not span the declared preview.");
            decisionIndices = obj.fullChannelDecisionIndices();
            nDecision = numel(decisionIndices);
            assert(isequal(size(responseJacobian,2),nDecision), ...
                "CoupledRtiAllocatorAudit:FullChannelJacobian", ...
                "The full-channel response Jacobian is invalid.");
            assert(isscalar(trustRegionBound) && isfinite(trustRegionBound) && ...
                any(trustRegionBound == [0.25,0.50,0.75,1.00]), ...
                "CoupledRtiAllocatorAudit:FullChannelTrustRegion", ...
                "The full-channel trust-region bound is not approved.");
            % Keep each SQP correction inside the declared local trust region.
            A = [eye(nDecision);-eye(nDecision)];
            b = trustRegionBound*ones(2*nDecision,1);
            labels = ["trust_upper_"+string((1:nDecision).'); ...
                "trust_lower_"+string((1:nDecision).')];
            % The nonlinear actuator rollout is the authoritative realization,
            % but its linearized endpoint rows constrain the SQP candidate too.
            endpointRows = reshape(nominal.layout.endpoint,2*nSurface,nPreview);
            for interval = 1:nPreview
                for channel = 1:2*nSurface
                    row = responseJacobian(endpointRows(channel,interval),:);
                    if channel<=nSurface
                        lower = actuator.deltaL(channel); upper = actuator.deltaU(channel);
                    else
                        j = channel-nSurface;
                        lower = actuator.rateL(j); upper = actuator.rateU(j);
                    end
                    value = nominal.endpoint(channel,interval);
                    A = [A;row;-row]; %#ok<AGROW>
                    b = [b;upper-value;value-lower]; %#ok<AGROW>
                    labels = [labels; ... %#ok<AGROW>
                        "endpoint_upper_"+string(channel)+"_"+string(interval); ...
                        "endpoint_lower_"+string(channel)+"_"+string(interval)];
                end
            end
            % The active rigid interface has trim-relative elevator and thrust
            % bounds, but no separate tail/thrust servo state to invent here.
            uMax = obj.cfg.outerLQR.uMax(:);
            rigidNames = ["delta_e","thrust"];
            rigidIndices = [1,4];
            nCoordinate = 3 + double(obj.jointSharedSurfaceSafetyCoordinationEnabled);
            rigidRows = (nCoordinate-1):nCoordinate;
            for interval = 1:n
                for rigidIndex = 1:2
                    rowIndex = rigidRows(rigidIndex);
                    index = nCoordinate*(interval-1)+rowIndex;
                    value = nominalCommands(interval).(rigidNames(rigidIndex));
                    lower = -uMax(rigidIndices(rigidIndex));
                    upper = uMax(rigidIndices(rigidIndex));
                    if rowIndex==3
                        lower = max(lower,-plant.trimThrust);
                    end
                    row = zeros(1,nDecision);
                    activeIndex = find(decisionIndices==index,1);
                    if ~isempty(activeIndex)
                        row(activeIndex) = scale(activeIndex);
                    end
                    A = [A;row;-row]; %#ok<AGROW>
                    b = [b;upper-value;value-lower]; %#ok<AGROW>
                    labels = [labels; ... %#ok<AGROW>
                        "rigid_upper_"+rigidNames(rigidIndex)+"_"+string(interval); ...
                        "rigid_lower_"+rigidNames(rigidIndex)+"_"+string(interval)];
                end
            end
            absolute = struct("wingtip",0.009656201218759807, ...
                "clampFz",1.464539133337300,"clampMy",345.88503202222086);
            for name = string(fieldnames(absolute)).'
                field = char(name); value = nominal.(field);
                row = responseJacobian(nominal.layout.(field),:);
                limit = absolute.(field);
                if obj.sourceRootCondensedMultiInputCoordinationEnabled && ...
                        name=="wingtip"
                    assert(isstruct(outputReference) && ...
                        isfield(outputReference,"wingtip") && ...
                        isfinite(outputReference.wingtip), ...
                        "CoupledRtiAllocatorAudit:SourceRootWingtipReference", ...
                        ['The source-root discriminator requires the ', ...
                         'package-owned trim-relative wingtip reference.']);
                    value = value-outputReference.wingtip;
                end
                A = [A;row;-row]; %#ok<AGROW>
                b = [b;limit-value;limit+value]; %#ok<AGROW>
                labels = [labels; ... %#ok<AGROW>
                    "absolute_upper_"+name+"_"+string((1:numel(value)).'); ...
                    "absolute_lower_"+name+"_"+string((1:numel(value)).')];
            end
            assert(numel(labels)==numel(b), ...
                "CoupledRtiAllocatorAudit:FullChannelConstraintLabels", ...
                "The full-channel constraint labels are inconsistent.");
            [minimumZeroStepSlack,index] = min(b);
            diagnostic = struct("minimumZeroStepSlack",minimumZeroStepSlack, ...
                "minimumZeroStepSlackLabel",labels(index), ...
                "zeroStepViolationInfinity",max(0,-minimumZeroStepSlack));
        end

