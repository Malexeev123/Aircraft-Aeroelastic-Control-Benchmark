        function [flexible,rigid] = residuals( ...
                obj,controller,detail,~,rigidReference,costIntervalCount)
            if nargin < 6 || isempty(costIntervalCount)
                costIntervalCount = size(detail.endpoint,2);
            end
            n = double(costIntervalCount);
            assert(isscalar(n) && n >= 1 && n <= size(detail.endpoint,2) && ...
                n == round(n),"CoupledRtiAllocatorAudit:ResidualHorizon", ...
                "The residual cost horizon is invalid.");
            qFactor = obj.psdFactor(controller.Qc,"Qc");
            rFactor = obj.psdFactor(controller.Rc,"Rc");
            pFactor = obj.psdFactor(controller.Pc,"Pc");
            xNodes = [detail.initialFlexible,detail.flexibleNodes];
            blocks = cell(2*n+1,1);
            for interval = 1:n
                blocks{2*interval-1} = qFactor*( ...
                    xNodes(:,interval)-controller.xTrim(:));
                blocks{2*interval} = rFactor*( ...
                    detail.endpoint(:,interval)-detail.uBase(:,interval));
            end
            blocks{end} = pFactor*( ...
                xNodes(:,end)-controller.xTrim(:));
            flexible = vertcat(blocks{:});
            if controller.wingtipOutputCostEnabled
                referenceTip = obj.tipValue(controller.xTrim(:),detail.tip);
                tipResidual = zeros(n+1,1);
                for interval = 1:n
                    tipResidual(interval) = sqrt( ...
                        controller.wingtipOutputCostStageWeight)*( ...
                        obj.tipValue(xNodes(:,interval),detail.tip)-referenceTip);
                end
                tipResidual(end) = sqrt( ...
                    controller.wingtipOutputCostTerminalWeight)*( ...
                    obj.tipValue(xNodes(:,end),detail.tip)-referenceTip);
                flexible = [flexible;tipResidual];
            end
            rigidReference = rigidReference(:);
            scales = obj.rigidResidualScales();
            uReference = rigidReference(1);
            wReference = rigidReference(3);
            thetaReference = rigidReference(5);
            qReference = rigidReference(8);
            substepsPerInterval = numel(detail.timeSeconds)/size(detail.endpoint,2);
            rigidStepCount = n*substepsPerInterval;
            assert(rigidStepCount == round(rigidStepCount), ...
                "CoupledRtiAllocatorAudit:ResidualCadence", ...
                "The residual cost horizon has inconsistent substeps.");
            rigidStepCount = round(rigidStepCount);
            rigid = [(detail.uBody(1:rigidStepCount)-uReference)/scales.u; ...
                (detail.wBody(1:rigidStepCount)-wReference)/scales.w; ...
                obj.angleDifference(detail.theta(1:rigidStepCount),thetaReference)/scales.theta; ...
                (detail.pitchRate(1:rigidStepCount)-qReference)/scales.pitchRate];
            rigid = rigid/sqrt(numel(detail.timeSeconds));
        end

        function factor = psdFactor(~,matrix,name)
            matrix = full(0.5*(matrix+matrix.'));
            [vectors,values] = eig(matrix,"vector");
            scale = max(1,max(abs(values)));
            assert(min(values) >= -1e-10*scale, ...
                "CoupledRtiAllocatorAudit:Weight", ...
                "%s is not positive semidefinite within tolerance.",name);
            values = max(values,0);
            keep = values > 1e-14*scale;
            factor = diag(sqrt(values(keep)))*vectors(:,keep).';
        end

        function [response,detail] = rollout(obj,plantOwner,package, ...
                fusionOwner,actuatorOwner,xInitial,uPrevious,uOuter, ...
                rigidCommand,gustHorizon,rates,rawInnerHorizon,endpointTargetHorizon)
            if nargin < 12
                rawInnerHorizon = [];
            end
            if nargin < 13
                endpointTargetHorizon = [];
            end
            [plant,fusion,actuator,tip] = obj.cloneRuntime( ...
                plantOwner,package,fusionOwner,actuatorOwner,xInitial);
            nSurface = obj.cfg.ctrl.n_surf;
            n = size(rates,2);
            rigidCommands = obj.normalizeRigidCommandSequence(rigidCommand,n);
            Ts = obj.cfg.ctrl.Ts;
            if obj.fullChannelLexicographicEnabled || ...
                    obj.nonlinearOuterReferenceGovernorEnabled
                % The approved full-channel decision is owned by the outer
                % 25 Hz cadence.  Ten intervals must cover 0.40 s, whereas
                % the three-interval wing-only audit retains the inner rate.
                Ts = obj.cfg.ctrl.outerTs;
            end
            assert(isfinite(Ts) && Ts > 0 && ...
                abs(Ts/plant.dt-round(Ts/plant.dt)) <= ...
                100*eps(max(1,Ts/plant.dt)), ...
                "CoupledRtiAllocatorAudit:PreviewCadence", ...
                "The allocator preview interval must be an integer plant-step count.");
            substeps = round(Ts/plant.dt);
            innerControlSteps = 1;
            plantStepsPerInnerControl = substeps;
            innerTs = Ts;
            if obj.fullChannelLexicographicEnabled || ...
                    obj.nonlinearOuterReferenceGovernorEnabled
                % Preserve the physical multirate runtime contract: fusion
                % and servo states advance at the inner controller cadence,
                % while each full-channel decision is held for one outer
                % interval.  Advancing the plant for 0.04 s but the servo only
                % once at 0.01 s breaks endpoint equality by construction.
                innerTs = obj.cfg.ctrl.Ts;
                innerControlSteps = round(Ts/innerTs);
                assert(innerControlSteps >= 1 && ...
                    abs(innerControlSteps*innerTs-Ts) <= ...
                    100*eps(max(1,Ts)), ...
                    "CoupledRtiAllocatorAudit:MultirateControlCadence", ...
                    "The full-channel interval must contain whole inner control steps.");
                plantStepsPerInnerControl = round(innerTs/plant.dt);
                assert(plantStepsPerInnerControl >= 1 && ...
                    abs(plantStepsPerInnerControl*plant.dt-innerTs) <= ...
                    100*eps(max(1,innerTs)), ...
                    "CoupledRtiAllocatorAudit:MultiratePlantCadence", ...
                    "The inner controller interval must contain whole plant steps.");
                assert(substeps == innerControlSteps*plantStepsPerInnerControl, ...
                    "CoupledRtiAllocatorAudit:MultirateSubsteps", ...
                    "The full-channel preview has inconsistent multirate substeps.");
            end
            nStep = n*substeps;
            if isvector(uOuter)
                uOuterSequence = repmat(uOuter(:),1,n);
            else
                assert(isequal(size(uOuter),[2*nSurface,n]) && ...
                    all(isfinite(uOuter),'all'), ...
                    'CoupledRtiAllocatorAudit:OuterReferenceSequence', ...
                    'The outer-reference sequence is invalid.');
                uOuterSequence = uOuter;
            end
            uBase = fusion.previewOuterBaseHorizon(uOuterSequence,n);
            jointEndpointSequence = [];
            if ~isempty(endpointTargetHorizon)
                assert(isnumeric(endpointTargetHorizon) && isreal(endpointTargetHorizon) && ...
                    size(endpointTargetHorizon,1)==2*nSurface && ...
                    size(endpointTargetHorizon,2)==n*innerControlSteps && ...
                    all(isfinite(endpointTargetHorizon),'all'), ...
                    'CoupledRtiAllocatorAudit:JointEndpointSequence', ...
                    'The joint coordinator endpoint sequence is invalid.');
                jointEndpointSequence = endpointTargetHorizon;
            end
            if isempty(rawInnerHorizon)
                % The zero-correction member must follow the runtime fusion
                % equation from its current filter state.  ``uBase`` is retained
                % as a diagnostic outer low-pass preview, but it is not itself an
                % actuator endpoint: its rate rows are zero and hence it cannot
                % be sent through the endpoint-inversion path without cancelling
                % the outer command.
                if fusion.innerIsDeviation
                    rawInnerBaseline = zeros(2*nSurface,1);
                else
                    rawInnerBaseline = fusion.uTrim(:);
                end
                rawInnerSequence = [];
            else
                assert(isnumeric(rawInnerHorizon) && isreal(rawInnerHorizon) && ...
                    all(isfinite(rawInnerHorizon),"all") && ...
                    size(rawInnerHorizon,1) == 2*nSurface && ...
                    any(size(rawInnerHorizon,2) == [1,n]), ...
                    "CoupledRtiAllocatorAudit:CapturedRawInner", ...
                    ['The captured raw inner command must have 2*nSurface ', ...
                     'rows and one or one-per-interval columns.']);
                rawInnerSequence = rawInnerHorizon;
                if size(rawInnerSequence,2) == 1
                    rawInnerSequence = repmat(rawInnerSequence,1,n);
                end
                rawInnerBaseline = zeros(2*nSurface,1);
            end
            innerDeflectionCorrection = zeros(nSurface,1);
            time = nan(nStep,1); wingtip = nan(nStep,1);
            clampFz = nan(nStep,1); clampMy = nan(nStep,1);
            sourceRootFz = nan(nStep,1); sourceRootMy = nan(nStep,1);
            sourceRootReferenceFz = nan(nStep,1);
            sourceRootReferenceMy = nan(nStep,1);
            sourceRootForceScale = nan(nStep,1);
            sourceRootMomentScale = nan(nStep,1);
            sourceRootQualified = true;
            totalFz = nan(nStep,1); totalMy = nan(nStep,1);
            uBody = nan(nStep,1); wBody = nan(nStep,1);
            theta = nan(nStep,1); pitchRate = nan(nStep,1);
            speed = nan(nStep,1);
            flexibleNodes = nan(plant.nx,n);
            rigidNodes = nan(12,n);
            endpoint = nan(2*nSurface,n);
            firstEndpoint = nan(2*nSurface,n);
            intervalCommand = nan(2*nSurface,n);
            endpointEquality = nan(1,n);
            fusionError = nan(1,n);
            previousEndpoint = uPrevious(:);
            minimumMargin = inf;
            stepIndex = 0;
            packageMu = nan(2,n);
            packagePointIds = cell(1,n);
            packageTransitions = cell(1,n);
            packageScheduleInfo = cell(1,n);
            tipNodes = cell(1,n);
            stateToReference = eye(plant.nx);
            stateToReferenceNodes = cell(1,n);
            for interval = 1:n
                if obj.futureScheduledPackageSequenceEnabled
                    if interval == 1
                        % The current package owns the first preview interval.
                        activePackage = package;
                        plant.controlSampleScheduleHoldStepsRemaining = substeps;
                        transition = struct("enabled",false, ...
                            "reason","current_package");
                        scheduleInfo = struct("controlSampleIndex", ...
                            plant.controlSampleIndex, ...
                            "requestedScheduleUInfMps",nan, ...
                            "composedScheduleUInfMps",nan, ...
                            "scheduleChanged",false, ...
                            "holdStepsRemaining",substeps);
                    else
                        [activePackage,scheduleInfo] = ...
                            plant.prepareControlSample(gustHorizon(:,interval), ...
                            intervalCommand(:,interval-1), ...
                            rigidCommands(interval),substeps);
                        transition = scheduleInfo.stateTransport;
                        if isstruct(transition) && ...
                                isfield(transition,"enabled") && ...
                                transition.enabled
                            assert(isfield(transition,"valid") && ...
                                transition.valid && isfield(transition,"transform") && ...
                                isequal(size(transition.transform), ...
                                [plant.nx,plant.nx]), ...
                                "CoupledRtiAllocatorAudit:FuturePackageChart", ...
                                ['A future package transition must provide a ', ...
                                 'qualified state-chart map.']);
                            stateToReference = stateToReference/ ...
                                transition.transform;
                        end
                    end
                    tip = obj.tipMap(activePackage,plant.beam);
                    packageMu(:,interval) = activePackage.mu(:);
                    if isfield(activePackage,"pointIds")
                        packagePointIds{interval} = activePackage.pointIds(:).';
                    else
                        packagePointIds{interval} = zeros(0,1);
                    end
                    packageTransitions{interval} = transition;
                    packageScheduleInfo{interval} = scheduleInfo;
                    tipNodes{interval} = tip;
                else
                    packageMu(:,interval) = package.mu(:);
                    if isfield(package,"pointIds")
                        packagePointIds{interval} = package.pointIds(:).';
                    else
                        packagePointIds{interval} = zeros(0,1);
                    end
                    packageTransitions{interval} = struct("enabled",false, ...
                        "reason","disabled");
                    packageScheduleInfo{interval} = struct( ...
                        "scheduleChanged",false);
                    tipNodes{interval} = tip;
                end
                endpointEqualityInterval = 0;
                for innerStep = 1:innerControlSteps
                    if ~isempty(jointEndpointSequence)
                        endpointIndex = (interval-1)*innerControlSteps+innerStep;
                        [rawInner,~] = fusion.rawInnerForApplied( ...
                            jointEndpointSequence(:,endpointIndex), ...
                            uOuterSequence(:,interval));
                    elseif isempty(rawInnerSequence)
                        innerDeflectionCorrection = innerDeflectionCorrection + ...
                            innerTs*rates(:,interval);
                        rawInner = rawInnerBaseline + [ ...
                            innerDeflectionCorrection;rates(:,interval)];
                    else
                        rawInner = rawInnerSequence(:,interval);
                    end
                    [fusedRequest,~] = fusion.fuse(uOuterSequence(:,interval),rawInner);
                    [endpoint(:,interval),~] = actuator.step(fusedRequest);
                    if innerStep == 1
                        firstEndpoint(:,interval) = endpoint(:,interval);
                    end
                    intervalCommand(:,interval) = endpoint(:,interval);
                    alpha = obj.cfg.ctrl.actuatorDeflectionAlpha;
                    intervalCommand(1:nSurface,interval) = ...
                        (1-alpha)*previousEndpoint(1:nSurface)+ ...
                        alpha*endpoint(1:nSurface,interval);
                    endpointEqualityInterval = max(endpointEqualityInterval,norm( ...
                        endpoint(1:nSurface,interval)- ...
                        previousEndpoint(1:nSurface)-innerTs* ...
                        endpoint(nSurface+1:end,interval),inf));
                    % The final runtime endpoint is independently verified by
                    % sim_run's inverse/forward fusion assertion.  This preview
                    % propagates the source fusion state directly, so no endpoint
                    % inversion is performed within the nonlinear rollout.
                    margin = min([actuator.delta-actuator.deltaL; ...
                        actuator.deltaU-actuator.delta; ...
                        actuator.deltaDot-actuator.rateL; ...
                        actuator.rateU-actuator.deltaDot]);
                    minimumMargin = min(minimumMargin,margin);
                    for plantStep = 1:plantStepsPerInnerControl
                        plant.stepCoupled(intervalCommand(:,interval), ...
                            gustHorizon(:,interval),rigidCommands(interval));
                        stepIndex = stepIndex+1;
                        time(stepIndex) = plant.t;
                        wingtip(stepIndex) = obj.tipValue(plant.xFlex,tip);
                        clampFz(stepIndex) = plant.last.Clamp6(3);
                        clampMy(stepIndex) = plant.last.Clamp6(5);
                        reciprocal = plant.last.reciprocalTangentCorrection;
                        qualified = isstruct(reciprocal) && ...
                            isfield(reciprocal,"loadOutputQualified") && ...
                            logical(reciprocal.loadOutputQualified) && ...
                            isfield(reciprocal,"sourceRootWrench") && ...
                            numel(reciprocal.sourceRootWrench) == 6 && ...
                            isfield(reciprocal,"rootLoadOwner") && ...
                            isstruct(plant.reciprocalTangentCorrection) && ...
                            isfield(plant.reciprocalTangentCorrection, ...
                                "sourceRootOutput") && ...
                            isfield(plant.reciprocalTangentCorrection. ...
                                sourceRootOutput,"equilibrium");
                        sourceRootQualified = sourceRootQualified && qualified;
                        if qualified
                            sourceWrench = double( ...
                                reciprocal.sourceRootWrench(:));
                            sourceReference = double(plant. ...
                                reciprocalTangentCorrection.sourceRootOutput. ...
                                equilibrium(:));
                            forceScale = norm(sourceReference(1:3),2);
                            momentScale = norm(sourceReference(4:6),2);
                            assert(all(isfinite([sourceWrench;sourceReference])) && ...
                                forceScale > 0 && momentScale > 0 && ...
                                string(reciprocal.rootLoadOwner) == ...
                                "source wing dynamic equilibrium at root cut", ...
                                "CoupledRtiAllocatorAudit:SourceRootOutputOwner", ...
                                ['The reciprocal source-root output or its ', ...
                                 'dimensional normalization is invalid.']);
                            sourceRootFz(stepIndex) = sourceWrench(3);
                            sourceRootMy(stepIndex) = sourceWrench(5);
                            sourceRootReferenceFz(stepIndex) = sourceReference(3);
                            sourceRootReferenceMy(stepIndex) = sourceReference(5);
                            sourceRootForceScale(stepIndex) = forceScale;
                            sourceRootMomentScale(stepIndex) = momentScale;
                        end
                        totalFz(stepIndex) = plant.last.Ftot_B(3);
                        totalMy(stepIndex) = plant.last.Mtot_B(2);
                        uBody(stepIndex) = plant.rb.v_B(1);
                        wBody(stepIndex) = plant.rb.v_B(3);
                        theta(stepIndex) = plant.rb.euler(2);
                        pitchRate(stepIndex) = plant.rb.omega_B(2);
                        speed(stepIndex) = norm(plant.rb.v_B);
                    end
                    previousEndpoint = endpoint(:,interval);
                end
                endpointEquality(interval) = endpointEqualityInterval;
                fusionError(interval) = 0;
                flexibleNodes(:,interval) = stateToReference*plant.xFlex;
                stateToReferenceNodes{interval} = stateToReference;
                rigidNodes(:,interval) = obj.rigidState(plant.rb);
            end
            wingCoordinates = double(tipNodes{1}.coordinates(:,2));
            wingtipScale = max(abs(wingCoordinates));
            assert(isfinite(wingtipScale) && wingtipScale > 0, ...
                "CoupledRtiAllocatorAudit:WingtipScale", ...
                "The package-owned semispan normalization is invalid.");
            if obj.sourceNormalizedPhysicalOutputObjectiveEnabled
                assert(sourceRootQualified && ...
                    all(isfinite([sourceRootFz;sourceRootMy; ...
                    sourceRootReferenceFz;sourceRootReferenceMy; ...
                    sourceRootForceScale;sourceRootMomentScale])), ...
                    "CoupledRtiAllocatorAudit:SourceRootOutputUnavailable", ...
                    ['The source-normalized objective requires a qualified ', ...
                     'source-root output at every preview substep.']);
            end
            response = [flexibleNodes(:);rigidNodes(:);endpoint(:); ...
                wingtip;clampFz;clampMy;totalFz;totalMy; ...
                uBody;wBody;theta;pitchRate;speed];
            if obj.sourceNormalizedPhysicalOutputObjectiveEnabled
                response = [response;sourceRootFz;sourceRootMy];
            end
            layout = obj.responseLayout(plant.nx,nSurface,n,nStep);
            if isempty(jointEndpointSequence)
                firstInnerEndpointTarget = firstEndpoint(:,1);
            else
                firstInnerEndpointTarget = jointEndpointSequence(:,1);
            end
            detail = struct("initialFlexible",xInitial(:), ...
                "timeSeconds",time,"wingtip",wingtip, ...
                "clampFz",clampFz,"clampMy",clampMy, ...
                "sourceRootFz",sourceRootFz, ...
                "sourceRootMy",sourceRootMy, ...
                "sourceRootReferenceFz",sourceRootReferenceFz, ...
                "sourceRootReferenceMy",sourceRootReferenceMy, ...
                "sourceRootForceScale",sourceRootForceScale, ...
                "sourceRootMomentScale",sourceRootMomentScale, ...
                "sourceRootQualified",sourceRootQualified, ...
                "sourceRootOwner", ...
                    "source wing dynamic equilibrium at root cut", ...
                "wingtipScale",wingtipScale, ...
                "normalizationOwner", ...
                    "active scheduled package equilibrium and beam semispan", ...
                "totalFz",totalFz,"totalMy",totalMy, ...
                "uBody",uBody,"wBody",wBody,"theta",theta, ...
                "pitchRate",pitchRate,"flexibleNodes",flexibleNodes, ...
                "speed",speed, ...
                "rigidNodes",rigidNodes,"endpoint",endpoint, ...
                "firstEndpoint",firstEndpoint, ...
                "rigidCommand",rigidCommands, ...
                "intervalCommand",intervalCommand,"rates",rates, ...
                "outerReference",uOuterSequence, ...
                "firstInnerEndpointTarget",firstInnerEndpointTarget, ...
                "uBase",uBase,"tip",tipNodes{1},"tipNodes",{tipNodes}, ...
                "futurePackageMu",packageMu, ...
                "futurePackagePointIds",{packagePointIds}, ...
                "futurePackageTransitions",{packageTransitions}, ...
                "futurePackageScheduleInfo",{packageScheduleInfo}, ...
                "futureStateToReference",{stateToReferenceNodes}, ...
                "futurePackageSequenceEnabled", ...
                obj.futureScheduledPackageSequenceEnabled,"layout",layout, ...
                "substepsPerInterval",substeps, ...
                "maximumEndpointEquality",max(endpointEquality), ...
                "maximumFusionInverseError",max(fusionError), ...
                "minimumActuatorMargin",minimumMargin);
        end

        function [plant,fusion,actuator,tip] = cloneRuntime( ...
                obj,owner,package,fusionOwner,actuatorOwner,xInitial)
            plant = AeroFlex.sim.PlantRunTime(owner.cfg,obj.beam, ...
                obj.aero,obj.base,owner.xFlex0,owner.trim);
            AeroFlex.sched.applyToPlant(plant,package);
            plant.debugCoupled = false;
