                [trial,~,exitflag,output] = quadprog( ...
                    0.5*(metric.hessian+metric.hessian.'), ...
                    metric.gradient,scaledA,scaledB,[],[],[],[], ...
                    selected,options);
                if ~isempty(trial) && all(isfinite(trial))
                    selected = trial;
                end
                violation = A*selected-b;
                add = obj.mostViolatedTrajectoryRows( ...
                    violation,working,128);
                working(add) = true;
                fullViolation = max([0;violation]);
                trace(pass) = struct("pass",pass, ...
                    "workingRows",nnz(working),"rowsAdded",numel(add), ...
                    "exitflag",exitflag,"iterations",safeField( ...
                    output,"iterations",nan), ...
                    "cost",obj.trajectoryMetricCost(metric,selected), ...
                    "fullViolation",fullViolation);
                if exitflag>0 && fullViolation<=1e-10
                    accepted = true;
                    break
                end
                if isempty(add), break, end
            end
            if ~accepted && exitflag>0 && all(isfinite(selected))
                feasibleInitial = initial(:);
                if max([0;A*feasibleInitial-b])>1e-10
                    [feasibleInitial,feasibilityRestoration] = ...
                        AeroFlex.ctrl.CoupledRtiAllocatorAudit. ...
                        restoreLinearFeasibility(A,b);
                end
                [polished,feasibilityPolish] = ...
                    obj.polishTrajectoryFeasibility( ...
                    selected,A,b,metric,feasibleInitial);
                if feasibilityPolish.accepted
                    selected = polished;
                    accepted = true;
                end
            end
            primaryCost = obj.trajectoryMetricCost(metric,selected);
            info = struct("attempted",true,"accepted",accepted, ...
                "algorithm","exact-working-set-quadprog", ...
                "maximumIterations",200,"exitflag",exitflag, ...
                "iterations",safeField(output,"iterations",nan), ...
                "constraintViolation",max([0;A*selected-b]), ...
                "primaryCost",primaryCost,"passes",pass, ...
                "workingRows",nnz(working),"trace",trace(1:pass), ...
                "linearRowsBefore",size(A,1)+reduction.removed, ...
                "linearRowsAfter",size(A,1), ...
                "exactRedundantRowsRemoved",reduction.removed, ...
                "feasibilityRestoration",feasibilityRestoration, ...
                "feasibilityPolish",feasibilityPolish, ...
                "solveSeconds",toc(solveTimer));
            if ~accepted
                selected = initial(:);
            end
        end

        function [selected,info] = polishTrajectoryFeasibility( ...
                obj,candidate,A,b,metric,feasibleInitial)
        %POLISHTRAJECTORYFEASIBILITY Project onto the complete unchanged rows.
            solveTimer = tic;
            tolerance = 1e-10;
            before = max([0;A*candidate-b]);
            selected = candidate;
            initialViolation = max([0;A*feasibleInitial-b]);
            if initialViolation>tolerance
                selected = feasibleInitial(:);
                info = struct('attempted',true,'accepted',false, ...
                    'exitflag',-6,'iterations',0, ...
                    'constraintViolationBefore',before, ...
                    'constraintViolationAfter',initialViolation, ...
                    'objectiveNondegraded',false, ...
                    'seedFeasible',false, ...
                    'disposition',"infeasible_seed_fail_closed", ...
                    'solveSeconds',toc(solveTimer));
                return
            end
            [scaledA,scaledB] = obj.scaleTrajectoryRows(A,b);
            options = optimoptions("quadprog","Display","none", ...
                "Algorithm","active-set","ConstraintTolerance",1e-12, ...
                "OptimalityTolerance",1e-12,"MaxIterations",500);
            [trial,~,exitflag,output] = quadprog( ...
                eye(numel(candidate)),-candidate,scaledA,scaledB, ...
                [],[],[],[],feasibleInitial,options);
            if ~isempty(trial) && all(isfinite(trial))
                selected = trial;
            end
            after = max([0;A*selected-b]);
            selectedCost = obj.trajectoryMetricCost(metric,selected);
            objectiveAllowance = 1e-10*max(1,abs(metric.nominalCost));
            objectiveNondegraded = selectedCost <= ...
                metric.nominalCost+objectiveAllowance;
            accepted = exitflag>0 && after<=tolerance && ...
                objectiveNondegraded;
            info = struct('attempted',true,'accepted',accepted, ...
                'exitflag',exitflag,'iterations',safeField( ...
                output,'iterations',nan), ...
                'constraintViolationBefore',before, ...
                'constraintViolationAfter',after, ...
                'objectiveNondegraded',objectiveNondegraded, ...
                'seedFeasible',true,'disposition',"projection_attempted", ...
                'solveSeconds',toc(solveTimer));
            if ~accepted
                selected = candidate;
            end
        end

        function [selected,info] = solveTrajectoryMetricNearTie( ...
                obj,secondary,primary,initial,primaryCost,A,b)
            [A,b,reduction] = obj.removeTrustBoxRedundantRows(A,b);
            tolerance = max(1e-9*max(1,abs(primaryCost)),1e-12);
            limit = primaryCost+tolerance;
            working = obj.initialTrajectoryWorkingRows(A,b,initial);
            selected = initial(:);
            accepted = false;
            solveTimer = tic;
            exitflag = -inf;
            output = struct();
            for pass = 1:8
                [scaledA,scaledB] = obj.scaleTrajectoryRows( ...
                    A(working,:),b(working));
                objective = @(value)obj.trajectoryMetricObjective( ...
                    value,secondary);
                constraint = @(value)obj.trajectoryPrimaryConstraint( ...
                    value,primary,limit);
                options = optimoptions("fmincon","Algorithm","sqp", ...
                    "Display","none","SpecifyObjectiveGradient",true, ...
                    "SpecifyConstraintGradient",true,"MaxIterations",100, ...
                    "MaxFunctionEvaluations",2500, ...
                    "ConstraintTolerance",1e-10, ...
                    "OptimalityTolerance",1e-9,"StepTolerance",1e-12);
                [trial,~,exitflag,output] = fmincon(objective,selected, ...
                    scaledA,scaledB,[],[],[],[],constraint,options);
                if ~isempty(trial) && all(isfinite(trial))
                    selected = trial;
                end
                violation = A*selected-b;
                add = obj.mostViolatedTrajectoryRows( ...
                    violation,working,128);
                working(add) = true;
                fullViolation = max([0;violation]);
                tieViolation = max(0, ...
                    obj.trajectoryMetricCost(primary,selected)-limit);
                if exitflag>0 && fullViolation<=1e-10 && tieViolation<=1e-10
                    accepted = true;
                    break
                end
                if isempty(add), break, end
            end
            selectionPrimaryCost = obj.trajectoryMetricCost(primary,selected);
            info = struct("attempted",true,"accepted",accepted, ...
                "algorithm","exact-working-set-fmincon-sqp", ...
                "exitflag",exitflag,"iterations",safeField( ...
                output,"iterations",nan),"primaryTolerance",tolerance, ...
                "primaryCostAtSelection",selectionPrimaryCost, ...
                "constraintViolation",max([0;A*selected-b; ...
                selectionPrimaryCost-limit]), ...
                "commandCost",obj.trajectoryMetricCost(secondary,selected), ...
                "passes",pass,"workingRows",nnz(working), ...
                "exactRedundantRowsRemoved",reduction.removed, ...
                "solveSeconds",toc(solveTimer));
            if ~accepted
                selected = initial(:);
            end
        end

        function working = initialTrajectoryWorkingRows(~,A,b,initial)
            slack = b-A*initial;
            tolerance = max(1e-12,256*eps(max(1,max(abs(b)))));
            working = slack<=tolerance;
            working(1:min(8,numel(working))) = true;
        end

        function rows = mostViolatedTrajectoryRows(~,violation,working,maximumRows)
            available = find(violation>1e-10 & ~working);
            if isempty(available)
                rows = zeros(0,1);
                return
            end
            [~,order] = sort(violation(available),"descend");
            rows = available(order(1:min(maximumRows,numel(order))));
        end

        function [scaledA,scaledB] = scaleTrajectoryRows(~,A,b)
            denominator = max([max(abs(A),[],2),abs(b), ...
                ones(size(b))],[],2);
            scaledA = A./denominator;
            scaledB = b./denominator;
        end

        function [cost,gradient] = trajectoryMetricObjective(~,value,metric)
            trial = metric.residual+metric.jacobian*value;
            cost = 0.5*(trial.'*trial);
            gradient = metric.jacobian.'*trial;
        end

        function [constraint,equality,gradient,gradientEquality] = ...
                trajectoryPrimaryConstraint(obj,value,metric,limit)
            [cost,gradient] = obj.trajectoryMetricObjective(value,metric);
            constraint = cost-limit;
            equality = zeros(0,1);
            gradientEquality = zeros(numel(value),0);
        end

        function cost = trajectoryMetricCost(~,metric,value)
            trial = metric.residual+metric.jacobian*value;
            cost = 0.5*(trial.'*trial);
        end

        function [checks,tube] = trajectoryMetricReplayChecks(obj, ...
                nominalPhysical,nominalRigid,candidate,candidateRigid, ...
                outputReference)
            candidatePhysical = obj.sourceNormalizedPhysicalResidual( ...
                candidate,outputReference);
            nominalFlexibleCost = 0.5*(nominalPhysical.'*nominalPhysical);
            candidateFlexibleCost = 0.5*(candidatePhysical.'*candidatePhysical);
            nominalRigidCost = 0.5*(nominalRigid.'*nominalRigid);
            candidateRigidCost = 0.5*(candidateRigid.'*candidateRigid);
            flexibleTolerance = 1e-10*max(1,abs(nominalFlexibleCost));
            rigidTolerance = 1e-10*max(1,abs(nominalRigidCost));
