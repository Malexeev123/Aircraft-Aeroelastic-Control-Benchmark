        function risk = predictFullChannelHardConstraintRisk(obj,plant, ...
                package,fusion,actuator,controller,xFlexible,uPrevious, ...
                uOuter,rigidCommand,rigidReference,gustHorizon, ...
                timeSeconds,nmpcCandidateHorizon)
        %PREDICTFULLCHANNELHARDCONSTRAINTRISK Audit-only nominal safety preview.
        %   Propagates the existing multirate fusion, actuator, flexible, and
        %   rigid runtime with held nominal commands. It identifies whether
        %   existing unscaled hard rows require lead-time allocation; it does
        %   not optimize or alter a runtime owner.
            assert(obj.fullChannelLexicographicEnabled && obj.nInterval == 10, ...
                "CoupledRtiAllocatorAudit:PredictiveActivationMode", ...
                "Predictive activation requires ten-interval full-channel mode.");
            gustHorizon = obj.normalizeGustHorizon(gustHorizon);
            obj.validateRuntime(plant,fusion,actuator,controller,xFlexible, ...
                uPrevious,uOuter,rigidCommand,rigidReference,gustHorizon,timeSeconds);
            nSurface = obj.cfg.ctrl.n_surf;
            assert(size(nmpcCandidateHorizon,1)==2*nSurface && ...
                size(nmpcCandidateHorizon,2)>=1 && ...
                all(isfinite(nmpcCandidateHorizon),"all"), ...
                "CoupledRtiAllocatorAudit:PredictiveActivationCandidate", ...
                "The predictive preview requires a finite nMPC horizon.");
            candidateIndex = min(1:obj.nInterval,size(nmpcCandidateHorizon,2));
            nominalRates = nmpcCandidateHorizon(nSurface+(1:nSurface),candidateIndex);
            nominalCommands = repmat(rigidCommand,1,obj.nInterval);
            [nominalRates,nominalCommands] = obj.appendFullChannelFeasibilityTail( ...
                nominalRates,nominalCommands);
            [~,nominal] = obj.rollout(plant,package,fusion,actuator, ...
                xFlexible,uPrevious,uOuter,nominalCommands,gustHorizon,nominalRates);
            checks = obj.fullChannelHardChecks(plant,actuator,nominal);
            margins = struct( ...
                "wingtip",0.009656201218759807-max(abs(nominal.wingtip)), ...
                "clampFz",1.464539133337300-max(abs(nominal.clampFz)), ...
                "clampMy",345.88503202222086-max(abs(nominal.clampMy)), ...
                "actuator",nominal.minimumActuatorMargin, ...
                "endpointEquality",1e-12-nominal.maximumEndpointEquality, ...
                "fusionInverse",1e-12-nominal.maximumFusionInverseError, ...
                "nonnegativeThrust",min(plant.trimThrust + ...
                    [nominal.rigidCommand.thrust]));
            names = string(fieldnames(margins));
            values = cell2mat(struct2cell(margins));
            [minimumMargin,index] = min(values);
            risk = struct('available',true,'active',~all(structfun(@logical,checks)), ...
                'checks',checks,'minimumUnscaledSlack',minimumMargin, ...
                'minimumUnscaledSlackLabel',names(index), ...
                'trajectory',obj.fullChannelTrajectoryCapture(nominal));
        end

        function [appliedEndpointTarget,info] = compute(obj,plant,package, ...
                fusion,actuator,controller,xFlexible,uPrevious,uOuter, ...
                rigidCommand,rigidReference,gustHorizon,timeSeconds)
        %COMPUTE Return one applied-endpoint target for normal realization.
            solveTimer = tic;
            obj.callCount = obj.callCount+1;
            gustHorizon = obj.normalizeGustHorizon(gustHorizon);
            obj.validateRuntime(plant,fusion,actuator,controller, ...
                xFlexible,uPrevious,uOuter,rigidCommand,rigidReference, ...
                gustHorizon,timeSeconds);
            nSurface = obj.cfg.ctrl.n_surf;
            nDecision = nSurface*obj.nInterval;
            nominalRates = zeros(nSurface,obj.nInterval);
            if obj.initialized && ~obj.rigidPreservationGuardEnabled
                nominalRates = [obj.warmRates(:,2:end), ...
                    obj.warmRates(:,end)];
            end
            try
                [nominalResponse,nominal] = obj.rollout(plant,package, ...
                    fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    rigidCommand,gustHorizon,nominalRates);
            catch
                nominalRates(:) = 0;
                [nominalResponse,nominal] = obj.rollout(plant,package, ...
                    fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    rigidCommand,gustHorizon,nominalRates);
            end
            outputReference = obj.outputReference(plant,xFlexible,nominal.tip);
            if obj.coupledNmpcPredictorEnabled
                % Keep the source envelope tied to the preserved nMPC
                % target. Resetting it to the current tip each sample lets
                % individually bounded corrections accumulate into drift.
                outputReference.wingtip = obj.tipValue( ...
                    controller.xTrim(:),nominal.tip);
            end
            [nominalFlexible,nominalRigid] = obj.residuals( ...
                controller,nominal,outputReference,rigidReference);
            if obj.sourceNormalizedPhysicalOutputObjectiveEnabled
                nominalResidual = obj.sourceNormalizedPhysicalResidual( ...
                    nominal,outputReference);
            else
                nominalResidual = [nominalFlexible;nominalRigid];
            end

            responseJacobian = zeros(numel(nominalResponse),nDecision);
            residualJacobian = zeros(numel(nominalResidual),nDecision);
            rigidResidualJacobian = zeros(numel(nominalRigid),nDecision);
            step = obj.finiteDifferenceStep;
            for decisionIndex = 1:nDecision
                plusRates = nominalRates;
                minusRates = nominalRates;
                plusRates(decisionIndex) = plusRates(decisionIndex)+step;
                minusRates(decisionIndex) = minusRates(decisionIndex)-step;
                [plusResponse,plus] = obj.rollout(plant,package, ...
                    fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    rigidCommand,gustHorizon,plusRates);
                [minusResponse,minus] = obj.rollout(plant,package, ...
                    fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    rigidCommand,gustHorizon,minusRates);
                plusResidual = obj.combinedResidual( ...
                    controller,plus,outputReference,rigidReference);
                minusResidual = obj.combinedResidual( ...
                    controller,minus,outputReference,rigidReference);
                responseJacobian(:,decisionIndex) = ...
                    (plusResponse-minusResponse)/(2*step);
                residualJacobian(:,decisionIndex) = ...
                    (plusResidual-minusResidual)/(2*step);
                if obj.sourceNormalizedPhysicalOutputObjectiveEnabled
                    [~,plusRigid] = obj.residuals(controller,plus, ...
                        outputReference,rigidReference);
                    [~,minusRigid] = obj.residuals(controller,minus, ...
                        outputReference,rigidReference);
                    rigidResidualJacobian(:,decisionIndex) = ...
                        (plusRigid-minusRigid)/(2*step);
                end
            end

            rateScale = min(abs([actuator.rateL(:), ...
                actuator.rateU(:)]),[],2);
            decisionScale = repmat(rateScale,obj.nInterval,1);
            scaledJacobian = residualJacobian.*decisionScale.';
            hessian = scaledJacobian.'*scaledJacobian;
            gradient = scaledJacobian.'*nominalResidual;
            regularization = 1e-10*max(trace(hessian)/nDecision,1);
            hessian = 0.5*(hessian+hessian.') + ...
                regularization*eye(nDecision);
            [Aphysical,bphysical] = obj.physicalConstraints( ...
                actuator,uPrevious,nominalRates,rateScale);
            [Aoutput,boutput,outputLimits] = obj.outputConstraints( ...
                nominal,responseJacobian,decisionScale,outputReference);
            [AobjectiveGuard,bobjectiveGuard,objectiveGuardCapture, ...
                objectiveGuardData] = ...
                obj.objectiveNondegradationConstraints(nominalResidual, ...
                residualJacobian,nominalRigid,rigidResidualJacobian, ...
                decisionScale);
            Alinear = [Aphysical;Aoutput;AobjectiveGuard];
            blinear = [bphysical;boutput;bobjectiveGuard];
            options = optimoptions("quadprog","Display","none", ...
                "Algorithm","interior-point-convex");
            qpTimer = tic;
            [scaledStep,qpCost,qpExitflag,qpOutput] = quadprog( ...
                hessian,gradient,Alinear,blinear,[],[],[],[],[],options);
            primaryQp = struct("algorithm","interior-point-convex", ...
                "exitflag",qpExitflag,"cost",qpCost, ...
                "firstOrderOptimality",safeField( ...
                    qpOutput,"firstorderopt",nan), ...
                "constraintViolation",safeField( ...
                    qpOutput,"constrviolation",nan));
            selectedQpAlgorithm = "interior-point-convex";
            recoveryQp = struct("attempted",false, ...
                "algorithm","active-set","selected",false, ...
                "exitflag",nan,"cost",nan, ...
                "firstOrderOptimality",nan, ...
                "constraintViolation",nan);
            zeroLinearConstraintViolation = max( ...
                [0;-blinear]);
            qpDominanceTolerance = 100*eps(max(1,norm(gradient,inf)));
            validPrimaryCost = isscalar(qpCost) && isfinite(qpCost);
            primaryDominatesZero = qpExitflag > 0 && ...
                validPrimaryCost && qpCost <= qpDominanceTolerance;
            primaryReferenceCost = 0;
            if qpExitflag > 0 && validPrimaryCost
                primaryReferenceCost = min(qpCost,0);
            end
            if zeroLinearConstraintViolation <= 1e-12 && ...
                    ~primaryDominatesZero
                recoveryOptions = optimoptions("quadprog", ...
                    "Display","none","Algorithm","active-set");
                [recoveryStep,recoveryCost,recoveryExitflag, ...
                    recoveryOutput] = quadprog(hessian,gradient, ...
                    Alinear,blinear,[],[],[],[], ...
                    zeros(nDecision,1),recoveryOptions);
                recoveryQp = struct("attempted",true, ...
                    "algorithm","active-set","selected",false, ...
                    "exitflag",recoveryExitflag,"cost",recoveryCost, ...
                    "firstOrderOptimality",safeField( ...
                        recoveryOutput,"firstorderopt",nan), ...
                    "constraintViolation",safeField( ...
                        recoveryOutput,"constrviolation",nan));
                if recoveryExitflag > 0 && ...
                        all(isfinite(recoveryStep)) && ...
                        isfinite(recoveryCost) && ...
                        recoveryCost < primaryReferenceCost- ...
                        qpDominanceTolerance
                    scaledStep = recoveryStep;
                    qpCost = recoveryCost;
                    qpExitflag = recoveryExitflag;
                    qpOutput = recoveryOutput;
                    selectedQpAlgorithm = "active-set-recovery";
                    recoveryQp.selected = true;
                end
            end
            guardedPhysicalQp = struct("attempted",false,"accepted",false, ...
                "exitflag",nan,"iterations",nan,"constraintViolation",nan, ...
                "primaryCost",nan);
            if obj.sourceNormalizedPhysicalOutputObjectiveEnabled && ...
                    qpExitflag > 0 && all(isfinite(scaledStep)) && ...
                    isfinite(qpCost)
                [guardedStep,guardedPhysicalQp] = ...
                    obj.solveGuardedPhysicalStep(hessian,gradient, ...
                    Alinear,blinear,objectiveGuardData);
                if guardedPhysicalQp.accepted
                    scaledStep = guardedStep;
                    qpCost = guardedPhysicalQp.primaryCost;
                    selectedQpAlgorithm = ...
                        "source-normalized-guarded-primary";
                else
                    qpExitflag = 0;
                end
            end
            secondaryNearTie = struct("attempted",false,"accepted",false, ...
                "exitflag",nan,"iterations",nan,"primaryTolerance",nan, ...
                "primaryCostAtSelection",nan,"commandCost",nan);
            if obj.sourceNormalizedPhysicalOutputObjectiveEnabled && ...
                    qpExitflag > 0 && all(isfinite(scaledStep)) && ...
                    isfinite(qpCost)
                [nearTieStep,secondaryNearTie] = obj.nearTieCommandStep( ...
                    hessian,gradient,Alinear,blinear,scaledStep,qpCost, ...
                    objectiveGuardData);
                if secondaryNearTie.accepted
                    scaledStep = nearTieStep;
                    selectedQpAlgorithm = ...
                        "source-normalized-primary-near-tie";
                end
            end
            qpSeconds = toc(qpTimer);
            if isempty(scaledStep) || any(~isfinite(scaledStep))
                scaledStep = zeros(nDecision,1);
            end
            physicalStep = decisionScale.*scaledStep;
            accepted = false;
            selectedAlpha = 0;
            selected = nominal;
            selectedFlexible = nominalFlexible;
            selectedRigid = nominalRigid;
            totalThrust = plant.trimThrust+rigidCommand.thrust;
            selectedChecks = obj.replayChecks(totalThrust,nominal,nominal, ...
                nominalFlexible,nominalRigid,nominalFlexible, ...
                nominalRigid,outputReference,outputLimits,rigidReference,false);
            nominalChecks = selectedChecks;
            lastTrialChecks = selectedChecks;
            trialDiagnostics = repmat(struct( ...
                "alpha",nan,"checks",struct(),"passed",false, ...
                "cost",struct()),0,1);
            trialIndex = 0;
            for alpha = [1,0.5,0.25,0.125,0.0625, ...
                    0.03125,0.015625,0.0078125]
                trialRates = nominalRates + reshape( ...
                    alpha*physicalStep,nSurface,obj.nInterval);
                [~,trial] = obj.rollout(plant,package, ...
                    fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    rigidCommand,gustHorizon,trialRates);
                [trialFlexible,trialRigid] = obj.residuals( ...
                    controller,trial,outputReference,rigidReference);
                trialChecks = obj.replayChecks(totalThrust,nominal,trial, ...
                    nominalFlexible,nominalRigid,trialFlexible, ...
                    trialRigid,outputReference,outputLimits,rigidReference,true);
                lastTrialChecks = trialChecks;
                trialIndex = trialIndex+1;
                trialDiagnostics(trialIndex,1) = struct( ...
                    "alpha",alpha,"checks",trialChecks, ...
                    "passed",all(structfun(@logical,trialChecks)), ...
                    "cost",obj.costSummary(trialFlexible,trialRigid));
                if qpExitflag > 0 && all(structfun(@logical,trialChecks))
                    accepted = true;
                    selectedAlpha = alpha;
                    selected = trial;
                    selectedFlexible = trialFlexible;
                    selectedRigid = trialRigid;
                    selectedChecks = trialChecks;
                    break
                end
            end

            if accepted
                appliedEndpointTarget = selected.endpoint(:,1);
                obj.warmRates = selected.rates;
                obj.initialized = true;
                exitflag = 1;
                message = "Accepted coupled one-SQP nonlinear replay.";
            else
                % A rejected correction must retain the same-state outer-only
                % endpoint from the nonlinear preview, not an older inner
                % endpoint that would cancel the current outer request.
                appliedEndpointTarget = nominal.endpoint(:,1);
                obj.warmRates(:) = 0;
                obj.initialized = false;
                exitflag = 0;
                message = "Retained outer-only endpoint after coupled replay rejection.";
            end
            assert(all(isfinite(appliedEndpointTarget)) && ...
                numel(appliedEndpointTarget) == 2*nSurface, ...
                "CoupledRtiAllocatorAudit:Output", ...
