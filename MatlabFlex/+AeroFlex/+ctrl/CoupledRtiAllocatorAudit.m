                obj.fullChannelPrimarySolver = "quadprog-interior-point-convex";
            end
            assert(any(obj.fullChannelFminconAlgorithm == ["sqp","interior-point"]), ...
                "CoupledRtiAllocatorAudit:FullChannelAlgorithm", ...
                "The full-channel audit supports only fmincon sqp or interior-point.");
            assert(any(obj.fullChannelPrimarySolver == ...
                ["fmincon-sqp","quadprog-interior-point-convex"]), ...
                "CoupledRtiAllocatorAudit:FullChannelPrimarySolver", ...
                "The full-channel primary solver request is invalid.");
            nativeHorizonCoupledPredictor = ...
                obj.coupledNmpcPredictorEnabled && ...
                obj.nInterval == cfg.ctrl.Nc && ...
                any(coupledPredictorSource == [ ...
                "phase18c-v17a-caseb-native-horizon-coupled-predictor-objective-audit-v1", ...
                "phase18c-v17a-caseb-source-normalized-physical-output-objective-audit-v1"]) && ...
                ~obj.fullChannelLexicographicEnabled && ...
                ~obj.dynamicNullspaceWingOnlyEnabled;
            assert((obj.nInterval == 3 && ~obj.fullChannelLexicographicEnabled && ...
                ~obj.dynamicNullspaceWingOnlyEnabled) || ...
                nativeHorizonCoupledPredictor || ...
                (obj.nInterval == 10 && (obj.fullChannelLexicographicEnabled || ...
                obj.nonlinearOuterReferenceGovernorEnabled || ...
                obj.jointSharedSurfaceSafetyCoordinationEnabled || ...
                obj.dynamicNullspaceWingOnlyEnabled)), ...
                "CoupledRtiAllocatorAudit:Horizon", ...
                ['The allocator supports only the qualified three-interval wing ', ...
                 'audit, the source-bound native-horizon coupled predictor, ', ...
                 'the approved ten-interval full-channel audit, or the approved ', ...
                 'ten-interval wing-only dynamic-nullspace audit.']);
            assert(isfinite(obj.finiteDifferenceStep) && ...
                obj.finiteDifferenceStep > 0 && ...
                obj.finiteDifferenceStep <= 1e-2, ...
                "CoupledRtiAllocatorAudit:DifferenceStep", ...
                "The finite-difference step must lie in (0,1e-2].");
            assert(cfg.ctrl.n_surf == 2 && cfg.ctrl.var_per == 2, ...
                "CoupledRtiAllocatorAudit:ControlOrdering", ...
                "The audit requires two [deflection; rate] flap sets.");
            obj.cfg = cfg;
            obj.beam = beam;
            obj.aero = aero;
            obj.base = base;
            if isfield(request,"estimatorConditionedSafetyGate") && ...
                    logical(request.estimatorConditionedSafetyGate)
                assert(isfield(request,"protectedOutputEnvelope") && ...
                    isstruct(request.protectedOutputEnvelope), ...
                    "CoupledRtiAllocatorAudit:ProtectedOutputEnvelope", ...
                    "The estimator-conditioned audit requires its envelope.");
                obj.protectedOutputEnvelope = ...
                    request.protectedOutputEnvelope;
            end
            if isfield(request,"rigidPreservationGuard") && ...
                    ~isempty(request.rigidPreservationGuard)
                guard = request.rigidPreservationGuard;
                assert(isstruct(guard) && isscalar(guard) && ...
                    isfield(guard,"enabled") && isfield(guard,"auditOnly") && ...
                    logical(guard.auditOnly), ...
                    "CoupledRtiAllocatorAudit:RigidPreservationGuard", ...
                    ['The rigid-preservation guard requires an explicit ', ...
                     'audit-only request.']);
                obj.rigidPreservationGuardEnabled = logical(guard.enabled);
            end
            if isfield(request,"futureScheduledPackageSequence") && ...
                    ~isempty(request.futureScheduledPackageSequence)
                sequenceRequest = request.futureScheduledPackageSequence;
                assert(isstruct(sequenceRequest) && isscalar(sequenceRequest) && ...
                    isfield(sequenceRequest,"enabled") && ...
                    isfield(sequenceRequest,"auditOnly") && ...
                    logical(sequenceRequest.auditOnly), ...
                    "CoupledRtiAllocatorAudit:FuturePackageSequence", ...
                    ['Future scheduled package prediction requires an ', ...
                     'explicit audit-only request.']);
                obj.futureScheduledPackageSequenceEnabled = ...
                    logical(sequenceRequest.enabled);
            end
            obj.warmRates = zeros(cfg.ctrl.n_surf,obj.nInterval);
        end

        function replay = replaySourceRootCondensedDecision(obj,plant,package, ...
                fusion,actuator,controller,xFlexible,uPrevious,uOuter, ...
                rigidCommand,rigidReference,gustHorizon,timeSeconds, ...
                nmpcCandidateHorizon,decision)
        %REPLAYSOURCEROOTCONDENSEDDECISION Verify a saved four-coordinate step.
            assert(obj.sourceRootCondensedMultiInputCoordinationEnabled && ...
                obj.nInterval==10 && numel(decision)==4 && ...
                all(isfinite(decision)) && max(abs(decision))<=0.25, ...
                "CoupledRtiAllocatorAudit:SourceRootReplayDecision", ...
                "The saved source-root decision is outside its approved chart.");
            timer = tic;
            gustHorizon = obj.normalizeGustHorizon(gustHorizon);
            obj.validateRuntime(plant,fusion,actuator,controller,xFlexible, ...
                uPrevious,uOuter,rigidCommand,rigidReference,gustHorizon,timeSeconds);
            nSurface = obj.cfg.ctrl.n_surf;
            assert(isequal(size(nmpcCandidateHorizon), ...
                [2*nSurface,controller.Nc]) && ...
                all(isfinite(nmpcCandidateHorizon),"all"), ...
                "CoupledRtiAllocatorAudit:SourceRootReplayHorizon", ...
                "The saved source-root replay requires the native nMPC horizon.");
            candidateIndex = min(1:obj.nInterval,size(nmpcCandidateHorizon,2));
            nominalRates = nmpcCandidateHorizon( ...
                nSurface+(1:nSurface),candidateIndex);
            nominalCommands = repmat(rigidCommand,1,obj.nInterval);
            [nominalResponse,nominal] = obj.fullChannelRollout(plant,package, ...
                fusion,actuator,xFlexible,uPrevious,uOuter,nominalRates, ...
                nominalCommands,gustHorizon,[],zeros(0,1),nmpcCandidateHorizon);
            outputReference = obj.outputReference(plant,xFlexible,nominal.tip);
            outputReference.wingtip = obj.tipValue( ...
                controller.xTrim(:),nominal.tip);
            scale = obj.fullChannelDecisionScale(actuator);
            scale = scale(obj.fullChannelDecisionIndices());
            [~,candidate] = obj.fullChannelRollout(plant,package, ...
                fusion,actuator,xFlexible,uPrevious,uOuter,nominalRates, ...
                nominalCommands,gustHorizon,scale,decision(:), ...
                nmpcCandidateHorizon);
            [nominalFlexible,nominalRigid] = obj.residuals( ...
                controller,nominal,struct(),rigidReference,obj.nInterval);
            [candidateFlexible,candidateRigid] = obj.residuals( ...
                controller,candidate,struct(),rigidReference,obj.nInterval);
            [~,~,limits] = obj.outputConstraints(nominal, ...
                zeros(numel(nominalResponse),numel(decision)), ...
                ones(numel(decision),1),outputReference);
            hardChecks = obj.fullChannelHardChecks( ...
                plant,actuator,candidate,outputReference);
            checks = obj.replayChecks( ...
                min(plant.trimThrust+[candidate.rigidCommand.thrust]), ...
                nominal,candidate,nominalFlexible,nominalRigid, ...
                candidateFlexible,candidateRigid,outputReference,limits, ...
                rigidReference,true);
            checks.hardPhysicalReplay = all(structfun(@logical,hardChecks));
            replay = struct( ...
                "accepted",all(structfun(@logical,checks)), ...
                "decision",decision(:),"decisionScale",scale(:), ...
                "checks",checks,"hardChecks",hardChecks, ...
                "nominalCost",obj.costSummary(nominalFlexible,nominalRigid), ...
                "candidateCost",obj.costSummary(candidateFlexible,candidateRigid), ...
                "nominalPhysicalMetrics",obj.physicalOutputMetrics( ...
                    nominal,outputReference.wingtip), ...
                "candidatePhysicalMetrics",obj.physicalOutputMetrics( ...
                    candidate,outputReference.wingtip), ...
                "nominalTrajectory",obj.fullChannelTrajectoryCapture(nominal), ...
                "candidateTrajectory",obj.fullChannelTrajectoryCapture(candidate), ...
                "firstEndpoint",candidate.firstEndpoint(:,1), ...
                "firstRigidCommand",candidate.rigidCommand(1), ...
                "maximumEndpointEquality",candidate.maximumEndpointEquality, ...
                "minimumActuatorMargin",candidate.minimumActuatorMargin, ...
                "solveSeconds",toc(timer));
        end

        function [appliedEndpointTarget,appliedRigidCommand,info,appliedOuterReference,appliedInnerEndpointTarget] = ...
                computeFullChannelLexicographic(obj,plant,package,fusion, ...
                actuator,controller,xFlexible,uPrevious,uOuter,rigidCommand, ...
                rigidReference,gustHorizon,timeSeconds,nmpcCandidateHorizon)
        %COMPUTEFULLCHANNELLEXICOGRAPHIC Audit-only rigid/flexible allocation.
        %   The nominal commands remain the active outer-LQR and nMPC values.
        %   Governor mode changes the outer symmetric-wing reference before
        %   existing fusion/servo realization; nMPC retains its raw request.
            assert((obj.fullChannelLexicographicEnabled || ...
                obj.nonlinearOuterReferenceGovernorEnabled || ...
                obj.jointSharedSurfaceSafetyCoordinationEnabled) && obj.nInterval == 10, ...
                "CoupledRtiAllocatorAudit:FullChannelMode", ...
                "The full-channel method requires an explicit ten-interval mode.");
            solveTimer = tic;
            phaseSeconds = struct('nominalRollout',nan,'finiteDifference',nan, ...
                'constraintAssembly',nan,'primarySolve',nan,'secondarySolve',nan, ...
                'nonlinearReplay',nan);
            primaryTrace = struct('iteration',zeros(0,1),'fval',zeros(0,1), ...
                'firstorderopt',zeros(0,1),'constrviolation',zeros(0,1));
            secondaryTrace = primaryTrace;
            obj.callCount = obj.callCount + 1;
            gustHorizon = obj.normalizeGustHorizon(gustHorizon);
            obj.validateRuntime(plant,fusion,actuator,controller,xFlexible, ...
                uPrevious,uOuter,rigidCommand,rigidReference,gustHorizon,timeSeconds);
            nSurface = obj.cfg.ctrl.n_surf;
            assert(size(nmpcCandidateHorizon,1)==2*nSurface && ...
                size(nmpcCandidateHorizon,2)>=1 && ...
                all(isfinite(nmpcCandidateHorizon),"all"), ...
                "CoupledRtiAllocatorAudit:FullChannelCandidate", ...
                "The full-channel allocator requires a finite nMPC horizon.");
            candidateIndex = min(1:obj.nInterval,size(nmpcCandidateHorizon,2));
            nominalRates = nmpcCandidateHorizon(nSurface+(1:nSurface),candidateIndex);
            nominalCommands = repmat(rigidCommand,1,obj.nInterval);
            phaseTimer = tic;
            [nominalResponse,nominal] = obj.fullChannelRollout(plant,package, ...
                fusion,actuator,xFlexible,uPrevious,uOuter,nominalRates, ...
                nominalCommands,gustHorizon,[],zeros(0,1),nmpcCandidateHorizon);
            phaseSeconds.nominalRollout = toc(phaseTimer);
            [~,nominalRigid] = obj.residuals(controller,nominal,struct(), ...
                rigidReference,obj.nInterval);
            outputReference = obj.outputReference(plant,xFlexible,nominal.tip);
            if obj.sourceRootCondensedMultiInputCoordinationEnabled
                outputReference.wingtip = obj.tipValue( ...
                    controller.xTrim(:),nominal.tip);
                nominalPhysical = obj.sourceNormalizedPhysicalResidual( ...
                    nominal,outputReference);
            else
                nominalPhysical = zeros(0,1);
            end
            nominalHardChecks = obj.fullChannelHardChecks( ...
                plant,actuator,nominal,outputReference);
            if (obj.nonlinearOuterReferenceGovernorEnabled || ...
                    obj.jointSharedSurfaceSafetyCoordinationEnabled) && ...
                    ~obj.sourceRootCondensedMultiInputCoordinationEnabled && ...
                    all(structfun(@logical,nominalHardChecks))
                % A reference governor is transparent inside the nonlinear
                % previewed safe set.  It must not retune or attenuate a
                % nominal LQR/nMPC command merely because a lower-cost local
                % correction exists.
                appliedEndpointTarget = nominal.firstEndpoint(:,1);
                appliedRigidCommand = rigidCommand;
                appliedOuterReference = uOuter(:);
                appliedInnerEndpointTarget = nmpcCandidateHorizon(:,1);
                obj.lastSafeRigidCommand = appliedRigidCommand;
                obj.warmRates = nominalRates;
                obj.initialized = true;
                info = obj.nonlinearGovernorNominalIdentityInfo( ...
                    nominal,nominalRigid,appliedEndpointTarget, ...
                    controller,gustHorizon,timeSeconds,nominalHardChecks, ...
                    toc(solveTimer));
                obj.lastPrediction = obj.firstIntervalPrediction( ...
                    nominal,package,timeSeconds,true);
                obj.lastPrediction.initialFlexibleStateErrorInfinity = ...
                    norm(xFlexible(:)-plant.xFlex(:),inf);
                return
            end
            decisionIndices = obj.fullChannelDecisionIndices();
            nDecision = numel(decisionIndices);
            fullScale = obj.fullChannelDecisionScale(actuator);
            scale = fullScale(decisionIndices);
            responseJacobian = zeros(numel(nominalResponse),nDecision);
            rigidJacobian = zeros(numel(nominalRigid),nDecision);
            physicalJacobian = zeros(numel(nominalPhysical),nDecision);
            step = obj.finiteDifferenceStep;
            phaseTimer = tic;
            for decisionIndex = 1:nDecision
                plus = zeros(nDecision,1); minus = plus;
                plus(decisionIndex) = step; minus(decisionIndex) = -step;
                [plusResponse,plusDetail] = obj.fullChannelRollout(plant, ...
                    package,fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    nominalRates,nominalCommands,gustHorizon,scale,plus, ...
                    nmpcCandidateHorizon);
                [minusResponse,minusDetail] = obj.fullChannelRollout(plant, ...
                    package,fusion,actuator,xFlexible,uPrevious,uOuter, ...
                    nominalRates,nominalCommands,gustHorizon,scale,minus, ...
                    nmpcCandidateHorizon);
                [~,plusRigid] = obj.residuals(controller,plusDetail,struct(), ...
                    rigidReference,obj.nInterval);
                [~,minusRigid] = obj.residuals(controller,minusDetail,struct(), ...
                    rigidReference,obj.nInterval);
                responseJacobian(:,decisionIndex) = ...
                    (plusResponse-minusResponse)/(2*step);
                rigidJacobian(:,decisionIndex) = (plusRigid-minusRigid)/(2*step);
                if obj.sourceRootCondensedMultiInputCoordinationEnabled
                    plusPhysical = obj.sourceNormalizedPhysicalResidual( ...
                        plusDetail,outputReference);
                    minusPhysical = obj.sourceNormalizedPhysicalResidual( ...
                        minusDetail,outputReference);
                    physicalJacobian(:,decisionIndex) = ...
                        (plusPhysical-minusPhysical)/(2*step);
                end
                if obj.debugEnabled && obj.debugPrintIterations
                    fprintf('[Full-channel allocator %d] finite difference %d/%d; elapsed %.3f s\n', ...
                        obj.callCount,decisionIndex,nDecision,toc(phaseTimer));
                end
            end
            phaseSeconds.finiteDifference = toc(phaseTimer);
            objectiveJacobian = rigidJacobian;
            objectiveResidual = nominalRigid;
            if obj.sourceRootCondensedMultiInputCoordinationEnabled
                objectiveJacobian = physicalJacobian;
                objectiveResidual = nominalPhysical;
            end
            regularization = 1e-10*max(trace(objectiveJacobian.'* ...
                objectiveJacobian)/nDecision,1);
            primaryHessian = objectiveJacobian.'*objectiveJacobian;
            primaryHessian = 0.5*(primaryHessian+primaryHessian.') + ...
                regularization*eye(nDecision);
            primaryGradient = objectiveJacobian.'*objectiveResidual;
            options = optimoptions("fmincon","Algorithm", ...
                char(obj.fullChannelFminconAlgorithm), ...
                "Display","none","MaxIterations",50, ...
                "OptimalityTolerance",1e-8,"ConstraintTolerance",1e-9);
            primaryObjective = @(z) 0.5*z.'*primaryHessian*z + primaryGradient.'*z;
            zero = zeros(nDecision,1);
            secondaryObjective = @(z) 0.5*(z.'*z) + 0.5*regularization*(z.'*z);
            objectiveGuardCapture = struct("enabled",false);
            objectiveGuardData = struct("enabled",false);
            AobjectiveGuard = zeros(0,nDecision);
            bobjectiveGuard = zeros(0,1);
            outputLimits = struct();
            Aoutput = zeros(0,nDecision);
            boutput = zeros(0,1);
            if obj.sourceRootCondensedMultiInputCoordinationEnabled
                [AobjectiveGuard,bobjectiveGuard,objectiveGuardCapture, ...
                    objectiveGuardData] = obj.objectiveNondegradationConstraints( ...
                    nominalPhysical,physicalJacobian,nominalRigid, ...
                    rigidJacobian,ones(nDecision,1));
                if obj.trajectoryMetricSharedAllocationEnabled
                    AobjectiveGuard = zeros(0,nDecision);
                    bobjectiveGuard = zeros(0,1);
                    objectiveGuardCapture.appliedAsConstraint = false;
                    objectiveGuardCapture.disposition = ...
                        "removed_zero_reference_non_degradation_rows";
                end
                [Aoutput,boutput,outputLimits] = obj.outputConstraints( ...
                    nominal,responseJacobian,ones(nDecision,1),outputReference);
            end
            selected = nominal; selectedStep = zero;
            hardChecks = obj.fullChannelHardChecks( ...
                plant,actuator,nominal,outputReference);
            primaryReplayChecks = struct('available',false);
            primaryRigidTrajectoryTube = struct('enabled',false);
            phaseSeconds.constraintAssembly = 0;
            phaseSeconds.primarySolve = 0;
            phaseSeconds.secondarySolve = 0;
            phaseSeconds.primaryNonlinearReplay = 0;
            phaseSeconds.nonlinearReplay = 0;
            accepted = false;
            primarySafeFallback = false;
            guardedPrimaryCapture = struct("attempted",false, ...
                "accepted",false,"exitflag",nan,"iterations",nan, ...
                "constraintViolation",nan,"primaryCost",nan);
            primaryExitflag = nan; primaryValue = nan; primaryOutput = struct();
            secondaryExitflag = nan; secondaryValue = nan; secondaryOutput = struct();
            primaryTolerance = nan; secondaryPrimaryConstraintValue = nan;
            secondaryConstraintSatisfied = false; secondaryTieConstraintFailed = false;
            coordinationNearTie = struct("attempted",false,"accepted",false, ...
                "exitflag",nan,"iterations",nan,"primaryTolerance",nan, ...
                "primaryCostAtSelection",nan,"constraintViolation",nan, ...
                "commandCost",nan);
            trustRegionAttempts = repmat(struct('bound',nan,'primaryExitflag',nan, ...
                'primaryValue',nan,'secondaryExitflag',nan,'accepted',false, ...
                'primaryReplayHardChecks',struct('available',false), ...
                'coordinationReplayChecks',struct('available',false), ...
                'guardedPrimary',guardedPrimaryCapture, ...
                'constraintDiagnostic',struct('minimumZeroStepSlack',nan, ...
                'minimumZeroStepSlackLabel',"",'zeroStepViolationInfinity',nan), ...
                'rowScalingDiagnostic',struct('enabled',false,'rowScale',[], ...
                'minimum',nan,'maximum',nan,'reconstructionErrorInf',nan, ...
                'unscaledCondition',nan,'scaledCondition',nan), ...
                'primaryUnscaledViolationInf',nan, ...
                'primaryScaledViolationInf',nan, ...
                'secondaryUnscaledViolationInf',nan, ...
                'secondaryScaledViolationInf',nan, ...
                'replayAttempts',repmat(struct('alpha',nan, ...
                'accepted',false,'hardChecks',struct(), ...
                'coordinationReplayChecks',struct('available',false), ...
                'rigidTrajectoryTube',struct('enabled',false), ...
                'flexibleCost',nan,'rigidCost',nan),0,1), ...
                'selectedByPrimarySafeFallback',false),0,1);
            selectedTrustRegionBound = nan;
            selectedReplayAlpha = 0;
            lastCoordinationChecks = struct('available',false);
            lastRigidTrajectoryTube = struct('enabled',false);
            selectedRigidTrajectoryTube = struct('enabled',false);
            lastReplayAttempts = repmat(struct('alpha',nan, ...
                'accepted',false,'hardChecks',struct(), ...
                'coordinationReplayChecks',struct('available',false), ...
                'rigidTrajectoryTube',struct('enabled',false), ...
                'flexibleCost',nan,'rigidCost',nan),0,1);
            guardedProblemCapture = struct('available',false);
            for trustRegionBound = obj.fullChannelTrustRegionBounds
                phaseTimer = tic;
                [AUnscaled,bUnscaled,constraintDiagnostic] = obj.fullChannelConstraints(actuator,plant,nominal, ...
                    responseJacobian,scale,nominalRates,nominalCommands, ...
                    trustRegionBound,outputReference);
                AUnscaled = [AUnscaled;Aoutput;AobjectiveGuard];
                bUnscaled = [bUnscaled;boutput;bobjectiveGuard];
                [A,b,rowScalingDiagnostic] = ...
                    obj.applyFullChannelRowScaling(AUnscaled,bUnscaled);
                if obj.sourceRootCondensedMultiInputCoordinationEnabled
                    guardedProblemCapture = struct( ...
                        'available',true, ...
                        'hessian',primaryHessian, ...
                        'gradient',primaryGradient, ...
                        'linearA',A, ...
                        'linearB',b, ...
                        'linearAUnscaled',AUnscaled, ...
                        'linearBUnscaled',bUnscaled, ...
                        'physicalGuard',objectiveGuardData, ...
                        'trustRegionBound',trustRegionBound, ...
                        'constraintDiagnostic',constraintDiagnostic, ...
                        'rowScalingDiagnostic',rowScalingDiagnostic);
                end
                phaseSeconds.constraintAssembly = phaseSeconds.constraintAssembly + toc(phaseTimer);
                phaseTimer = tic;
                if obj.trajectoryMetricSharedAllocationEnabled
                    physicalMetric = obj.trajectoryMetric( ...
                        nominalPhysical,physicalJacobian);
                    [primaryStep,guardedPrimary] = ...
                        obj.solveTrajectoryMetricWorkingSet(physicalMetric, ...
                        AUnscaled,bUnscaled,zero);
                    guardedPrimaryCapture = guardedPrimary;
                    primaryValue = guardedPrimary.primaryCost;
                    primaryExitflag = guardedPrimary.exitflag;
                    primaryOutput = struct( ...
                        'iterations',guardedPrimary.iterations, ...
                        'constrviolation',guardedPrimary.constraintViolation);
                elseif obj.sourceRootCondensedMultiInputCoordinationEnabled
                    [primaryStep,guardedPrimary] = ...
                        obj.solveGuardedPhysicalStepLadder(primaryHessian, ...
                        primaryGradient,A,b,objectiveGuardData);
                    guardedPrimaryCapture = guardedPrimary;
                    primaryValue = guardedPrimary.primaryCost;
                    primaryExitflag = guardedPrimary.exitflag;
                    primaryOutput = struct( ...
                        'iterations',guardedPrimary.iterations, ...
                        'constrviolation',guardedPrimary.constraintViolation);
                elseif obj.fullChannelPrimarySolver == "quadprog-interior-point-convex"
                    primaryOptions = optimoptions("quadprog","Display","none", ...
                        "Algorithm","interior-point-convex", ...
                        "OptimalityTolerance",1e-8,"ConstraintTolerance",1e-9);
                    [primaryStep,primaryValue,primaryExitflag,primaryOutput] = ...
                        quadprog(primaryHessian,primaryGradient,A,b,[],[],[],[], ...
                        zero,primaryOptions);
                else
                    primaryOptions = optimoptions(options,"OutputFcn", ...
                        @primaryIterationOutputFcn);
                    [primaryStep,primaryValue,primaryExitflag,primaryOutput] = ...
                        fmincon(primaryObjective,zero,A,b,[],[],[],[],[],primaryOptions);
                end
                phaseSeconds.primarySolve = phaseSeconds.primarySolve + toc(phaseTimer);
                primaryUnscaledViolationInf = obj.linearConstraintViolation( ...
                    AUnscaled,bUnscaled,primaryStep);
                primaryScaledViolationInf = obj.linearConstraintViolation( ...
                    A,b,primaryStep);
                primaryAccepted = primaryExitflag > 0 && all(isfinite(primaryStep)) && ...
                    isfinite(primaryValue) && primaryUnscaledViolationInf <= ...
                    options.ConstraintTolerance;
                if obj.sourceRootCondensedMultiInputCoordinationEnabled
                    primaryAccepted = primaryAccepted && ...
                        guardedPrimary.accepted;
                end
                primaryTolerance = max(100*options.ConstraintTolerance, ...
                    256*eps(max(1,abs(primaryValue))));
                if primaryAccepted && obj.trajectoryMetricSharedAllocationEnabled
                    physicalMetric = obj.trajectoryMetric( ...
                        nominalPhysical,physicalJacobian);
                    rigidMetric = obj.trajectoryMetric( ...
                        nominalRigid,rigidJacobian);
                    phaseTimer = tic;
                    [secondaryStep,nearTie] = ...
                        obj.solveTrajectoryMetricNearTie(rigidMetric, ...
                        physicalMetric,primaryStep,primaryValue,AUnscaled,bUnscaled);
                    phaseSeconds.secondarySolve = ...
                        phaseSeconds.secondarySolve + toc(phaseTimer);
                    coordinationNearTie = nearTie;
                    secondaryValue = nearTie.commandCost;
                    secondaryExitflag = nearTie.exitflag;
                    secondaryOutput = struct('iterations',nearTie.iterations);
                elseif primaryAccepted && ...
                        obj.sourceRootCondensedMultiInputCoordinationEnabled
                    [secondaryStep,nearTie] = obj.nearTieCommandStep( ...
                        primaryHessian,primaryGradient,A,b,primaryStep, ...
                        primaryValue,objectiveGuardData);
                    coordinationNearTie = nearTie;
                    secondaryValue = nearTie.commandCost;
                    % Command proximity is a near-tie selector only.  If its
                    % solve fails, the already qualified primary remains the
                    % candidate for nonlinear replay.
                    secondaryExitflag = 1;
                    secondaryOutput = struct('iterations',nearTie.iterations);
                elseif primaryAccepted && obj.nonlinearOuterReferenceGovernorEnabled
                    % The primary Hessian includes a strictly positive
                    % regularization*I term.  Within the primary rigid-cost
                    % level set that is the deterministic minimum-deviation
                    % tie selector, so a second nonlinear solve cannot change
                    % the unique QP minimizer.  Reusing it prevents an
                    % otherwise redundant fmincon stage from stalling the
                    % safety governor before replay can decide feasibility.
                    secondaryStep = primaryStep;
                    secondaryValue = secondaryObjective(primaryStep);
                    secondaryExitflag = 1;
                    secondaryOutput = struct('iterations',0);
                elseif primaryAccepted
                    primaryConstraint = @(z) deal( ...
                        primaryObjective(z)-primaryValue-primaryTolerance,[]);
                    secondaryOptions = optimoptions(options,"OutputFcn",@secondaryIterationOutputFcn);
                    phaseTimer = tic;
                    [secondaryStep,secondaryValue,secondaryExitflag,secondaryOutput] = ...
                        fmincon(secondaryObjective,primaryStep,A,b,[],[],[],[], ...
                        primaryConstraint,secondaryOptions);
                    phaseSeconds.secondarySolve = phaseSeconds.secondarySolve + toc(phaseTimer);
                else
                    secondaryStep = zero; secondaryValue = nan; secondaryExitflag = -inf;
                    secondaryOutput = struct();
                end
                if obj.trajectoryMetricSharedAllocationEnabled
                    secondaryPrimaryConstraintValue = ...
                        obj.trajectoryMetricCost(physicalMetric,secondaryStep) - ...
                        primaryValue;
                else
                    secondaryPrimaryConstraintValue = ...
                        primaryObjective(secondaryStep) - primaryValue;
                end
                secondaryUnscaledViolationInf = obj.linearConstraintViolation( ...
                    AUnscaled,bUnscaled,secondaryStep);
                secondaryScaledViolationInf = obj.linearConstraintViolation( ...
                    A,b,secondaryStep);
                secondaryConstraintSatisfied = primaryAccepted && secondaryExitflag > 0 && ...
                    all(isfinite(secondaryStep)) && isfinite(secondaryValue) && ...
                    secondaryPrimaryConstraintValue <= primaryTolerance && ...
                    secondaryUnscaledViolationInf <= options.ConstraintTolerance;
                primaryReplayChecks = struct('available',false);
                if primaryAccepted
                    phaseTimer = tic;
                    [~,primaryTrial] = obj.fullChannelRollout(plant,package,fusion, ...
                        actuator,xFlexible,uPrevious,uOuter,nominalRates, ...
                        nominalCommands,gustHorizon,scale,primaryStep, ...
                        nmpcCandidateHorizon);
                    primaryReplayChecks = obj.fullChannelHardChecks( ...
                        plant,actuator,primaryTrial,outputReference);
                    if obj.sourceRootCondensedMultiInputCoordinationEnabled
                        [primaryFlexible,primaryRigid] = obj.residuals( ...
                            controller,primaryTrial,outputReference, ...
                            rigidReference,obj.nInterval);
                        if obj.trajectoryMetricSharedAllocationEnabled
                            [primaryCoordinationChecks, ...
                                primaryRigidTrajectoryTube] = ...
                                obj.trajectoryMetricReplayChecks( ...
                                nominalPhysical,nominalRigid,primaryTrial, ...
                                primaryRigid,outputReference);
                        else
                            primaryCoordinationChecks = obj.replayChecks( ...
                                min(plant.trimThrust+[primaryTrial.rigidCommand.thrust]), ...
                                nominal,primaryTrial,zeros(0,1),nominalRigid, ...
                                primaryFlexible,primaryRigid,outputReference, ...
                                outputLimits,rigidReference,true);
                        end
                        primaryCoordinationChecks.available = true;
                        primaryReplayChecks.sourceRootCoordination = ...
                            all(structfun(@logical,primaryCoordinationChecks));
                    end
                    primaryReplayChecks.available = true;
                    phaseSeconds.primaryNonlinearReplay = ...
                        phaseSeconds.primaryNonlinearReplay + toc(phaseTimer);
                end
                secondaryTieConstraintFailed = primaryAccepted && ...
                    all(isfinite(secondaryStep)) && isfinite(secondaryValue) && ...
                    secondaryPrimaryConstraintValue > primaryTolerance;
                primarySafeFallback = obj.fullChannelPrimarySafeFallbackEnabled && ...
                    AeroFlex.ctrl.CoupledRtiAllocatorAudit.primarySafeFallbackEligibility( ...
                    primaryAccepted,primaryReplayChecks,secondaryTieConstraintFailed);
                if obj.trajectoryMetricSharedAllocationEnabled
                    primarySafeFallback = primaryAccepted && ...
                        primaryReplayChecks.available && ...
                        all(structfun(@logical,rmfield( ...
                        primaryReplayChecks,"available"))) && ...
                        ~secondaryConstraintSatisfied;
                end
                candidateAccepted = secondaryConstraintSatisfied;
                candidateSelected = nominal; candidateStep = zero;
                candidateChecks = obj.fullChannelHardChecks( ...
                    plant,actuator,nominal,outputReference);
                replayAttempts = repmat(struct('alpha',nan, ...
                    'accepted',false,'hardChecks',struct(), ...
                    'coordinationReplayChecks',struct('available',false), ...
                    'rigidTrajectoryTube',struct('enabled',false), ...
                    'flexibleCost',nan,'rigidCost',nan),0,1);
                if candidateAccepted
                    phaseTimer = tic;
                    replayAlphas = 1;
                    if obj.trajectoryMetricSharedAllocationEnabled
                        replayAlphas = [1,0.5,0.25,0.125,0.0625];
                    end
                    candidateAccepted = false;
                    for replayAlpha = replayAlphas
                        replayStep = replayAlpha*secondaryStep;
                        [~,trial] = obj.fullChannelRollout(plant,package,fusion, ...
                            actuator,xFlexible,uPrevious,uOuter,nominalRates, ...
                            nominalCommands,gustHorizon,scale,replayStep, ...
                            nmpcCandidateHorizon);
                        trialChecks = obj.fullChannelHardChecks( ...
                            plant,actuator,trial,outputReference);
                        trialCoordinationChecks = struct('available',false);
                        trialRigidTrajectoryTube = struct('enabled',false);
                        trialFlexibleCost = nan;
                        trialRigidCost = nan;
                        if obj.sourceRootCondensedMultiInputCoordinationEnabled
                            [trialFlexible,trialRigid] = obj.residuals( ...
                                controller,trial,outputReference,rigidReference, ...
                                obj.nInterval);
                            if obj.trajectoryMetricSharedAllocationEnabled
                                [trialCoordinationChecks, ...
                                    trialRigidTrajectoryTube] = ...
                                    obj.trajectoryMetricReplayChecks( ...
                                    nominalPhysical,nominalRigid,trial, ...
                                    trialRigid,outputReference);
                                trialPhysical = ...
                                    obj.sourceNormalizedPhysicalResidual( ...
                                    trial,outputReference);
                                trialFlexibleCost = ...
                                    0.5*(trialPhysical.'*trialPhysical);
                                trialRigidCost = 0.5*(trialRigid.'*trialRigid);
                            else
                                trialCoordinationChecks = obj.replayChecks( ...
                                    min(plant.trimThrust+[trial.rigidCommand.thrust]), ...
                                    nominal,trial,zeros(0,1),nominalRigid, ...
                                    trialFlexible,trialRigid,outputReference, ...
                                    outputLimits,rigidReference,true);
                            end
                            trialChecks.sourceRootCoordination = ...
                                all(structfun(@logical,trialCoordinationChecks));
                            lastCoordinationChecks = trialCoordinationChecks;
                            lastCoordinationChecks.available = true;
                            lastRigidTrajectoryTube = trialRigidTrajectoryTube;
                        end
                        replayAccepted = all(structfun(@logical,trialChecks));
                        replayAttempts(end+1,1) = struct( ... %#ok<AGROW>
                            'alpha',replayAlpha,'accepted',replayAccepted, ...
                            'hardChecks',trialChecks, ...
                            'coordinationReplayChecks', ...
                                trialCoordinationChecks, ...
                            'rigidTrajectoryTube',trialRigidTrajectoryTube, ...
                            'flexibleCost',trialFlexibleCost, ...
                            'rigidCost',trialRigidCost);
                        if replayAccepted
                            candidateAccepted = true;
                            candidateSelected = trial;
                            candidateStep = replayStep;
                            candidateChecks = trialChecks;
                            selectedRigidTrajectoryTube = ...
                                trialRigidTrajectoryTube;
                            selectedReplayAlpha = replayAlpha;
                            break
                        end
                    end
                    lastReplayAttempts = replayAttempts;
                    phaseSeconds.nonlinearReplay = phaseSeconds.nonlinearReplay + toc(phaseTimer);
                end
                if ~candidateAccepted && primarySafeFallback
                    candidateSelected = primaryTrial; candidateStep = primaryStep;
                    candidateChecks = primaryReplayChecks; candidateAccepted = true;
                    selectedReplayAlpha = 1;
                    selectedRigidTrajectoryTube = ...
                        primaryRigidTrajectoryTube;
                end
                trustRegionAttempts(end+1,1) = struct('bound',trustRegionBound, ...
                    'primaryExitflag',primaryExitflag,'primaryValue',primaryValue, ...
                    'secondaryExitflag',secondaryExitflag,'accepted',candidateAccepted, ...
                    'primaryReplayHardChecks',primaryReplayChecks, ...
                    'coordinationReplayChecks',lastCoordinationChecks, ...
                    'guardedPrimary',guardedPrimaryCapture, ...
                    'constraintDiagnostic',constraintDiagnostic, ...
                    'rowScalingDiagnostic',rowScalingDiagnostic, ...
                    'primaryUnscaledViolationInf',primaryUnscaledViolationInf, ...
                    'primaryScaledViolationInf',primaryScaledViolationInf, ...
