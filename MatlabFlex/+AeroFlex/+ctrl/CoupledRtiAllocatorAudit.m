                    'secondaryScaledViolationInf',secondaryScaledViolationInf, ...
                    'replayAttempts',replayAttempts, ...
                    'selectedByPrimarySafeFallback',primarySafeFallback); %#ok<AGROW>
                if candidateAccepted
                    accepted = true; selected = candidateSelected;
                    selectedStep = candidateStep; hardChecks = candidateChecks;
                    selectedTrustRegionBound = trustRegionBound;
                    break
                end
            end
            if accepted
                % The nonlinear preview spans the outer 0.04 s interval,
                % but receding-horizon runtime application advances the
                % fusion/actuator chain once at the first 0.01 s inner
                % sample.  Return that first realized endpoint, not the
                % endpoint at the end of the preview interval.
                appliedEndpointTarget = selected.firstEndpoint(:,1);
                appliedRigidCommand = selected.rigidCommand(1);
                appliedOuterReference = selected.outerReference(:,1);
                appliedInnerEndpointTarget = selected.firstInnerEndpointTarget;
                obj.lastSafeRigidCommand = appliedRigidCommand;
                obj.warmRates = selected.rates;
                obj.initialized = true;
                exitflag = 1;
                if primarySafeFallback
                    message = "Applied replay-safe primary endpoint after secondary tie failure.";
                else
                    message = "Accepted full-channel lexicographic nonlinear replay.";
                end
            else
                appliedEndpointTarget = uPrevious(:);
                if isempty(fieldnames(obj.lastSafeRigidCommand))
                    appliedRigidCommand = rigidCommand;
                else
                    appliedRigidCommand = obj.lastSafeRigidCommand;
                end
                if obj.nonlinearOuterReferenceGovernorEnabled || ...
                        obj.jointSharedSurfaceSafetyCoordinationEnabled
                    appliedOuterReference = fusion.uTrim(:);
                else
                    appliedOuterReference = uOuter(:);
                end
                appliedInnerEndpointTarget = uPrevious(:);
                obj.warmRates(:) = 0;
                obj.initialized = false;
                exitflag = 0;
                message = "Retained preceding safe full endpoint after allocation rejection.";
            end
            assert(plant.trimThrust + appliedRigidCommand.thrust >= 0, ...
                "CoupledRtiAllocatorAudit:FullChannelThrust", ...
                "The full-channel fallback attempted negative thrust.");
            [~,selectedRigid] = obj.residuals(controller,selected,struct(), ...
                rigidReference,obj.nInterval);
            if obj.normalizedRigidTrajectoryTubeEnabled && ...
                    (~isfield(selectedRigidTrajectoryTube,'enabled') || ...
                    ~selectedRigidTrajectoryTube.enabled)
                selectedRigidTrajectoryTube = ...
                    obj.rigidTrajectoryTubeMembership( ...
                    nominalRigid,selectedRigid);
            end
            [nominalFlexible,~] = obj.residuals(controller,nominal,struct(), ...
                rigidReference,obj.nInterval);
            [selectedFlexible,~] = obj.residuals(controller,selected,struct(), ...
                rigidReference,obj.nInterval);
            nominalCost = obj.costSummary(nominalFlexible,nominalRigid);
            selectedCost = obj.costSummary(selectedFlexible,selectedRigid);
            if obj.sourceRootCondensedMultiInputCoordinationEnabled
                selectedPhysical = obj.sourceNormalizedPhysicalResidual( ...
                    selected,outputReference);
                nominalCost.combined = 0.5*(nominalPhysical.'*nominalPhysical);
                selectedCost.combined = 0.5*(selectedPhysical.'*selectedPhysical);
            end
            secondarySelection = "separate_fmincon_near_tie";
            if obj.nonlinearOuterReferenceGovernorEnabled
                secondarySelection = "embedded_positive_primary_regularization";
            elseif obj.trajectoryMetricSharedAllocationEnabled
                secondarySelection = "rigid_trajectory_inside_flexible_near_tie";
            end
            info = struct("cost",0.5*(selectedRigid.'*selectedRigid), ...
                "exitflag",exitflag,"accepted",accepted,"solveAttempted",true, ...
                "uHorizon",obj.padHorizon(selected.firstEndpoint,appliedEndpointTarget,controller.Nc), ...
                "wHorizon",obj.padGustHorizon(gustHorizon,controller.Nc), ...
                "continuity",0,"continuityTwoNorm",0, ...
                "constraintViolationInf",obj.constraintViolation(hardChecks), ...
                "output",struct("iterations",safeField(secondaryOutput,"iterations",nan), ...
                "message",message,"auditCapture",struct( ...
                "schemaVersion","phase18c-v17a-casea-full-channel-lexicographic-trajectory-allocation-v1", ...
                "sample",obj.callCount,"timeSeconds",timeSeconds, ...
                "nonlinearOuterReferenceGovernor", ...
                obj.nonlinearOuterReferenceGovernorEnabled, ...
                "jointSharedSurfaceSafetyCoordination", ...
                obj.jointSharedSurfaceSafetyCoordinationEnabled, ...
                "sourceRootCondensedMultiInputCoordination", ...
                obj.sourceRootCondensedMultiInputCoordinationEnabled, ...
                "trajectoryMetricSharedAllocation", ...
                obj.trajectoryMetricSharedAllocationEnabled, ...
                "normalizedRigidTrajectoryTube", ...
                    obj.normalizedRigidTrajectoryTubeCapture( ...
                    selectedRigidTrajectoryTube,lastRigidTrajectoryTube), ...
                "governorIntervened",obj.nonlinearOuterReferenceGovernorEnabled, ...
                "primaryExitflag",primaryExitflag,"primaryValue",primaryValue, ...
                "primaryTolerance",primaryTolerance, ...
                "primaryIterations",safeField(primaryOutput,"iterations",nan), ...
                "secondaryExitflag",secondaryExitflag, ...
                "secondaryValue",secondaryValue, ...
                "secondaryIterations",safeField(secondaryOutput,"iterations",nan), ...
                "primaryConstraintValue",secondaryPrimaryConstraintValue, ...
                "primaryConstraintSatisfied",secondaryConstraintSatisfied, ...
                "rowScalingEnabled",obj.fullChannelRowScalingEnabled, ...
                "unscaledConstraintTolerance",options.ConstraintTolerance, ...
                "secondaryTieConstraintFailed",secondaryTieConstraintFailed, ...
                "primarySafeFallbackEnabled",obj.fullChannelPrimarySafeFallbackEnabled, ...
                "primarySafeFallbackApplied",primarySafeFallback, ...
                "trustRegionContinuationEnabled",obj.fullChannelTrustRegionContinuationEnabled, ...
                "trustRegionCandidates",obj.fullChannelTrustRegionBounds, ...
                "trustRegionAttempts",trustRegionAttempts, ...
                "selectedTrustRegionBound",selectedTrustRegionBound, ...
                "hardChecks",hardChecks, ...
                "decisionScale",scale,"decisionIndices",decisionIndices, ...
                "condensedFirstMove",obj.fullChannelCondensedFirstMoveEnabled, ...
                "selectedDecision",selectedStep, ...
                "qpExitflag",primaryExitflag, ...
                "qpSelectedAlgorithm", ...
                    localGuardedAlgorithmLabel(guardedPrimaryCapture, ...
                    obj.sourceRootCondensedMultiInputCoordinationEnabled, ...
                    obj.trajectoryMetricSharedAllocationEnabled), ...
                "selectedAlpha",selectedReplayAlpha, ...
                "fallback",~accepted, ...
                "primaryNumericallyConverged",primaryExitflag>0 && ...
                    isfinite(primaryValue), ...
                "primaryLinearFeasible",primaryAccepted, ...
                "numericalSolveAccepted",primaryAccepted && ...
                    (secondaryConstraintSatisfied || primarySafeFallback), ...
                "nonlinearReplayAttempted", ...
                    primaryReplayChecks.available || ~isempty(lastReplayAttempts), ...
                "nonlinearReplayAccepted",accepted, ...
                "checks",hardChecks, ...
                "lastTrialChecks",hardChecks, ...
                "trialDiagnostics",trustRegionAttempts, ...
