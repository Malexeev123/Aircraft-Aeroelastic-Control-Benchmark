                "secondaryNearTie",coordinationNearTie, ...
                "guardedPrimary",guardedPrimaryCapture, ...
                "guardedProblem",guardedProblemCapture, ...
                "physicalOutputNormalization", ...
                    obj.physicalOutputNormalizationCapture(nominal), ...
                "physicalResidualJacobian",physicalJacobian, ...
                "coordinationReplayChecks",lastCoordinationChecks, ...
                "objectiveNondegradationConstraints", ...
                    objectiveGuardCapture, ...
                "outputReference",outputReference, ...
                "nominalCost",nominalCost, ...
                "candidateCost",selectedCost, ...
                "trajectoryMetricOutcome", ...
                    obj.trajectoryMetricOutcome(nominalPhysical, ...
                    nominalRigid,selected,selectedRigid,outputReference), ...
                "safeZero",accepted && norm(selectedStep,inf)<=1e-10, ...
                "nonzeroIntervention",accepted && norm(selectedStep,inf)>1e-10, ...
                "selectedRates",selected.rates, ...
                "maximumEndpointEquality",selected.maximumEndpointEquality, ...
                "minimumActuatorMargin",selected.minimumActuatorMargin, ...
                "appliedRigidCommand",appliedRigidCommand, ...
                "nominalRigidCost",0.5*(nominalRigid.'*nominalRigid), ...
                "selectedRigidCost",0.5*(selectedRigid.'*selectedRigid), ...
                "responseJacobianFinite",all(isfinite(responseJacobian),"all"), ...
                "responseJacobianColumnInfinity", ...
                max(abs(responseJacobian),[],1).', ...
                "rigidJacobianFinite",all(isfinite(rigidJacobian),"all"), ...
                "rigidJacobianColumnInfinity", ...
                max(abs(rigidJacobian),[],1).', ...
                "responseJacobianCondition",cond(responseJacobian), ...
                "rigidJacobianCondition",cond(rigidJacobian), ...
                "fminconAlgorithm",obj.fullChannelFminconAlgorithm, ...
                "primarySolver",obj.fullChannelPrimarySolver, ...
                "secondarySelection",secondarySelection, ...
                "primaryReplayHardChecks",primaryReplayChecks, ...
