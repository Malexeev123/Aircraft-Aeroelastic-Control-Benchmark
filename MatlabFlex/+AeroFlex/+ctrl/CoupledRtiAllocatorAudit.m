        function [selected,info] = solveGuardedPhysicalStepLadder( ...
                obj,H,g,A,b,guardData)
        %SOLVEGUARDEDPHYSICALSTEPLADDER Compare small-QCQP solvers in place.
            % The saved S141 QCQP isolates the solver choice: SQP stopped
            % infeasible after 248.4 s, while interior-point passed the same
            % guards in 5.31 s. Keep only the qualified branch here.
            algorithms = "interior-point";
            iterationLimits = 200;
            linearRowsBefore = size(A,1);
            [A,b,reduction] = obj.removeTrustBoxRedundantRows(A,b);
            attempts = repmat(struct("attempted",false,"accepted",false, ...
                "algorithm","","maximumIterations",nan,"exitflag",nan, ...
                "iterations",nan,"constraintViolation",nan, ...
                "primaryCost",nan),numel(algorithms),1);
