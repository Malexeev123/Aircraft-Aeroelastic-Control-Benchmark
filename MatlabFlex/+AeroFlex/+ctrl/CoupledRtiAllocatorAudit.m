            nominalCost = obj.costSummary(nominalFlexible,nominalRigid);
            selectedCost = obj.costSummary(selectedFlexible,selectedRigid);
            rigidPreservation = obj.rigidPreservationCheck( ...
                nominal,selected,rigidReference);
            info = struct( ...
                "cost",selectedCost.combined,"exitflag",exitflag, ...
                "accepted",accepted,"solveAttempted",true, ...
                "uHorizon",uHorizon, ...
                "candidateUHorizon",uHorizon, ...
                "candidateFirstCommand",appliedEndpointTarget, ...
                "uBaseHorizon",uBaseHorizon, ...
