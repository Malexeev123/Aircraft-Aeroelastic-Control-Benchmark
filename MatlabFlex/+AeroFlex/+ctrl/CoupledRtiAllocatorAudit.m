        function [A,b] = physicalConstraints(obj,actuator,uPrevious, ...
                nominalRates,rateScale)
            nSurface = numel(rateScale);
            nDecision = nSurface*obj.nInterval;
            Ts = obj.cfg.ctrl.Ts;
            correctionMap = kron(tril(ones(obj.nInterval)), ...
                diag(Ts*rateScale));
            nominalDelta = repmat(uPrevious(1:nSurface), ...
                obj.nInterval,1)+kron(tril(ones(obj.nInterval)), ...
                Ts*eye(nSurface))*nominalRates(:);
            deltaLower = repmat(actuator.deltaL(:), ...
                obj.nInterval,1)-nominalDelta;
            deltaUpper = repmat(actuator.deltaU(:), ...
                obj.nInterval,1)-nominalDelta;
            nominalRate = nominalRates(:);
            rateLower = (repmat(actuator.rateL(:), ...
                obj.nInterval,1)-nominalRate)./repmat( ...
                rateScale,obj.nInterval,1);
            rateUpper = (repmat(actuator.rateU(:), ...
                obj.nInterval,1)-nominalRate)./repmat( ...
                rateScale,obj.nInterval,1);
            lower = max(rateLower,-obj.trustRegionFraction* ...
                ones(nDecision,1));
            upper = min(rateUpper,obj.trustRegionFraction* ...
                ones(nDecision,1));
            A = [correctionMap;-correctionMap; ...
                eye(nDecision);-eye(nDecision)];
            b = [deltaUpper;-deltaLower;upper;-lower];
        end

        function [A,b,limits] = outputConstraints(obj,nominal, ...
                responseJacobian,decisionScale,reference)
            A = []; b = []; limits = struct();
            protectedNames = ["wingtip","clampFz","clampMy"];
            if ~isempty(fieldnames(obj.protectedOutputEnvelope))
                protectedNames = [protectedNames,"totalFz","totalMy", ...
                    "pitchRate"];
            end
            if obj.coupledNmpcPredictorEnabled
                % A commanded free-flight trajectory cannot be constrained to
                % the exact zero-inner trajectory: that makes every nonzero
                % correction infeasible at command onset.  This audit uses
                % the declared physical output limits instead, while retaining
                % nonlinear preview/backtracking and the zero-inner fallback.
                absolute = struct("wingtip",0.009656201218759807, ...
                    "clampFz",1.464539133337300, ...
                    "clampMy",345.88503202222086, ...
                    "totalFz",inf,"totalMy",inf,"pitchRate",inf);
                for name = protectedNames
                    jacobian = responseJacobian( ...
                        nominal.layout.(name),:).*decisionScale.';
                    limit = absolute.(name);
                    if name == "wingtip"
                        % The source envelope is trim-relative heave, while
                        % tipValue now returns the package-owned signed
                        % physical position. Apply the bound to departure.
                        value = nominal.(name)-reference.(name);
                        if isfinite(limit)
                            A = [A;jacobian;-jacobian]; %#ok<AGROW>
                            b = [b;limit-value;limit+value]; %#ok<AGROW>
                        end
                        limits.(name) = struct("departureLimit",limit, ...
                            "reference",reference.(name),"tolerance",0);
                    else
                        value = nominal.(name);
                        if isfinite(limit)
                            A = [A;jacobian;-jacobian]; %#ok<AGROW>
                            b = [b;limit-value;limit+value]; %#ok<AGROW>
                        end
                        limits.(name) = struct("absoluteLimit",limit, ...
                            "reference",reference.(name),"tolerance",0);
                    end
                end
            else
                for name = protectedNames
                    values = nominal.(name)-reference.(name);
                    tolerance = max(1e-10, ...
                        1e-8*max(1,abs(reference.(name))));
                    limit = max(abs(values))+tolerance;
                    jacobian = responseJacobian( ...
                        nominal.layout.(name),:).*decisionScale.';
                    A = [A;jacobian;-jacobian]; %#ok<AGROW>
                    b = [b;limit-values;limit+values]; %#ok<AGROW>
                    limits.(name) = struct("departureLimit",limit, ...
                        "reference",reference.(name), ...
                        "tolerance",tolerance);
                end
            end
            speedLower = 15;
            speedUpper = 20;
            % Speed is owned by the fixed outer rigid loop in this audit.
            % Preserve the hard corridor when its zero-wing preview is
            % admissible; if that exogenous preview already crosses a
            % boundary, keep the zero wing action feasible and prohibit the
            % inner allocation from worsening the predicted excursion.
            effectiveSpeedLower = min(speedLower,min(nominal.speed));
            effectiveSpeedUpper = max(speedUpper,max(nominal.speed));
            speedJacobian = responseJacobian( ...
                nominal.layout.speed,:).*decisionScale.';
            A = [A;speedJacobian;-speedJacobian];
            b = [b;effectiveSpeedUpper-nominal.speed; ...
                nominal.speed-effectiveSpeedLower];
            limits.speed = struct("corridorLower",speedLower, ...
                "corridorUpper",speedUpper, ...
                "lower",effectiveSpeedLower, ...
                "upper",effectiveSpeedUpper,"tolerance",1e-10, ...
                "nominalMinimum",min(nominal.speed), ...
                "nominalMaximum",max(nominal.speed), ...
                "nominalCorridorViolation",max([0; ...
                    speedLower-nominal.speed; ...
                    nominal.speed-speedUpper]));
            limits.robustEnvelope = obj.protectedOutputEnvelope;
        end

        function scale = fullChannelDecisionScale(obj,actuator)
        %FULLCHANNELDECISIONSCALE Normalize outer wing, elevator, and thrust.
            wing = 0.5*(actuator.deltaU(:)-actuator.deltaL(:));
            assert(all(isfinite(wing)) && all(wing>0), ...
                "CoupledRtiAllocatorAudit:FullChannelWingScale", ...
                "The actuator-position limits are invalid.");
            assert(norm(wing-wing(1),inf) <= 100*eps(max(wing)), ...
                "CoupledRtiAllocatorAudit:FullChannelSymmetricPosition", ...
                "The symmetric audit requires equal left/right position limits.");
            uMax = obj.cfg.outerLQR.uMax(:);
            assert(numel(uMax)==4 && all(isfinite(uMax)) && ...
                all(uMax>0),"CoupledRtiAllocatorAudit:FullChannelRigidScale", ...
                "The outer-LQR increment limits are invalid.");
            if obj.jointSharedSurfaceSafetyCoordinationEnabled
                rate = min(abs([actuator.rateL(:),actuator.rateU(:)]),[],2);
                assert(norm(rate-rate(1),inf) <= 100*eps(max(rate)), ...
                    "CoupledRtiAllocatorAudit:JointSymmetricRate", ...
                    "The joint audit requires equal left/right rate limits.");
                scale = repmat([wing(1);rate(1);uMax(1);uMax(4)], ...
                    obj.nInterval,1);
            else
                scale = repmat([wing(1);uMax(1);uMax(4)],obj.nInterval,1);
            end
        end

        function indices = fullChannelDecisionIndices(obj)
        %FULLCHANNELDECISIONINDICES Active correction entries in full ordering.
            if obj.fullChannelCondensedFirstMoveEnabled
                if obj.jointSharedSurfaceSafetyCoordinationEnabled
                    indices = (1:4).';
                else
                    indices = (1:3).';
                end
            else
                if obj.jointSharedSurfaceSafetyCoordinationEnabled
                    indices = (1:4*obj.nInterval).';
                else
                    indices = (1:3*obj.nInterval).';
                end
            end
        end

        function [response,detail] = fullChannelRollout(obj,plant,package, ...
                fusion,actuator,xFlexible,uPrevious,uOuter,nominalRates, ...
                nominalCommands,gustHorizon,scale,decision,nmpcCandidateHorizon)
            if nargin < 14 || isempty(nmpcCandidateHorizon)
                nmpcCandidateHorizon = [];
            end
            if isempty(scale)
                rates = nominalRates;
                commands = nominalCommands;
                outerReference = repmat(uOuter(:),1,obj.nInterval);
                innerRateCorrection = zeros(1,obj.nInterval);
            else
                [rates,commands,outerReference,innerRateCorrection] = ...
                    obj.fullChannelCommands(nominalRates,nominalCommands, ...
                    uOuter,scale,decision);
            end
            [rates,commands] = obj.appendFullChannelFeasibilityTail( ...
                rates,commands);
            outerReference = obj.appendFullChannelOuterReferenceTail( ...
                outerReference,size(rates,2));
            endpointTarget = [];
            if obj.jointSharedSurfaceSafetyCoordinationEnabled
                endpointTarget = obj.fullChannelJointEndpointTargets( ...
                    nmpcCandidateHorizon,uPrevious,innerRateCorrection, ...
                    size(rates,2));
            end
            [response,detail] = obj.rollout(plant,package,fusion,actuator, ...
                xFlexible,uPrevious,outerReference,commands,gustHorizon,rates, ...
                [],endpointTarget);
        end

        function [rates,commands,outerReference,innerRateCorrection] = fullChannelCommands(obj,nominalRates, ...
                nominalCommands,uOuter,scale,decision)
            assert(isequal(size(nominalRates),[obj.cfg.ctrl.n_surf,obj.nInterval]) && ...
                numel(nominalCommands)==obj.nInterval && ...
                numel(scale)==numel(obj.fullChannelDecisionIndices()) && ...
                numel(decision)==numel(obj.fullChannelDecisionIndices()), ...
                "CoupledRtiAllocatorAudit:FullChannelDimensions", ...
                "The full-channel command data have inconsistent dimensions.");
            nCoordinate = 3 + double(obj.jointSharedSurfaceSafetyCoordinationEnabled);
            scaledDecision = zeros(nCoordinate*obj.nInterval,1);
            indices = obj.fullChannelDecisionIndices();
            scaledDecision(indices) = scale(:).*decision(:);
            scaled = reshape(scaledDecision,nCoordinate,obj.nInterval);
            if obj.fullChannelCondensedFirstMoveEnabled && ...
                    obj.jointSharedSurfaceSafetyCoordinationEnabled
                scaled = repmat(scaled(:,1),1,obj.nInterval);
            end
            outerReference = repmat(uOuter(:),1,obj.nInterval);
            innerRateCorrection = zeros(1,obj.nInterval);
            if obj.nonlinearOuterReferenceGovernorEnabled || ...
                    obj.jointSharedSurfaceSafetyCoordinationEnabled
                % Govern the outer reference itself; reinterpreting this
                % correction as an inner rate leaves fusion's outer term fixed.
                rates = nominalRates;
                outerReference(1:obj.cfg.ctrl.n_surf,:) = ...
                    outerReference(1:obj.cfg.ctrl.n_surf,:) + ...
                    ones(obj.cfg.ctrl.n_surf,1)*scaled(1,:);
                if obj.jointSharedSurfaceSafetyCoordinationEnabled
                    innerRateCorrection = scaled(2,:);
                end
            else
                rates = nominalRates + ones(obj.cfg.ctrl.n_surf,1)*scaled(1,:);
            end
            commands = nominalCommands;
            for interval = 1:obj.nInterval
                rigidStart = 1 + double(obj.jointSharedSurfaceSafetyCoordinationEnabled);
                commands(interval).delta_e = commands(interval).delta_e + ...
                    scaled(rigidStart+1,interval);
                commands(interval).thrust = commands(interval).thrust + ...
                    scaled(rigidStart+2,interval);
            end
        end

