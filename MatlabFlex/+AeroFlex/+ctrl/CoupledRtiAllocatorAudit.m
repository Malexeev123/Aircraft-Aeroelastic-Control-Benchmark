                     'reciprocal runtime memory.']);
            end
            % The reciprocal correction is a separately installed runtime
            % provider, not a field of the scheduled flexible package.
            % Inherit its complete active record so preview and replay use
            % the same operators, schedule ownership, and causal memory.
            plant.reciprocalTangentCorrection = ownerReciprocal;
            tip = obj.tipMap(package,plant.beam);
        end

        function tip = tipMap(obj,package,beam)
            chart = struct();
            if isfield(package,"scheduleStateCoordinate") && ...
                    isstruct(package.scheduleStateCoordinate)
                chart = package.scheduleStateCoordinate;
            end
            if isfield(chart,"q2ToPhysical") && ...
                    isfield(chart,"qxiToPhysical")
                q2Map = double(chart.q2ToPhysical);
                qxiMap = double(chart.qxiToPhysical);
                mapOwner = "schedule_state_coordinate";
            else
                % Exact fixed-basis packages intentionally omit a transport
                % chart. Recover their native physical map using the same
                % package-owned rule as the signed-wingtip output contract.
                assert(obj.hasMember(package,"beam") && ...
                    obj.hasMember(package.beam,"red") && ...
                    obj.hasMember(package.beam.red,"ModeVars_discrete") && ...
                    obj.hasMember(package.beam.red.ModeVars_discrete, ...
                    "phi0_local") && obj.hasMember(obj.base,"phi_xi_modes"), ...
                    "CoupledRtiAllocatorAudit:TipMap", ...
                    "The exact package lacks its native physical recovery maps.");
                omega = -double(package.L(package.idx.q2,package.idx.q1));
                assert(isequal(size(omega),[numel(package.idx.q2), ...
                    numel(package.idx.q1)]) && all(isfinite(omega),"all") && ...
                    rcond(omega) > 100*eps, ...
                    "CoupledRtiAllocatorAudit:TipMapFrequency", ...
                    "The exact package q2/q1 recovery operator is invalid.");
                q2Map = -double(package.beam.red.ModeVars_discrete. ...
                    phi0_local)/omega;
                qxiMap = double(obj.base.phi_xi_modes);
                mapOwner = "exact_package_recovery";
            end
            assert(size(q2Map,2) == numel(package.idx.q2) && ...
                size(qxiMap,2) == numel(package.idx.qxi) && ...
                all(isfinite(q2Map),"all") && all(isfinite(qxiMap),"all"), ...
                "CoupledRtiAllocatorAudit:TipMap", ...
                "The active package physical recovery maps are invalid.");
            activeNodes = unique(ceil(double(beam.fem.keepDofs(:))/6), ...
                "stable");
            coordinates = double(beam.fem.coordinates(activeNodes,:));
            [~,positive] = max(coordinates(:,2));
            [~,negative] = min(coordinates(:,2));
            tip = struct("idx",package.idx, ...
                "q2Map",q2Map, ...
                "qxiMap",qxiMap,"mapOwner",mapOwner, ...
                "coordinates",coordinates,"positive",positive, ...
                "negative",negative,"base",obj.base);
        end

        function value = tipValue(~,state,tip)
            configuration = tip.q2Map*state(tip.idx.q2);
            quaternion = reshape( ...
                tip.qxiMap*state(tip.idx.qxi),4,[]).';
            quaternion = quaternion./vecnorm(quaternion,2,2);
            blocks = [tip.positive,tip.negative];
            z = zeros(2,1);
            for index = 1:2
                block = blocks(index);
                rows = (block-1)*6+(1:3);
                translation = AeroFlex.core.T_phi_quat( ...
                    quaternion(block,:).')*configuration(rows);
                z(index) = tip.coordinates(block,3)+translation(3);
            end
            value = mean(z);
        end

