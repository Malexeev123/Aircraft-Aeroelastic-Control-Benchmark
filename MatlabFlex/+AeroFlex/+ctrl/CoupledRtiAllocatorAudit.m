        function tube = normalizedRigidTubeMembership( ...
                nominal,candidate,fractions,auditFraction)
        %NORMALIZEDRIGIDTUBEMEMBERSHIP Componentwise additive RMS tube.
            nominal = double(nominal(:));
            candidate = double(candidate(:));
            fractions = double(fractions(:));
            assert(numel(nominal)==numel(candidate) && ...
                mod(numel(nominal),4)==0 && all(isfinite(nominal)) && ...
                all(isfinite(candidate)) && all(isfinite(fractions)) && ...
                isscalar(auditFraction) && isfinite(auditFraction) && ...
                any(fractions==auditFraction), ...
                "CoupledRtiAllocatorAudit:RigidTrajectoryTubeDimensions", ...
                ['The rigid tube requires four finite equal trajectory ', ...
                 'groups and a declared audit fraction.']);
            nStep = numel(nominal)/4;
            nominalGroups = reshape(nominal,nStep,4);
            candidateGroups = reshape(candidate,nStep,4);
            nominalRms = vecnorm(nominalGroups,2,1).';
            candidateRms = vecnorm(candidateGroups,2,1).';
            increase = candidateRms-nominalRms;
            tolerance = 256*eps(max(1,max([nominalRms;candidateRms])));
            membership = false(numel(fractions),1);
            for index = 1:numel(fractions)
                membership(index) = all(increase<=fractions(index)+tolerance);
            end
            tube = struct('nominalNormalizedRms',nominalRms, ...
                'candidateNormalizedRms',candidateRms, ...
                'normalizedRmsIncrease',increase, ...
                'fractions',fractions,'membership',membership, ...
                'auditFraction',auditFraction, ...
                'auditPassed',membership(fractions==auditFraction), ...
                'tolerance',tolerance);
        end

