classdef CoupledRtiAllocatorAudit < handle
%COUPLEDRTIALLOCATORAUDIT Default-disabled coupled allocation checkpoint.
%   Propagates the active flexible and rigid runtime from the current nMHE
%   flexible estimate and measured rigid state. The class is audit-only;
%   sim_run retains scheduling, fusion, actuator, fallback, and plant owners.

    properties (SetAccess=private)
        cfg struct
        beam
        aero
        base
        nInterval (1,1) double = 3
        finiteDifferenceStep (1,1) double = 2.5e-3
        trustRegionFraction (1,1) double = 0.05
        protectedOutputEnvelope struct = struct()
        rigidPreservationGuardEnabled (1,1) logical = false
        futureScheduledPackageSequenceEnabled (1,1) logical = false
        fullChannelLexicographicEnabled (1,1) logical = false
        fullChannelFminconAlgorithm (1,1) string = "sqp"
        fullChannelPrimarySolver (1,1) string = "fmincon-sqp"
        fullChannelPrimarySafeFallbackEnabled (1,1) logical = false
        fullChannelCondensedFirstMoveEnabled (1,1) logical = false
        fullChannelTrustRegionContinuationEnabled (1,1) logical = false
        fullChannelTrustRegionBounds double = 0.25
        fullChannelFeasibilityTailEnabled (1,1) logical = false
        fullChannelFeasibilityTailIntervals (1,1) double = 0
        fullChannelFeasibilityTailMaximumAllocatorCalls (1,1) double = inf
        fullChannelMaximumAllocatorCalls (1,1) double = inf
        fullChannelPreviewIntervalCount (1,1) double = 10
        fullChannelRowScalingEnabled (1,1) logical = false
        nonlinearOuterReferenceGovernorEnabled (1,1) logical = false
        jointSharedSurfaceSafetyCoordinationEnabled (1,1) logical = false
        dynamicNullspaceWingOnlyEnabled (1,1) logical = false
        baselineRelativeRigidTubeEnabled (1,1) logical = false
        baselineRelativeRigidTubeFractions double = zeros(0,1)
        coupledNmpcPredictorEnabled (1,1) logical = false
        sourceNormalizedPhysicalOutputObjectiveEnabled (1,1) logical = false
        sourceRootCondensedMultiInputCoordinationEnabled (1,1) logical = false
        trajectoryMetricSharedAllocationEnabled (1,1) logical = false
        normalizedRigidTrajectoryTubeEnabled (1,1) logical = false
        normalizedRigidTrajectoryTubeFractions double = [0.001;0.01;0.05]
        normalizedRigidTrajectoryTubeFraction (1,1) double = 0.05
        debugEnabled (1,1) logical = false
        debugPrintIterations (1,1) logical = false
        warmRates double
        lastSafeRigidCommand struct = struct()
        initialized (1,1) logical = false
        callCount (1,1) double = 0
        lastPrediction struct = struct("valid",false)
        lastRealized struct = struct("valid",false)
    end

    methods
        function obj = CoupledRtiAllocatorAudit(cfg,beam,aero,base,request)
            arguments
                cfg struct
                beam
                aero
                base
                request struct
            end
            assert(isfield(request,"enabled") && logical(request.enabled) && ...
                isfield(request,"auditOnly") && logical(request.auditOnly), ...
                "CoupledRtiAllocatorAudit:AuditOnly", ...
                "The persistent coupled allocator requires auditOnly=true.");
            coupledPredictorSource = "";
            if isfield(request,"predictionIntervals")
                obj.nInterval = double(request.predictionIntervals);
            end
            if isfield(request,"finiteDifferenceStep")
                obj.finiteDifferenceStep = ...
                    double(request.finiteDifferenceStep);
            end
            if isfield(request,"fullChannelLexicographic") && ...
                    logical(request.fullChannelLexicographic)
                obj.fullChannelLexicographicEnabled = true;
            end
            if isfield(request,"nonlinearOuterReferenceGovernor") && ...
                    logical(request.nonlinearOuterReferenceGovernor)
                assert(isfield(request,"source") && string(request.source) == ...
                    "phase18c-v17a-casea-nonlinear-outer-reference-governor-audit-v1", ...
                    "CoupledRtiAllocatorAudit:NonlinearOuterReferenceGovernorSource", ...
                    ['The nonlinear outer-reference governor requires its ', ...
                     'approved, source-bound audit request.']);
                obj.nonlinearOuterReferenceGovernorEnabled = true;
            end
            if isfield(request,"jointSharedSurfaceSafetyCoordination") && ...
                    logical(request.jointSharedSurfaceSafetyCoordination)
                assert(isfield(request,"source") && any(string(request.source) == [ ...
                    "phase18c-v17a-casea-joint-shared-surface-safety-coordination-audit-v1", ...
                    "phase18c-v17a-casea-predictive-time-parameterized-joint-coordination-audit-v1", ...
                    "phase18c-v17a-caseb-source-root-condensed-multi-input-coordination-discriminator-v1", ...
                    "phase18c-v17a-caseb-trajectory-metric-shared-allocation-persistent-integration-v1"]), ...
                    "CoupledRtiAllocatorAudit:JointSharedSurfaceSource", ...
                    ['The joint shared-surface coordinator requires its ', ...
                     'approved, source-bound audit request.']);
                obj.jointSharedSurfaceSafetyCoordinationEnabled = true;
            end
            if isfield(request,"timeParameterizedJointCoordination") && ...
                    logical(request.timeParameterizedJointCoordination)
                assert(obj.jointSharedSurfaceSafetyCoordinationEnabled && ...
                    isfield(request,"source") && string(request.source) == ...
                    "phase18c-v17a-casea-predictive-time-parameterized-joint-coordination-audit-v1" && ...
                    isfield(request,"maximumAllocatorCalls") && ...
                    double(request.maximumAllocatorCalls)==1, ...
                    "CoupledRtiAllocatorAudit:TimeParameterizedJoint", ...
                    ['The time-parameterized joint study is restricted to its ', ...
                     'approved source and exactly one allocator call.']);
                obj.fullChannelMaximumAllocatorCalls = 1;
            end
            if isfield(request,"dynamicNullspaceWingOnly") && ...
                    logical(request.dynamicNullspaceWingOnly)
                assert(isfield(request,"source") && any(string(request.source) == ...
                    ["phase18c-v17a-casea-full-state-dynamic-nullspace-shared-wing-allocation-audit-v1", ...
                     "phase18c-v17a-casea-baseline-relative-rigid-tube-formal-integration-audit-v1"]), ...
                    "CoupledRtiAllocatorAudit:DynamicNullspaceSource", ...
                    ['The ten-interval wing-only allocation requires an ', ...
                     'approved source-bound audit request.']);
                obj.dynamicNullspaceWingOnlyEnabled = true;
            end
            if isfield(request,"baselineRelativeRigidTube") && ...
                    ~isempty(request.baselineRelativeRigidTube) && ...
                    isfield(request.baselineRelativeRigidTube,"enabled") && ...
                    logical(request.baselineRelativeRigidTube.enabled)
                tube = request.baselineRelativeRigidTube;
                assert(isstruct(tube) && logical(tube.enabled) && ...
                    logical(tube.auditOnly) && string(tube.source) == ...
                    "phase18c-v17a-casea-baseline-relative-rigid-output-tube-allocation-audit-v1", ...
                    "CoupledRtiAllocatorAudit:BaselineRelativeRigidTube", ...
                    "The baseline-relative rigid tube requires its approved audit record.");
                fractions = double(tube.fractions(:));
                assert(isequal(fractions,[0.001;0.01;0.05]), ...
                    "CoupledRtiAllocatorAudit:BaselineRelativeRigidTubeFractions", ...
                    "The rigid-output tube fractions must be [0.001;0.01;0.05].");
                obj.baselineRelativeRigidTubeEnabled = true;
                obj.baselineRelativeRigidTubeFractions = fractions;
            end
            if isfield(request,"debug") && ~isempty(request.debug)
                assert(isstruct(request.debug) && isfield(request.debug,"enabled"), ...
                    "CoupledRtiAllocatorAudit:Debug", ...
                    "The audit debug request must contain an enabled flag.");
                obj.debugEnabled = logical(request.debug.enabled);
                if isfield(request.debug,"printIterations")
                    obj.debugPrintIterations = logical( ...
                        request.debug.printIterations);
                end
            end
            if isfield(request,"solverAlgorithm")
                obj.fullChannelFminconAlgorithm = lower(string( ...
                    request.solverAlgorithm));
            end
            if isfield(request,"primarySolver")
                obj.fullChannelPrimarySolver = lower(string( ...
                    request.primarySolver));
            end
            if isfield(request,"primarySafeFallback")
                obj.fullChannelPrimarySafeFallbackEnabled = logical( ...
                    request.primarySafeFallback);
            end
            if isfield(request,"condensedFirstMove") && ...
                    ~isempty(request.condensedFirstMove)
                condensed = request.condensedFirstMove;
                assert(isstruct(condensed) && isscalar(condensed) && ...
                    isfield(condensed,"enabled") && isfield(condensed,"auditOnly") && ...
                    logical(condensed.auditOnly) && isfield(condensed,"source") && ...
                    any(string(condensed.source) == [ ...
                    "phase18c-v17a-casea-condensed-first-move-full-channel-allocation-audit-v1", ...
                    "phase18c-v17a-casea-nonlinear-outer-reference-governor-audit-v1", ...
                    "phase18c-v17a-casea-joint-shared-surface-safety-coordination-audit-v1", ...
                    "phase18c-v17a-casea-predictive-time-parameterized-joint-coordination-audit-v1", ...
                    "phase18c-v17a-caseb-source-root-condensed-multi-input-coordination-discriminator-v1", ...
                    "phase18c-v17a-caseb-trajectory-metric-shared-allocation-persistent-integration-v1"]), ...
                    "CoupledRtiAllocatorAudit:CondensedFirstMove", ...
                    ['The condensed first-move parameterization requires an ', ...
                     'approved audit-only source-bound request.']);
                obj.fullChannelCondensedFirstMoveEnabled = logical(condensed.enabled);
            end
            if isfield(request,"trustRegionContinuation") && ...
                    ~isempty(request.trustRegionContinuation)
                continuation = request.trustRegionContinuation;
                assert(isstruct(continuation) && isscalar(continuation) && ...
                    isfield(continuation,"enabled") && ...
                    isfield(continuation,"auditOnly") && ...
                    logical(continuation.auditOnly) && isfield(continuation,"source") && ...
                    string(continuation.source) == ...
                    "phase18c-v17a-casea-full-channel-trust-region-continuation-audit-v1" && ...
                    isfield(continuation,"candidateBounds"), ...
                    "CoupledRtiAllocatorAudit:TrustRegionContinuation", ...
                    ['The trust-region continuation requires the approved ', ...
                     'audit-only source-bound request.']);
                bounds = double(continuation.candidateBounds(:).');
                assert(isequal(bounds,[0.25,0.50,0.75,1.00]), ...
                    "CoupledRtiAllocatorAudit:TrustRegionCandidates", ...
                    "The continuation candidate bounds must be [0.25 0.50 0.75 1.00].");
                obj.fullChannelTrustRegionContinuationEnabled = logical( ...
                    continuation.enabled);
                if obj.fullChannelTrustRegionContinuationEnabled
                    obj.fullChannelTrustRegionBounds = bounds;
                end
            end
            if isfield(request,"feasibilityTail") && ...
                    ~isempty(request.feasibilityTail)
                tail = request.feasibilityTail;
                assert(isstruct(tail) && isscalar(tail) && ...
                    isfield(tail,"enabled") && isfield(tail,"auditOnly") && ...
                    logical(tail.auditOnly) && isfield(tail,"source") && ...
                    string(tail.source) == ...
                    "phase18c-v17a-casea-full-channel-feasibility-tail-audit-v1" && ...
                    isfield(tail,"intervals") && double(tail.intervals) == 10, ...
                    "CoupledRtiAllocatorAudit:FeasibilityTail", ...
                    ['The feasibility tail requires the approved ', ...
                     'audit-only source-bound ten-interval request.']);
                obj.fullChannelFeasibilityTailEnabled = logical(tail.enabled);
                if obj.fullChannelFeasibilityTailEnabled
                    obj.fullChannelFeasibilityTailIntervals = 10;
                    if isfield(tail,"maximumAllocatorCalls")
                        maximumCalls = double(tail.maximumAllocatorCalls);
                        assert(isscalar(maximumCalls) && isfinite(maximumCalls) && ...
                            maximumCalls >= 1 && maximumCalls == round(maximumCalls), ...
                            "CoupledRtiAllocatorAudit:FeasibilityTailCallLimit", ...
                            "The feasibility-tail allocator-call limit is invalid.");
                        obj.fullChannelFeasibilityTailMaximumAllocatorCalls = maximumCalls;
                    end
                end
            end
            if isfield(request,"rowScaling") && ~isempty(request.rowScaling)
                rowScaling = request.rowScaling;
                assert(isstruct(rowScaling) && isscalar(rowScaling) && ...
                    isfield(rowScaling,"enabled") && isfield(rowScaling,"auditOnly") && ...
                    logical(rowScaling.auditOnly) && isfield(rowScaling,"source") && ...
                    string(rowScaling.source) == ...
                    "phase18c-v17a-casea-full-channel-row-scaling-equivalence-audit-v1", ...
                    "CoupledRtiAllocatorAudit:FullChannelRowScaling", ...
                    ['The full-channel row scaling requires the approved ', ...
                     'audit-only source-bound request.']);
                obj.fullChannelRowScalingEnabled = logical(rowScaling.enabled);
            end
            obj.fullChannelPreviewIntervalCount = obj.nInterval + ...
                obj.fullChannelFeasibilityTailIntervals;
            if isfield(request,"coupledNmpcPredictor") && ...
                    ~isempty(request.coupledNmpcPredictor) && ...
                    isfield(request.coupledNmpcPredictor,"enabled") && ...
                    logical(request.coupledNmpcPredictor.enabled)
                predictor = request.coupledNmpcPredictor;
                assert(isstruct(predictor) && isscalar(predictor) && ...
                    isfield(predictor,"enabled") && isfield(predictor,"auditOnly") && ...
                    logical(predictor.auditOnly) && isfield(predictor,"source"), ...
                    "CoupledRtiAllocatorAudit:CoupledNmpcPredictor", ...
                    ['The coupled nMPC predictor requires the approved ', ...
                     'audit-only source-bound request.']);
                coupledPredictorSource = string(predictor.source);
                assert(any(coupledPredictorSource == [ ...
                    "phase18c-v17a-casea-coupled-nmpc-predictor-architecture-audit-v1", ...
                    "phase18c-v17a-caseb-native-horizon-coupled-predictor-objective-audit-v1", ...
                    "phase18c-v17a-caseb-source-normalized-physical-output-objective-audit-v1", ...
                    "phase18c-v17a-caseb-source-root-condensed-multi-input-coordination-discriminator-v1", ...
                    "phase18c-v17a-caseb-trajectory-metric-shared-allocation-persistent-integration-v1"]), ...
                    "CoupledRtiAllocatorAudit:CoupledNmpcPredictor", ...
                    ['The coupled nMPC predictor requires the approved ', ...
                     'audit-only source-bound request.']);
                obj.coupledNmpcPredictorEnabled = logical(predictor.enabled);
            end
            if isfield(request,"sourceNormalizedPhysicalOutputObjective") && ...
                    ~isempty(request.sourceNormalizedPhysicalOutputObjective)
                physical = request.sourceNormalizedPhysicalOutputObjective;
                assert(isstruct(physical) && isscalar(physical) && ...
                    isfield(physical,"enabled") && logical(physical.enabled) && ...
                    isfield(physical,"auditOnly") && logical(physical.auditOnly) && ...
                    isfield(physical,"source") && string(physical.source) == ...
                    "phase18c-v17a-caseb-source-normalized-physical-output-objective-audit-v1", ...
                    "CoupledRtiAllocatorAudit:PhysicalOutputObjectiveSource", ...
                    ['The source-normalized physical-output objective requires ', ...
                     'its approved audit-only source-bound request.']);
                assert(obj.coupledNmpcPredictorEnabled && ...
                    obj.nInterval == cfg.ctrl.Nc && obj.nInterval == 10 && ...
                    coupledPredictorSource == string(physical.source), ...
                    "CoupledRtiAllocatorAudit:PhysicalOutputObjectiveContract", ...
                    ['The source-normalized physical-output objective requires ', ...
                     'the native ten-interval coupled predictor.']);
                obj.sourceNormalizedPhysicalOutputObjectiveEnabled = true;
            end
            if isfield(request,"sourceRootCondensedMultiInputCoordination") && ...
                    ~isempty(request.sourceRootCondensedMultiInputCoordination)
                coordination = request.sourceRootCondensedMultiInputCoordination;
                source = string(request.source);
                allowedSources = [ ...
                    "phase18c-v17a-caseb-source-root-condensed-multi-input-coordination-discriminator-v1", ...
                    "phase18c-v17a-caseb-trajectory-metric-shared-allocation-persistent-integration-v1"];
                assert(isstruct(coordination) && isscalar(coordination) && ...
                    isfield(coordination,"enabled") && logical(coordination.enabled) && ...
                    isfield(coordination,"auditOnly") && logical(coordination.auditOnly) && ...
                    isfield(coordination,"source") && ...
                    string(coordination.source)==source && any(source==allowedSources), ...
                    "CoupledRtiAllocatorAudit:SourceRootCoordinationSource", ...
                    ['The source-root condensed coordination discriminator ', ...
                     'requires its approved audit-only source-bound request.']);
                assert(obj.fullChannelLexicographicEnabled && ...
                    obj.jointSharedSurfaceSafetyCoordinationEnabled && ...
                    obj.fullChannelCondensedFirstMoveEnabled && ...
                    obj.coupledNmpcPredictorEnabled && obj.nInterval==10 && ...
                    obj.nInterval==cfg.ctrl.Nc && coupledPredictorSource==source, ...
                    "CoupledRtiAllocatorAudit:SourceRootCoordinationContract", ...
                    ['The source-root discriminator requires exactly four ', ...
                     'condensed coordinates and the native ten-interval predictor.']);
                obj.sourceNormalizedPhysicalOutputObjectiveEnabled = true;
                obj.sourceRootCondensedMultiInputCoordinationEnabled = true;
            end
            if isfield(request,"trajectoryMetricSharedAllocation") && ...
                    ~isempty(request.trajectoryMetricSharedAllocation)
                trajectory = request.trajectoryMetricSharedAllocation;
                source = ...
                    "phase18c-v17a-caseb-trajectory-metric-shared-allocation-persistent-integration-v1";
                assert(isstruct(trajectory) && isscalar(trajectory) && ...
                    isfield(trajectory,"enabled") && logical(trajectory.enabled) && ...
                    isfield(trajectory,"auditOnly") && logical(trajectory.auditOnly) && ...
                    isfield(trajectory,"source") && string(trajectory.source)==source && ...
                    isfield(trajectory,"priority") && ...
                    string(trajectory.priority)=="flexible_first_rigid_near_tie" && ...
                    isfield(request,"source") && string(request.source)==source && ...
                    obj.sourceRootCondensedMultiInputCoordinationEnabled, ...
                    "CoupledRtiAllocatorAudit:TrajectoryMetricSharedAllocation", ...
                    ['The trajectory-metric allocation requires its approved ', ...
                     'source-bound flexible-first request and source-root owner.']);
                obj.trajectoryMetricSharedAllocationEnabled = true;
                if isfield(trajectory,"normalizedRigidTrajectoryTube") && ...
                        ~isempty(trajectory.normalizedRigidTrajectoryTube)
                    tube = trajectory.normalizedRigidTrajectoryTube;
                    tubeSource = ...
                        "phase18c-v17a-caseb-normalized-rigid-trajectory-tube-coordination-audit-v1";
                    assert(isstruct(tube) && isscalar(tube) && ...
                        isfield(tube,"enabled") && logical(tube.enabled) && ...
                        isfield(tube,"auditOnly") && logical(tube.auditOnly) && ...
                        isfield(tube,"source") && string(tube.source)==tubeSource && ...
                        isfield(tube,"fractions") && isfield(tube,"auditFraction"), ...
                        "CoupledRtiAllocatorAudit:NormalizedRigidTrajectoryTube", ...
                        ['The normalized rigid-trajectory tube requires its ', ...
                         'approved audit-only source-bound request.']);
                    fractions = double(tube.fractions(:));
                    auditFraction = double(tube.auditFraction);
                    assert(isequal(fractions,[0.001;0.01;0.05]) && ...
                        isscalar(auditFraction) && auditFraction==0.05 && ...
                        obj.nInterval==10 && obj.nInterval==cfg.ctrl.Nc, ...
                        "CoupledRtiAllocatorAudit:NormalizedRigidTrajectoryTubeContract", ...
                        ['The Case-B rigid tube requires Nc=10, fractions ', ...
                         '[0.001;0.01;0.05], and auditFraction=0.05.']);
                    obj.normalizedRigidTrajectoryTubeEnabled = true;
                    obj.normalizedRigidTrajectoryTubeFractions = fractions;
                    obj.normalizedRigidTrajectoryTubeFraction = auditFraction;
                end
            end
            if isfield(request,"source") && string(request.source)== ...
                    "phase18c-v17a-caseb-trajectory-metric-shared-allocation-persistent-integration-v1"
                assert(obj.trajectoryMetricSharedAllocationEnabled, ...
                    "CoupledRtiAllocatorAudit:TrajectoryMetricSharedAllocationRequired", ...
                    "The persistent integration source requires the trajectory-metric mode.");
            end
            if obj.nonlinearOuterReferenceGovernorEnabled
                % The governor's primary problem is a convex QP assembled
                % from the nonlinear-preview sensitivities.  Keep its solver
                % deterministic and bounded; nonlinear replay remains the
