function [c,ceq,gradient,gradientEquality] = ...
        localPrimaryTieConstraint(value,H,g,upper,guardData)
[guard,~,guardGradient] = localPhysicalGroupConstraints(value,guardData);
c = [0.5*(value.'*H*value)+g.'*value-upper;guard];
ceq = zeros(0,1);
if nargout > 2
    gradient = [H*value+g,guardGradient];
    gradientEquality = zeros(numel(value),0);
end
end

function [cost,gradient] = localMinimumCommandObjective(value)
cost = 0.5*(value.'*value);
if nargout > 1
    gradient = value;
end
end

function [cost,gradient] = localQuadraticObjective(value,H,g)
cost = 0.5*(value.'*H*value)+g.'*value;
if nargout > 1
    gradient = H*value+g;
end
end

function [c,ceq,gradient,gradientEquality] = ...
        localPhysicalGroupConstraints(value,data)
if ~isstruct(data) || ~isfield(data,"enabled") || ~data.enabled
    c = zeros(0,1);
    ceq = zeros(0,1);
    gradient = zeros(numel(value),0);
    gradientEquality = zeros(numel(value),0);
    return
end
nGroup = numel(data.residuals);
c = zeros(nGroup,1);
gradient = zeros(numel(value),nGroup);
for index = 1:nGroup
    residual = data.residuals{index};
    jacobian = data.jacobians{index};
    trial = residual+jacobian*value;
    c(index) = 0.5*(trial.'*trial-residual.'*residual);
    gradient(:,index) = jacobian.'*trial;
end
ceq = zeros(0,1);
gradientEquality = zeros(numel(value),0);
end
