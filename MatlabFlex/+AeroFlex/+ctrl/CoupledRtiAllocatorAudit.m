                candidateFlexibleCost<=nominalFlexibleCost+flexibleTolerance);
            if obj.normalizedRigidTrajectoryTubeEnabled
                checks.rigidTrajectoryTube = tube.auditPassed;
            else
                checks.rigidTrajectoryNondegraded = ...
                    candidateRigidCost<=nominalRigidCost+rigidTolerance;
            end
        end

