                "continuity",0,"continuityTwoNorm",0, ...
                "constraintViolationInf",obj.constraintViolation( ...
                    selectedChecks),"terminalSetValue",nan, ...
                "terminalSetSatisfied",false, ...
                "output",struct("iterations",safeField( ...
                    qpOutput,"iterations",nan),"message",message, ...
                    "auditCapture",struct( ...
                    "schemaVersion","phase18c-v17a-persistent-coupled-rti-v1", ...
                    "sample",obj.callCount,"timeSeconds",timeSeconds, ...
                    "qpExitflag",qpExitflag,"qpCost",qpCost, ...
                    "qpSelectedAlgorithm",selectedQpAlgorithm, ...
                    "qpDominanceTolerance",qpDominanceTolerance, ...
                    "primaryQp",primaryQp,"recoveryQp",recoveryQp, ...
                    "guardedPhysicalQp",guardedPhysicalQp, ...
                    "secondaryNearTie",secondaryNearTie, ...
                    "qpFirstOrderOptimality",safeField( ...
                        qpOutput,"firstorderopt",nan), ...
                    "qpConstraintViolation",safeField( ...
                        qpOutput,"constrviolation",nan), ...
                    "qpSeconds",qpSeconds,"selectedAlpha",selectedAlpha, ...
