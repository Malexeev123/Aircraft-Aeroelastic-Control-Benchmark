                "lastWingControl","trimWingControl","trimMu", ...
                "scheduleEnabled", ...
                "controlSampleScheduleHoldStepsRemaining", ...
                "controlSampleIndex","ROMlib","sched","trimThrust", ...
                "trimTailDelta","rbParams"];
            for field = fields
                plant.(field) = owner.(field);
            end
            plant.xFlex = xInitial(:);
            if obj.coupledNmpcPredictorEnabled
                assert(plant.useRigidBody && isstruct(plant.rb) && ...
                    all(isfinite([plant.rb.v_B(:);plant.rb.euler(:); ...
                    plant.rb.omega_B(:)])), ...
                    'CoupledRtiAllocatorAudit:CoupledPredictionState', ...
                    ['The coupled nMPC prediction state requires the finite ', ...
                     'measured/fused rigid runtime state.']);
            end
            if isfield(owner.cfg,'sim') && ...
                    isfield(owner.cfg.sim,'packageRelativeRigidAttitudeChi') && ...
                    isstruct(owner.cfg.sim.packageRelativeRigidAttitudeChi) && ...
                    isfield(owner.cfg.sim.packageRelativeRigidAttitudeChi,'enable') && ...
                    logical(owner.cfg.sim.packageRelativeRigidAttitudeChi.enable)
                assert(isfield(plant.cfg.sim,'packageRelativeRigidAttitudeChi') && ...
                    logical(plant.cfg.sim.packageRelativeRigidAttitudeChi.enable), ...
                    'CoupledRtiAllocatorAudit:RigidAttitudeChiOwner', ...
                    ['The cloned nonlinear preview lost the approved ', ...
                     'package-relative rigid-attitude chi owner.']);
            end
            fusion = AeroFlex.ctrl.ComplementaryCommandFusion( ...
                obj.cfg,owner.trim);
            fusion.yOuterLP = fusionOwner.yOuterLP;
            fusion.yInnerLP = fusionOwner.yInnerLP;
            fusion.initialized = fusionOwner.initialized;
            fusion.innerIsDeviation = fusionOwner.innerIsDeviation;
