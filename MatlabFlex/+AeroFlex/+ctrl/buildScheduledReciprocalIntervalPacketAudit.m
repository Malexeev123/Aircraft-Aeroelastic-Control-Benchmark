function packet = buildScheduledReciprocalIntervalPacketAudit(model,scheduledPacket)
%BUILDSCHEDULEDRECIPROCALINTERVALPACKETAUDIT Numeric scheduled-kernel data.
%   The packet is a code-generation-compatible copy of the current
%   common-coordinate aggregate. Schedule selection and package construction
%   remain outside the numerical kernel.

arguments
    model (1,1) AeroFlex.sim.ROMIntegrator
    scheduledPacket (1,1) struct
end

required = {'plantCandidate','queryPackageHash','schedule','queryTrim'};
assert(all(isfield(scheduledPacket,required)), ...
    'AeroFlex:ctrl:ScheduledReciprocalPacket', ...
    'The scheduled reciprocal aggregate packet is incomplete.');
candidate = scheduledPacket.plantCandidate;
nativeCount = size(model.L,1);
hiddenCount = double(candidate.hidden.count);
sourceCounts = arrayfun(@(member) ...
    double(member.candidate.hidden.count),scheduledPacket.members(:));
assert(nativeCount==74 && hiddenCount==546 && ...
    numel(sourceCounts)==14 && all(sourceCounts==39) && ...
    sum(sourceCounts)==hiddenCount && ...
    candidate.runtimeState.count==83 && candidate.visible.count==69 && ...
    candidate.input.count==7 && ...
    abs(model.dt-(0.01/14))<=1e-15 && ...
    ~model.internalCoupledCoordinate.enabled && ...
    model.parConst.RateProject.projSet, ...
    'AeroFlex:ctrl:ScheduledReciprocalPacketArchitecture', ...
    'The scheduled compiled kernel requires the qualified 620-state contract.');

rateProjection = eye(nativeCount);
rateProjection(model.idx.q1,model.idx.q1) = ...
    full(model.parConst.RateProject.Pz);
sourcePar = model.parConst;
affineOffset = zeros(nativeCount,1);
if isfield(sourcePar,'affineOffset') && ~isempty(sourcePar.affineOffset)
    affineOffset = full(sourcePar.affineOffset(:));
end
assert(numel(affineOffset)==nativeCount && all(isfinite(affineOffset)), ...
    'AeroFlex:ctrl:ScheduledReciprocalPacketAffineOffset', ...
    'The optional affine offset must contain 74 finite entries.');
par = struct( ...
    'Gamma1',full(sourcePar.Gamma1), ...
    'Gamma2',full(sourcePar.Gamma2), ...
    'Gamma_g',full(sourcePar.Gamma_g), ...
    'Gamma_xi',full(sourcePar.Gamma_xi), ...
    'forces_0',full(sourcePar.forces_0(:)), ...
    'scaleAero',double(sourcePar.scaleAero), ...
    't_inf',double(sourcePar.t_inf), ...
    'Fscale',double(sourcePar.Fscale), ...
    'Bw',full(sourcePar.Bw), ...
    'Dw',full(sourcePar.Dw), ...
    'Bdel',full(sourcePar.Bdel), ...
    'Ddel',full(sourcePar.Ddel), ...
    'Bddel',full(sourcePar.Bddel), ...
    'Dddel',full(sourcePar.Dddel), ...
    'N_Thrust',full(sourcePar.N_Thrust(:)), ...
    'affineOffset',affineOffset, ...
    'gust',0, ...
    'u_ctrl',zeros(4,1));

runtimeFromNative = zeros(candidate.runtimeState.count,nativeCount);
runtimeFromNative(candidate.runtimeState.sourceVisible(1:60), ...
    [model.idx.q1(:);model.idx.q2(:);model.idx.qGam(:)]) = eye(60);
runtimeFromNative(candidate.runtimeState.qxi,model.idx.qxi) = ...
    eye(numel(model.idx.qxi));
runtimeFromNative(candidate.runtimeState.chi,model.idx.chi) = ...
    eye(numel(model.idx.chi));
runtimeFromRigid = zeros(candidate.runtimeState.count,9);
runtimeFromRigid(candidate.visible.rigid,:) = eye(9);
correctionToNative = zeros(nativeCount,candidate.visible.count);
correctionToNative(model.idx.q1,candidate.visible.q1) = ...
    eye(numel(model.idx.q1));
correctionToNative(model.idx.q2,candidate.visible.q2) = ...
    eye(numel(model.idx.q2));
correctionToNative(model.idx.qGam,candidate.visible.qGam) = ...
    eye(numel(model.idx.qGam));

packet = struct( ...
    'dt',double(model.dt), ...
    'gamma',double(model.gamma), ...
    'delta',double(model.delta), ...
    'Ldyn',full(model.Ldyn), ...
    'Lfac',full(model.Lfac), ...
    'Ufac',full(model.Ufac), ...
    'piv',double(model.piv(:)), ...
    'rateProjection',rateProjection, ...
    'par',par, ...
    'runtimeFromNative',runtimeFromNative, ...
    'runtimeFromRigid',runtimeFromRigid, ...
    'correctionToNative',correctionToNative, ...
    'queryTrimWing',full(scheduledPacket.queryTrim.wing(:)), ...
    'queryTrimThrust',double(scheduledPacket.queryTrim.thrust), ...
    'interpolationWeights', ...
        full(double(scheduledPacket.schedule.weights(:))), ...
    'hiddenStateCounts',full(double(sourceCounts(:))), ...
    'sensitivitySourceMask',true(numel(sourceCounts),1), ...
    'correctionStateEquilibrium', ...
        full(candidate.base.correctionStateEquilibrium(:)), ...
    'inputEquilibrium',full(candidate.base.inputEquilibrium(:)), ...
    'deltaAFullState',full(candidate.correction.deltaAFullState), ...
    'Avh',full(candidate.partition.Avh), ...
    'deltaBv',full(candidate.correction.deltaBv), ...
    'hiddenFromFullState', ...
        full(candidate.partition.hiddenFromFullState), ...
    'Ahh',full(candidate.partition.Ahh), ...
    'Bh',full(candidate.partition.Bh), ...
    'rootWrenchEquilibrium', ...
        full(candidate.rootWrenchOutput.equilibrium(:)), ...
    'rootWrenchStateMap', ...
        full(candidate.rootWrenchOutput.runtimeStateMap), ...
    'rootWrenchInputMap', ...
        full(candidate.rootWrenchOutput.runtimeInputMap));

assert(localAllFinite(packet), ...
    'AeroFlex:ctrl:ScheduledReciprocalPacketFinite', ...
    'The scheduled reciprocal interval packet contains a nonfinite field.');
end

function finite = localAllFinite(value)
if isnumeric(value) || islogical(value)
    finite = all(isfinite(value),'all');
elseif isstruct(value)
    names = fieldnames(value);
    finite = true;
    for index = 1:numel(names)
        finite = finite && localAllFinite(value.(names{index}));
    end
else
    finite = false;
end
end
