function [trim,info] = interpolateScheduledEquilibriumTrimAudit( ...
        ROMlib,mu,cfgLibrary,bankCache)
%INTERPOLATESCHEDULEDEQUILIBRIUMTRIMAUDIT Interpolate Case-B source trim.
%   This audit-only path avoids constructing a complete scheduled plant when
%   the outer guidance needs only the source-owned equilibrium commands.

arguments
    ROMlib (1,1) struct
    mu (1,2) double {mustBeFinite}
    cfgLibrary (1,1) struct
    bankCache (1,1) struct
end

requiredCache = {'schemaVersion','manifestPath','manifestSha256', ...
    'sourceIds','sourceCount','members'};
acceptedSchemas = [ ...
    "phase18c-v17a-scheduled-reciprocal-bank-cache-v2", ...
    "phase18c-v17a-scheduled-reciprocal-bank-cache-v3"];
assert(all(isfield(bankCache,requiredCache)) && ...
    ismember(string(bankCache.schemaVersion),acceptedSchemas) && ...
    double(bankCache.sourceCount)==numel(bankCache.sourceIds) && ...
    numel(bankCache.members)==double(bankCache.sourceCount), ...
    'AeroFlex:ctrl:ScheduledTrimBankCache', ...
    'The scheduled reciprocal source-bank cache is incomplete.');
assert(isfield(ROMlib,'points') && isfield(ROMlib.points,'name') && ...
    isfield(ROMlib.points,'u_eq'), ...
    'AeroFlex:ctrl:ScheduledTrimLibrary', ...
    'The scheduled trim library lacks source identity or equilibrium input.');

owner = localCaseViewOwner(cfgLibrary,mu);
weightCfg = cfgLibrary;
if isfield(weightCfg,'caseView')
    weightCfg = rmfield(weightCfg,'caseView');
end
[weights,indices,weightInfo] = ...
    AeroFlex.sched.interpWeights(ROMlib,mu,weightCfg);
weights = double(weights(:));
indices = double(indices(:));
sourceIds = string({ROMlib.points(indices).name}).';
sourceKey = strjoin(sort(sourceIds),'|');
assert(nnz(string(owner.sourceSetKeys(:))==sourceKey)==1, ...
    'AeroFlex:ctrl:ScheduledTrimStencil', ...
    'The reference query resolved an unapproved Case-B source set {%s}.', ...
    sourceKey);
assert(numel(weights)==numel(indices) && all(weights>=-1e-14) && ...
    abs(sum(weights)-1)<=1e-12 && numel(unique(sourceIds))==numel(sourceIds), ...
    'AeroFlex:ctrl:ScheduledTrimWeights', ...
    'The scheduled trim interpolation weights are not convex and unique.');

wing = zeros(numel(ROMlib.points(indices(1)).u_eq),1);
elevator = 0;
thrust = 0;
rigid = [];
bankIndices = zeros(numel(sourceIds),1);
for sourceIndex = 1:numel(sourceIds)
    bankIndex = find(string(bankCache.sourceIds(:))==sourceIds(sourceIndex));
    assert(isscalar(bankIndex), ...
        'AeroFlex:ctrl:ScheduledTrimSource', ...
        'Source %s is absent or duplicated in the reciprocal bank.', ...
        sourceIds(sourceIndex));
    bankIndices(sourceIndex) = bankIndex;
    member = bankCache.members(bankIndex);
    pointInput = double(member.trim.wing(:));
    assert(numel(pointInput)==numel(wing), ...
        'AeroFlex:ctrl:ScheduledTrimWingChart', ...
        'Source %s has an incompatible physical-chart wing trim.', ...
        sourceIds(sourceIndex));
    candidate = member.candidate;
    sourceRigid = double(candidate.base.correctionStateEquilibrium( ...
        candidate.visible.rigid));
    if isempty(rigid)
        rigid = zeros(size(sourceRigid));
    end
    wing = wing+weights(sourceIndex)*pointInput;
    elevator = elevator+weights(sourceIndex)*double(member.trim.elevator);
    thrust = thrust+weights(sourceIndex)*double(member.trim.thrust);
    rigid = rigid+weights(sourceIndex)*sourceRigid;
end

trim = struct('wing',wing,'elevator',double(elevator), ...
    'thrust',double(thrust),'rigid',rigid);
assert(numel(trim.wing)==4 && isscalar(trim.elevator) && ...
    isscalar(trim.thrust) && trim.thrust>=0 && numel(trim.rigid)==9 && ...
    all(isfinite([trim.wing;trim.elevator;trim.thrust;trim.rigid])), ...
    'AeroFlex:ctrl:ScheduledTrimValue', ...
    'The interpolated Case-B trim is nonfinite or violates T >= 0.');

info = struct('auditOnly',true, ...
    'owner',"source_bank_equilibrium_trim_interpolation", ...
    'query',mu,'sourceIds',sourceIds,'weights',weights, ...
    'bankIndices',bankIndices,'sourceSetKey',sourceKey, ...
    'weightMode',string(weightInfo.mode), ...
    'caseManifestSha256',string(owner.caseManifestSha256), ...
    'bankManifestSha256',string(bankCache.manifestSha256));
end

function owner = localCaseViewOwner(cfgLibrary,mu)
assert(isfield(cfgLibrary,'runtimeCaseViewOwner') && ...
    isstruct(cfgLibrary.runtimeCaseViewOwner), ...
    'AeroFlex:ctrl:ScheduledTrimCaseView', ...
    'The reference trim requires the approved Case-B runtime case view.');
owner = cfgLibrary.runtimeCaseViewOwner;
required = {'enabled','auditOnly','speedRangeMps','alphaOffsetDeg', ...
    'tolerance','sourceSetKeys','caseManifestSha256'};
assert(all(isfield(owner,required)) && logical(owner.enabled) && ...
    logical(owner.auditOnly), ...
    'AeroFlex:ctrl:ScheduledTrimCaseView', ...
    'The Case-B runtime case-view owner is disabled or incomplete.');
speedRange = double(owner.speedRangeMps(:).');
alphaOffset = double(owner.alphaOffsetDeg);
tolerance = double(owner.tolerance);
assert(isequal(size(speedRange),[1,2]) && ...
    mu(1)>=speedRange(1)-tolerance && mu(1)<=speedRange(2)+tolerance && ...
    abs(mu(2)-(alphaOffset-mu(1)))<=tolerance, ...
    'AeroFlex:ctrl:ScheduledTrimCorridor', ...
    'The reference trim query lies outside the approved Case-B centerline.');
end
