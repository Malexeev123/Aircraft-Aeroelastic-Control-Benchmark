function [endpoints,latentEndpoints,stateExpansion,stateOffset] = ...
        scheduledReciprocalEstimatorReducedTangentHorizonAudit( ...
        nativeNodes,latentInitial,disturbances,wingTotal,wingIncrement, ...
        elevatorIncrement,thrustIncrement,rigidState,packets)
%SCHEDULEDRECIPROCALESTIMATORREDUCEDTANGENTHORIZONAUDIT Exact Ne=8 map.

assert(isequal(size(nativeNodes),[74 9]) && ...
    numel(disturbances)==8 && numel(packets)==8, ...
    'AeroFlex:ctrl:ScheduledEstimatorReducedTangentLength', ...
    'The estimator reduced tangent requires Ne=8.');
reducedCount = 82;
initialExpansion = [eye(74),zeros(74,8)];
disturbanceExpansion = zeros(1,reducedCount,8);
for interval = 1:8
    disturbanceExpansion(1,74+interval,interval) = 1;
end
wingExpansion = zeros(4,reducedCount,8);
[endpoints,latentEndpoints,stateExpansion,stateOffset] = ...
    AeroFlex.ctrl.scheduledReciprocalReducedTangentHorizonCoreAudit( ...
        nativeNodes,latentInitial,disturbances,wingTotal,wingIncrement, ...
        elevatorIncrement,thrustIncrement,rigidState, ...
        initialExpansion,zeros(74,1),disturbanceExpansion, ...
        wingExpansion,packets);
end
