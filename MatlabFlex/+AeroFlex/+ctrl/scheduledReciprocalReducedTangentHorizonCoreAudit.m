function [endpoints,latentEndpoints,stateExpansion,stateOffset] = ...
        scheduledReciprocalReducedTangentHorizonCoreAudit(nativeNodes, ...
        latentInitial,disturbances,wingTotal,wingIncrement, ...
        elevatorIncrement,thrustIncrement,rigidState, ...
        initialNativeExpansion,initialNativeOffset, ...
        disturbanceExpansion,wingExpansion,packets)
%SCHEDULEDRECIPROCALREDUCEDTANGENTHORIZONCOREAUDIT Causal RTI expansion.
%   The last tangent column carries the affine continuity-defect offset.
%   Other columns are the retained RTI coordinates. This implements the same
%   chain rule and equality substitution as full-state condensing without
%   constructing a full augmented state-transition matrix per interval.

nativeNodes = double(nativeNodes);
latent = double(latentInitial(:));
disturbances = double(disturbances(:).');
horizonLength = numel(disturbances);
reducedCount = size(initialNativeExpansion,2);
assert(size(nativeNodes,1)==74 && ...
    size(nativeNodes,2)==horizonLength+1 && numel(latent)==546 && ...
    isequal(size(initialNativeExpansion),[74 reducedCount]) && ...
    isequal(size(initialNativeOffset),[74 1]) && ...
    isequal(size(disturbanceExpansion), ...
        [1 reducedCount horizonLength]) && ...
    isequal(size(wingExpansion),[4 reducedCount horizonLength]) && ...
    isequal(size(wingTotal),[4 14 horizonLength]) && ...
    isequal(size(wingIncrement),[4 14 horizonLength]) && ...
    isequal(size(elevatorIncrement),[1 14 horizonLength]) && ...
    isequal(size(thrustIncrement),[1 14 horizonLength]) && ...
    isequal(size(rigidState),[9 14 horizonLength]) && ...
    numel(packets)==horizonLength && ismember(horizonLength,[8 10]), ...
    'AeroFlex:ctrl:ScheduledReducedTangentHorizonDimensions', ...
    'The reduced scheduled horizon inputs have invalid dimensions.');
assert(all(isfinite(nativeNodes),'all') && all(isfinite(latent)) && ...
    all(isfinite(disturbances)) && ...
    all(isfinite(initialNativeExpansion),'all') && ...
    all(isfinite(initialNativeOffset)) && ...
    all(isfinite(disturbanceExpansion),'all') && ...
    all(isfinite(wingExpansion),'all') && ...
    all(isfinite(wingTotal),'all') && ...
    all(isfinite(wingIncrement),'all') && ...
    all(isfinite(elevatorIncrement),'all') && ...
    all(isfinite(thrustIncrement),'all') && ...
    all(isfinite(rigidState),'all'), ...
    'AeroFlex:ctrl:ScheduledReducedTangentHorizonFinite', ...
    'The reduced scheduled horizon inputs must be finite.');

directionCount = reducedCount+1;
stateDirections = zeros(620,directionCount);
stateDirections(1:74,1:reducedCount) = initialNativeExpansion;
stateDirections(1:74,end) = initialNativeOffset;
endpoints = zeros(620,horizonLength);
latentEndpoints = zeros(546,horizonLength);
stateExpansion = zeros(74,reducedCount,horizonLength+1);
stateOffset = zeros(74,horizonLength+1);
stateExpansion(:,:,1) = initialNativeExpansion;
stateOffset(:,1) = initialNativeOffset;

for interval = 1:horizonLength
    state = [nativeNodes(:,interval);latent];
    stateDirections(1:74,1:reducedCount) = ...
        stateExpansion(:,:,interval);
    stateDirections(1:74,end) = stateOffset(:,interval);
    disturbanceDirections = zeros(1,directionCount);
    disturbanceDirections(1:reducedCount) = ...
        disturbanceExpansion(:,:,interval);
    wingDirections = zeros(4,directionCount);
    wingDirections(:,1:reducedCount) = wingExpansion(:,:,interval);
    [endpoint,endpointDirections] = localDirectionalInterval( ...
        state,stateDirections,disturbances(interval), ...
        disturbanceDirections,wingTotal(:,:,interval), ...
        wingIncrement(:,:,interval),wingDirections, ...
        elevatorIncrement(:,:,interval), ...
        thrustIncrement(:,:,interval),rigidState(:,:,interval), ...
        packets(interval));
    endpoints(:,interval) = endpoint;
    latent = endpoint(75:620);
    latentEndpoints(:,interval) = latent;

    defect = nativeNodes(:,interval+1)-endpoint(1:74);
    stateExpansion(:,:,interval+1) = ...
        endpointDirections(1:74,1:reducedCount);
    stateOffset(:,interval+1) = endpointDirections(1:74,end)-defect;
    stateDirections(75:620,:) = endpointDirections(75:620,:);
end
end

function [state,stateDirections] = localDirectionalInterval( ...
        state,stateDirections,disturbance,disturbanceDirections, ...
        wingTotal,wingIncrement,wingDirections,elevatorIncrement, ...
        thrustIncrement,rigidState,packet)
sourceMask = logical(packet.sensitivitySourceMask(:));
sourceCounts = double(packet.hiddenStateCounts(:));
activeHidden = localActiveHiddenIndices(sourceMask,sourceCounts);
activeState = [reshape(1:74,[],1);74+activeHidden];
assert(numel(sourceMask)==14 && all(sourceCounts==39) && ...
    all(sourceMask(packet.interpolationWeights(:)>0)), ...
    'AeroFlex:ctrl:ScheduledReducedTangentStencil', ...
    'The reduced tangent stencil omits a positive-weight source member.');
assert(all(packet.queryTrimThrust+thrustIncrement>=0), ...
    'AeroFlex:ctrl:ScheduledReducedTangentThrust', ...
    'The reduced scheduled horizon violates T >= 0.');
assert(norm(wingTotal-(packet.queryTrimWing+wingIncrement),inf)<= ...
    100*eps(max(1,norm(wingTotal,inf))), ...
    'AeroFlex:ctrl:ScheduledReducedTangentWingOwner', ...
    'Total and trim-relative scheduled wing commands disagree.');

directions = stateDirections(activeState,:);
for substep = 1:14
    nativeState = state(1:74);
    hiddenState = state(75:620);
    nativeDirections = directions(1:74,:);
    hiddenDirections = directions(75:end,:);
    sourceInput = [disturbance;wingIncrement(:,substep); ...
        elevatorIncrement(substep);thrustIncrement(substep)];
    sourceInputDirections = [disturbanceDirections;wingDirections; ...
        zeros(2,size(directions,2))];
    runtimeDeparture = packet.runtimeFromNative*nativeState+ ...
        packet.runtimeFromRigid*rigidState(:,substep)- ...
        packet.correctionStateEquilibrium;
    runtimeDirections = packet.runtimeFromNative*nativeDirections;
    inputDeparture = sourceInput-packet.inputEquilibrium;
    visibleCorrection = packet.deltaAFullState*runtimeDeparture+ ...
        packet.Avh*hiddenState+packet.deltaBv*inputDeparture;
    visibleDirections = packet.deltaAFullState*runtimeDirections+ ...
        packet.Avh(:,activeHidden)*hiddenDirections+ ...
        packet.deltaBv*sourceInputDirections;
    hiddenNext = packet.hiddenFromFullState*runtimeDeparture+ ...
        packet.Ahh*hiddenState+packet.Bh*inputDeparture;
    activeHiddenDirections = ...
        packet.hiddenFromFullState(activeHidden,:)*runtimeDirections+ ...
        packet.Ahh(activeHidden,activeHidden)*hiddenDirections+ ...
        packet.Bh(activeHidden,:)*sourceInputDirections;

    nativeInputDirections = [disturbanceDirections;wingDirections];
    [nativeNext,nativeNextDirections] = localNativeDirectionalStep( ...
        nativeState,nativeDirections,wingTotal(:,substep),disturbance, ...
        nativeInputDirections,packet);
    nativeNext = nativeNext+packet.correctionToNative*visibleCorrection;
    nativeNextDirections = nativeNextDirections+ ...
        packet.correctionToNative*visibleDirections;
    state = [nativeNext;hiddenNext];
    directions = [nativeNextDirections;activeHiddenDirections];
end
stateDirections = zeros(620,size(directions,2));
stateDirections(activeState,:) = directions;
assert(all(isfinite(state)) && all(isfinite(stateDirections),'all'), ...
    'AeroFlex:ctrl:ScheduledReducedTangentOutputFinite', ...
    'The reduced scheduled tangent produced a nonfinite output.');
end

function [stateNext,directionNext] = localNativeDirectionalStep( ...
        state,direction,wingTotal,disturbance,inputDirection,packet)
par = packet.par;
par.gust = disturbance;
par.u_ctrl = wingTotal;
dt = packet.dt;
gamma = packet.gamma;
delta = packet.delta;

k1Nonlinear = packet.rateProjection*(dt*localNonlinearTerms(state,par));
[jacobian1,inputJacobian1] = localNonlinearJacobian(state,par);
j1Nonlinear = packet.rateProjection* ...
    (dt*(jacobian1*direction+inputJacobian1(:,75:79)*inputDirection));
j1Linear = localImplicitSolve(packet,dt*packet.Ldyn* ...
    (direction+gamma*j1Nonlinear));
direction1 = direction+gamma*(j1Linear+j1Nonlinear);
k1Linear = localImplicitSolve(packet,dt*packet.Ldyn* ...
    (state+gamma*k1Nonlinear));
stage1 = state+gamma*(k1Linear+k1Nonlinear);

k2Nonlinear = packet.rateProjection*(dt*localNonlinearTerms(stage1,par));
[jacobian2,inputJacobian2] = localNonlinearJacobian(stage1,par);
j2Nonlinear = packet.rateProjection* ...
    (dt*(jacobian2*direction1+inputJacobian2(:,75:79)*inputDirection));
j2Linear = localImplicitSolve(packet,dt*packet.Ldyn* ...
    (direction+(1-gamma)*j1Linear+delta*j1Nonlinear+ ...
    (1-delta)*j2Nonlinear));
direction2 = direction+(1-gamma)*j1Linear+gamma*j2Linear+ ...
    delta*j1Nonlinear+(1-delta)*j2Nonlinear;
k2Linear = localImplicitSolve(packet,dt*packet.Ldyn* ...
    (state+(1-gamma)*k1Linear+delta*k1Nonlinear+ ...
    (1-delta)*k2Nonlinear));
stage2 = state+(1-gamma)*k1Linear+gamma*k2Linear+ ...
    delta*k1Nonlinear+(1-delta)*k2Nonlinear;

k3Nonlinear = packet.rateProjection*(dt*localNonlinearTerms(stage2,par));
[jacobian3,inputJacobian3] = localNonlinearJacobian(stage2,par);
j3Nonlinear = packet.rateProjection* ...
    (dt*(jacobian3*direction2+inputJacobian3(:,75:79)*inputDirection));
directionNext = direction+(1-gamma)*(j1Linear+j2Nonlinear)+ ...
    gamma*(j2Linear+j3Nonlinear);
stateNext = state+(1-gamma)*(k1Linear+k2Nonlinear)+ ...
    gamma*(k2Linear+k3Nonlinear);
end

function value = localImplicitSolve(packet,rightHandSide)
value = packet.Ufac\(packet.Lfac\rightHandSide(packet.piv,:));
end

function nonlinear = localNonlinearTerms(state,par)
q1 = state(1:10);
q2 = state(11:20);
qxi = state(21:31);
nonlinear = zeros(74,1);
gamma1q1 = squeeze(pagemtimes(par.Gamma1,'none',q1,'none'));
gamma2q2 = squeeze(pagemtimes(par.Gamma2,'none',q2,'none'));
gammaGqxi = squeeze(pagemtimes(par.Gamma_g,'none',qxi,'none'));
gammaXiqxi = squeeze(pagemtimes(par.Gamma_xi,'none',qxi,'none'));
gamma2TransposeQ1 = squeeze(pagemtimes( ...
    par.Gamma2,'transpose',q1,'none'));
nonlinear(1:10) = -(gamma1q1*q1)-(gamma2q2*q2)+ ...
    gammaGqxi*qxi+par.Fscale*par.forces_0+par.N_Thrust;
nonlinear(11:20) = gamma2TransposeQ1*q2;
nonlinear(21:31) = gammaXiqxi*q1;
nonlinear(32:71) = par.Bw*par.gust+ ...
    (1/par.t_inf)*par.Bdel*par.u_ctrl(1:2)+ ...
    par.Bddel*par.u_ctrl(3:4);
nonlinear(1:10) = nonlinear(1:10)+ ...
    par.scaleAero*par.Dw*par.gust+ ...
    par.Ddel*par.u_ctrl(1:2)+ ...
    par.t_inf*par.Dddel*par.u_ctrl(3:4);
nonlinear = nonlinear+par.affineOffset;
end

function [stateJacobian,inputJacobian] = localNonlinearJacobian(state,par)
q1 = state(1:10);
q2 = state(11:20);
qxi = state(21:31);
gamma1 = par.Gamma1;
gamma2 = par.Gamma2;
gammaG = par.Gamma_g;
gammaXi = par.Gamma_xi;
termB = localGammaContract(permute(gamma1,[1 3 2]),q1);
termA = localGammaContract(gamma1,q1);
termD = localGammaContract(permute(gamma2,[1 3 2]),q2);
termC = localGammaContract(gamma2,q2);
termF = localGammaContract(gammaG,qxi);
termE = localGammaContract(permute(gammaG,[1 3 2]),qxi);
termJ = localGammaContract(gammaXi,qxi);
termI = localGammaContract(permute(gammaXi,[1 3 2]),q1);
termG = zeros(10,10);
termH = zeros(10,10);
for mode = 1:10
    termG = termG+q2(mode)*gamma2(:,:,mode).';
    termH(:,mode) = gamma2(:,:,mode).'*q1;
end
stateJacobian = zeros(74,74);
stateJacobian(1:10,1:10) = -termA-termB;
stateJacobian(1:10,11:20) = -termC-termD;
stateJacobian(1:10,21:31) = termE+termF;
stateJacobian(11:20,1:10) = termG;
stateJacobian(11:20,11:20) = termH;
stateJacobian(21:31,1:10) = termJ;
stateJacobian(21:31,21:31) = termI;
inputJacobian = zeros(74,79);
inputJacobian(1:10,75) = par.scaleAero*par.Dw;
inputJacobian(32:71,75) = par.Bw;
inputJacobian(1:10,76:77) = par.Ddel;
inputJacobian(1:10,78:79) = par.t_inf*par.Dddel;
inputJacobian(32:71,76:77) = (1/par.t_inf)*par.Bdel;
inputJacobian(32:71,78:79) = par.Bddel;
end

function contracted = localGammaContract(tensor,coordinates)
pageCoordinates = repmat(reshape(coordinates,[],1,1), ...
    1,1,size(tensor,3));
contractedPages = pagemtimes(tensor,pageCoordinates);
contracted = reshape(contractedPages,size(tensor,1),size(tensor,3));
end

function indices = localActiveHiddenIndices(sourceMask,sourceCounts)
offsets = [0;cumsum(sourceCounts(:))];
indices = zeros(sum(sourceCounts(sourceMask)),1);
cursor = 0;
for source = 1:numel(sourceMask)
    if sourceMask(source)
        count = sourceCounts(source);
        indices(cursor+(1:count)) = offsets(source)+(1:count);
        cursor = cursor+count;
    end
end
end
