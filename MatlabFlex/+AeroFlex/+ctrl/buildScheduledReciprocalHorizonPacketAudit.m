function packets = buildScheduledReciprocalHorizonPacketAudit(contexts)
%BUILDSCHEDULEDRECIPROCALHORIZONPACKETAUDIT Pack an ordered scheduled horizon.
%   Each interval retains its qualified scheduled package. The common active
%   source mask is the exact union of strictly positive interpolation weights
%   across the horizon; no source with positive weight is omitted.

arguments
    contexts (1,:) cell
end

assert(ismember(numel(contexts),[8 10]), ...
    'AeroFlex:ctrl:ScheduledReciprocalHorizonLength', ...
    'The compiled scheduled horizon supports only Ne=8 or Nc=10.');

sourceMask = false(14,1);
for interval = 1:numel(contexts)
    context = contexts{interval};
    assert(isstruct(context) && isscalar(context) && ...
        all(isfield(context,{'scheduledModel','scheduledPacket'})) && ...
        isa(context.scheduledModel,'AeroFlex.sim.ROMIntegrator'), ...
        'AeroFlex:ctrl:ScheduledReciprocalHorizonContext', ...
        'Scheduled context %d is incomplete.',interval);
    schedule = context.scheduledPacket.schedule;
    assert(isstruct(schedule) && isscalar(schedule) && ...
        isfield(schedule,'weights'), ...
        'AeroFlex:ctrl:ScheduledReciprocalHorizonSchedule', ...
        'Scheduled context %d has no interpolation weights.',interval);
    weights = double(schedule.weights(:));
    assert(numel(weights)==14 && all(isfinite(weights)) && ...
        all(weights>=0) && abs(sum(weights)-1)<=1e-12, ...
        'AeroFlex:ctrl:ScheduledReciprocalHorizonWeights', ...
        'Scheduled context %d has invalid interpolation weights.',interval);
    sourceMask = sourceMask | weights>0;
end
assert(any(sourceMask), ...
    'AeroFlex:ctrl:ScheduledReciprocalHorizonStencil', ...
    'The scheduled horizon has no active source member.');

first = AeroFlex.ctrl.buildScheduledReciprocalIntervalPacketAudit( ...
    contexts{1}.scheduledModel,contexts{1}.scheduledPacket);
first.sensitivitySourceMask = sourceMask;
packets = repmat(first,1,numel(contexts));
for interval = 2:numel(contexts)
    packet = AeroFlex.ctrl.buildScheduledReciprocalIntervalPacketAudit( ...
        contexts{interval}.scheduledModel, ...
        contexts{interval}.scheduledPacket);
    packet.sensitivitySourceMask = sourceMask;
    packets(interval) = packet;
end
end
