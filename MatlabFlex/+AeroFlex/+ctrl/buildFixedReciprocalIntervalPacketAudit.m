function packet = buildFixedReciprocalIntervalPacketAudit(provider)
%BUILDFIXEDRECIPROCALINTERVALPACKETAUDIT Build fixed numeric kernel data.
%   The packet is an audit-only, code-generation-compatible copy of the
%   exact Case-A reciprocal provider and native ROM constants. Construction
%   is a one-time initialization operation, not recurring solve work.

arguments
    provider (1,1) AeroFlex.ctrl.ReciprocalControllerModelProvider
end

model = provider.model;
candidate = provider.candidate;
assert(provider.nativeStateCount==74 && provider.hiddenStateCount==47 && ...
    provider.stateCount==121 && abs(model.dt-0.000625)<=1e-15 && ...
    ~model.internalCoupledCoordinate.enabled && ...
    model.parConst.RateProject.projSet, ...
    'AeroFlex:ctrl:FixedReciprocalPacketArchitecture', ...
    'The fixed kernel requires the qualified exact Case-A architecture.');

rateProjection = eye(74);
rateProjection(model.idx.q1,model.idx.q1) = ...
    full(model.parConst.RateProject.Pz);
sourcePar = model.parConst;
affineOffset = zeros(74,1);
if isfield(sourcePar,'affineOffset') && ~isempty(sourcePar.affineOffset)
    affineOffset = full(sourcePar.affineOffset(:));
end
assert(numel(affineOffset)==74 && all(isfinite(affineOffset)), ...
    'AeroFlex:ctrl:FixedReciprocalPacketAffineOffset', ...
    'The optional affine offset must contain 74 finite entries.');
par = struct( ...
    'Gamma1',full(sourcePar.Gamma1), ...
    'Gamma2',full(sourcePar.Gamma2), ...
    'Gamma_g',full(sourcePar.Gamma_g), ...
    'Gamma_xi',full(sourcePar.Gamma_xi), ...
    'forces_0',full(sourcePar.forces_0(:)), ...
    'scaleAero',double(sourcePar.scaleAero), ...
    't_inf',double(sourcePar.t_inf), ...
    'Fscale',double(sourcePar.Fscale), ...
    'Bw',full(sourcePar.Bw), ...
    'Dw',full(sourcePar.Dw), ...
    'Bdel',full(sourcePar.Bdel), ...
    'Ddel',full(sourcePar.Ddel), ...
    'Bddel',full(sourcePar.Bddel), ...
    'Dddel',full(sourcePar.Dddel), ...
    'N_Thrust',full(sourcePar.N_Thrust(:)), ...
    'affineOffset',affineOffset, ...
    'gust',0, ...
    'u_ctrl',zeros(4,1));

packet = struct( ...
    'dt',double(model.dt), ...
    'gamma',double(model.gamma), ...
    'delta',double(model.delta), ...
    'Ldyn',full(model.Ldyn), ...
    'Lfac',full(model.Lfac), ...
    'Ufac',full(model.Ufac), ...
    'piv',double(model.piv(:)), ...
    'rateProjection',rateProjection, ...
    'par',par, ...
    'runtimeFromNative',full(provider.runtimeFromNative), ...
    'runtimeFromRigid',full(provider.runtimeFromRigid), ...
    'correctionToNative',full(provider.correctionToNative), ...
    'correctionStateEquilibrium', ...
        full(candidate.base.correctionStateEquilibrium(:)), ...
    'inputEquilibrium',full(candidate.base.inputEquilibrium(:)), ...
    'deltaAFullState',full(candidate.correction.deltaAFullState), ...
    'Avh',full(candidate.partition.Avh), ...
    'deltaBv',full(candidate.correction.deltaBv), ...
    'hiddenFromFullState', ...
        full(candidate.partition.hiddenFromFullState), ...
    'Ahh',full(candidate.partition.Ahh), ...
    'Bh',full(candidate.partition.Bh), ...
    'rootWrenchEquilibrium', ...
        full(candidate.rootWrenchOutput.equilibrium(:)), ...
    'rootWrenchStateMap', ...
        full(candidate.rootWrenchOutput.runtimeStateMap), ...
    'rootWrenchInputMap', ...
        full(candidate.rootWrenchOutput.runtimeInputMap));

assert(localAllFinite(packet), ...
    'AeroFlex:ctrl:FixedReciprocalPacketFinite', ...
    'The fixed reciprocal packet contains a nonfinite numeric field.');
end

function finite = localAllFinite(value)
if isnumeric(value)
    finite = all(isfinite(value),'all');
elseif isstruct(value)
    names = fieldnames(value);
    finite = true;
    for index = 1:numel(names)
        finite = finite && localAllFinite(value.(names{index}));
    end
else
    finite = false;
end
end
