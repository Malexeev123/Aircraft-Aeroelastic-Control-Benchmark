        function context = validateIntervalContext(obj,context)
            required = {'wingTotal','wingIncrement','elevatorIncrement', ...
                'thrustIncrement','rigidState'};
            assert(isstruct(context) && isscalar(context) && ...
                all(isfield(context,required)), ...
                'ReciprocalControllerModelProvider:IntervalContext', ...
                'The completed-interval context is incomplete.');
            context.wingTotal = double(context.wingTotal);
            context.wingIncrement = double(context.wingIncrement);
            context.elevatorIncrement = ...
                double(context.elevatorIncrement(:).');
            context.thrustIncrement = ...
                double(context.thrustIncrement(:).');
            context.rigidState = double(context.rigidState);
            substepCount = size(context.wingTotal,2);
            assert(substepCount>=1 && ...
                isequal(size(context.wingTotal),[4 substepCount]) && ...
                isequal(size(context.wingIncrement),[4 substepCount]) && ...
                isequal(size(context.elevatorIncrement),[1 substepCount]) && ...
                isequal(size(context.thrustIncrement),[1 substepCount]) && ...
                isequal(size(context.rigidState),[9 substepCount]) && ...
                all(isfinite(context.wingTotal),'all') && ...
                all(isfinite(context.wingIncrement),'all') && ...
                all(isfinite(context.elevatorIncrement)) && ...
                all(isfinite(context.thrustIncrement)) && ...
                all(isfinite(context.rigidState),'all') && ...
                norm(context.wingTotal-(obj.trimWingControl+ ...
                    context.wingIncrement),inf) <= ...
                    100*eps(max(1,norm(context.wingTotal,inf))), ...
                'ReciprocalControllerModelProvider:IntervalContext', ...
                'The completed-interval context dimensions or owners changed.');
        end

        function context = validateControlIntervalContext(~,context)
            required = {'elevatorIncrement','thrustIncrement','rigidState'};
            assert(isstruct(context) && isscalar(context) && ...
                all(isfield(context,required)), ...
                'ReciprocalControllerModelProvider:ControlIntervalContext', ...
                'The future controller interval context is incomplete.');
            context.elevatorIncrement = ...
                double(context.elevatorIncrement(:).');
            context.thrustIncrement = ...
                double(context.thrustIncrement(:).');
            context.rigidState = double(context.rigidState);
            substepCount = size(context.rigidState,2);
            assert(substepCount>=1 && ...
                isequal(size(context.rigidState),[9 substepCount]) && ...
                isequal(size(context.elevatorIncrement),[1 substepCount]) && ...
                isequal(size(context.thrustIncrement),[1 substepCount]) && ...
                all(isfinite(context.rigidState),'all') && ...
                all(isfinite(context.elevatorIncrement)) && ...
                all(isfinite(context.thrustIncrement)), ...
                'ReciprocalControllerModelProvider:ControlIntervalContext', ...
                'The future controller context dimensions or values changed.');
        end
    end

