classdef ReciprocalControllerModelProvider < handle
%RECIPROCALCONTROLLERMODELPROVIDER Source-bound flexible/latent transition.
%   This default-inactive audit provider composes the native intrinsic ROM
%   step with the exact V17A reciprocal source correction used by
%   PlantRunTime. Rigid motion is supplied as measured exogenous context;
%   the provider never reads the runtime plant's hidden state.

    properties (SetAccess = private)
        model
        candidate struct
        idx struct
        nativeStateCount (1,1) double
        hiddenStateCount (1,1) double
        stateCount (1,1) double
        trimWingControl double
        runtimeFromNative double
        runtimeFromRigid double
        correctionToNative double
        fixedIntervalKernelAuditEnabled (1,1) logical = false
        fixedIntervalKernelAuditPacket struct = struct()
        fixedIntervalKernelAuditPacketSynchronized (1,1) logical = false
        fixedIntervalKernelAuditFunction = []
        fixedIntervalKernelAuditCallCount (1,1) double = 0
        fixedIntervalKernelAuditEstimatorCallCount (1,1) double = 0
        fixedIntervalKernelAuditControllerCallCount (1,1) double = 0
        fixedIntervalKernelAuditFallbackCount (1,1) double = 0
        fixedIntervalKernelAuditDiagnosticFallbackCount (1,1) double = 0
        fixedIntervalKernelAuditLastFallback string = ""
    end

    methods
        function obj = ReciprocalControllerModelProvider( ...
                model,candidate,trimWingControl)
            arguments
                model
                candidate (1,1) struct
                trimWingControl (:,1) double
            end

            obj.validateCandidate(candidate);
            assert(isprop(model,'idx') && isprop(model,'L') && ...
                isprop(model,'dt'), ...
                'ReciprocalControllerModelProvider:NativeModel', ...
                'The native model must expose idx, L, and dt.');
            assert(abs(double(model.dt)- ...
                double(candidate.sampleTimeSeconds)) <= ...
                10*eps(max(1,double(model.dt))), ...
                'ReciprocalControllerModelProvider:SampleTime', ...
                'The native and reciprocal source sample times differ.');

            obj.model = model;
            obj.candidate = candidate;
            obj.idx = model.idx;
            obj.nativeStateCount = size(model.L,1);
            obj.hiddenStateCount = double(candidate.hidden.count);
            obj.stateCount = obj.nativeStateCount+obj.hiddenStateCount;
            obj.trimWingControl = trimWingControl(:);
            assert(numel(obj.trimWingControl)==4 && ...
                all(isfinite(obj.trimWingControl)), ...
                'ReciprocalControllerModelProvider:TrimWing', ...
                'The total trim wing input must contain four finite values.');

            obj.runtimeFromNative = zeros( ...
                candidate.runtimeState.count,obj.nativeStateCount);
            obj.runtimeFromNative(candidate.runtimeState.sourceVisible(1:60), ...
                [obj.idx.q1(:);obj.idx.q2(:);obj.idx.qGam(:)]) = eye(60);
            obj.runtimeFromNative(candidate.runtimeState.qxi,obj.idx.qxi) = ...
                eye(numel(obj.idx.qxi));
            obj.runtimeFromNative(candidate.runtimeState.chi,obj.idx.chi) = ...
                eye(numel(obj.idx.chi));

            obj.runtimeFromRigid = zeros(candidate.runtimeState.count,9);
            obj.runtimeFromRigid(candidate.visible.rigid,:) = eye(9);

            obj.correctionToNative = zeros( ...
                obj.nativeStateCount,candidate.visible.count);
            obj.correctionToNative(obj.idx.q1,candidate.visible.q1) = ...
                eye(numel(obj.idx.q1));
            obj.correctionToNative(obj.idx.q2,candidate.visible.q2) = ...
                eye(numel(obj.idx.q2));
            obj.correctionToNative(obj.idx.qGam,candidate.visible.qGam) = ...
                eye(numel(obj.idx.qGam));

            assert(rank(obj.runtimeFromNative)==obj.nativeStateCount && ...
                rank(obj.runtimeFromRigid)==9 && ...
                rank(obj.correctionToNative)==60, ...
                'ReciprocalControllerModelProvider:StateMaps', ...
                'The reciprocal controller state maps changed rank.');
        end

        function state = initialize(obj,nativeState)
        %INITIALIZE Start the causal latent state at the source equilibrium.
            nativeState = obj.validateNativeState(nativeState);
            state = [nativeState;zeros(obj.hiddenStateCount,1)];
        end

        function [nativeState,hiddenState] = splitState(obj,state)
            state = obj.validateState(state);
            nativeState = state(1:obj.nativeStateCount);
            hiddenState = state(obj.nativeStateCount+1:end);
        end

        function configureFixedIntervalKernelAudit(obj,request)
        %CONFIGUREFIXEDINTERVALKERNELAUDIT Select the fixed Case-A kernel.
        %   This selector is default-inactive and audit-only. The existing
        %   MATLAB interval propagation remains the immediate fallback.
            assert(isstruct(request) && isscalar(request) && ...
                isfield(request,'enabled') && isscalar(request.enabled), ...
                'ReciprocalControllerModelProvider:FixedKernelRequest', ...
                'The fixed-kernel request must contain a scalar enabled flag.');
            enabled = logical(request.enabled);
            if ~enabled
                obj.fixedIntervalKernelAuditEnabled = false;
                obj.fixedIntervalKernelAuditPacket = struct();
                obj.fixedIntervalKernelAuditPacketSynchronized = false;
                obj.fixedIntervalKernelAuditFunction = [];
                obj.resetFixedIntervalKernelAuditCounters();
                return
            end

            required = {'auditOnly','changeId'};
            auditAuthorized = all(isfield(request,required)) && ...
                isscalar(request.auditOnly) && logical(request.auditOnly) && ...
                string(request.changeId)== ...
                    "phase18c-v17a-fixed-size-reciprocal-interval-runtime-integration-v1";
            productionAuthorized = all(isfield(request,required)) && ...
                isscalar(request.auditOnly) && ~logical(request.auditOnly) && ...
                string(request.changeId)== ...
                    "phase18c-v17a-condensed-rti-compiled-runtime-owner-promotion-v1";
            assert(auditAuthorized || productionAuthorized, ...
                'ReciprocalControllerModelProvider:FixedKernelAuthorization', ...
                'The fixed-kernel selector requires an approved identity.');
            if productionAuthorized
                kernelFunction = str2func( ...
                    'AeroFlex_ctrl_fixedReciprocalIntervalKernelProduction_mex');
            else
                kernelFunction = str2func( ...
                    'AeroFlex_ctrl_fixedReciprocalIntervalKernelAudit_mex');
            end
            if isfield(request,'kernelFunction') && ...
                    ~isempty(request.kernelFunction)
                assert(auditAuthorized && ...
                    isa(request.kernelFunction,'function_handle'), ...
                    'ReciprocalControllerModelProvider:FixedKernelFunction', ...
                    ['A kernel-function override is permitted only by the ', ...
                     'audit selector and must be a function handle.']);
                kernelFunction = request.kernelFunction;
            end

            obj.fixedIntervalKernelAuditPacket = ...
                AeroFlex.ctrl.buildFixedReciprocalIntervalPacketAudit(obj);
            obj.fixedIntervalKernelAuditPacketSynchronized = false;
            obj.fixedIntervalKernelAuditFunction = kernelFunction;
            obj.resetFixedIntervalKernelAuditCounters();
            obj.fixedIntervalKernelAuditEnabled = true;
        end

        function snapshot = fixedIntervalKernelAuditSnapshot(obj)
        %FIXEDINTERVALKERNELAUDITSNAPSHOT Return non-dynamic audit counters.
            kernelFunction = "";
            if ~isempty(obj.fixedIntervalKernelAuditFunction)
                kernelFunction = string(func2str( ...
                    obj.fixedIntervalKernelAuditFunction));
            end
            snapshot = struct( ...
                'enabled',obj.fixedIntervalKernelAuditEnabled, ...
                'kernelFunction',kernelFunction, ...
                'packetSynchronized', ...
                    obj.fixedIntervalKernelAuditPacketSynchronized, ...
                'compiledCallCount',obj.fixedIntervalKernelAuditCallCount, ...
                'estimatorCallCount', ...
                    obj.fixedIntervalKernelAuditEstimatorCallCount, ...
                'controllerCallCount', ...
                    obj.fixedIntervalKernelAuditControllerCallCount, ...
                'fallbackCount',obj.fixedIntervalKernelAuditFallbackCount, ...
                'diagnosticFallbackCount', ...
                    obj.fixedIntervalKernelAuditDiagnosticFallbackCount, ...
                'lastFallback',obj.fixedIntervalKernelAuditLastFallback, ...
                'activeSourceMask',true, ...
                'activeSourceCount',1);
        end

        function refreshed = synchronizeFixedIntervalKernelAuditPacket(obj)
        %SYNCHRONIZEFIXEDINTERVALKERNELAUDITPACKET Bind the active package.
        %   Controller construction precedes the first authoritative runtime
        %   package installation. Refresh once after that installation so the
        %   fixed kernel and exact provider use the same ROMIntegrator data.
            refreshed = false;
            if ~obj.fixedIntervalKernelAuditEnabled || ...
                    obj.fixedIntervalKernelAuditPacketSynchronized
                return
            end
            obj.fixedIntervalKernelAuditPacket = ...
                AeroFlex.ctrl.buildFixedReciprocalIntervalPacketAudit(obj);
            obj.fixedIntervalKernelAuditPacketSynchronized = true;
            refreshed = true;
        end

        function [stateNext,jacobian,diagnostic] = step(obj,state, ...
                wingTotal,sourceInput,rigidState,needJacobian)
        %STEP Advance one source sample without using runtime hidden truth.
        %   sourceInput order is [gust; left/right wing increments;
        %   left/right wing rates; elevator increment; thrust increment].
            if nargin < 6 || isempty(needJacobian)
                needJacobian = false;
            end
            assert(isscalar(needJacobian), ...
                'ReciprocalControllerModelProvider:JacobianFlag', ...
                'needJacobian must be scalar.');
            needJacobian = logical(needJacobian);
            [nativeState,hiddenState] = obj.splitState(state);
            wingTotal = wingTotal(:);
            sourceInput = sourceInput(:);
            rigidState = rigidState(:);
            assert(numel(wingTotal)==4 && all(isfinite(wingTotal)) && ...
                numel(sourceInput)==7 && all(isfinite(sourceInput)) && ...
                numel(rigidState)==9 && all(isfinite(rigidState)), ...
                'ReciprocalControllerModelProvider:Input', ...
                'Wing, source-input, and rigid-state contexts are invalid.');
            assert(norm(wingTotal-(obj.trimWingControl+sourceInput(2:5)), ...
                inf) <= 100*eps(max(1,norm(wingTotal,inf))), ...
                'ReciprocalControllerModelProvider:WingOwnership', ...
                ['The native total wing input and reciprocal trim-relative ', ...
                 'wing input do not describe the same realized command.']);

            runtimeState = obj.runtimeFromNative*nativeState+ ...
                obj.runtimeFromRigid*rigidState;
            runtimeDeparture = runtimeState- ...
                obj.candidate.base.correctionStateEquilibrium(:);
            inputDeparture = sourceInput- ...
                obj.candidate.base.inputEquilibrium(:);
            visibleCorrection = ...
                obj.candidate.correction.deltaAFullState*runtimeDeparture+ ...
                obj.candidate.partition.Avh*hiddenState+ ...
                obj.candidate.correction.deltaBv*inputDeparture;
            hiddenNext = ...
                obj.candidate.partition.hiddenFromFullState*runtimeDeparture+ ...
                obj.candidate.partition.Ahh*hiddenState+ ...
                obj.candidate.partition.Bh*inputDeparture;

            sensitivity0 = [];
            if needJacobian
                sensitivity0 = [eye(obj.nativeStateCount), ...
                    zeros(obj.nativeStateCount,5)];
            end
            [nativeNext,nativeSensitivity] = obj.model.step( ...
                nativeState,wingTotal,sourceInput(1), ...
                sensitivity0,needJacobian);
            nativeNext = nativeNext+ ...
                obj.correctionToNative*visibleCorrection;
            stateNext = [nativeNext;hiddenNext];
            assert(all(isfinite(stateNext)), ...
                'ReciprocalControllerModelProvider:FiniteState', ...
                'The reciprocal controller transition produced a nonfinite state.');

            jacobian = struct();
            if needJacobian
                nativeA = nativeSensitivity(:,1:obj.nativeStateCount);
                nativeInput = nativeSensitivity(:, ...
                    obj.nativeStateCount+(1:5));
                correctionA = obj.candidate.correction.deltaAFullState;
                hiddenA = obj.candidate.partition.hiddenFromFullState;
                jacobian.state = [ ...
                    nativeA+obj.correctionToNative*correctionA* ...
                        obj.runtimeFromNative, ...
                    obj.correctionToNative*obj.candidate.partition.Avh; ...
                    hiddenA*obj.runtimeFromNative, ...
                    obj.candidate.partition.Ahh];
                sourceInputNative = zeros(obj.nativeStateCount,7);
                sourceInputNative(:,1:5) = nativeInput;
                jacobian.input = [ ...
                    sourceInputNative+obj.correctionToNative* ...
                        obj.candidate.correction.deltaBv; ...
                    obj.candidate.partition.Bh];
                jacobian.rigid = [ ...
                    obj.correctionToNative*correctionA* ...
                        obj.runtimeFromRigid; ...
                    hiddenA*obj.runtimeFromRigid];
                assert(all(isfinite(jacobian.state),'all') && ...
                    all(isfinite(jacobian.input),'all') && ...
                    all(isfinite(jacobian.rigid),'all'), ...
                    'ReciprocalControllerModelProvider:FiniteJacobian', ...
                    'The reciprocal controller Jacobian is nonfinite.');
            end

            sourceRootWrench = ...
                obj.candidate.rootWrenchOutput.equilibrium(:)+ ...
                obj.candidate.rootWrenchOutput.runtimeStateMap* ...
                    [runtimeDeparture;hiddenState]+ ...
                obj.candidate.rootWrenchOutput.runtimeInputMap*inputDeparture;
            diagnostic = struct( ...
                'runtimeState',runtimeState, ...
                'runtimeDeparture',runtimeDeparture, ...
                'inputDeparture',inputDeparture, ...
                'visibleCorrection',visibleCorrection, ...
                'rigidCorrection',visibleCorrection( ...
                    obj.candidate.visible.rigid), ...
                'hiddenStateBefore',hiddenState, ...
                'hiddenStateAfter',hiddenNext, ...
                'sourceRootWrench',sourceRootWrench, ...
                'plantHiddenStateRead',false);
        end

        function [state,sensitivity,diagnostics] = propagateInterval( ...
                obj,state,disturbance,context,needJacobian)
        %PROPAGATEINTERVAL Advance one estimator interval from causal context.
        %   Commands and rigid states are completed-interval records. The
        %   disturbance remains the nMHE decision and is held across the
        %   plant substeps of this interval.
            if nargin < 5 || isempty(needJacobian)
                needJacobian = false;
            end
            state = obj.validateState(state);
            assert(isscalar(disturbance) && isfinite(disturbance), ...
                'ReciprocalControllerModelProvider:IntervalDisturbance', ...
                'The interval disturbance must be a finite scalar.');
            context = obj.validateIntervalContext(context);
            substepCount = size(context.wingTotal,2);
            diagnosticsRequested = nargout>=3;
            if obj.fixedIntervalKernelAuditEnabled && ...
                    ~diagnosticsRequested && substepCount==16
                initialState = state;
                [used,state,sensitivity] = ...
                    obj.tryFixedIntervalKernelAudit( ...
                        state,disturbance,context.wingTotal, ...
                        context.wingIncrement,context.elevatorIncrement, ...
                        context.thrustIncrement,context.rigidState, ...
                        needJacobian,"estimator");
                if used
                    [state,sensitivity] = obj.verifyFixedEstimatorInterval( ...
                        initialState,state,sensitivity,disturbance, ...
                        context,needJacobian);
                    diagnostics = [];
                    return
                end
            elseif obj.fixedIntervalKernelAuditEnabled && diagnosticsRequested
                obj.fixedIntervalKernelAuditDiagnosticFallbackCount = ...
                    obj.fixedIntervalKernelAuditDiagnosticFallbackCount+1;
            end
            diagnostics = cell(1,substepCount);
            if needJacobian
                stateSensitivity = eye(obj.stateCount);
                disturbanceSensitivity = zeros(obj.stateCount,1);
            else
                stateSensitivity = [];
                disturbanceSensitivity = [];
            end
            for substep = 1:substepCount
                sourceInput = [disturbance; ...
                    context.wingIncrement(:,substep); ...
                    context.elevatorIncrement(substep); ...
                    context.thrustIncrement(substep)];
                [state,jacobian,diagnostics{substep}] = obj.step( ...
                    state,context.wingTotal(:,substep),sourceInput, ...
                    context.rigidState(:,substep),needJacobian);
                if needJacobian
                    disturbanceSensitivity = jacobian.state* ...
                        disturbanceSensitivity+jacobian.input(:,1);
                    stateSensitivity = jacobian.state*stateSensitivity;
                end
            end
            if needJacobian
                sensitivity = [stateSensitivity,disturbanceSensitivity];
            else
                sensitivity = [];
            end
        end

        function [state,sensitivity,diagnostics] = ...
                propagateControlInterval(obj,state,disturbance, ...
                wingIncrement,context,needJacobian)
        %PROPAGATECONTROLINTERVAL Advance one nMPC interval.
        %   The future rigid/elevator/thrust trajectory is exogenous. The
        %   four trim-relative wing endpoint/rate coordinates are supplied
        %   by the nMPC decision and remain constant over plant substeps.
            if nargin < 6 || isempty(needJacobian)
                needJacobian = false;
            end
            state = obj.validateState(state);
            wingIncrement = wingIncrement(:);
            assert(isscalar(disturbance) && isfinite(disturbance) && ...
                numel(wingIncrement)==4 && all(isfinite(wingIncrement)), ...
                'ReciprocalControllerModelProvider:ControlIntervalInput', ...
                ['The controller interval requires one finite disturbance ', ...
                 'and four finite wing coordinates.']);
            context = obj.validateControlIntervalContext(context);
            substepCount = size(context.rigidState,2);
            wingTotal = obj.trimWingControl+wingIncrement;
            diagnosticsRequested = nargout>=3;
            if obj.fixedIntervalKernelAuditEnabled && ...
                    ~diagnosticsRequested && substepCount==16
                initialState = state;
                wingTotalHistory = repmat(wingTotal,1,substepCount);
                wingIncrementHistory = repmat( ...
                    wingIncrement,1,substepCount);
                [used,state,sensitivity] = ...
                    obj.tryFixedIntervalKernelAudit( ...
                        state,disturbance,wingTotalHistory, ...
                        wingIncrementHistory,context.elevatorIncrement, ...
                        context.thrustIncrement,context.rigidState, ...
                        needJacobian,"controller");
                if used
                    [state,sensitivity] = obj.verifyFixedControllerInterval( ...
                        initialState,state,sensitivity,disturbance, ...
                        wingIncrement,context,needJacobian);
                    diagnostics = [];
                    return
                end
            elseif obj.fixedIntervalKernelAuditEnabled && diagnosticsRequested
                obj.fixedIntervalKernelAuditDiagnosticFallbackCount = ...
                    obj.fixedIntervalKernelAuditDiagnosticFallbackCount+1;
            end
            diagnostics = cell(1,substepCount);
            if needJacobian
                stateSensitivity = eye(obj.stateCount);
                disturbanceSensitivity = zeros(obj.stateCount,1);
                wingSensitivity = zeros(obj.stateCount,4);
            else
                stateSensitivity = [];
                disturbanceSensitivity = [];
                wingSensitivity = [];
            end
            for substep = 1:substepCount
                sourceInput = [disturbance;wingIncrement; ...
                    context.elevatorIncrement(substep); ...
                    context.thrustIncrement(substep)];
                [state,jacobian,diagnostics{substep}] = obj.step( ...
                    state,wingTotal,sourceInput, ...
                    context.rigidState(:,substep),needJacobian);
                if needJacobian
                    disturbanceSensitivity = jacobian.state* ...
                        disturbanceSensitivity+jacobian.input(:,1);
                    wingSensitivity = jacobian.state*wingSensitivity+ ...
                        jacobian.input(:,2:5);
                    stateSensitivity = jacobian.state*stateSensitivity;
                end
            end
            if needJacobian
                sensitivity = [stateSensitivity, ...
                    disturbanceSensitivity,wingSensitivity];
            else
                sensitivity = [];
            end
        end
    end

    methods (Access = private)
        function [state,sensitivity] = verifyFixedEstimatorInterval( ...
                obj,initialState,state,sensitivity,disturbance,context, ...
                needJacobian)
        %VERIFYFIXEDESTIMATORINTERVAL Qualify MEX at live initialization.
            if obj.fixedIntervalKernelAuditEstimatorCallCount~=1
                return
            end
            exactState = initialState;
            exactHistory = zeros(obj.stateCount,size(context.wingTotal,2));
            stateSensitivity = eye(obj.stateCount);
            disturbanceSensitivity = zeros(obj.stateCount,1);
            for substep = 1:size(context.wingTotal,2)
                sourceInput = [disturbance; ...
                    context.wingIncrement(:,substep); ...
                    context.elevatorIncrement(substep); ...
                    context.thrustIncrement(substep)];
                [exactState,jacobian] = obj.step(exactState, ...
                    context.wingTotal(:,substep),sourceInput, ...
                    context.rigidState(:,substep),needJacobian);
                if needJacobian
                    disturbanceSensitivity = jacobian.state* ...
                        disturbanceSensitivity+jacobian.input(:,1);
                    stateSensitivity = jacobian.state*stateSensitivity;
                end
                exactHistory(:,substep) = exactState;
            end
            if needJacobian
                exactSensitivity = [stateSensitivity, ...
                    disturbanceSensitivity];
            else
                exactSensitivity = [];
            end
            [matlabKernelState,matlabKernelSensitivity,~, ...
                matlabKernelHistory] = ...
                AeroFlex.ctrl.fixedReciprocalIntervalKernelAudit( ...
                    initialState,disturbance,context.wingTotal, ...
                    context.wingIncrement,context.elevatorIncrement, ...
                    context.thrustIncrement,context.rigidState, ...
                    needJacobian,obj.fixedIntervalKernelAuditPacket);
            if needJacobian
                matlabKernelSensitivity = ...
                    matlabKernelSensitivity(:,1:122);
            end
            [state,sensitivity] = obj.acceptLiveFixedParity( ...
                state,sensitivity,exactState,exactSensitivity, ...
                matlabKernelState,matlabKernelSensitivity,exactHistory, ...
                matlabKernelHistory,"estimator");
        end

        function [state,sensitivity] = verifyFixedControllerInterval( ...
                obj,initialState,state,sensitivity,disturbance, ...
                wingIncrement,context,needJacobian)
        %VERIFYFIXEDCONTROLLERINTERVAL Qualify MEX at live initialization.
            if obj.fixedIntervalKernelAuditControllerCallCount~=1
                return
            end
            exactState = initialState;
            exactHistory = zeros(obj.stateCount,size(context.rigidState,2));
            stateSensitivity = eye(obj.stateCount);
            disturbanceSensitivity = zeros(obj.stateCount,1);
            wingSensitivity = zeros(obj.stateCount,4);
            wingTotal = obj.trimWingControl+wingIncrement;
            for substep = 1:size(context.rigidState,2)
                sourceInput = [disturbance;wingIncrement; ...
                    context.elevatorIncrement(substep); ...
                    context.thrustIncrement(substep)];
                [exactState,jacobian] = obj.step(exactState,wingTotal, ...
                    sourceInput,context.rigidState(:,substep),needJacobian);
                if needJacobian
                    disturbanceSensitivity = jacobian.state* ...
                        disturbanceSensitivity+jacobian.input(:,1);
                    wingSensitivity = jacobian.state*wingSensitivity+ ...
                        jacobian.input(:,2:5);
                    stateSensitivity = jacobian.state*stateSensitivity;
                end
                exactHistory(:,substep) = exactState;
            end
            if needJacobian
                exactSensitivity = [stateSensitivity, ...
                    disturbanceSensitivity,wingSensitivity];
            else
                exactSensitivity = [];
            end
            wingTotalHistory = repmat(wingTotal,1, ...
                size(context.rigidState,2));
            wingIncrementHistory = repmat(wingIncrement,1, ...
                size(context.rigidState,2));
            [matlabKernelState,matlabKernelSensitivity,~, ...
                matlabKernelHistory] = ...
                AeroFlex.ctrl.fixedReciprocalIntervalKernelAudit( ...
                    initialState,disturbance,wingTotalHistory, ...
                    wingIncrementHistory,context.elevatorIncrement, ...
                    context.thrustIncrement,context.rigidState, ...
                    needJacobian,obj.fixedIntervalKernelAuditPacket);
            [state,sensitivity] = obj.acceptLiveFixedParity( ...
                state,sensitivity,exactState,exactSensitivity, ...
                matlabKernelState,matlabKernelSensitivity,exactHistory, ...
                matlabKernelHistory,"controller");
        end

        function [state,sensitivity] = acceptLiveFixedParity(obj,state, ...
                sensitivity,exactState,exactSensitivity,matlabKernelState, ...
                matlabKernelSensitivity,exactHistory,matlabKernelHistory,owner)
        %ACCEPTLIVEFIXEDPARITY Fail closed to MATLAB on a live mismatch.
            stateError = norm(state-exactState,inf);
            sensitivityError = 0;
            if ~isempty(exactSensitivity)
                sensitivityError = norm(sensitivity-exactSensitivity,inf);
            end
            matlabStateError = norm(matlabKernelState-exactState,inf);
            mexToMatlabStateError = norm(state-matlabKernelState,inf);
            historyError = max(abs(matlabKernelHistory-exactHistory),[],1);
            firstBadSubstep = find(historyError>1e-11,1);
            if isempty(firstBadSubstep)
                firstBadSubstep = 0;
            end
            [largestComponentError,largestComponent] = max( ...
                abs(matlabKernelState-exactState));
            matlabSensitivityError = 0;
            if ~isempty(exactSensitivity)
                matlabSensitivityError = norm( ...
                    matlabKernelSensitivity-exactSensitivity,inf);
            end
            if stateError<=1e-11 && sensitivityError<=1e-8
                return
            end
            state = exactState;
            sensitivity = exactSensitivity;
            obj.fixedIntervalKernelAuditEnabled = false;
            obj.fixedIntervalKernelAuditFallbackCount = ...
                obj.fixedIntervalKernelAuditFallbackCount+1;
            obj.fixedIntervalKernelAuditLastFallback = sprintf( ...
                ['Live %s parity rejected the compiled kernel: state ', ...
                 'error %.6g, sensitivity error %.6g, MATLAB-kernel ', ...
                 'state/sensitivity error %.6g/%.6g, MEX-to-MATLAB ', ...
                 'kernel state error %.6g.'],owner,stateError, ...
                sensitivityError,matlabStateError, ...
                matlabSensitivityError,mexToMatlabStateError);
            warning('ReciprocalControllerModelProvider:LiveFixedKernelParity', ...
                ['Compiled %s interval parity failed (state %.3e, ', ...
                 'sensitivity %.3e; MATLAB kernel %.3e/%.3e; ', ...
                 'MEX-to-MATLAB %.3e; first bad substep %d, largest ', ...
                 'component %d at %.3e; required <= 1e-11/1e-8). ', ...
                 'The provider disabled the MEX and retained the exact ', ...
                 'MATLAB transition.'],owner,stateError,sensitivityError, ...
                matlabStateError,matlabSensitivityError, ...
                mexToMatlabStateError,firstBadSubstep,largestComponent, ...
                largestComponentError);
        end

        function [used,stateNext,sensitivity] = ...
                tryFixedIntervalKernelAudit(obj,state,disturbance, ...
                wingTotal,wingIncrement,elevatorIncrement, ...
                thrustIncrement,rigidState,needJacobian,owner)
            used = false;
            stateNext = state;
            sensitivity = [];
            try
                assert(~isempty(obj.fixedIntervalKernelAuditFunction), ...
                    'ReciprocalControllerModelProvider:FixedKernelMissing', ...
                    'The configured fixed-kernel function is unavailable.');
                [candidateState,candidateSensitivity] = feval( ...
                    obj.fixedIntervalKernelAuditFunction,state,disturbance, ...
                    wingTotal,wingIncrement,elevatorIncrement, ...
                    thrustIncrement,rigidState,logical(needJacobian), ...
                    obj.fixedIntervalKernelAuditPacket);
                candidateState = candidateState(:);
                assert(numel(candidateState)==obj.stateCount && ...
                    all(isfinite(candidateState)), ...
                    'ReciprocalControllerModelProvider:FixedKernelState', ...
                    'The fixed kernel returned an invalid state.');
                if needJacobian
                    assert(isequal(size(candidateSensitivity),[121 126]) && ...
                        all(isfinite(candidateSensitivity),'all'), ...
                        'ReciprocalControllerModelProvider:FixedKernelSensitivity', ...
                        'The fixed kernel returned an invalid sensitivity.');
                    if owner=="estimator"
                        sensitivity = candidateSensitivity(:,1:122);
                    else
                        sensitivity = candidateSensitivity;
                    end
                else
                    sensitivity = [];
                end
                stateNext = candidateState;
                obj.fixedIntervalKernelAuditCallCount = ...
                    obj.fixedIntervalKernelAuditCallCount+1;
                if owner=="estimator"
                    obj.fixedIntervalKernelAuditEstimatorCallCount = ...
                        obj.fixedIntervalKernelAuditEstimatorCallCount+1;
                else
                    obj.fixedIntervalKernelAuditControllerCallCount = ...
                        obj.fixedIntervalKernelAuditControllerCallCount+1;
                end
                used = true;
            catch exception
                obj.fixedIntervalKernelAuditFallbackCount = ...
                    obj.fixedIntervalKernelAuditFallbackCount+1;
                obj.fixedIntervalKernelAuditLastFallback = ...
                    string(exception.identifier)+": "+string(exception.message);
            end
        end

        function resetFixedIntervalKernelAuditCounters(obj)
            obj.fixedIntervalKernelAuditCallCount = 0;
            obj.fixedIntervalKernelAuditEstimatorCallCount = 0;
            obj.fixedIntervalKernelAuditControllerCallCount = 0;
            obj.fixedIntervalKernelAuditFallbackCount = 0;
            obj.fixedIntervalKernelAuditDiagnosticFallbackCount = 0;
            obj.fixedIntervalKernelAuditLastFallback = "";
        end

