function [endpoints,sensitivities,rootWrenches,stateHistories] = ...
        scheduledReciprocalHorizonKernelCoreAudit(nativeNodes,latentInitial, ...
        disturbances,wingTotal,wingIncrement,elevatorIncrement, ...
        thrustIncrement,rigidState,needJacobian,packets)
%SCHEDULEDRECIPROCALHORIZONKERNELCOREAUDIT Ordered multiple-shooting horizon.
%   Native decision nodes remain independent interval starts. Prescribed
%   reciprocal memory is propagated causally between intervals, exactly as in
%   the current MATLAB nMHE/nMPC continuity functions.

nativeNodes = double(nativeNodes);
latent = double(latentInitial(:));
disturbances = double(disturbances(:).');
horizonLength = size(nativeNodes,2);
assert(size(nativeNodes,1)==74 && numel(latent)==546 && ...
    numel(disturbances)==horizonLength && ...
    isequal(size(wingTotal),[4 14 horizonLength]) && ...
    isequal(size(wingIncrement),[4 14 horizonLength]) && ...
    isequal(size(elevatorIncrement),[1 14 horizonLength]) && ...
    isequal(size(thrustIncrement),[1 14 horizonLength]) && ...
    isequal(size(rigidState),[9 14 horizonLength]) && ...
    numel(packets)==horizonLength && ismember(horizonLength,[8 10]), ...
    'AeroFlex:ctrl:ScheduledReciprocalHorizonDimensions', ...
    'The scheduled reciprocal horizon inputs have invalid dimensions.');
assert(all(isfinite(nativeNodes),'all') && all(isfinite(latent)) && ...
    all(isfinite(disturbances)) && all(isfinite(wingTotal),'all') && ...
    all(isfinite(wingIncrement),'all') && ...
    all(isfinite(elevatorIncrement),'all') && ...
    all(isfinite(thrustIncrement),'all') && ...
    all(isfinite(rigidState),'all'), ...
    'AeroFlex:ctrl:ScheduledReciprocalHorizonFinite', ...
    'The scheduled reciprocal horizon inputs must be finite.');

endpoints = zeros(620,horizonLength);
sensitivities = zeros(620,625,horizonLength);
rootWrenches = zeros(6,14,horizonLength);
stateHistories = zeros(620,14,horizonLength);
for interval = 1:horizonLength
    intervalState = [nativeNodes(:,interval);latent];
    [endpoint,sensitivity,rootWrench,stateHistory] = ...
        AeroFlex.ctrl.scheduledReciprocalIntervalKernelAudit( ...
            intervalState,disturbances(interval), ...
            wingTotal(:,:,interval),wingIncrement(:,:,interval), ...
            elevatorIncrement(:,:,interval), ...
            thrustIncrement(:,:,interval),rigidState(:,:,interval), ...
            needJacobian,packets(interval));
    endpoints(:,interval) = endpoint;
    if needJacobian
        sensitivities(:,:,interval) = sensitivity;
    end
    rootWrenches(:,:,interval) = rootWrench;
    stateHistories(:,:,interval) = stateHistory;
    latent = endpoint(75:620);
end
end
