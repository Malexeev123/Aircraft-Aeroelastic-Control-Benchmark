classdef SourceCoordinateOuterFeedback < handle
%SOURCECOORDINATEOUTERFEEDBACK Exact-Case-A dynamic outer controller.
%   The controller owns a source-coordinate observer and one leaky pitch
%   integral state. Its three outputs are virtual longitudinal demands;
%   runtime allocation realizes symmetric wing, elevator, and thrust.

    properties (SetAccess = private)
        design struct
        trimThrust double
        prior double
        posterior double
        integralState double = 0
        previousRealizedDemand double
        pendingRawDemand double
        pendingIntegralState double = 0
        pendingAccepted logical = false
        updateCount double = 0
        fallbackCount double = 0
        last struct = struct()
    end

    methods
        function obj = SourceCoordinateOuterFeedback(design,trimThrust)
            obj.validateDesign(design,trimThrust);
            obj.design = design;
            obj.trimThrust = trimThrust;
            obj.reset();
        end

        function reset(obj)
            obj.prior = zeros(obj.design.stateCount,1);
            obj.posterior = obj.prior;
            obj.integralState = 0;
            obj.previousRealizedDemand = zeros(obj.design.demandCount,1);
            obj.pendingRawDemand = obj.previousRealizedDemand;
            obj.pendingIntegralState = 0;
            obj.pendingAccepted = false;
            obj.updateCount = 0;
            obj.fallbackCount = 0;
            obj.last = struct("status","RESET","accepted",true);
        end

        function [demand,info] = update(obj,measurement,referencePitch,gustEstimate)
            measurement = measurement(:);
            referencePitch = double(referencePitch);
            gustEstimate = double(gustEstimate);
            info = obj.emptyInfo();
            try
                assert(numel(measurement)==obj.design.measurementCount && ...
                    all(isfinite(measurement)), ...
                    "AeroFlex:SourceOuterMeasurement", ...
                    "The source-coordinate measurement is invalid.");
                assert(isscalar(referencePitch) && isfinite(referencePitch) && ...
                    isscalar(gustEstimate) && isfinite(gustEstimate), ...
                    "AeroFlex:SourceOuterContext", ...
                    "The source-coordinate reference or gust is invalid.");
                normalized = measurement./obj.design.measurementSigma(:);
                innovation = normalized-obj.design.observer.C*obj.prior;
                posteriorCandidate = obj.prior+ ...
                    obj.design.observer.gain*innovation;
                raw = -obj.design.controller.stateGain*posteriorCandidate- ...
                    obj.design.controller.integralGain*obj.integralState+ ...
                    obj.design.controller.referencePrefilter*referencePitch;
                demand = obj.limitDemand(raw);
                integralCandidate = obj.design.controller.leakPole* ...
                    obj.integralState+obj.design.sampleTimeSeconds* ...
                    (measurement(3)-referencePitch);
                assert(all(isfinite([posteriorCandidate;raw;demand; ...
                    integralCandidate])), ...
                    "AeroFlex:SourceOuterFinite", ...
                    "The source-coordinate update is nonfinite.");
                obj.posterior = posteriorCandidate;
                obj.pendingRawDemand = raw;
                obj.pendingIntegralState = integralCandidate;
                obj.pendingAccepted = true;
                obj.updateCount = obj.updateCount+1;
                info = struct("status","ACCEPTED","accepted",true, ...
                    "measurement",measurement,"normalizedMeasurement",normalized, ...
                    "innovation",innovation,"posterior",posteriorCandidate, ...
                    "rawDemand",raw,"limitedDemand",demand, ...
                    "referencePitchRadians",referencePitch, ...
                    "gustEstimateMetersPerSecond",gustEstimate, ...
                    "fallbackCount",obj.fallbackCount);
            catch err
                demand = obj.previousRealizedDemand;
                obj.posterior = obj.prior;
                obj.pendingRawDemand = demand;
                obj.pendingIntegralState = obj.integralState;
                obj.pendingAccepted = true;
                obj.fallbackCount = obj.fallbackCount+1;
                info.status = "FALLBACK_"+string(err.identifier);
                info.accepted = false;
                info.errorMessage = string(err.message);
                info.limitedDemand = demand;
                info.fallbackCount = obj.fallbackCount;
            end
            obj.last = info;
        end

        function info = acceptRealizedDemand(obj,realizedDemand,gustEstimate)
            realizedDemand = realizedDemand(:);
            gustEstimate = double(gustEstimate);
            assert(obj.pendingAccepted, ...
                "AeroFlex:SourceOuterPending", ...
                "No source-coordinate update is pending realization.");
            assert(numel(realizedDemand)==obj.design.demandCount && ...
                all(isfinite(realizedDemand)) && isfinite(gustEstimate), ...
                "AeroFlex:SourceOuterRealized", ...
                "The realized demand or gust estimate is invalid.");
            realizedDemand = obj.limitDemand(realizedDemand);
            residual = realizedDemand-obj.pendingRawDemand;
            integralGain = obj.design.controller.integralGain(:);
            correction = 0;
            if any(integralGain)
                correction = -(integralGain.'*residual)/ ...
                    max(integralGain.'*integralGain,eps);
            end
            obj.integralState = obj.pendingIntegralState+ ...
                obj.design.sampleTimeSeconds/ ...
                obj.design.controller.antiWindupTimeConstantSeconds*correction;
            obj.prior = obj.design.observer.A*obj.posterior+ ...
                obj.design.observer.B*realizedDemand+ ...
                obj.design.observer.Bg*gustEstimate;
            assert(all(isfinite([obj.integralState;obj.prior])) && ...
                obj.trimThrust+realizedDemand(3)>=0, ...
                "AeroFlex:SourceOuterAdvance", ...
                "The realized source-coordinate advance is invalid.");
            obj.previousRealizedDemand = realizedDemand;
            obj.pendingAccepted = false;
            info = struct("accepted",true,"realizedDemand",realizedDemand, ...
                "requestedRealizationResidual",residual, ...
                "antiWindupCorrection",correction, ...
                "integralState",obj.integralState, ...
                "prior",obj.prior,"gustEstimate",gustEstimate);
            obj.last.realization = info;
        end

        function state = snapshot(obj)
            state = struct("prior",obj.prior,"posterior",obj.posterior, ...
                "integralState",obj.integralState, ...
                "previousRealizedDemand",obj.previousRealizedDemand, ...
                "pendingAccepted",obj.pendingAccepted, ...
                "updateCount",obj.updateCount, ...
                "fallbackCount",obj.fallbackCount,"last",obj.last);
        end
    end

    methods (Access = private)
        function demand = limitDemand(obj,demand)
            demand = min(max(demand(:),obj.design.demandLower(:)), ...
                obj.design.demandUpper(:));
            demand(3) = max(demand(3),-obj.trimThrust);
        end

        function info = emptyInfo(obj)
            info = struct("status","NOT_EVALUATED","accepted",false, ...
                "measurement",zeros(obj.design.measurementCount,1), ...
                "normalizedMeasurement",zeros(obj.design.measurementCount,1), ...
                "innovation",zeros(obj.design.measurementCount,1), ...
                "posterior",obj.posterior,"rawDemand",zeros(3,1), ...
                "limitedDemand",obj.previousRealizedDemand, ...
                "referencePitchRadians",nan, ...
                "gustEstimateMetersPerSecond",nan, ...
                "fallbackCount",obj.fallbackCount,"errorMessage","");
        end

        function validateDesign(~,design,trimThrust)
            required = ["schemaVersion","sourceId","defaultActive", ...
                "sampleTimeSeconds","stateCount","measurementCount", ...
                "demandCount","measurementSigma","demandLower", ...
                "demandUpper","observer","controller"];
            for field = required
                assert(isfield(design,field), ...
                    "AeroFlex:SourceOuterDesign", ...
                    "The source-coordinate design lacks %s.",field);
            end
            assert(string(design.sourceId)=="CASEA_U040_ALPHA_P01" && ...
                ~logical(design.defaultActive) && ...
                design.stateCount==45 && design.measurementCount==6 && ...
                design.demandCount==3 && design.sampleTimeSeconds>0 && ...
                isfinite(trimThrust) && trimThrust>=0, ...
                "AeroFlex:SourceOuterDesign", ...
                "The source-coordinate design identity is invalid.");
            assert(isequal(size(design.observer.A),[45,45]) && ...
                isequal(size(design.observer.B),[45,3]) && ...
                isequal(size(design.observer.Bg),[45,1]) && ...
                isequal(size(design.observer.C),[6,45]) && ...
                isequal(size(design.observer.gain),[45,6]) && ...
                isequal(size(design.controller.stateGain),[3,45]) && ...
                numel(design.controller.integralGain)==3 && ...
                numel(design.controller.referencePrefilter)==3 && ...
                design.controller.antiWindupTimeConstantSeconds>0 && ...
                all(isfinite([design.observer.A(:);design.observer.B(:); ...
                    design.observer.Bg(:);design.observer.C(:); ...
                    design.observer.gain(:); ...
                    design.controller.stateGain(:)])), ...
                "AeroFlex:SourceOuterDesign", ...
                "The source-coordinate matrices are invalid.");
        end
    end
end
