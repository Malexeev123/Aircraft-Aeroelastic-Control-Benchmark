function [endpoints,latentEndpoints,stateExpansion,stateOffset] = ...
        scheduledReciprocalControllerReducedTangentHorizonAudit( ...
        nativeNodes,latentInitial,initialStateTarget,disturbances, ...
        wingTotal,wingIncrement,elevatorIncrement,thrustIncrement, ...
        rigidState,wingExpansion,packets)
%SCHEDULEDRECIPROCALCONTROLLERREDUCEDTANGENTHORIZONAUDIT Exact Nc=10 map.

initialStateTarget = initialStateTarget(:);
assert(isequal(size(nativeNodes),[74 11]) && ...
    numel(initialStateTarget)==74 && numel(disturbances)==10 && ...
    isequal(size(wingExpansion),[4 10 10]) && numel(packets)==10, ...
    'AeroFlex:ctrl:ScheduledControllerReducedTangentLength', ...
    'The controller reduced tangent requires Nc=10 and ten rate coordinates.');
disturbanceExpansion = zeros(1,10,10);
[endpoints,latentEndpoints,stateExpansion,stateOffset] = ...
    AeroFlex.ctrl.scheduledReciprocalReducedTangentHorizonCoreAudit( ...
        nativeNodes,latentInitial,disturbances,wingTotal,wingIncrement, ...
        elevatorIncrement,thrustIncrement,rigidState,zeros(74,10), ...
        initialStateTarget-nativeNodes(:,1),disturbanceExpansion, ...
        wingExpansion,packets);
end
