function endpoints = scheduledReciprocalEstimatorCausalRolloutAudit( ...
        nativeInitial,latentInitial,disturbances,wingTotal,wingIncrement, ...
        elevatorIncrement,thrustIncrement,rigidState,packets)
%SCHEDULEDRECIPROCALESTIMATORCAUSALROLLOUTAUDIT Exact Ne=8 rollout.

assert(numel(disturbances)==8 && numel(packets)==8, ...
    'AeroFlex:ctrl:ScheduledReciprocalEstimatorCausalRolloutLength', ...
    'The scheduled estimator causal rollout must contain eight intervals.');
