function [endpoints,sensitivities,rootWrenches,stateHistories] = ...
        scheduledReciprocalEstimatorHorizonKernelAudit(nativeNodes, ...
        latentInitial,disturbances,wingTotal,wingIncrement, ...
        elevatorIncrement,thrustIncrement,rigidState,needJacobian,packets)
%SCHEDULEDRECIPROCALESTIMATORHORIZONKERNELAUDIT Exact Ne=8 horizon batch.

assert(size(nativeNodes,2)==8 && numel(packets)==8, ...
    'AeroFlex:ctrl:ScheduledReciprocalEstimatorHorizonLength', ...
    'The scheduled estimator horizon must contain eight intervals.');
[endpoints,sensitivities,rootWrenches,stateHistories] = ...
    AeroFlex.ctrl.scheduledReciprocalHorizonKernelCoreAudit( ...
        nativeNodes,latentInitial,disturbances,wingTotal,wingIncrement, ...
        elevatorIncrement,thrustIncrement,rigidState,needJacobian,packets);
end
