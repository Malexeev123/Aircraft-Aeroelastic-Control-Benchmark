function [cfg,measurement] = buildLongitudinalPhysicalOutputAudit( ...
        cfg,source,candidate)
%BUILDLONGITUDINALPHYSICALOUTPUTAUDIT Build the qualified audit sensor map.
%   This default-inactive helper defines the same ideal physical-output
%   measurement contract used by the Phase-18C longitudinal nMHE audits. It
%   does not model calibrated hardware noise, bias, latency, or quantization.

arguments
    cfg struct
    source struct
    candidate (1,1) string {mustBeMember(candidate, ...
        ["imu","imu_attitude","imu_attitude_airdata", ...
         "imu_attitude_airdata_scheduled"])}
end

requiredSourceFields = ["beam","base","trim","p5"];
for field = requiredSourceFields
    assert(isfield(source,field),"AeroFlex:PhysicalOutputAuditSource", ...
        "The audit source is missing field %s.",field);
end
assert(isfield(source.p5,"idx") && isfield(source.p5,"mu") && ...
    numel(source.p5.mu) >= 1,"AeroFlex:PhysicalOutputAuditPackage", ...
    "The audit source package must provide idx and its flight coordinate.");
assert(isfield(cfg,"struct") && isfield(cfg.struct,"L") && ...
    isfield(cfg,"ctrl") && isfield(cfg.ctrl,"Ts") && ...
    isfinite(cfg.ctrl.Ts) && cfg.ctrl.Ts > 0, ...
    "AeroFlex:PhysicalOutputAuditConfiguration", ...
    "The audit configuration requires finite span and sample time.");

idx = source.p5.idx;
nx = numel(source.trim.states);
spanFractions = [0,.25,.75,1];
scheduledQ1Map = [];
scheduledQxiMap = [];
scheduledCenterQ1Map = [];
scheduledCenterQxiMap = [];
if isfield(source,"scheduleStateCoordinate")
    scheduledQ1Map = source.scheduleStateCoordinate.q1ToPhysical;
    scheduledQxiMap = source.scheduleStateCoordinate.qxiToPhysical;
    if isfield(source.scheduleStateCoordinate,"q1CenterToPhysical")
        scheduledCenterQ1Map = ...
            source.scheduleStateCoordinate.q1CenterToPhysical;
    end
    if isfield(source.scheduleStateCoordinate,"qxiCenterToPhysical")
        scheduledCenterQxiMap = ...
            source.scheduleStateCoordinate.qxiCenterToPhysical;
    end
end
[velocityMap,velocityDetail] = localVelocityRecovery( ...
    source.beam,spanFractions,cfg.struct.L,scheduledQ1Map, ...
    scheduledCenterQ1Map);
translationalMap = velocityMap(localComponentRows(1:3,5),:);
angularMap = velocityMap(localComponentRows(4:6,5),:);
gyroJacobian = zeros(size(angularMap,1),nx);
gyroJacobian(:,idx.q1) = angularMap;
accelerationJacobian = zeros(size(translationalMap,1),nx);
accelerationJacobian(:,idx.q1) = translationalMap;

includeAttitude = candidate ~= "imu";
includeAirData = ismember(candidate, ...
    ["imu_attitude_airdata","imu_attitude_airdata_scheduled"]);
scheduledAirData = candidate == "imu_attitude_airdata_scheduled";
attitudeReferenceQuaternion = zeros(4,0);
if includeAttitude
    [quaternionMap,trimQuaternion] = localQuaternionRecovery( ...
        source.base,source.beam,spanFractions,cfg.struct.L,idx, ...
        source.trim.states(:),scheduledQxiMap,scheduledCenterQxiMap);
    attitudeReferenceQuaternion = trimQuaternion;
    if isfield(cfg,"mheMeasurement") && ...
            isstruct(cfg.mheMeasurement) && ...
            isfield(cfg.mheMeasurement,"physicalReference") && ...
            isfield(cfg.mheMeasurement.physicalReference, ...
                "attitudeQuaternion")
        declaredReference = cfg.mheMeasurement.physicalReference. ...
            attitudeQuaternion;
        assert(isequal(size(declaredReference),size(trimQuaternion)) && ...
            all(isfinite(declaredReference),"all"), ...
            "AeroFlex:PhysicalOutputAuditAttitudeReference", ...
            "The fixed physical attitude reference is invalid.");
        attitudeReferenceQuaternion = declaredReference;
    end
    attitudeMeasurement = @(state) localAttitudeMeasurement( ...
        state,idx,quaternionMap,attitudeReferenceQuaternion);
    attitudeJacobian = @(state) localAttitudeStateJacobian( ...
        state,idx,quaternionMap,attitudeReferenceQuaternion,nx);
    attitudeRows = 3*5;
else
    attitudeMeasurement = @(~) zeros(0,1);
    attitudeJacobian = @(~) zeros(0,nx);
    attitudeRows = 0;
end

gyroRows = size(gyroJacobian,1);
accelerationRows = size(accelerationJacobian,1);
airDataRows = 2*double(includeAirData);
nodeRows = gyroRows+attitudeRows;
intervalRows = accelerationRows+airDataRows;
cfg.ny = nodeRows+intervalRows;

gyroSigma = 0.02;
accelerationSigma = 0.20;
attitudeSigma = deg2rad(0.5);
airspeedSigma = 0.5;
angleOfAttackSigma = deg2rad(0.5);
weightDiagonal = [repmat(1/gyroSigma^2,gyroRows,1); ...
    repmat(1/attitudeSigma^2,attitudeRows,1); ...
    repmat(1/accelerationSigma^2,accelerationRows,1); ...
    repmat(1/airspeedSigma^2,double(includeAirData),1); ...
    repmat(1/angleOfAttackSigma^2,double(includeAirData),1)];
cfg.Qe = diag(weightDiagonal);

trimState = source.trim.states(:);
trimMeasurement = [gyroJacobian*trimState; ...
    attitudeMeasurement(trimState);zeros(intervalRows,1)];
trimJacobian = [gyroJacobian;attitudeJacobian(trimState); ...
    zeros(intervalRows,nx)];
measurement = struct();
measurement.measure = @(state) [gyroJacobian*state(:); ...
    attitudeMeasurement(state(:));zeros(intervalRows,1)];
measurement.jacobian = @(state) [gyroJacobian; ...
    attitudeJacobian(state(:));zeros(intervalRows,nx)];
measurement.intervalRows = (nodeRows+1:cfg.ny).';
measurement.measureInterval = @(previous,current,disturbance,~,Ts) ...
    localIntervalMeasurement(previous,current,disturbance,Ts, ...
        accelerationJacobian,nodeRows,source.p5.mu(1),includeAirData);
measurement.jacobianInterval = @(previous,current,disturbance,~,Ts) ...
    localIntervalJacobians(previous,current,disturbance,Ts, ...
        accelerationJacobian,nodeRows,nx,cfg.nw,source.p5.mu(1),includeAirData);
measurement.linearizationAtTrim = struct( ...
    "measurement",trimMeasurement,"jacobian",trimJacobian, ...
    "context",zeros(0,1));
measurement.contextWidth = 0;
measurement.physicalReference = struct( ...
    "owner","fixed_initial_sensor_calibration", ...
    "attitudeQuaternion",attitudeReferenceQuaternion);
if scheduledAirData
    measurement.contextWidth = 1;
    measurement.linearizationAtTrim.context = source.p5.mu(1);
    measurement.validateContext = @localValidateAirDataContext;
    measurement.measureIntervalWithContext = ...
        @(previous,current,disturbance,~,Ts,context) ...
        localIntervalMeasurement(previous,current,disturbance,Ts, ...
            accelerationJacobian,nodeRows, ...
            localValidateAirDataContext(context),includeAirData);
    measurement.jacobianIntervalWithContext = ...
        @(previous,current,disturbance,~,Ts,context) ...
        localIntervalJacobians(previous,current,disturbance,Ts, ...
            accelerationJacobian,nodeRows,nx,cfg.nw, ...
            localValidateAirDataContext(context),includeAirData);
end
measurement.groups = struct( ...
    "gyro",(1:gyroRows).', ...
    "attitude",(gyroRows+1:nodeRows).', ...
    "acceleration",(nodeRows+1:nodeRows+accelerationRows).', ...
    "airdata",(nodeRows+accelerationRows+1:cfg.ny).');
measurement.detail = struct( ...
    "type","audit-only symmetric longitudinal physical-output sensor suite", ...
    "candidate",candidate,"bodyStation","centerline/CG recovery", ...
    "wingSpanFractions",spanFractions, ...
    "stationCoordinatesMeters",velocityDetail.stationCoordinatesMeters, ...
    "stationLabels",velocityDetail.stationLabels, ...
    "centerVelocityRecovery","beam.red.phi1_sA", ...
    "centerAttitudeRecovery","base.phiXi_sA", ...
    "wingVelocityRecovery","beam.phi1", ...
    "wingAttitudeRecovery","base.phi_xi_modes", ...
    "gyroRows",gyroRows,"attitudeRows",attitudeRows, ...
    "accelerationRows",accelerationRows,"airDataRows",airDataRows, ...
    "gyroSigmaRadPerSecond",gyroSigma, ...
    "attitudeSigmaRadians",attitudeSigma, ...
    "accelerationSigmaMetersPerSecondSquared",accelerationSigma, ...
    "airspeedSigmaMetersPerSecond",airspeedSigma, ...
    "angleOfAttackSigmaRadians",angleOfAttackSigma, ...
    "directQxiMeasurement",false, ...
    "attitudeDependsOnQxiThroughPhysicalRecovery",includeAttitude, ...
    "airDataDependsDirectlyOnDisturbance",includeAirData, ...
    "airDataContextRequired",scheduledAirData, ...
    "airDataContext","measured rigid-body speed [m/s] per interval", ...
    "attitudeReferenceOwner","fixed initial sensor calibration", ...
    "productionEligible",false);
measurement.detail.packageRuntimeStepSeconds = cfg.sim.dt;
measurement.detail.controlSampleSeconds = cfg.ctrl.Ts;
measurement.detail.substepsPerControlSample = ...
    round(cfg.ctrl.Ts/cfg.sim.dt);
cfg.mheMeasurement = rmfield(measurement,{'groups','detail'});
end

function [map,detail] = localVelocityRecovery( ...
        beam,spanFractions,span,scheduledMap,scheduledCenterMap)
coordinates = [0,spanFractions*span-span/2];
labels = ["body_center","left_tip","left_mid","right_mid","right_tip"];
map = zeros(6*numel(coordinates),beam.Nm);
for station = 1:numel(coordinates)
    rows = (station-1)*6+(1:6);
    if station == 1
        if isempty(scheduledCenterMap)
            map(rows,:) = beam.red.phi1_sA;
        else
            assert(isequal(size(scheduledCenterMap), ...
                size(beam.red.phi1_sA)), ...
                "AeroFlex:PhysicalOutputAuditScheduledCenterVelocityMap", ...
                "The scheduled center velocity map has incompatible dimensions.");
            map(rows,:) = scheduledCenterMap;
        end
    else
        map(rows,:) = localVelocityAtCoordinate( ...
            beam,coordinates(station),scheduledMap);
    end
end
detail = struct("stationCoordinatesMeters",coordinates, ...
    "stationLabels",labels);
end

function value = localVelocityAtCoordinate(beam,target,scheduledMap)
coordinates = beam.fem.coordinates(:,2);
[distance,node] = min(abs(coordinates-target));
assert(distance <= 1e-10 && node > 1, ...
    "AeroFlex:PhysicalOutputAuditSensorStation", ...
    "The declared wing sensor station is not an exact unclamped source node.");
fullRows = (node-1)*6+(1:6);
keptRows = AeroFlex.core.localDofIndex(beam.fem.keepDofs,fullRows);
assert(numel(keptRows) == 6, ...
    "AeroFlex:PhysicalOutputAuditSensorStation", ...
    "The declared wing sensor does not retain six source DOFs.");
if isempty(scheduledMap)
    value = beam.phi1(keptRows,:);
else
    assert(size(scheduledMap,1) == numel(beam.fem.keepDofs), ...
        "AeroFlex:PhysicalOutputAuditScheduledVelocityMap", ...
        "The scheduled physical velocity map has incompatible rows.");
    value = scheduledMap(keptRows,:);
end
end

function rows = localComponentRows(components,stationCount)
rows = zeros(1,numel(components)*stationCount);
cursor = 0;
for station = 1:stationCount
    selection = (station-1)*6+components;
    rows(cursor+(1:numel(components))) = selection;
    cursor = cursor+numel(components);
end
end

function [map,trimQuaternion] = localQuaternionRecovery( ...
        base,beam,spanFractions,span,idx,trimState,scheduledMap, ...
        scheduledCenterMap)
coordinates = [0,spanFractions*span-span/2];
map = zeros(4*numel(coordinates),numel(idx.qxi));
for station = 1:numel(coordinates)
    rows = (station-1)*4+(1:4);
    if station == 1
        assert(isequal(size(base.phiXi_sA),[4,numel(idx.qxi)]), ...
            "AeroFlex:PhysicalOutputAuditCenterAttitudeMap", ...
            "base.phiXi_sA is incompatible with qxi.");
        if isempty(scheduledCenterMap)
            map(rows,:) = base.phiXi_sA;
        else
            assert(isequal(size(scheduledCenterMap), ...
                size(base.phiXi_sA)), ...
                "AeroFlex:PhysicalOutputAuditScheduledCenterAttitudeMap", ...
                "The scheduled center attitude map has incompatible dimensions.");
            map(rows,:) = scheduledCenterMap;
        end
    else
        sourceCoordinates = beam.fem.coordinates(2:end,2);
        [distance,node] = min(abs(sourceCoordinates-coordinates(station)));
        assert(distance <= 1e-10, ...
            "AeroFlex:PhysicalOutputAuditWingAttitudeMap", ...
            "The declared attitude station is not an exact source node.");
        sourceRows = (node-1)*4+(1:4);
        if isempty(scheduledMap)
            map(rows,:) = base.phi_xi_modes(sourceRows,:);
        else
            assert(size(scheduledMap,1) == size(base.phi_xi_modes,1), ...
                "AeroFlex:PhysicalOutputAuditScheduledAttitudeMap", ...
                "The scheduled physical attitude map has incompatible rows.");
            map(rows,:) = scheduledMap(sourceRows,:);
        end
    end
end
trimQuaternion = reshape(map*trimState(idx.qxi),4,[]);
trimQuaternion = trimQuaternion./vecnorm(trimQuaternion,2,1);
end

function value = localAttitudeMeasurement(state,idx,map,trimQuaternion)
quaternion = reshape(map*state(idx.qxi),4,[]);
quaternion = quaternion./vecnorm(quaternion,2,1);
value = zeros(3,size(quaternion,2));
for station = 1:size(quaternion,2)
    relative = localQuaternionMultiply( ...
        localQuaternionConjugate(trimQuaternion(:,station)), ...
        quaternion(:,station));
    if relative(1) < 0
        relative = -relative;
    end
    value(:,station) = localQuaternionLog(relative);
end
value = value(:);
end

function jacobian = localAttitudeStateJacobian( ...
        state,idx,map,trimQuaternion,nx)
step = 1e-7;
jacobian = zeros(3*size(trimQuaternion,2),nx);
for column = 1:numel(idx.qxi)
    plus = state;
    minus = state;
    plus(idx.qxi(column)) = plus(idx.qxi(column))+step;
    minus(idx.qxi(column)) = minus(idx.qxi(column))-step;
    jacobian(:,idx.qxi(column)) = ( ...
        localAttitudeMeasurement(plus,idx,map,trimQuaternion)- ...
        localAttitudeMeasurement(minus,idx,map,trimQuaternion))/(2*step);
end
end

function value = localQuaternionConjugate(value)
value(2:4) = -value(2:4);
end

function value = localQuaternionMultiply(left,right)
value = [left(1)*right(1)-dot(left(2:4),right(2:4)); ...
    left(1)*right(2:4)+right(1)*left(2:4)+ ...
    cross(left(2:4),right(2:4))];
end

function value = localQuaternionLog(quaternion)
vector = quaternion(2:4);
vectorNorm = norm(vector);
if vectorNorm < 1e-12
    value = 2*vector;
else
    value = 2*atan2(vectorNorm,quaternion(1))*vector/vectorNorm;
end
end

function output = localIntervalMeasurement( ...
        previous,current,disturbance,Ts,Ca,nodeRows,U,includeAirData)
acceleration = Ca*(current(:)-previous(:))/Ts;
if includeAirData
    airData = localAirData(disturbance(1),U);
else
    airData = zeros(0,1);
end
output = [zeros(nodeRows,1);acceleration;airData];
end

function [previousJacobian,currentJacobian,disturbanceJacobian] = ...
        localIntervalJacobians( ...
        ~,~,disturbance,Ts,Ca,nodeRows,nx,nw,U,includeAirData)
intervalRows = size(Ca,1)+2*double(includeAirData);
previousJacobian = zeros(nodeRows+intervalRows,nx);
currentJacobian = zeros(nodeRows+intervalRows,nx);
disturbanceJacobian = zeros(nodeRows+intervalRows,nw);
accelerationRows = nodeRows+(1:size(Ca,1));
previousJacobian(accelerationRows,:) = -Ca/Ts;
currentJacobian(accelerationRows,:) = Ca/Ts;
if includeAirData
    airRows = nodeRows+size(Ca,1)+(1:2);
    disturbanceJacobian(airRows,1) = ...
        localAirDataJacobian(disturbance(1),U);
end
end

function value = localAirData(gust,U)
value = [hypot(U,gust)-U;atan2(gust,U)];
end

function value = localAirDataJacobian(gust,U)
value = [gust/hypot(U,gust);U/(U^2+gust^2)];
end

function speed = localValidateAirDataContext(context)
assert(isnumeric(context) && isreal(context) && isscalar(context) && ...
    isfinite(context) && context > 0, ...
    "AeroFlex:PhysicalOutputAuditAirDataContext", ...
    "The air-data interval context must be one finite positive speed in m/s.");
speed = double(context);
end
