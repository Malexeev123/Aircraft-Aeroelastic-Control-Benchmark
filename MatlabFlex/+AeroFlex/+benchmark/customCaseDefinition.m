function definition = customCaseDefinition(options)
%CUSTOMCASEDEFINITION Define one continuous custom benchmark maneuver.
%   Custom references share one plant/controller runtime for the complete
%   maneuver. Formal-case labels are descriptive only and do not splice or
%   reset the qualified A/B runners.

arguments
    options.Name (1,1) string = "custom"
    options.BodyCase (1,1) string {mustBeMember(options.BodyCase, ...
        ["wing_only","coupled_full"])} = "coupled_full"
    options.DurationSeconds (1,1) double = 5
    options.Reference (1,1) struct = struct()
    options.Gust (1,1) struct = struct()
    options.InitialCondition (1,1) struct = struct()
    options.ControlMask (1,1) struct = struct()
    options.RuntimeFamily (1,1) string {mustBeMember( ...
        options.RuntimeFamily,["auto","fixed_source","scheduled"])} = ...
        "auto"
end

assert(isfinite(options.DurationSeconds) && options.DurationSeconds>0, ...
    "AeroFlex:CustomCaseDuration", ...
    "DurationSeconds must be positive and finite.");
assert(strlength(options.Name)>0 && isempty(regexp(options.Name, ...
    "[^A-Za-z0-9_-]","once")),"AeroFlex:CustomCaseName", ...
    "Name may contain only letters, numbers, underscores, and hyphens.");

reference = localReference(options.Reference,options.DurationSeconds);
gust = localGust(options.Gust,options.DurationSeconds);
initialCondition = localInitialCondition(options.InitialCondition);
controlMask = localControlMask(options.ControlMask,options.BodyCase,reference);
speedVaries = numel(reference.speedMps)>1 && ...
    any(abs(reference.speedMps-reference.speedMps(1))>10*eps( ...
        max(abs(reference.speedMps))));

runtimeFamily = options.RuntimeFamily;
if runtimeFamily=="auto"
    if speedVaries
        runtimeFamily = "scheduled";
    else
        runtimeFamily = "fixed_source";
    end
end
assert(runtimeFamily~="fixed_source" || ~speedVaries, ...
    "AeroFlex:CustomCaseFixedSourceSpeed", ...
    "A varying speed reference requires the scheduled runtime. " + ...
    "A fixed-source runtime cannot represent a Case-B transition.");
assert(options.BodyCase~="wing_only" || runtimeFamily=="fixed_source", ...
    "AeroFlex:CustomCaseWingScheduling", ...
    "The retained wing-only workflow does not use free-flight scheduling.");
initialStatus = AeroFlex.benchmark.internal. ...
    customInitialConditionStatus(initialCondition);
executionImplemented = runtimeFamily=="scheduled" && ...
    options.BodyCase=="coupled_full" && ...
    isempty(reference.altitudeM) && ~controlMask.altitude && ...
    ~controlMask.roll && ~controlMask.yaw && ...
    initialStatus.supported;

definition = struct( ...
    "schemaVersion","pazy-custom-case-definition-v1", ...
    "caseId","CUSTOM_"+upper(options.Name), ...
    "name",options.Name, ...
    "modelRevision","locked_production", ...
    "bodyCase",options.BodyCase, ...
    "durationSeconds",options.DurationSeconds, ...
    "reference",reference, ...
    "terminalTarget",localTerminalTarget(reference), ...
    "gust",gust, ...
    "initialCondition",initialCondition, ...
    "initialConditionExecutionStatus",initialStatus, ...
    "controlMask",controlMask, ...
    "runtimeFamily",runtimeFamily, ...
    "continuousRuntime",true, ...
    "stateResetAllowed",false, ...
    "formalCasesModified",false, ...
    "qualificationStatus","CUSTOM_VALIDATION_PENDING", ...
    "executionImplemented",executionImplemented, ...
    "executionRequirement", ...
        "Execution is available for the supported scheduled coupled-full speed/pitch domain.");

% The manifest must remain portable and deterministic.
jsonencode(definition);
end

function reference = localReference(value,duration)
reference = localFill(value,struct( ...
    "timeSeconds",[0,duration], ...
    "speedMps",double.empty(1,0), ...
    "altitudeM",double.empty(1,0), ...
    "rollRad",double.empty(1,0), ...
    "pitchRad",double.empty(1,0), ...
    "yawRad",double.empty(1,0), ...
    "phaseLabel","maneuver"));
reference.timeSeconds = double(reference.timeSeconds(:).');
assert(numel(reference.timeSeconds)>=2 && ...
    all(isfinite(reference.timeSeconds)) && ...
    all(diff(reference.timeSeconds)>0) && ...
    reference.timeSeconds(1)==0 && ...
    reference.timeSeconds(end)==duration, ...
    "AeroFlex:CustomCaseReferenceTime", ...
    "Reference time must be strictly increasing from zero to the duration.");
names = ["speedMps","altitudeM","rollRad","pitchRad","yawRad"];
for name = names
    signal = double(reference.(name));
    assert(isempty(signal) || (isvector(signal) && all(isfinite(signal)) && ...
        any(numel(signal)==[1,numel(reference.timeSeconds)])), ...
        "AeroFlex:CustomCaseReferenceSignal", ...
        "Reference.%s must be empty, scalar, or match timeSeconds.",name);
    reference.(name) = signal(:).';
end
assert(isempty(reference.speedMps) || all(reference.speedMps>0), ...
    "AeroFlex:CustomCaseReferenceSpeed", ...
    "Airspeed references must be positive.");
reference.phaseLabel = string(reference.phaseLabel(:).');
assert(any(numel(reference.phaseLabel)==[1,numel(reference.timeSeconds)]), ...
    "AeroFlex:CustomCasePhaseLabel", ...
    "phaseLabel must be scalar or match timeSeconds.");
end

function gust = localGust(value,duration)
gust = localFill(value,struct("enabled",false,"type","none", ...
    "onsetSeconds",0,"durationSeconds",0,"peakVelocityMps",0, ...
    "directionBody",[0;0;1],"timeSeconds",double.empty(1,0), ...
    "velocityMps",double.empty(1,0)));
gust.enabled = logical(gust.enabled);
gust.type = string(gust.type);
assert(isscalar(gust.enabled) && isscalar(gust.type) && ...
    any(gust.type==["none","one_minus_cosine","time_history"]), ...
    "AeroFlex:CustomCaseGustType","Unsupported custom gust type.");
gust.onsetSeconds = double(gust.onsetSeconds);
gust.durationSeconds = double(gust.durationSeconds);
gust.peakVelocityMps = double(gust.peakVelocityMps);
gust.directionBody = double(gust.directionBody(:));
assert(numel(gust.directionBody)==3 && all(isfinite(gust.directionBody)) && ...
    norm(gust.directionBody)>0,"AeroFlex:CustomCaseGustDirection", ...
    "Gust directionBody must be a finite nonzero three-vector.");
gust.directionBody = gust.directionBody/norm(gust.directionBody);
if gust.enabled && gust.type=="one_minus_cosine"
    assert(isfinite(gust.onsetSeconds) && gust.onsetSeconds>=0 && ...
        isfinite(gust.durationSeconds) && gust.durationSeconds>0 && ...
        gust.onsetSeconds+gust.durationSeconds<=duration && ...
        isfinite(gust.peakVelocityMps) && gust.peakVelocityMps>=0, ...
        "AeroFlex:CustomCaseGustWindow", ...
        "The one-minus-cosine gust must lie inside the maneuver.");
elseif gust.enabled && gust.type=="time_history"
    gust.timeSeconds = double(gust.timeSeconds(:).');
    gust.velocityMps = double(gust.velocityMps(:).');
    assert(numel(gust.timeSeconds)>=2 && ...
        numel(gust.timeSeconds)==numel(gust.velocityMps) && ...
        all(isfinite(gust.timeSeconds)) && ...
        all(isfinite(gust.velocityMps)) && ...
        all(diff(gust.timeSeconds)>0) && ...
        gust.timeSeconds(1)>=0 && gust.timeSeconds(end)<=duration, ...
        "AeroFlex:CustomCaseGustHistory", ...
        "The gust time history must be finite, ordered, and in bounds.");
else
    gust.enabled = false;
    gust.type = "none";
    gust.peakVelocityMps = 0;
end
end

function initial = localInitialCondition(value)
initial = localFill(value,struct("policy","source_trim", ...
    "sourceId","","rigidPerturbation",zeros(9,1), ...
    "physicalWingPerturbation",struct(), ...
    "airspeedMps",double.empty(1,0), ...
    "angleOfAttackDeg",double.empty(1,0), ...
    "sideslipDeg",double.empty(1,0), ...
    "positionNedM",double.empty(1,0), ...
    "altitudeM",double.empty(1,0), ...
    "eulerRad",double.empty(1,0), ...
    "bodyVelocityMps",double.empty(1,0), ...
    "bodyRatesRadPerSec",double.empty(1,0), ...
    "actuatorPositionRad",double.empty(1,0), ...
    "actuatorRateRadPerSec",double.empty(1,0)));
initial.policy = string(initial.policy);
initial.sourceId = string(initial.sourceId);
initial.rigidPerturbation = double(initial.rigidPerturbation(:));
assert(any(initial.policy==["source_trim","scheduled_trim", ...
    "trim_perturbation"]) && ...
    numel(initial.rigidPerturbation)==9 && ...
    all(isfinite(initial.rigidPerturbation)) && ...
    isstruct(initial.physicalWingPerturbation) && ...
    isscalar(initial.physicalWingPerturbation), ...
    "AeroFlex:CustomCaseInitialCondition", ...
    "Initial conditions must use source trim plus physical perturbations.");

scalarNames = ["airspeedMps","angleOfAttackDeg","sideslipDeg", ...
    "altitudeM"];
for name = scalarNames
    initial.(name) = double(initial.(name));
    assert(isempty(initial.(name)) || ...
        (isscalar(initial.(name)) && isfinite(initial.(name))), ...
        "AeroFlex:CustomCaseInitialScalar", ...
        "InitialCondition.%s must be empty or a finite scalar.",name);
end
assert(isempty(initial.airspeedMps) || initial.airspeedMps>0, ...
    "AeroFlex:CustomCaseInitialAirspeed", ...
    "Initial airspeed must be positive.");
assert(isempty(initial.sideslipDeg) || abs(initial.sideslipDeg)<90, ...
    "AeroFlex:CustomCaseInitialSideslip", ...
    "Initial sideslip must lie strictly between -90 and 90 degrees.");
assert((isempty(initial.airspeedMps) && ...
    isempty(initial.angleOfAttackDeg)) || ...
    (~isempty(initial.airspeedMps) && ...
    ~isempty(initial.angleOfAttackDeg)), ...
    "AeroFlex:CustomCaseInitialOperatingPoint", ...
    "Initial airspeed and aerodynamic angle of attack must be supplied " + ...
    "together.");

vectorSizes = struct("positionNedM",3,"eulerRad",3, ...
    "bodyVelocityMps",3,"bodyRatesRadPerSec",3);
for name = string(fieldnames(vectorSizes)).'
    initial.(name) = double(initial.(name)(:));
    assert(isempty(initial.(name)) || ...
        (numel(initial.(name))==vectorSizes.(name) && ...
        all(isfinite(initial.(name)))), ...
        "AeroFlex:CustomCaseInitialVector", ...
        "InitialCondition.%s must be empty or a finite three-vector.",name);
end
initial.actuatorPositionRad = double(initial.actuatorPositionRad(:));
initial.actuatorRateRadPerSec = double(initial.actuatorRateRadPerSec(:));
assert(all(isfinite(initial.actuatorPositionRad)) && ...
    all(isfinite(initial.actuatorRateRadPerSec)), ...
    "AeroFlex:CustomCaseInitialActuator", ...
    "Initial actuator positions and rates must be finite.");
if ~isempty(initial.actuatorPositionRad) && ...
        ~isempty(initial.actuatorRateRadPerSec)
    assert(numel(initial.actuatorPositionRad)== ...
        numel(initial.actuatorRateRadPerSec), ...
        "AeroFlex:CustomCaseInitialActuator", ...
        "Initial actuator position and rate vectors must have equal length.");
end

localValidateInitialKinematics(initial);
end

function localValidateInitialKinematics(initial)
if ~isempty(initial.positionNedM) && ~isempty(initial.altitudeM)
    tolerance = 1e-9*max(1,abs(initial.altitudeM));
    assert(abs(initial.altitudeM+initial.positionNedM(3))<=tolerance, ...
        "AeroFlex:CustomCaseInitialAltitude", ...
        "Altitude must equal minus the NED down position.");
end
if isempty(initial.bodyVelocityMps) || isempty(initial.airspeedMps)
    return
end

velocity = initial.bodyVelocityMps;
speed = norm(velocity);
alphaDeg = rad2deg(atan2(velocity(3),velocity(1)));
betaDeg = rad2deg(asin(max(-1,min(1,velocity(2)/speed))));
tolerance = 1e-9*max(1,initial.airspeedMps);
assert(abs(speed-initial.airspeedMps)<=tolerance && ...
    abs(alphaDeg-initial.angleOfAttackDeg)<=1e-9 && ...
    (isempty(initial.sideslipDeg) || ...
    abs(betaDeg-initial.sideslipDeg)<=1e-9), ...
    "AeroFlex:CustomCaseInitialVelocity", ...
    "Body velocity is inconsistent with the supplied airspeed, angle of " + ...
    "attack, or sideslip.");
end

function target = localTerminalTarget(reference)
target = struct("timeSeconds",reference.timeSeconds(end));
names = ["speedMps","altitudeM","rollRad","pitchRad","yawRad"];
for name = names
    value = reference.(name);
    if isempty(value)
        target.(name) = double.empty(1,0);
    else
        target.(name) = value(end);
    end
end
end

function mask = localControlMask(value,bodyCase,reference)
defaults = struct("speed",~isempty(reference.speedMps), ...
    "altitude",~isempty(reference.altitudeM), ...
    "roll",~isempty(reference.rollRad), ...
    "pitch",~isempty(reference.pitchRad), ...
    "yaw",~isempty(reference.yawRad));
mask = localFill(value,defaults);
names = string(fieldnames(defaults));
for name = names.'
    assert(isscalar(mask.(name)),"AeroFlex:CustomCaseControlMask", ...
        "ControlMask.%s must be scalar.",name);
    mask.(name) = logical(mask.(name));
end
if bodyCase=="wing_only"
    assert(~any(cell2mat(struct2cell(mask))), ...
        "AeroFlex:CustomCaseWingRigidControl", ...
        "A wing-only case cannot request rigid-body guidance channels.");
end
end

function value = localFill(value,defaults)
for name = string(fieldnames(defaults)).'
    if ~isfield(value,name)
        value.(name) = defaults.(name);
    end
end
end
