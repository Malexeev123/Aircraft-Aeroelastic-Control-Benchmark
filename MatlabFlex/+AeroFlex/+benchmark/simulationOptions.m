function settings = simulationOptions(options)
%SIMULATIONOPTIONS Validate public execution, diagnostics, and output options.

arguments
    options.Execute (1,1) logical = true
    options.DurationSeconds (1,1) double = nan
    options.ControllerMode (1,1) string ...
        {mustBeMember(options.ControllerMode,["full","outer_only"])} = "full"
    options.DiagnosticsLevel (1,1) double ...
        {mustBeInteger,mustBeInRange(options.DiagnosticsLevel,0,3)} = 1
    options.FiguresVisible (1,1) logical = false
    options.SavePlots (1,1) logical = true
    options.PublicationMode (1,1) logical = false
    options.OutputRoot (1,1) string = ""
    options.RunId (1,1) string = "auto"
    options.NativeKernelPolicy (1,1) string ...
        {mustBeMember(options.NativeKernelPolicy,["auto","required","off"])} = ...
        "auto"
    options.AllowUnqualified (1,1) logical = false
end

assert(isnan(options.DurationSeconds) || ...
    (isfinite(options.DurationSeconds) && options.DurationSeconds>0), ...
    "AeroFlex:BenchmarkCaseDuration", ...
    "DurationSeconds must be NaN or a positive finite scalar.");
assert(options.RunId=="auto" || (strlength(options.RunId)>0 && ...
    isempty(regexp(options.RunId,"[^A-Za-z0-9_-]","once"))), ...
    "AeroFlex:BenchmarkRunId", ...
    "RunId must be 'auto' or contain only letters, numbers, '_' and '-'.");

settings = struct( ...
    "schemaVersion","pazy-benchmark-simulation-options-v1", ...
    "execute",options.Execute, ...
    "durationSeconds",options.DurationSeconds, ...
    "controllerMode",options.ControllerMode, ...
    "diagnosticsLevel",options.DiagnosticsLevel, ...
    "figuresVisible",options.FiguresVisible, ...
    "savePlots",options.SavePlots, ...
    "publicationMode",options.PublicationMode, ...
    "outputRoot",options.OutputRoot, ...
    "runId",options.RunId, ...
    "nativeKernelPolicy",options.NativeKernelPolicy, ...
    "allowUnqualified",options.AllowUnqualified);
end
