function arguments = runnerArguments(plan,runRoot)
%RUNNERARGUMENTS Bind a benchmark plan to its retained numerical owner.
%   Keeping this positional interface in one function makes the protected
%   runtime profile inspectable without starting a simulation.

arguments
    plan (1,1) struct
    runRoot (1,1) string
end

switch plan.runnerKind
    case "formal_case_a"
        arguments = { ...
            plan.durationSeconds,plan.subcase,runRoot, ...
            "fmincon","fmincon",0,true,plan.holdNmpcAtTrim, ...
            true,struct(),struct(),plan.runtimeAcceleration};

    case {"scheduled_case_b_v90","custom_scheduled_v17a"}
        owner = plan.protectedRuntime.caseB;
        tracePath = string(fullfile(runRoot,"logs","caseb_trace.jsonl"));
        customScenario = struct();
        if plan.runnerKind=="custom_scheduled_v17a"
            assert(isfield(plan,"customScenario") && ...
                isstruct(plan.customScenario) && ...
                isscalar(plan.customScenario), ...
                "AeroFlex:CustomCaseRunnerArguments", ...
                "The custom scheduled plan requires one scenario manifest.");
            customScenario = plan.customScenario;
        end
        arguments = { ...
            plan.durationSeconds,plan.diagnosticsEnabled,runRoot, ...
            owner.benchmarkProfileName, ...
            true,[nan;nan],owner.outerLqrEvery, ...
            owner.scheduleGateBacktrackingEnabled, ...
            owner.preserveNmpcControlTarget,[],[nan,nan], ...
            false,false,"profile",nan,false, ...
            owner.mheScheduledPackageHistoryEnabled, ...
            owner.futureScheduledPackageSequenceEnabled, ...
            owner.runtimeCaseViewOwnerEnabled,false, ...
            owner.scheduledReciprocalRuntimeEnabled, ...
            owner.scheduledReciprocalRuntimeAccelerationEnabled, ...
            owner.scheduledReciprocalFminconCorrectnessEnabled, ...
            struct(), ...
            owner.compiledEstimatorEnabled, ...
            owner.compiledControllerEnabled, ...
            owner.activeStencilSensitivityEnabled, ...
            owner.condensedRtiQpMode,false,owner.predictionIntervals, ...
            false,false,false,owner.scheduledEquilibriumGuidance, ...
            owner.outerOnlyEstimatorEnabled, ...
            owner.symmetricLongitudinalRuntimeEnabled, ...
            owner.deferredOutputEnabled,false,"",false, ...
            owner.symmetricSurfaceEnabled,tracePath,plan.gustEnabled,[], ...
            false,owner.nmheHealthGateEnabled,false,false, ...
            owner.providerPacketCacheEnabled, ...
            owner.nativeReducedHorizonEnabled,false,false, ...
            owner.p1PlantIntervalEnabled,false,false,false,false,false, ...
            owner.preparedHorizonReuseEnabled, ...
            owner.acceptedReplayReuseEnabled, ...
            owner.rigidWrenchRefinementEnabled, ...
            owner.solverRejectionSafeEndpointEnabled, ...
            owner.qGamBoundOwnerEnabled,customScenario};

    otherwise
        error("AeroFlex:BenchmarkCaseUnavailable", ...
            "No execution adapter is available for case %s.",plan.caseId);
end
end
