function status = customInitialConditionStatus(initial)
%CUSTOMINITIALCONDITIONSTATUS Check the current scheduled-runtime start.
%   The retained custom runner begins from its qualified 15 m/s, 10 deg
%   source trim. Equivalent physical fields may be stated explicitly, but
%   this check prevents unsupported position, actuator, or perturbation
%   values from being silently ignored.

arguments
    initial (1,1) struct
end

nominalSpeedMps = 15;
nominalAlphaDeg = 10;
nominalEulerRad = [0;deg2rad(10);0];
nominalVelocityMps = nominalSpeedMps*[cosd(nominalAlphaDeg);0; ...
    sind(nominalAlphaDeg)];
tolerance = 1e-10;

checks = struct( ...
    "policy",any(string(initial.policy)==["source_trim", ...
        "scheduled_trim"]), ...
    "source",strlength(string(initial.sourceId))==0, ...
    "rigidPerturbation",norm(double(initial.rigidPerturbation(:)),inf)==0, ...
    "wingPerturbation",isempty(fieldnames( ...
        initial.physicalWingPerturbation)), ...
    "airspeed",localEmptyOrNear(initial.airspeedMps, ...
        nominalSpeedMps,tolerance), ...
    "angleOfAttack",localEmptyOrNear(initial.angleOfAttackDeg, ...
        nominalAlphaDeg,tolerance), ...
    "sideslip",localEmptyOrNear(initial.sideslipDeg,0,tolerance), ...
    "position",isempty(initial.positionNedM), ...
    "altitude",isempty(initial.altitudeM), ...
    "attitude",localEmptyOrNear(initial.eulerRad, ...
        nominalEulerRad,tolerance), ...
    "velocity",localEmptyOrNear(initial.bodyVelocityMps, ...
        nominalVelocityMps,tolerance), ...
    "angularRate",localEmptyOrNear(initial.bodyRatesRadPerSec, ...
        zeros(3,1),tolerance), ...
    "actuatorPosition",isempty(initial.actuatorPositionRad), ...
    "actuatorRate",isempty(initial.actuatorRateRadPerSec));

names = string(fieldnames(checks));
failed = names(~cell2mat(struct2cell(checks)));
status = struct( ...
    "supported",isempty(failed), ...
    "failedChecks",failed(:).', ...
    "requiredOperatingPoint",struct( ...
        "airspeedMps",nominalSpeedMps, ...
        "angleOfAttackDeg",nominalAlphaDeg), ...
    "policy","qualified_source_trim_only");
end

function passed = localEmptyOrNear(value,expected,tolerance)
if isempty(value)
    passed = true;
    return
end
value = double(value(:));
expected = double(expected(:));
passed = numel(value)==numel(expected) && ...
    norm(value-expected,inf)<=tolerance;
end
