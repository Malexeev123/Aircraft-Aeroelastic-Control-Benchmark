function [request,samples] = customReferenceProvider( ...
        definition,controlTime,corridor,defaults)
%CUSTOMREFERENCEPROVIDER Build a continuous custom rigid-reference owner.
%   Attitude and aerodynamic scheduling coordinates remain independent:
%   Euler pitch is a guidance command, whereas scheduleAlphaDeg follows the
%   locked slow trim corridor as a function of the commanded airspeed.

arguments
    definition (1,1) struct
    controlTime (1,:) double
    corridor (1,1) struct
    defaults (1,1) struct
end

time = double(definition.reference.timeSeconds(:).');
controlTime = double(controlTime(:).');
assert(all(isfinite(controlTime)) && all(diff(controlTime)>=0) && ...
    controlTime(1)>=time(1) && controlTime(end)<=time(end), ...
    "AeroFlex:CustomReferenceControlTime", ...
    "Control sample times must lie inside the custom reference interval.");

requiredDefaults = ["speedMps","eulerRad"];
assert(all(isfield(defaults,requiredDefaults)) && ...
    isscalar(defaults.speedMps) && isfinite(defaults.speedMps) && ...
    defaults.speedMps>0 && numel(defaults.eulerRad)==3 && ...
    all(isfinite(defaults.eulerRad)), ...
    "AeroFlex:CustomReferenceDefaults", ...
    "Custom reference defaults must contain finite speed and Euler states.");

contract = struct( ...
    "timeSeconds",time, ...
    "speed",localCurve(time,definition.reference.speedMps, ...
        defaults.speedMps), ...
    "roll",localCurve(time,definition.reference.rollRad, ...
        defaults.eulerRad(1)), ...
    "pitch",localCurve(time,definition.reference.pitchRad, ...
        defaults.eulerRad(2)), ...
    "yaw",localCurve(time,definition.reference.yawRad, ...
        defaults.eulerRad(3)), ...
    "corridor",localCorridor(corridor));

samples = repmat(localEvaluate(contract,controlTime(1)),1, ...
    numel(controlTime));
for index = 1:numel(controlTime)
    samples(index) = localEvaluate(contract,controlTime(index));
end

request = struct( ...
    "enable",true, ...
    "schemaVersion","pazy-production-reference-provider-v1", ...
    "source","phase18c-v17a-custom-continuous-guidance-runtime-adapter-v1", ...
    "provider",@(t,rb)localProvider(contract,t,rb));
end

function curve = localCurve(time,value,defaultValue)
value = double(value(:).');
if isempty(value)
    value = double(defaultValue);
end
if isscalar(value)
    curve = struct("constant",true,"value",value,"pp",struct(), ...
        "derivative",struct());
    return
end
assert(numel(value)==numel(time) && all(isfinite(value)), ...
    "AeroFlex:CustomReferenceCurve", ...
    "A custom reference signal must be scalar or match timeSeconds.");
pp = pchip(time,value);
curve = struct("constant",false,"value",nan,"pp",pp, ...
    "derivative",localDerivative(pp));
end

function derivative = localDerivative(pp)
[breaks,coefficients,pieces,order,dimension] = unmkpp(pp);
if order==1
    derivativeCoefficients = zeros(pieces,1);
else
    powers = order-1:-1:1;
    derivativeCoefficients = coefficients(:,1:end-1).*powers;
end
derivative = mkpp(breaks,derivativeCoefficients,dimension);
end

function corridor = localCorridor(value)
required = ["speedMps","alphaDeg"];
assert(all(isfield(value,required)), ...
    "AeroFlex:CustomReferenceCorridor", ...
    "The scheduled trim corridor requires speedMps and alphaDeg.");
speed = double(value.speedMps(:));
alpha = double(value.alphaDeg(:));
assert(numel(speed)>=2 && numel(speed)==numel(alpha) && ...
    all(isfinite(speed)) && all(isfinite(alpha)), ...
    "AeroFlex:CustomReferenceCorridor", ...
    "The scheduled trim corridor is incomplete or nonfinite.");
[uniqueSpeed,~,group] = unique(speed,"sorted");
uniqueAlpha = accumarray(group,alpha,[],@mean);
assert(numel(uniqueSpeed)>=2 && all(diff(uniqueSpeed)>0), ...
    "AeroFlex:CustomReferenceCorridor", ...
    "The scheduled trim corridor must span at least two speeds.");
corridor = struct("speedMps",uniqueSpeed, ...
    "alphaDeg",uniqueAlpha,"minimumSpeedMps",uniqueSpeed(1), ...
    "maximumSpeedMps",uniqueSpeed(end));
end

function ref = localProvider(contract,t,rb)
assert(isstruct(rb) && isscalar(rb), ...
    "AeroFlex:CustomReferenceRigidState", ...
    "The custom reference provider requires a scalar rigid-state struct.");
ref = localEvaluate(contract,double(t));
end

function ref = localEvaluate(contract,t)
assert(isscalar(t) && isfinite(t) && t>=contract.timeSeconds(1) && ...
    t<=contract.timeSeconds(end)+100*eps(contract.timeSeconds(end)), ...
    "AeroFlex:CustomReferenceTime", ...
    "The requested custom reference time is outside the maneuver.");
t = min(max(t,contract.timeSeconds(1)),contract.timeSeconds(end));
[speed,speedRate] = localCurveValue(contract.speed,t);
[roll,rollRate] = localCurveValue(contract.roll,t);
[pitch,pitchRate] = localCurveValue(contract.pitch,t);
[yaw,yawRate] = localCurveValue(contract.yaw,t);
assert(speed>=contract.corridor.minimumSpeedMps-1e-12 && ...
    speed<=contract.corridor.maximumSpeedMps+1e-12, ...
    "AeroFlex:CustomReferenceSpeedDomain", ...
    "The custom speed reference leaves the locked scheduling corridor.");
alphaDeg = interp1(contract.corridor.speedMps, ...
    contract.corridor.alphaDeg,speed,"linear");
alpha = deg2rad(alphaDeg);
euler = [roll;pitch;yaw];
eulerRate = [rollRate;pitchRate;yawRate];
omega = localEulerRateToBodyRate(euler,eulerRate);
ref = struct( ...
    "v_B_ref",[speed*cos(alpha);0;speed*sin(alpha)], ...
    "euler_ref",euler, ...
    "omega_B_ref",omega, ...
    "speedReferenceRateMps2",speedRate, ...
    "scheduleUInfMps",speed, ...
    "scheduleAlphaDeg",alphaDeg);
end

function [value,rate] = localCurveValue(curve,t)
if curve.constant
    value = curve.value;
    rate = 0;
else
    value = ppval(curve.pp,t);
    rate = ppval(curve.derivative,t);
end
assert(isfinite(value) && isfinite(rate), ...
    "AeroFlex:CustomReferenceFinite", ...
    "The custom reference and its derivative must remain finite.");
end

function omega = localEulerRateToBodyRate(euler,eulerRate)
phi = euler(1);
theta = euler(2);
transform = [1,0,-sin(theta); ...
    0,cos(phi),sin(phi)*cos(theta); ...
    0,-sin(phi),cos(phi)*cos(theta)];
omega = transform*eulerRate;
end
