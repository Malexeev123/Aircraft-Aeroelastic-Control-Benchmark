function layout = outputLayout(plan,options)
%OUTPUTLAYOUT Resolve a versioned benchmark result layout.

arguments
    plan (1,1) struct
    options.Create (1,1) logical = false
end

runId = plan.runId;
if runId=="auto"
    if options.Create
        runId = lower(plan.caseId)+"_"+string(datetime("now", ...
            "TimeZone","UTC","Format","yyyyMMdd'T'HHmmss'Z'"));
    else
        runId = "<auto-utc-run-id>";
    end
end
runRoot = fullfile(plan.outputRoot,runId);
layout = struct( ...
    "schemaVersion","pazy-benchmark-output-layout-v1", ...
    "runId",runId,"runRoot",runRoot, ...
    "manifest",fullfile(runRoot,"manifest.json"), ...
    "configuration",fullfile(runRoot,"configuration"), ...
    "data",fullfile(runRoot,"data"), ...
    "metrics",fullfile(runRoot,"metrics"), ...
    "logs",fullfile(runRoot,"logs"), ...
    "checkpoints",fullfile(runRoot,"checkpoints"), ...
    "diagnosticPlots",fullfile(runRoot,"plots","diagnostic"), ...
    "publicationPlots",fullfile(runRoot,"plots","publication"), ...
    "captions",fullfile(runRoot,"captions"));
if options.Create
    names = ["configuration","data","metrics","logs","checkpoints", ...
        "diagnosticPlots","publicationPlots","captions"];
    for name = names
        folder = layout.(name);
        if ~isfolder(folder)
            mkdir(folder);
        end
    end
end
end
