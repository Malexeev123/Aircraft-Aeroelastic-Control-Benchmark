function relative = localRelativePath(path,root)
relative = string(path);
prefix = string(root) + filesep;
if startsWith(relative,prefix), relative = extractAfter(relative,strlength(prefix)); end
relative = replace(relative,"\","/");
end

function value = localFileHash(path)
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
fileId = fopen(path,"rb");
assert(fileId >= 0,"Phase18C:CaseBProfileHash","Unable to read %s.",path);
cleanup = onCleanup(@() fclose(fileId));
while ~feof(fileId)
    buffer = fread(fileId,1024*1024,"*uint8");
    if isempty(buffer), break, end
    engine.update(typecast(buffer(:),"int8"));
end
bytes = typecast(engine.digest(),"uint8");
value = lower(string(reshape(dec2hex(bytes,2).',1,[])));
clear cleanup
end

function value = localNumericHash(data)
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
engine.update(typecast(double(data(:)),"int8"));
bytes = typecast(engine.digest(),"uint8");
value = lower(string(reshape(dec2hex(bytes,2).',1,[])));
end
