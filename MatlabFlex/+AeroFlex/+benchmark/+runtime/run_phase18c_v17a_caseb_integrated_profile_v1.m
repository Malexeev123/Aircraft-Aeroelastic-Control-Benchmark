function gust = localCustomGust(contract,time)
gust = zeros(size(time));
if ~logical(contract.enabled)
    return
end
direction = double(contract.directionBody(:));
assert(norm(direction-[0;0;1],inf)<=1e-12, ...
    "Phase18C:CustomCaseGustDirection", ...
    "The retained scalar gust input supports the positive body-z direction.");
switch string(contract.type)
    case "one_minus_cosine"
        active = time>=contract.onsetSeconds & ...
            time<=contract.onsetSeconds+contract.durationSeconds;
        phase = (time(active)-contract.onsetSeconds)/ ...
            contract.durationSeconds;
        gust(active) = 0.5*double(contract.peakVelocityMps).* ...
            (1-cos(2*pi*phase));
    case "time_history"
        gust = interp1(double(contract.timeSeconds(:)), ...
            double(contract.velocityMps(:)),time,"linear",0);
    otherwise
        error("Phase18C:CustomCaseGustType", ...
            "Unsupported enabled custom gust type: %s",contract.type);
end
assert(all(isfinite(gust)),"Phase18C:CustomCaseGustFinite", ...
    "The custom gust realization must remain finite.");
end

function result = localSolverSummary(seconds,attempted,accepted)
sample = seconds(attempted);
if ~any(attempted)
    result = struct("attempted",0,"accepted",0,"successRate",1, ...
        "meanSeconds",NaN,"p95Seconds",NaN,"maximumSeconds",NaN);
else
    result = struct("attempted",sum(attempted),"accepted",sum(accepted), ...
        "successRate",sum(accepted)/sum(attempted), ...
        "meanSeconds",mean(sample,"omitnan"), ...
        "p95Seconds",prctile(sample,95), ...
        "maximumSeconds",max(sample,[],"omitnan"));
end
end

function [accepted,maximumCoordinateError,backtracked] = ...
        localAcceptedScheduleTransitionContract( ...
        changed,gates,activeMu,filteredMu,tolerance)
%LOCALACCEPTEDSCHEDULETRANSITIONCONTRACT Verify the installed package owner.
%
% A scheduler update may use the filtered candidate directly or the
% documented fail-closed backtracked coordinate.  Only changed samples need
% a new gate record; held samples retain the preceding accepted package.

changed = logical(changed(:).');
count = numel(changed);
assert(iscell(gates) && numel(gates) == count && ...
    isequal(size(activeMu),[2,count]) && isequal(size(filteredMu),[2,count]), ...
    "Phase18C:CaseBScheduleTransitionHistory", ...
    "The Case-B schedule transition histories are incomplete.");
accepted = true(1,count);
backtracked = false(1,count);
maximumCoordinateError = 0;
for index = find(changed)
    gate = gates{index};
    accepted(index) = isstruct(gate) && isfield(gate,"accept") && ...
        logical(gate.accept) && isfield(gate,"reason") && ...
        string(gate.reason) == "accepted";
    candidateMu = filteredMu(:,index);
    if isstruct(gate) && isfield(gate,"scheduleBacktracking") && ...
            isstruct(gate.scheduleBacktracking) && ...
            isfield(gate.scheduleBacktracking,"enabled") && ...
            logical(gate.scheduleBacktracking.enabled)
        backtracked(index) = true;
        accepted(index) = accepted(index) && ...
            isfield(gate.scheduleBacktracking,"acceptedCoordinate") && ...
            numel(gate.scheduleBacktracking.acceptedCoordinate) == 2;
        if accepted(index)
            candidateMu = double( ...
                gate.scheduleBacktracking.acceptedCoordinate(:));
        end
    end
    maximumCoordinateError = max(maximumCoordinateError, ...
        norm(activeMu(:,index)-candidateMu,inf));
end
accepted = all(accepted);
assert(isfinite(maximumCoordinateError) && ...
    maximumCoordinateError >= 0 && isfinite(tolerance) && tolerance >= 0, ...
    "Phase18C:CaseBScheduleTransitionContract", ...
    "The Case-B accepted schedule-transition contract is non-finite.");
end

