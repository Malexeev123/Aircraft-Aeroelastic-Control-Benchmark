function summary = run_phase18c_v17a_reciprocal_formal_casea_member_v1( ...
        durationSeconds,subcase,outputRoot,mheSolver,mpcSolver, ...
        estimatorActivationSeconds,innerLoopEnabled,holdNmpcAtTrim, ...
        symmetricSurfaceSubspace,runtimeSegmentAuditRequest, ...
        formalPackageOwnedOutputAuditRequest,runtimeAccelerationRequest)
%RUN_PHASE18C_V17A_RECIPROCAL_FORMAL_CASEA_MEMBER_V1
% Execute one bounded formal Case-A member with the qualified controllers.

arguments
    durationSeconds (1,1) double {mustBePositive,mustBeFinite} = 0.05
    subcase (1,1) string {mustBeMember(subcase,[ ...
        "command_no_gust","hold_gust","command_gust"])} = "hold_gust"
    outputRoot (1,1) string = ""
    mheSolver (1,1) string {mustBeMember(mheSolver, ...
        ["fmincon","custom_sqp"])} = "fmincon"
    mpcSolver (1,1) string {mustBeMember(mpcSolver, ...
        ["fmincon","custom_sqp"])} = "fmincon"
    estimatorActivationSeconds (1,1) double ...
        {mustBeNonnegative,mustBeFinite} = 0
    innerLoopEnabled (1,1) logical = true
    holdNmpcAtTrim (1,1) logical = false
    symmetricSurfaceSubspace (1,1) logical = false
    runtimeSegmentAuditRequest (1,1) struct = struct()
    formalPackageOwnedOutputAuditRequest (1,1) struct = struct()
    runtimeAccelerationRequest (1,1) struct = struct()
end

assert(~holdNmpcAtTrim || innerLoopEnabled, ...
    "Phase18C:ReciprocalFormalCaseABaselineContract", ...
    "The matched outer-loop baseline requires the reciprocal nMHE provider.");

repositoryRoot = string(fileparts(mfilename("fullpath")));
for level = 1:5
    repositoryRoot = string(fileparts(repositoryRoot));
end
setupProject;
if strlength(outputRoot)==0
    outputRoot = fullfile(repositoryRoot,"results","benchmark","case-a");
end
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end
phase18TracePath = fullfile(outputRoot, ...
    "PHASE18C_V17A_RECIPROCAL_FORMAL_CASEA_RUNTIME_TRACE_V1.jsonl");
segmentResume = ~isempty(fieldnames(runtimeSegmentAuditRequest)) && ...
    isfield(runtimeSegmentAuditRequest,"resume") && ...
    logical(runtimeSegmentAuditRequest.resume);
assert(segmentResume || ~isfile(phase18TracePath), ...
    "Phase18C:ReciprocalFormalCaseATraceExists", ...
    "Use a new output root rather than appending to an existing runtime trace.");

sourceArtifactPath = fullfile(repositoryRoot,"MatlabFlex","configs", ...
    "control", ...
    "phase18c_v17a_casea_source_coordinate_dynamic_output_feedback_v1.mat");
sourceOuterRequest = struct( ...
    "enable",true, ...
    "source", ...
        "phase18c-v17a-casea-source-coordinate-dynamic-output-feedback-production-integration-v1", ...
    "sourceId","CASEA_U040_ALPHA_P01", ...
    "artifactPath",sourceArtifactPath, ...
    "expectedArtifactSha256", ...
        "04e685ffbfad300581ecc57e9d7c031e343f1ed914c120403dac47f06a4cf369", ...
    "exactCaseAOnly",true);
emptyRequest = struct();
providerRequest = emptyRequest;
if innerLoopEnabled
    providerRequest = struct( ...
        "enabled",true,"auditOnly",true, ...
        "changeId", ...
            "phase18c-v17a-casea-reciprocal-controller-model-provider-audit-v1", ...
        "formulation","condensed_internal_memory", ...
        "estimatorActivationSeconds",estimatorActivationSeconds, ...
        "disturbanceWarmStart","bounded_secant", ...
        "unboundedAerodynamicLagStates",true, ...
        "futureRigidPolicy","held_measured", ...
        "mheSolver",mheSolver,"mpcSolver",mpcSolver);
    if ~isempty(fieldnames(runtimeAccelerationRequest))
        providerRequest.runtimeAcceleration = runtimeAccelerationRequest;
    end
end
surfaceRequest = emptyRequest;
if symmetricSurfaceSubspace
    surfaceRequest = struct( ...
        "enabled",true,"auditOnly",true, ...
        "changeId", ...
            "phase18c-v17a-casea-nmpc-symmetric-surface-subspace-audit-v1", ...
        "caseId","formal_case_a", ...
        "surfaceMode","symmetric_longitudinal", ...
        "sourceMap",[1;1]);
end

summary = AeroFlex.benchmark.runtime. ...
    run_phase18c_v17a_formal_casea_freeflight_attitude_hold_v1( ...
    durationSeconds,innerLoopEnabled,outputRoot,subcase,1.765,false,"", ...
    emptyRequest,emptyRequest,emptyRequest,emptyRequest,emptyRequest, ...
    emptyRequest,emptyRequest,emptyRequest,emptyRequest,phase18TracePath, ...
    emptyRequest,emptyRequest,emptyRequest,emptyRequest,emptyRequest, ...
    emptyRequest,emptyRequest,sourceOuterRequest,providerRequest,holdNmpcAtTrim, ...
    surfaceRequest,runtimeSegmentAuditRequest, ...
    formalPackageOwnedOutputAuditRequest);
end
