    size(history.x,2)>=controlCount && ...
    size(log.xhat,1)>=nativeCount && size(log.xhat,2)>=controlCount, ...
    "Phase18C:FormalCaseAWingtipState", ...
    "The state history cannot recover the signed physical wingtip.");
