function gust = localGust(durationSeconds,dt,nw,peakMetersPerSecond)
time = (0:round(durationSeconds/dt)).'*dt;
value = zeros(size(time));
phase = (time-1)/(10/40);
active = phase>=0 & phase<=1;
value(active) = peakMetersPerSecond*.5*(1-cos(2*pi*phase(active)));
gust = repmat(value,1,nw);
end

