end

function digest = localNumericHash(value)
path = char(string(tempname(tempdir))+".bin"); fileId = fopen(path,"w");
cleanup = onCleanup(@() delete(path)); fwrite(fileId,value,"double"); fclose(fileId); clear fileId
digest = localFileHash(path); clear cleanup
end

function digest = localFileHash(path)
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
fileId = fopen(path,"rb"); assert(fileId>=0,"Phase18C:FormalCaseAHash","Cannot read %s.",path);
cleanup = onCleanup(@() fclose(fileId));
while ~feof(fileId), bytes = fread(fileId,1024*1024,"*uint8"); if isempty(bytes), break, end; engine.update(typecast(bytes(:),"int8")); end
digest = lower(string(reshape(dec2hex(typecast(engine.digest(),"uint8"),2).',1,[]))); clear cleanup
end
