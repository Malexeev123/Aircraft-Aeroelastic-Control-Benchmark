function status = localStatus(success,history,innerLoopEnabled, ...
        sharedWingDaisyChainEnabled,valid,correctedAttributionMember, ...
        sourceCoordinateOuterEnabled)
profile = history.log.benchmarkControlProfile;
finite = all(isfinite(history.x),"all") && all(isfinite(history.log.U(:,valid)),"all");
% An outer-only shared-wing LQR baseline intentionally applies its certified
% nominal wing request while the inner correction remains held at trim.
baselineHeld = innerLoopEnabled || sharedWingDaisyChainEnabled || ...
    correctedAttributionMember || sourceCoordinateOuterEnabled || ...
    max(abs(history.log.U(:,valid)),[],"all")<=1e-12;
solverGate = true;
if innerLoopEnabled || sourceCoordinateOuterEnabled
    diagnostics = history.log.controlDiagnostics;
    mheAttempted = logical(diagnostics.mheAttempted(valid));
    mheAccepted = logical(diagnostics.mheAccepted(valid));
    % The formal profile retains the approved 97.5 percent solve-success
    % requirement whenever the active controller consumes nMHE output.
    % Warmup samples are excluded because no estimate is attempted there.
    solverGate = (~any(mheAttempted) || ...
        sum(mheAccepted(mheAttempted))/sum(mheAttempted) >= 0.975);
    if innerLoopEnabled
        mpcAttempted = logical(diagnostics.mpcAttempted(valid));
        mpcAccepted = logical(diagnostics.mpcAccepted(valid));
        solverGate = solverGate && (~any(mpcAttempted) || ...
            sum(mpcAccepted(mpcAttempted))/sum(mpcAttempted) >= 0.975);
    end
end
if success && profile.enabled && profile.formalBenchmarkCase=="A" && ...
        finite && baselineHeld && solverGate
    if innerLoopEnabled, status = "PASS_CONTROLLED_INTEGRITY"; else, status = "PASS_BASELINE_INTEGRITY"; end
else
    if ~solverGate
        status = "FAIL_SOLVER_GATE";
    else
        status = "FAIL_INTEGRITY";
    end
end
end

function metrics = localAttitudeMetrics(history,scenario,trimAlphaDeg)
%LOCALATTITUDEMETRICS Report Case-A pitch response without adding a constraint.
    time = double(history.t(:).');
    theta = double(history.log.rb.euler(2,:));
    reference = deg2rad(trimAlphaDeg + scenario.commandDegrees*(time >= ...
        scenario.commandOnsetSeconds));
    error = theta-reference;
    finite = isfinite(time) & isfinite(theta) & isfinite(reference);
    post = time >= scenario.commandOnsetSeconds & finite;
    if ~any(post)
        post = finite;
    end
    assert(any(post),"Phase18C:FormalCaseAAttitudeMetrics", ...
        "The formal Case-A trace contains no finite attitude sample.");
    last = find(finite,1,"last");
    metrics = struct( ...
        "referenceRadians",reference, ...
        "errorRadians",error, ...
        "rmsErrorRadians",sqrt(mean(error(post).^2)), ...
        "peakAbsoluteErrorRadians",max(abs(error(post))), ...
        "finalErrorRadians",error(last), ...
        "peakPitchRadians",max(theta(post)), ...
        "finalPitchRadians",theta(last), ...
        "commandedPitchIncrementRadians",deg2rad(scenario.commandDegrees), ...
        "commandOnsetSeconds",scenario.commandOnsetSeconds);
end

function metrics = localOuterRigidCommandMetrics(history,valid)
%LOCALOUTERRIGIDCOMMANDMETRICS Keep elevator and thrust visible beside wing data.
    increment = double(history.log.uOuterRigidIncrement(:,valid));
    total = double(history.log.uOuterRigidTotal(:,valid));
    metrics = struct( ...
        "maximumElevatorIncrementRadians",max(abs(increment(1,:))), ...
        "maximumThrustIncrementNewtons",max(abs(increment(4,:))), ...
        "minimumTotalThrustNewtons",min(total(4,:)), ...
        "maximumTotalThrustNewtons",max(total(4,:)));
end

function summary = localSolver(time,attempted,accepted)
attempted = logical(attempted); accepted = logical(accepted);
if ~any(attempted)
    summary = struct("attempted",0,"accepted",0,"successRate",1, ...
        "meanSeconds",0,"p95Seconds",0,"maximumSeconds",0);
    return
end
value = time(attempted);
summary = struct("attempted",sum(attempted),"accepted",sum(accepted), ...
    "successRate",sum(accepted)/sum(attempted),"meanSeconds",mean(value), ...
    "p95Seconds",prctile(value,95),"maximumSeconds",max(value));
end

function metrics = localRuntimeAccelerationMetrics(diag,valid)
%LOCALRUNTIMEACCELERATIONMETRICS Record compiled-provider ownership.
metrics = struct("recorded",false,"mheCompiledCalls",0, ...
    "mheFallbacks",0,"mpcCompiledCalls",0,"mpcFallbacks",0, ...
    "mheLastFallback","","mpcLastFallback","", ...
    "zeroFallback",false);
required = ["mheCompiledProviderCalls", ...
    "mheCompiledProviderFallbacks","mpcCompiledProviderCalls", ...
    "mpcCompiledProviderFallbacks"];
if ~all(isfield(diag,required))
    return
end
mheCalls = double(diag.mheCompiledProviderCalls(valid));
mheFallbacks = double(diag.mheCompiledProviderFallbacks(valid));
mpcCalls = double(diag.mpcCompiledProviderCalls(valid));
mpcFallbacks = double(diag.mpcCompiledProviderFallbacks(valid));
finite = isfinite(mheCalls) & isfinite(mheFallbacks) & ...
    isfinite(mpcCalls) & isfinite(mpcFallbacks);
if ~any(finite)
    return
end
metrics.recorded = true;
metrics.mheCompiledCalls = max(mheCalls(finite));
metrics.mheFallbacks = max(mheFallbacks(finite));
metrics.mpcCompiledCalls = max(mpcCalls(finite));
metrics.mpcFallbacks = max(mpcFallbacks(finite));
if isfield(diag,"mheCompiledProviderLastFallback")
    metrics.mheLastFallback = localLastNonemptyText( ...
        diag.mheCompiledProviderLastFallback(valid));
end
if isfield(diag,"mpcCompiledProviderLastFallback")
    metrics.mpcLastFallback = localLastNonemptyText( ...
        diag.mpcCompiledProviderLastFallback(valid));
end
metrics.zeroFallback = metrics.mheCompiledCalls>0 && ...
    metrics.mpcCompiledCalls>0 && metrics.mheFallbacks==0 && ...
    metrics.mpcFallbacks==0;
end

function value = localLastNonemptyText(values)
%LOCALLASTNONEMPTYTEXT Return the final recorded diagnostic string.
value = "";
values = string(values);
index = find(strlength(values)>0,1,"last");
if ~isempty(index)
    value = values(index);
end
end

function metrics = localCoupledRtiMetrics(diag,valid)
%LOCALCOUPLEDRTIMETRICS Report the audit owner without recasting it as nMPC.
active = false(size(valid));
if isfield(diag,"coupledRtiActive")
    active = logical(diag.coupledRtiActive(valid));
end
realized = struct("valid",false);
if any(active) && isfield(diag,"coupledRtiRealized")
    entries = diag.coupledRtiRealized(valid);
    first = find(active,1,"first");
    if ~isempty(first) && ~isempty(entries{first})
        realized = entries{first};
    end
end
metrics = struct("activeSamples",sum(active), ...
    "requested",isfield(diag,"coupledRtiActive"), ...
    "firstIntervalReplay",realized);
end

function metrics = localFullChannelAllocatorMetrics(diag,valid)
%LOCALFULLCHANNELALLOCATORMETRICS Keep full-channel ownership distinct from RTI.
metrics = struct("requested",false,"jointSafetyCoordination",false, ...
    "activeSamples",0,"attempted",0,"accepted",0,"successRate",1, ...
    "fallbackCount",0,"maximumResponseJacobianColumnInfinity",nan, ...
    "maximumRigidJacobianColumnInfinity",nan);
if ~isfield(diag,"fullChannelLexicographicAllocation")
    return
end
metrics.requested = true;
entries = diag.fullChannelLexicographicAllocation(valid);
entries = entries(~cellfun(@isempty,entries));
if isempty(entries)
    return
end
attempted = false(numel(entries),1);
accepted = false(numel(entries),1);
joint = false(numel(entries),1);
responseColumnInfinity = zeros(0,1);
rigidColumnInfinity = zeros(0,1);
for index = 1:numel(entries)
    entry = entries{index};
    attempted(index) = logical(localField(entry,"solveAttempted",false));
    accepted(index) = logical(localField(entry,"accepted",false));
    capture = localField(localField(entry,"output",struct()),"auditCapture",struct());
    joint(index) = logical(localField(capture, ...
        "jointSharedSurfaceSafetyCoordination",false));
    if isfield(capture,"responseJacobianColumnInfinity")
        responseColumnInfinity = [responseColumnInfinity; ... %#ok<AGROW>
            capture.responseJacobianColumnInfinity(:)];
    end
    if isfield(capture,"rigidJacobianColumnInfinity")
        rigidColumnInfinity = [rigidColumnInfinity; ... %#ok<AGROW>
            capture.rigidJacobianColumnInfinity(:)];
    end
end
metrics.jointSafetyCoordination = any(joint);
metrics.activeSamples = sum(attempted);
metrics.attempted = metrics.activeSamples;
metrics.accepted = sum(accepted & attempted);
if metrics.attempted > 0
    metrics.successRate = metrics.accepted/metrics.attempted;
end
metrics.fallbackCount = sum(attempted & ~accepted);
if ~isempty(responseColumnInfinity)
    metrics.maximumResponseJacobianColumnInfinity = ...
        max(responseColumnInfinity);
end
if ~isempty(rigidColumnInfinity)
    metrics.maximumRigidJacobianColumnInfinity = max(rigidColumnInfinity);
end
end

function metrics = localLexicographicSharedWingMetrics(diag,valid)
%LOCALLEXICOGRAPHICSHAREDWINGMETRICS Preserve allocator acceptance evidence.
metrics = struct("requested",false,"attempted",0,"accepted",0, ...
    "successRate",1,"wingOnlyFallbackCount",0, ...
    "meanSeconds",0,"p95Seconds",0,"maximumSeconds",0, ...
    "maximumPrimaryConstraintValue",nan,"maximumPrimaryTolerance",nan);
if ~isfield(diag,"lexicographicSharedWingAllocation")
    return
end
entries = diag.lexicographicSharedWingAllocation(valid);
entries = entries(~cellfun(@isempty,entries));
if isempty(entries)
    return
end
metrics.requested = true;
attempted = false(1,numel(entries)); accepted = false(1,numel(entries));
fallback = false(1,numel(entries)); seconds = nan(1,numel(entries));
primaryValue = nan(1,numel(entries)); primaryTolerance = nan(1,numel(entries));
for index = 1:numel(entries)
    entry = entries{index};
    attempted(index) = logical(localField(entry,"solveAttempted",false));
    accepted(index) = logical(localField(entry,"accepted",false));
    capture = localField(localField(entry,"output",struct()), ...
        "auditCapture",struct());
    fallback(index) = logical(localField(capture,"fallbackWingOnly",false));
    seconds(index) = double(localField(entry,"solverSeconds",nan));
    primaryValue(index) = double(localField(capture, ...
        "primaryConstraintValue",nan));
    primaryTolerance(index) = double(localField(capture, ...
        "primaryTolerance",nan));
end
metrics.attempted = sum(attempted);
metrics.accepted = sum(accepted);
metrics.successRate = sum(accepted)/max(1,sum(attempted));
metrics.wingOnlyFallbackCount = sum(fallback);
if any(attempted)
    values = seconds(attempted & isfinite(seconds));
    if ~isempty(values)
        metrics.meanSeconds = mean(values);
        metrics.p95Seconds = prctile(values,95);
        metrics.maximumSeconds = max(values);
    end
end
if any(isfinite(primaryValue))
    metrics.maximumPrimaryConstraintValue = max(primaryValue,[],"omitnan");
end
if any(isfinite(primaryTolerance))
    metrics.maximumPrimaryTolerance = max(primaryTolerance,[],"omitnan");
end
end

function value = localField(value,name,default)
if ~isstruct(value) || ~isfield(value,name)
    value = default;
else
    value = value.(name);
end
end

function value = localMaximum(value)
if isempty(value), value = 0; else, value = max(value); end
end

