    truthTip = double(log.physicalWingtip. ...
        symmetricMeanAbsoluteMeters(1:controlCount));
    estimatedTip = double(log.physicalWingtip. ...
        estimatedSymmetricMeanAbsoluteMeters(1:controlCount));
    owner = "packed package-owned signed symmetric-mean physical tip";
    return
