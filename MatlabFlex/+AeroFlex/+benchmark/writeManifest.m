function manifest = writeManifest(plan,layout,summary,projectInfo)
%WRITEMANIFEST Write one reproducibility manifest after execution.

arguments
    plan (1,1) struct
    layout (1,1) struct
    summary (1,1) struct
    projectInfo (1,1) struct
end

repositoryRoot = string(projectInfo.repositoryRoot);
registryPath = fullfile(repositoryRoot,"context","audits", ...
    "phase18b-kkt-path-closure","static-feedback-source-placement-v1", ...
    "V17_PRODUCTION_SOURCE_REGISTRY_V1.json");
manifest = struct( ...
    "schemaVersion","pazy-benchmark-run-manifest-v1", ...
    "generatedUtc",string(datetime("now","TimeZone","UTC", ...
        "Format","yyyy-MM-dd'T'HH:mm:ss.SSS'Z'")), ...
    "caseId",plan.caseId, ...
    "qualificationStatus",plan.qualificationStatus, ...
    "qualified",plan.qualified, ...
    "allowUnqualified",plan.allowUnqualified, ...
    "modelRevision",plan.modelRevision, ...
    "durationSeconds",plan.durationSeconds, ...
    "resolvedPlanSha256",localTextHash(jsonencode(plan)), ...
    "repository",struct("revision",string(projectInfo.gitRevision), ...
        "branch",localOptionalText(projectInfo,"gitBranch","unknown"), ...
        "dirty",localOptionalLogical(projectInfo,"gitDirty",true)), ...
    "matlab",struct("release",string(projectInfo.matlabRelease), ...
        "version",string(projectInfo.matlabVersion), ...
        "computer",string(projectInfo.computer)), ...
    "source",struct("registryPath",localRelative( ...
        registryPath,repositoryRoot),"registrySha256", ...
        localFileHash(registryPath),"sharpyXbeamPolicy","immutable"), ...
    "nativeKernels",struct("policy",plan.nativeKernelPolicy, ...
        "fixedActive",logical(projectInfo.compiledControl.active), ...
        "scheduledActive",logical( ...
            projectInfo.scheduledCompiledControl.active)), ...
    "execution",localExecutionSummary(summary), ...
    "output",struct("runId",layout.runId,"runRoot",layout.runRoot));
file = fopen(layout.manifest,"w");
assert(file>=0,"AeroFlex:BenchmarkManifestWrite", ...
    "Cannot write manifest: %s",layout.manifest);
cleanup = onCleanup(@()fclose(file));
fprintf(file,"%s\n",jsonencode(manifest,"PrettyPrint",true));
clear cleanup
end

function value = localOptionalText(source,name,defaultValue)
if isfield(source,name)
    value = string(source.(name));
else
    value = string(defaultValue);
end
end

function value = localOptionalLogical(source,name,defaultValue)
if isfield(source,name)
    value = logical(source.(name));
else
    value = logical(defaultValue);
end
end

function execution = localExecutionSummary(summary)
execution = struct("status","completed");
names = ["status","passed","caseBClosed","preparationSeconds", ...
    "wallSeconds","totalEntryWallSeconds", ...
    "completedTimeSeconds"];
for name = names
    if isfield(summary,name)
        execution.(name) = summary.(name);
    end
end
end

function relative = localRelative(path,root)
relative = replace(string(path),string(root)+filesep,"");
relative = replace(relative,filesep,"/");
end

function value = localTextHash(text)
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
engine.update(uint8(char(text)));
value = lower(string(reshape(dec2hex( ...
    typecast(engine.digest(),"uint8"),2).',1,[])));
end

function value = localFileHash(path)
file = fopen(path,"rb");
assert(file>=0,"AeroFlex:BenchmarkHashRead","Cannot read %s.",path);
cleanup = onCleanup(@()fclose(file));
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
while ~feof(file)
    bytes = fread(file,1024*1024,"*uint8");
    if isempty(bytes), break, end
    engine.update(typecast(bytes(:),"int8"));
end
value = lower(string(reshape(dec2hex( ...
    typecast(engine.digest(),"uint8"),2).',1,[])));
clear cleanup
end
