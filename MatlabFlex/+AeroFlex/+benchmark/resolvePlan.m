function plan = resolvePlan(definition,settings,repositoryRoot)
%RESOLVEPLAN Compose the public request and protected runtime ownership.

arguments
    definition (1,1) struct
    settings (1,1) struct
    repositoryRoot (1,1) string
end

duration = settings.durationSeconds;
if isnan(duration)
    duration = definition.defaultDurationSeconds;
end
profile = AeroFlex.benchmark.internal.runtimeProfile(definition.caseId);
outputRoot = settings.outputRoot;
if strlength(outputRoot)==0
    outputRoot = fullfile(repositoryRoot,"results",lower(definition.caseId));
end
executionAllowed = definition.qualified || ...
    (definition.allowResearchOverride && settings.allowUnqualified);
if ~definition.executionImplemented
    executionAllowed = false;
end

plan = struct( ...
    "schemaVersion","pazy-benchmark-execution-plan-v1", ...
    "requestedCaseId",definition.requestedCaseId, ...
    "caseId",definition.caseId, ...
    "modelRevision",definition.modelRevision, ...
    "bodyCase",definition.bodyCase, ...
    "subcase",definition.subcase, ...
    "referenceType",definition.referenceType, ...
    "durationSeconds",duration, ...
    "commandEnabled",definition.commandEnabled, ...
    "gustEnabled",definition.gustEnabled, ...
    "controllerMode",settings.controllerMode, ...
    "diagnosticsLevel",settings.diagnosticsLevel, ...
    "diagnosticsEnabled",settings.diagnosticsLevel>0, ...
    "figuresVisible",settings.figuresVisible, ...
    "savePlots",settings.savePlots, ...
    "publicationMode",settings.publicationMode, ...
    "outputRoot",outputRoot, ...
    "runId",settings.runId, ...
    "nativeKernelPolicy",settings.nativeKernelPolicy, ...
    "qualificationStatus",definition.qualificationStatus, ...
    "qualified",definition.qualified, ...
    "allowUnqualified",settings.allowUnqualified, ...
    "executionAllowed",executionAllowed, ...
    "available",executionAllowed, ...
    "unavailableReason",definition.limitation, ...
    "evidence",definition.evidence, ...
    "runner",profile.runner, ...
    "runnerKind",profile.runnerKind, ...
    "runtimeAcceleration",profile.runtimeAcceleration, ...
    "protectedRuntime",profile, ...
    "innerLoopEnabled",settings.controllerMode=="full", ...
    "holdNmpcAtTrim",settings.controllerMode=="outer_only", ...
    "executed",false);
if ismember(plan.caseId,["A1","A2","A3"])
    plan.innerLoopEnabled = true;
end
end
