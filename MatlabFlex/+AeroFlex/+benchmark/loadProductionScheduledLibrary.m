function [library,source] = loadProductionScheduledLibrary( ...
        repositoryRoot,operatingPoint)
%LOADPRODUCTIONSCHEDULEDLIBRARY Load the locked coordinate-aligned library.
%   The supplied operating point must be an accepted source node when it is
%   used as an initial condition. Interpolation remains available after the
%   source-consistent trim and causal runtime memories have been established.

arguments
    repositoryRoot (1,1) string
    operatingPoint (1,2) double {mustBeFinite}
end
assert(operatingPoint(1)>0,"AeroFlex:ProductionLibrarySpeed", ...
    "Airspeed must be positive.");

registryPath = fullfile(repositoryRoot,"context","audits", ...
    "phase18c-control-validation","plant", ...
    "V17A_DIMENSIONAL_STEADY_FORCE_PRODUCTION_SOURCE_REGISTRY_V1.json");
expectedRegistryHash = ...
    "c3dcb391b61caf163bcc6781e239be94992e9ef651a56040c17a2aec86c62c2c";
assert(localFileHash(registryPath)==expectedRegistryHash, ...
    "AeroFlex:ProductionLibraryRegistry", ...
    "The production source registry is missing or changed.");
registry = jsondecode(fileread(registryPath));

entries = registry.sources;
points = cell(numel(entries),1);
paths = strings(numel(entries),1);
coordinates = zeros(numel(entries),2);
for index = 1:numel(entries)
    packagePath = fullfile(repositoryRoot, ...
        string(entries(index).acceptedMatlabPackage.path));
    assert(localFileHash(packagePath)== ...
        string(entries(index).acceptedMatlabPackage.sha256), ...
        "AeroFlex:ProductionLibraryPackage", ...
        "Source package is missing or changed: %s.", ...
        entries(index).sourceId);
    loaded = load(packagePath,"p5");
    point = loaded.p5;
    point = localBindSelectedContract( ...
        point,entries(index),repositoryRoot);
    point.name = char(string(entries(index).sourceId));
    point.mu = double(entries(index).coordinates(:).');
    point.sourceContractId = point.name;
    point.dims = struct("Nm",numel(point.idx.q1), ...
        "Na",numel(point.idx.qGam),"Nx",size(point.L,1), ...
        "nu",numel(point.u_eq),"nw",size(point.parConst.Bw,2));
    points{index} = point;
    paths(index) = packagePath;
    coordinates(index,:) = point.mu;
end
points = localHarmonizeFields(points);
library = struct( ...
    "name","pazy-production-scheduled-library", ...
    "method","locked-coordinate-aligned-source-library", ...
    "muNames",{{"U_inf","alpha_deg"}}, ...
    "points",vertcat(points{:}), ...
    "mu",coordinates, ...
    "sourcePaths",paths, ...
    "compatibleCoordinates",true, ...
    "registryPath",string(registryPath), ...
    "registrySha256",expectedRegistryHash);

distance = max(abs(coordinates-operatingPoint),[],2);
sourceIndex = find(distance<=1e-10);
assert(isscalar(sourceIndex), ...
    "AeroFlex:ProductionLibraryInitialSource", ...
    "No unique accepted source trim exists at U_inf=%.12g m/s and " + ...
    "alpha=%.12g deg. A scheduled runtime may interpolate after start, " + ...
    "but its initial condition must use a certified source trim.", ...
    operatingPoint(1),operatingPoint(2));

loaded = load(paths(sourceIndex),"cfg","beam","aero","base","trim","p5");
candidate = localFullCoordinateCandidate(repositoryRoot,registryPath);
usesFullCoordinateRuntime = localCaseBCenterline(operatingPoint);
if usesFullCoordinateRuntime
    initialPackage = AeroFlex.sched.evalLibrary( ...
        library,operatingPoint,struct( ...
        "requireCompatible",true,"noExtrapolate",true, ...
        "interpTol",1e-10, ...
        "fullCoordinateRuntimeCandidate",candidate));
    assert(isscalar(initialPackage.pointIds) && ...
        initialPackage.pointIds==sourceIndex, ...
        "AeroFlex:ProductionLibraryInitialIdentity", ...
        "The initial runtime realization must retain one exact source owner.");
else
    % Exact sources outside the certified Case-B selector retain their
    % registry-owned coordinates. In particular, this leaves the protected
    % Case-A and wing-only exact-node paths unchanged.
    initialPackage = library.points(sourceIndex);
end

source = loaded;
source.p5 = initialPackage;
source.trim.states = initialPackage.x_eq(:);
source.trim.u_ctrl = initialPackage.u_eq(:);
source.trim.Uinpt = initialPackage.u_eq(:);
numberPositions = numel(initialPackage.u_eq)/2;
assert(numberPositions==round(numberPositions), ...
    "AeroFlex:ProductionLibraryInputOrdering", ...
    "The source input must retain [position; rate] ordering.");
source.trim.deltaWing = initialPackage.u_eq(1:numberPositions);
source.trim.deltaWingDeg = rad2deg(source.trim.deltaWing);
source.trim.deltaDeg = source.trim.deltaWingDeg;
source.trim.uWingTrim = initialPackage.u_eq(:);
source.trim.sourceId = string(entries(sourceIndex).sourceId);
source.packagePath = paths(sourceIndex);
source.packageSha256 = string( ...
    entries(sourceIndex).acceptedMatlabPackage.sha256);
source.operatingPoint = operatingPoint;
source.fullCoordinateRuntimeCandidate = candidate;
source.dynamicSchedulingSupported = usesFullCoordinateRuntime;
end

function point = localBindSelectedContract(point,entry,repositoryRoot)
%LOCALBINDSELECTEDCONTRACT Replace machine-local source paths after hashing.

assert(isfield(entry,"selectedContract") && ...
    all(isfield(entry.selectedContract,["path","sha256"])), ...
    "AeroFlex:ProductionLibrarySelectedContract", ...
    "Source %s has no selected physical-coordinate contract.", ...
    string(entry.sourceId));
contractPath = fullfile(repositoryRoot, ...
    string(entry.selectedContract.path));
expectedHash = lower(string(entry.selectedContract.sha256));
assert(localFileHash(contractPath)==expectedHash, ...
    "AeroFlex:ProductionLibrarySelectedContract", ...
    "The selected contract is missing or changed for source %s.", ...
    string(entry.sourceId));

assert(isfield(point,"p5") && isstruct(point.p5) && ...
    isfield(point.p5,"artifactPath"), ...
    "AeroFlex:ProductionLibrarySelectedContract", ...
    "Source %s does not expose its selected-contract path.", ...
    string(entry.sourceId));
embeddedPath = string(point.p5.artifactPath);
if isfile(embeddedPath)
    assert(localFileHash(embeddedPath)==expectedHash, ...
        "AeroFlex:ProductionLibraryEmbeddedContract", ...
        ["Source %s embeds a contract path whose bytes disagree with ", ...
         "the production registry."],string(entry.sourceId));
end

% Accepted packages preserve their original immutable bytes. Only the
% in-memory path is rebound so a clean clone resolves the identical contract
% inside its own repository instead of the generating workstation.
point.p5.artifactPath = char(contractPath);
end

function points = localHarmonizeFields(points)
fieldLists = cellfun(@fieldnames,points,"UniformOutput",false);
fields = unique(vertcat(fieldLists{:}));
for index = 1:numel(points)
    missing = setdiff(fields,fieldnames(points{index}));
    for fieldIndex = 1:numel(missing)
        points{index}.(missing{fieldIndex}) = [];
    end
    points{index} = orderfields(points{index},fields);
end
end

