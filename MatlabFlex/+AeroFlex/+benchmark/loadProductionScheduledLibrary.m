function supported = localCaseBCenterline(operatingPoint)
supported = operatingPoint(1)>=15-1e-12 && ...
    operatingPoint(1)<=20+1e-12 && ...
    abs(operatingPoint(2)-(25-operatingPoint(1)))<=1e-10;
end

function digest = localFileHash(path)
assert(isfile(path),"AeroFlex:ProductionLibraryFile", ...
    "Required file is missing: %s.",path);
engine = javaMethod("getInstance","java.security.MessageDigest","SHA-256");
fileId = fopen(path,"rb");
assert(fileId>=0,"AeroFlex:ProductionLibraryFile", ...
    "Unable to read: %s.",path);
cleanup = onCleanup(@()fclose(fileId));
while ~feof(fileId)
    buffer = fread(fileId,1024*1024,"*uint8");
    if isempty(buffer)
        break
    end
    engine.update(typecast(buffer(:),"int8"));
end
bytes = typecast(engine.digest(),"uint8");
digest = string(lower(reshape(dec2hex(bytes,2).',1,[])));
clear cleanup
end
