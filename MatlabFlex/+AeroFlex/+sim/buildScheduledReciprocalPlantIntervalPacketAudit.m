function packet = buildScheduledReciprocalPlantIntervalPacketAudit(plant)
%BUILDSCHEDULEDRECIPROCALPLANTINTERVALPACKETAUDIT Pack the P1 numeric owner.

arguments
    plant (1,1) AeroFlex.sim.PlantRunTime
end
runtime = plant.reciprocalTangentCorrection;
assert(plant.nx==74 && plant.useRigidBody && plant.scheduleEnabled && ...
    runtime.enabled && runtime.replacesFixedRootIncrement && ...
    numel(runtime.hiddenState)==546 && ...
    numel(runtime.scheduledMembers)==14 && ...
    ~plant.model.internalCoupledCoordinate.enabled && ...
    plant.model.parConst.RateProject.projSet && ...
    plant.controlSampleScheduleHoldStepsRemaining==14, ...
    'AeroFlex:sim:PlantIntervalArchitecture', ...
    'P1 requires the qualified scheduled 74+546-state Case-B plant owner.');
assert(plant.sched.equilibriumCentered.enabled && ...
    ~isempty(plant.sched.equilibriumCentered.recoveryVertices) && ...
    numel(plant.sched.equilibriumCentered.recoveryVertices)<=3 && ...
    ~plant.cfg.sim.mirrorWingClamp && ...
    ~plant.cfg.sim.shiftWingMomentToCG && ...
    ~plant.cfg.sim.packageRelativeRigidAttitudeChi.enable && ...
    ~localGetNested(plant.cfg, ...
        {'sim','coupleRigidAttitudeIntoWingChi'},false) && ...
    exist('finAeroForceMoment','file')~=2, ...
    'AeroFlex:sim:PlantIntervalScope', ...
    'P1 is restricted to the qualified symmetric-longitudinal Case-B scope.');

scheduledPacket = struct( ...
    'plantCandidate',runtime.candidate, ...
    'queryPackageHash',"p1_saved_state", ...
    'schedule',struct('weights',runtime.scheduledWeights(:)), ...
    'queryTrim',runtime.scheduledQueryTrim, ...
    'members',runtime.scheduledMembers);
native = AeroFlex.ctrl.buildScheduledReciprocalIntervalPacketAudit( ...
    plant.model,scheduledPacket);

centered = plant.sched.equilibriumCentered;
vertices = centered.recoveryVertices(:);
if isfield(plant.sched,'physicalRecoveryReferenceState')
    recoveryReferenceState = ...
        plant.sched.physicalRecoveryReferenceState(:);
    recoveryReferenceControl = ...
        plant.sched.physicalRecoveryReferenceControl(:);
else
    recoveryReferenceState = plant.sched.x_eq(:);
    recoveryReferenceControl = plant.sched.u_eq(:);
end
anchor = zeros(6,1);
if isfield(centered,'recoveryAnchorWrench')
    anchor = centered.recoveryAnchorWrench(:);
end
recoveryMembers = repmat(localRecoveryMember(vertices(1)), ...
    numel(vertices),1);
for index = 1:numel(vertices)
    recoveryMembers(index) = localRecoveryMember(vertices(index));
end
recovery = struct( ...
    'referenceState',full(recoveryReferenceState), ...
    'referenceControl',full(recoveryReferenceControl), ...
    'anchor',full(anchor), ...
    'members',recoveryMembers);

members = repmat(localMember(runtime.scheduledMembers(1)),14,1);
for index = 1:14
    members(index) = localMember(runtime.scheduledMembers(index));
end
tail = localTail(plant.cfg);
thrustArm = zeros(3,1);
if isfield(plant.rbParams,'rThrust_B') && ...
        ~isempty(plant.rbParams.rThrust_B)
    thrustArm = plant.rbParams.rThrust_B(:);
end
packet = struct( ...
    'schemaVersion', ...
        "phase18c-v17a-casebc-p1-plant-interval-packet-v1", ...
    'changeId', ...
        "phase18c-v17a-casebc-p1-plant-interval-runtime-integration-v1", ...
    'native',native, ...
    'rawL',full(plant.model.L), ...
    'recovery',recovery, ...
    'trimWing',full(plant.trimWingControl(:)), ...
    'trimElevator',double(plant.trimTailDelta), ...
    'trimThrust',double(plant.trimThrust), ...
    'queryTrimWing',full(runtime.scheduledQueryTrim.wing(:)), ...
    'queryTrimElevator',double(runtime.scheduledQueryTrim.elevator), ...
    'queryTrimThrust',double(runtime.scheduledQueryTrim.thrust), ...
    'inputEquilibrium', ...
        full(runtime.candidate.base.inputEquilibrium(:)), ...
    'correctionStateEquilibrium', ...
        full(runtime.correctionStateEquilibrium(:)), ...
    'visibleCorrectionMap',full(runtime.visibleCorrectionMap), ...
    'hiddenStateMap',full(runtime.hiddenStateMap), ...
    'Avh',full(runtime.candidate.partition.Avh), ...
    'Ahh',full(runtime.candidate.partition.Ahh), ...
    'Bh',full(runtime.candidate.partition.Bh), ...
    'deltaBv',full(runtime.candidate.correction.deltaBv), ...
    'rigidWrenchCommandOperator', ...
        full(runtime.rigidWrenchCommandOperator), ...
    'dynamicWrenchMap',full(runtime.rigidWrenchMap(1:6,:)), ...
    'rigidWrenchRefinementUpdateLimit',double(localGetNested(runtime, ...
        {'rigidWrenchRefinementUpdateLimit'},2)), ...
    'fixedRootWingEquilibrium', ...
        full(runtime.fixedRootWingEquilibrium(:)), ...
    'sourceRootEquilibrium', ...
        full(runtime.sourceRootOutput.equilibrium(:)), ...
    'sourceRootStateMap', ...
        full(runtime.sourceRootOutput.runtimeStateMap), ...
    'sourceRootInputMap', ...
        full(runtime.sourceRootOutput.runtimeInputMap), ...
    'weights',full(double(runtime.scheduledWeights(:))), ...
    'members',members, ...
    'tail',tail, ...
    'mass',double(plant.rbParams.mass), ...
    'inertia',full(plant.rbParams.I_B), ...
    'gravity',double(plant.rbParams.g), ...
    'thrustArm',full(thrustArm), ...
    'fallbackSpeed',double(localFlightSpeed(plant.cfg)), ...
    'fallbackAlpha',double(localFlightAlpha(plant)), ...
    'substepCount',14, ...
    'dt',double(plant.dt));
assert(localAllFinite(packet), ...
    'AeroFlex:sim:PlantIntervalPacketFinite', ...
    'The P1 plant interval packet contains a nonfinite numeric field.');
end

function member = localRecoveryMember(vertex)
par = localPar(vertex.parConst);
referenceWrench = localVertexReaction( ...
    vertex.xEq(:),vertex.uEq(:),0,par, ...
    full(vertex.Lq1),full(vertex.Pr),full(vertex.phi1_sA));
operator = localRootWrenchOperator( ...
    full(vertex.Pr),full(vertex.phi1_sA));
member = struct( ...
    'weight',double(vertex.weight), ...
    'xEq',full(vertex.xEq(:)), ...
    'uEq',full(vertex.uEq(:)), ...
    'referenceWrench',full(referenceWrench), ...
    'Lq1',full(vertex.Lq1), ...
    'rootWrenchOperator',full(operator), ...
    'par',par);
end

function member = localMember(source)
candidate = source.candidate;
assert(candidate.hidden.count==39 && ...
    candidate.runtimeState.count==83 && ...
    numel(candidate.runtimeState.sourceVisible)==69, ...
    'AeroFlex:sim:PlantIntervalMember', ...
    'A scheduled source member changed dimension.');
member = struct( ...
    'sourceId',string(source.sourceId), ...
    'runtimeFromQueryState',full(source.runtimeFromQueryState), ...
    'correctionStateEquilibrium', ...
        full(candidate.base.correctionStateEquilibrium(:)), ...
    'queryRuntimeDeparture',full(source.queryRuntimeDeparture(:)), ...
    'queryInputDeparture',full(source.queryInputDeparture(:)), ...
    'trimWing',full(source.trim.wing(:)), ...
    'trimElevator',double(source.trim.elevator), ...
    'trimThrust',double(source.trim.thrust), ...
    'inputEquilibrium',full(candidate.base.inputEquilibrium(:)), ...
    'queryHiddenEquilibrium',full(source.queryHiddenEquilibrium(:)), ...
    'queryRootWrench',full(source.queryRootWrench(:)), ...
    'sourceVisible',double(candidate.runtimeState.sourceVisible(:)), ...
    'rootEquilibrium',full(candidate.rootWrenchOutput.equilibrium(:)), ...
    'rootStateMap',full(candidate.rootWrenchOutput.runtimeStateMap), ...
    'rootInputMap',full(candidate.rootWrenchOutput.runtimeInputMap), ...
    'inputBounds',full(candidate.sourceDomain.inputBounds(:)), ...
    'visibleBound',double( ...
        candidate.sourceDomain.visibleDepartureInfinity), ...
    'hiddenBound',double( ...
        candidate.sourceDomain.hiddenDepartureInfinity), ...
    'memoryCertificateEnabled',localMemoryCertificateEnabled(candidate), ...
    'memoryLyapunovFactor',localMemoryLyapunovFactor(candidate), ...
    'memoryInvariantRadius',localMemoryInvariantRadius(candidate), ...
    'rootWrenchBound',double( ...
        candidate.sourceDomain.rootWrenchDepartureInfinity));
end

function enabled = localMemoryCertificateEnabled(candidate)
enabled = isfield(candidate.sourceDomain,'recurrentMemoryCertificate') && ...
    logical(candidate.sourceDomain.recurrentMemoryCertificate.enabled);
end

function factor = localMemoryLyapunovFactor(candidate)
factor = zeros(candidate.hidden.count);
if localMemoryCertificateEnabled(candidate)
    factor = full(candidate.sourceDomain.recurrentMemoryCertificate. ...
        lyapunovFactorLower);
end
end

function radius = localMemoryInvariantRadius(candidate)
radius = 1;
if localMemoryCertificateEnabled(candidate)
    certificate = candidate.sourceDomain.recurrentMemoryCertificate;
    assert(certificate.gateLimit==1 && ...
        isfinite(certificate.invariantRadius) && ...
        certificate.invariantRadius>0, ...
        'AeroFlex:sim:PlantIntervalMemoryCertificate', ...
        'The interval recurrent-memory certificate is invalid.');
    radius = double(certificate.invariantRadius);
end
end

function tail = localTail(cfg)
rho = localGetNested(cfg,{'flight','rho'},1.225);
area = localGetNested(cfg,{'tail','S'}, ...
    localGetNested(cfg,{'tail','area'},0.035));
clAlpha = localGetNested(cfg,{'tail','CL_alpha'},4.4);
etaDelta = localGetNested(cfg,{'tail','eta_delta'},1.0);
incidence = localGetNested(cfg,{'tail','incidence_deg'},0.01);
cd0 = localGetNested(cfg,{'tail','CD0'},0.01);
efficiency = localGetNested(cfg,{'tail','e'},0.8);
aspectRatio = localGetNested(cfg,{'tail','AR'},4.0);
chord = localGetNested(cfg,{'tail','c'}, ...
    localGetNested(cfg,{'tail','chord'},0.10));
cm0 = localGetNested(cfg,{'tail','Cm0'},0.0);
cmDelta = localGetNested(cfg,{'tail','Cm_delta'},0.0);
tailArm = localGetNested(cfg,{'tail','arm'},0.60);
if isfield(cfg,'tail') && isfield(cfg.tail,'r_B') && ...
        ~isempty(cfg.tail.r_B)
    rTail = cfg.tail.r_B(:);
elseif isfield(cfg,'rigidEOMset') && ...
        isfield(cfg.rigidEOMset,'rTail_B') && ...
        ~isempty(cfg.rigidEOMset.rTail_B)
    rTail = cfg.rigidEOMset.rTail_B(:);
elseif isfield(cfg,'geom') && isfield(cfg.geom,'rTail_B') && ...
        ~isempty(cfg.geom.rTail_B)
    rTail = cfg.geom.rTail_B(:);
else
    rTail = [-tailArm;0;0];
end
assert(numel(rTail)==3, ...
    'AeroFlex:sim:PlantIntervalTailArm', ...
    'The horizontal-tail moment arm must contain three components.');
tail = struct( ...
    'rho',double(rho), ...
    'area',double(area), ...
    'clAlpha',double(clAlpha), ...
    'etaDelta',double(etaDelta), ...
    'incidence',deg2rad(double(incidence)), ...
    'cd0',double(cd0), ...
    'efficiency',double(efficiency), ...
    'aspectRatio',double(aspectRatio), ...
    'chord',double(chord), ...
    'cm0',double(cm0), ...
    'cmDelta',double(cmDelta), ...
    'arm',full(rTail));
end

function value = localGetNested(source,path,defaultValue)
value = defaultValue;
current = source;
for index = 1:numel(path)
    name = path{index};
    if ~isstruct(current) || ~isfield(current,name) || ...
            isempty(current.(name))
        return
    end
    current = current.(name);
end
value = current;
end

function speed = localFlightSpeed(cfg)
if isfield(cfg,'flight') && isfield(cfg.flight,'U_inf') && ...
        ~isempty(cfg.flight.U_inf)
    speed = cfg.flight.U_inf;
elseif isfield(cfg,'trim') && isfield(cfg.trim,'U_inf') && ...
        ~isempty(cfg.trim.U_inf)
    speed = cfg.trim.U_inf;
else
    speed = 0;
end
end

function alpha = localFlightAlpha(plant)
if isstruct(plant.trim) && isfield(plant.trim,'alphaDeg') && ...
        ~isempty(plant.trim.alphaDeg) && isfinite(plant.trim.alphaDeg)
    alpha = deg2rad(plant.trim.alphaDeg);
elseif isfield(plant.cfg,'trim') && ...
        isfield(plant.cfg.trim,'alphaDeg') && ...
        ~isempty(plant.cfg.trim.alphaDeg) && ...
        isfinite(plant.cfg.trim.alphaDeg)
    alpha = deg2rad(plant.cfg.trim.alphaDeg);
elseif isfield(plant.cfg,'flight') && ...
        isfield(plant.cfg.flight,'aoa_deg') && ...
        ~isempty(plant.cfg.flight.aoa_deg)
    alpha = deg2rad(plant.cfg.flight.aoa_deg);
else
    alpha = 0;
end
end

function par = localPar(source)
affineOffset = zeros(74,1);
if isfield(source,'affineOffset') && ~isempty(source.affineOffset)
    affineOffset = full(source.affineOffset(:));
end
par = struct( ...
    'Gamma1',full(source.Gamma1), ...
    'Gamma2',full(source.Gamma2), ...
    'Gamma_g',full(source.Gamma_g), ...
    'Gamma_xi',full(source.Gamma_xi), ...
    'forces_0',full(source.forces_0(:)), ...
    'scaleAero',double(source.scaleAero), ...
    't_inf',double(source.t_inf), ...
    'Fscale',double(source.Fscale), ...
    'Bw',full(source.Bw), ...
    'Dw',full(source.Dw), ...
    'Bdel',full(source.Bdel), ...
    'Ddel',full(source.Ddel), ...
    'Bddel',full(source.Bddel), ...
    'Dddel',full(source.Dddel), ...
    'N_Thrust',full(source.N_Thrust(:)), ...
    'affineOffset',affineOffset);
end

function wrench = localVertexReaction(state,control,gust,par,Lq1,Pr,phi)
nonlinear = localNonlinear(state,control,gust,par);
q1raw = Lq1*state+nonlinear(1:10);
wrench = AeroFlex.beam.recoverRootWrench(phi,Pr,Pr*q1raw);
end

function operator = localRootWrenchOperator(Pr,phi)
calibration = Pr*phi.';
singularValues = svd(calibration);
rankTolerance = max(size(calibration))*eps(singularValues(1));
assert(sum(singularValues>rankTolerance)==6, ...
    'AeroFlex:sim:PlantIntervalRootRecoveryRank', ...
    'The P1 root-wrench recovery calibration must retain rank six.');
operator = calibration\Pr;
operator([2,4,6],:) = 0;
end

function nonlinear = localNonlinear(state,control,gust,par)
q1 = state(1:10); q2 = state(11:20); qxi = state(21:31);
nonlinear = zeros(74,1);
gamma1q1 = squeeze(pagemtimes(par.Gamma1,'none',q1,'none'));
gamma2q2 = squeeze(pagemtimes(par.Gamma2,'none',q2,'none'));
gammaGqxi = squeeze(pagemtimes(par.Gamma_g,'none',qxi,'none'));
gammaXiqxi = squeeze(pagemtimes(par.Gamma_xi,'none',qxi,'none'));
gamma2TransposeQ1 = squeeze(pagemtimes( ...
    par.Gamma2,'transpose',q1,'none'));
nonlinear(1:10) = -(gamma1q1*q1)-(gamma2q2*q2)+ ...
    gammaGqxi*qxi+par.Fscale*par.forces_0+par.N_Thrust;
nonlinear(11:20) = gamma2TransposeQ1*q2;
nonlinear(21:31) = gammaXiqxi*q1;
nonlinear(32:71) = par.Bw*gust+(1/par.t_inf)* ...
    par.Bdel*control(1:2)+par.Bddel*control(3:4);
nonlinear(1:10) = nonlinear(1:10)+par.scaleAero*par.Dw*gust+ ...
    par.Ddel*control(1:2)+par.t_inf*par.Dddel*control(3:4);
nonlinear = nonlinear+par.affineOffset;
end

function finite = localAllFinite(value)
if isnumeric(value) || islogical(value)
    finite = all(isfinite(value),'all');
elseif isstring(value)
    finite = all(~ismissing(value),'all');
elseif ischar(value)
    finite = true;
elseif isstruct(value)
    names = fieldnames(value);
    finite = true;
    for index = 1:numel(value)
        for nameIndex = 1:numel(names)
            finite = finite && ...
                localAllFinite(value(index).(names{nameIndex}));
        end
    end
else
    finite = false;
end
end
