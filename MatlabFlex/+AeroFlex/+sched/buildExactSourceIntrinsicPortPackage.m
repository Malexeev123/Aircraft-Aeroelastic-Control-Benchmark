function [candidate,contract] = buildExactSourceIntrinsicPortPackage( ...
        sourcePackage,cfg,intrinsicBasis)
%BUILDEXACTSOURCEINTRINSICPORTPACKAGE Align exact Case-A aero/beam ports.
%   This default-inactive Phase-18C utility constructs an in-memory package.
%   The accepted source package remains unchanged and is the rollback owner.

arguments
    sourcePackage (1,1) struct
    cfg (1,1) struct
    intrinsicBasis (:,:) double {mustBeReal,mustBeFinite}
end

required = {'mu','L','Ldyn','idx','beam','aero','base','parConst', ...
    'x_eq','u_eq','time','equilibriumCentered','p5'};
for index = 1:numel(required)
    assert(isfield(sourcePackage,required{index}), ...
        'AeroFlex:sched:IntrinsicPortMissingField', ...
        'The exact-source package is missing field %s.',required{index});
end
assert(norm(double(sourcePackage.mu(:).')-[40,1],inf)<=1e-12, ...
    'AeroFlex:sched:IntrinsicPortSource', ...
    'The local intrinsic-port transform is restricted to exact Case A.');
assert(~isfield(sourcePackage.p5,'intrinsicPortRuntimeIntegration') || ...
    ~logical(sourcePackage.p5.intrinsicPortRuntimeIntegration.enabled), ...
    'AeroFlex:sched:IntrinsicPortDoubleTransform', ...
    'An intrinsic-port package cannot be transformed twice.');
assert(isfield(sourcePackage.p5,'fixedBasis') && ...
    isfield(sourcePackage.p5,'dimensionalSteadyNormalization') && ...
    logical(sourcePackage.p5.dimensionalSteadyNormalization), ...
    'AeroFlex:sched:IntrinsicPortForceContract', ...
    'The exact Case-A dimensional steady-force contract is unavailable.');
if isfield(sourcePackage.p5,'forceScaleApplications')
    assert(sourcePackage.p5.forceScaleApplications==1, ...
        'AeroFlex:sched:IntrinsicPortForceScaleCount', ...
        'The source package declares an invalid force-scale application count.');
end
assert(isfield(cfg,'p5') && isfield(cfg.p5,'structuralBeam') && ...
    isprop(cfg.p5.structuralBeam,'Omega') && ...
    isprop(cfg.p5.structuralBeam,'Sigma'), ...
    'AeroFlex:sched:IntrinsicPortStructuralOwner', ...
    'The accepted structural model is required to rebuild the package.');

fixedBasis = sourcePackage.p5.fixedBasis;
assert(isequal(size(fixedBasis),size(intrinsicBasis)) && ...
    size(fixedBasis,1)==96 && size(fixedBasis,2)==10, ...
    'AeroFlex:sched:IntrinsicPortBasisSize', ...
    'The exact Case-A physical bases must both be 96-by-10.');

% x_phys=Phi_i*q_i=Phi_f*q_f, Phi_f=Phi_i*S. Hence q_f=S^{-1}q_i,
% while virtual work requires Q_i=S^{-T}Q_f.
transform = intrinsicBasis\fixedBasis;
inverseTransform = transform\eye(size(transform));
forceDual = transform.'\eye(size(transform));
[fixedOrtho,~] = qr(fixedBasis,0);
[intrinsicOrtho,~] = qr(intrinsicBasis,0);
principalCosines = svd(intrinsicOrtho.'*fixedOrtho);
basisResidual = norm(fixedBasis-intrinsicBasis*transform,'fro')/ ...
    max(norm(fixedBasis,'fro'),eps);
subspaceResidual = sqrt(max(0,1-min(principalCosines)^2));
inverseResidual = max(norm(transform*inverseTransform-eye(10),'fro'), ...
    norm(inverseTransform*transform-eye(10),'fro'));
assert(basisResidual<=5e-4 && subspaceResidual<=5e-4 && ...
    cond(transform)<=1.1 && inverseResidual<=1e-12, ...
    'AeroFlex:sched:IntrinsicPortBasisContract', ...
    ['The exact Case-A basis map failed: basis %.3e, subspace %.3e, ', ...
     'condition %.3e, inverse %.3e.'],basisResidual,subspaceResidual, ...
    cond(transform),inverseResidual);

candidate = sourcePackage;
fixedMap = sourcePackage.aero.forceMap;
mappedMap = fixedMap;
mappedMap.B0 = fixedMap.B0*inverseTransform;
mappedMap.B1 = fixedMap.B1*inverseTransform;
mappedMap.C_Gamma = forceDual*fixedMap.C_Gamma;
mappedMap.D0 = forceDual*fixedMap.D0*inverseTransform;
mappedMap.D1 = forceDual*fixedMap.D1*inverseTransform;
mappedMap.Dw = forceDual*fixedMap.Dw;
mappedMap.D_delta = forceDual*fixedMap.D_delta;
mappedMap.D_ddelta = forceDual*fixedMap.D_ddelta;
mappedSteady = forceDual*sourcePackage.aero.forces_aero_beam_dof(:);

candidate.aero.forceMap = mappedMap;
candidate.aero.forces_aero_beam_dof = mappedSteady;
candidate.parConst.Bw = mappedMap.Bw;
candidate.parConst.Dw = mappedMap.Dw;
candidate.parConst.Bdel = mappedMap.B_delta;
candidate.parConst.Ddel = mappedMap.D_delta;
candidate.parConst.Bddel = mappedMap.B_ddelta;
candidate.parConst.Dddel = mappedMap.D_ddelta;
candidate.parConst.forces_0 = candidate.beam.eta_e(:)+mappedSteady;
candidate.parConst.u_ctrl = candidate.u_eq(:);
candidate.parConst.affineOffset = [];

numberModes = numel(candidate.idx.q1);
numberAeroStates = numel(candidate.idx.qGam);
beamModel = candidate.beam;
beamModel.Nm = numberModes;
beamModel.Omega = cfg.p5.structuralBeam.Omega;
beamModel.Sigma = cfg.p5.structuralBeam.Sigma;
aeroModel = candidate.aero;
aeroModel.Na = numberAeroStates;
[candidate.L,candidate.blk] = AeroFlex.core.assemble_L_matrix( ...
    cfg,beamModel,aeroModel,candidate.base);

xEquilibrium = candidate.x_eq(:);
xEquilibrium(candidate.idx.qGam) = 0;
nonlinear = AeroFlex.sim.nonlinear_terms( ...
    xEquilibrium,candidate.parConst,candidate.idx);
gammaOperator = candidate.L(candidate.idx.qGam,candidate.idx.qGam);
gammaRightHandSide = candidate.L(candidate.idx.qGam,:)*xEquilibrium+ ...
    nonlinear(candidate.idx.qGam);
assert(rcond(full(gammaOperator))>=1e-12, ...
    'AeroFlex:sched:IntrinsicPortGammaCondition', ...
    'The transformed aerodynamic equilibrium operator is ill-conditioned.');
xEquilibrium(candidate.idx.qGam) = ...
    -(gammaOperator\gammaRightHandSide);
candidate.x_eq = xEquilibrium;

rawResidual = candidate.L*xEquilibrium+ ...
    AeroFlex.sim.nonlinear_terms( ...
    xEquilibrium,candidate.parConst,candidate.idx);
candidate.parConst.affineOffset = -rawResidual;
centeredResidual = candidate.L*xEquilibrium+ ...
    AeroFlex.sim.nonlinear_terms( ...
    xEquilibrium,candidate.parConst,candidate.idx);

candidate.equilibriumCentered.rEq = centeredResidual;
candidate.equilibriumCentered.form = ...
    'exact Case-A fixed-basis/intrinsic force-dual runtime field';
candidate.equilibriumCentered.recoveryVertices = struct( ...
    'weight',1,'xEq',xEquilibrium,'uEq',candidate.u_eq(:), ...
    'Lq1',candidate.L(candidate.idx.q1,:), ...
    'parConst',candidate.parConst,'idx',candidate.idx, ...
    'Pz',candidate.beam.Pz,'Pr',candidate.beam.Pr, ...
    'phi1_sA',candidate.beam.red.phi1_sA);
candidate.equilibriumCentered.finalTrimRecentering = struct( ...
    'applied',true,'equationChanged',true, ...
    'stateChanged',norm(xEquilibrium-sourcePackage.x_eq(:),inf)>0, ...
    'operatorChanged',true,'residualBefore2',norm(rawResidual), ...
    'residualBeforeQGamma2',norm(rawResidual(candidate.idx.qGam)), ...
    'residualAfter2',norm(centeredResidual), ...
    'affineBeforeHash',localNumericHash(sourcePackage.parConst.affineOffset), ...
    'affineAfterHash',localNumericHash(candidate.parConst.affineOffset));

candidate.Ldyn = candidate.L;
candidate.Ldyn(candidate.idx.q1,:) = candidate.beam.Pz* ...
    candidate.L(candidate.idx.q1,:);
gamma = (2-sqrt(2))/2;
implicitMatrix = speye(size(candidate.Ldyn))- ...
    gamma*candidate.time.runtimeDt*candidate.Ldyn;
[lowerFactor,upperFactor,pivots] = lu(implicitMatrix,'vector');
factorizationResidual = norm(implicitMatrix(pivots,:)- ...
    lowerFactor*upperFactor,'fro')/max(1,norm(implicitMatrix,'fro'));
candidate.imex = struct('gamma',gamma,'Ldyn',candidate.Ldyn, ...
    'implicitMatrix',implicitMatrix,'Lfac',lowerFactor, ...
    'Ufac',upperFactor,'piv',pivots, ...
    'factorizationResidual',factorizationResidual);
candidate.eigL = eig(full(candidate.L));
if isfield(candidate,'physicalChartEquilibrium')
    candidate.physicalChartEquilibrium.state = xEquilibrium;
    candidate.physicalChartEquilibrium.input = candidate.u_eq(:);
    candidate.physicalChartEquilibrium.provenance = ...
        'EXACT_CASEA_INTRINSIC_PORT_RUNTIME_CANDIDATE';
end

artifactPath = string(sourcePackage.p5.artifactPath);
nodalDirect = localReadH5(artifactPath,'/physical_output/nodal_D');
fixedDirect = fixedBasis.'*nodalDirect;
intrinsicDirect = intrinsicBasis.'*nodalDirect;
forceDualResidual = localRelative(forceDual*fixedDirect,intrinsicDirect);
probeCoordinate = sin((1:numberModes).');
probeForce = nodalDirect*cos((1:size(nodalDirect,2)).');
fixedCoordinate = inverseTransform*probeCoordinate;
physicalPower = (intrinsicBasis*probeCoordinate).'*probeForce;
fixedPower = fixedCoordinate.'*(fixedBasis.'*probeForce);
mappedPower = probeCoordinate.'*(forceDual*(fixedBasis.'*probeForce));
virtualPowerResidual = max(abs([fixedPower-physicalPower, ...
    mappedPower-physicalPower]))/max([1,abs(physicalPower), ...
    abs(fixedPower),abs(mappedPower)]);
assert(forceDualResidual<=1e-4 && virtualPowerResidual<=1e-4, ...
    'AeroFlex:sched:IntrinsicPortDualContract', ...
    'Force duality or virtual power failed (%.3e, %.3e).', ...
    forceDualResidual,virtualPowerResidual);

structuralIdentity = struct( ...
    'Pz',isequaln(candidate.beam.Pz,sourcePackage.beam.Pz), ...
    'Pr',isequaln(candidate.beam.Pr,sourcePackage.beam.Pr), ...
    'phi1_sA',isequaln(candidate.beam.red.phi1_sA, ...
        sourcePackage.beam.red.phi1_sA), ...
    'Gamma1',isequaln(candidate.parConst.Gamma1, ...
        sourcePackage.parConst.Gamma1), ...
    'Gamma2',isequaln(candidate.parConst.Gamma2, ...
        sourcePackage.parConst.Gamma2), ...
    'Gamma_g',isequaln(candidate.parConst.Gamma_g, ...
        sourcePackage.parConst.Gamma_g), ...
    'Gamma_xi',isequaln(candidate.parConst.Gamma_xi, ...
        sourcePackage.parConst.Gamma_xi), ...
    'Fscale',isequaln(candidate.parConst.Fscale, ...
        sourcePackage.parConst.Fscale));
assert(all(structfun(@logical,structuralIdentity)), ...
    'AeroFlex:sched:IntrinsicPortProtectedField', ...
    'A protected structural, projector, recovery, or force-scale field changed.');

contract = struct( ...
    'sourceId','CASEA_U040_ALPHA_P01', ...
    'coordinateIdentity', ...
        'Phi_fixed=Phi_intrinsic*S; q_fixed=S^{-1}q_intrinsic; Q_intrinsic=S^{-T}Q_fixed', ...
    'transform',transform,'inverseTransform',inverseTransform, ...
    'forceDual',forceDual,'basisResidual',basisResidual, ...
    'subspaceResidual',subspaceResidual, ...
    'transformConditionNumber',cond(transform), ...
    'inverseConsistency',inverseResidual, ...
    'forceDualResidual',forceDualResidual, ...
    'virtualPowerResidual',virtualPowerResidual, ...
    'rawResidualBeforeCentering',norm(rawResidual), ...
    'centeredResidual',norm(centeredResidual), ...
    'aerodynamicResidual',norm(centeredResidual(candidate.idx.qGam)), ...
    'factorizationResidual',factorizationResidual, ...
    'equilibriumStateChangeInfinityNorm', ...
        norm(xEquilibrium-sourcePackage.x_eq(:),inf), ...
    'protectedStructuralIdentity',structuralIdentity, ...
    'sourcePackagePreserved',isequaln(sourcePackage,sourcePackage));
assert(contract.centeredResidual<=1e-10 && ...
    contract.aerodynamicResidual<=1e-10 && ...
    factorizationResidual<=1e-12, ...
    'AeroFlex:sched:IntrinsicPortRebuildResidual', ...
    'The transformed equilibrium or IMEX rebuild exceeds tolerance.');

candidate.p5.intrinsicPortRuntimeIntegration = struct( ...
    'enabled',true,'auditOnly',true,'defaultActive',false, ...
    'sourceId','CASEA_U040_ALPHA_P01', ...
    'parentPackageHash',string(sourcePackage.p5.packageHash), ...
    'coordinateIdentity',contract.coordinateIdentity, ...
    'basisResidual',basisResidual,'subspaceResidual',subspaceResidual, ...
    'forceDualResidual',forceDualResidual, ...
    'virtualPowerResidual',virtualPowerResidual, ...
    'centeredResidual',contract.centeredResidual, ...
    'fallback','accepted_registry_bound_casea_package');
candidate.p5.aerodynamicResidual = contract.aerodynamicResidual;
candidate.p5.centeredResidual = contract.centeredResidual;
candidate.p5.packageHash = localPackageHash(candidate);
AeroFlex.sched.assertPackageConsistency(candidate);
end

function value = localReadH5(path,dataset)
raw = h5read(path,dataset);
if isstruct(raw)
    raw = double(raw.r)+1i*double(raw.i);
else
    raw = double(raw);
end
assert(max(abs(imag(raw(:))))<=1e-10*max(1,max(abs(raw(:)))), ...
    'AeroFlex:sched:IntrinsicPortComplex', ...
    'A source-real physical output contains a material imaginary residual.');
value = real(raw.');
end

function value = localRelative(actual,expected)
value = norm(actual-expected,'fro')/max(norm(expected,'fro'),eps);
end

function digest = localPackageHash(package)
payload = struct('mu',package.mu,'L',full(package.L), ...
    'xEq',package.x_eq,'uEq',package.u_eq, ...
    'forces0',package.parConst.forces_0, ...
    'affineOffset',package.parConst.affineOffset, ...
    'sourceHash',package.p5.sourceContractHash, ...
    'referenceHash',package.p5.referenceContractHash, ...
    'intrinsicPortRuntimeIntegration', ...
        package.p5.intrinsicPortRuntimeIntegration);
digest = localTextHash(jsonencode(payload));
end

function digest = localNumericHash(value)
engine = javaMethod('getInstance','java.security.MessageDigest','SHA-256');
engine.update(typecast(double(value(:)),'uint8'));
bytes = typecast(engine.digest(),'uint8');
digest = lower(string(reshape(dec2hex(bytes,2).',1,[])));
end

function digest = localTextHash(value)
engine = javaMethod('getInstance','java.security.MessageDigest','SHA-256');
engine.update(uint8(unicode2native(char(value),'UTF-8')));
bytes = typecast(engine.digest(),'uint8');
digest = lower(string(reshape(dec2hex(bytes,2).',1,[])));
end
