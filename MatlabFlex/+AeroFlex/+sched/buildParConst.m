function parConst = buildParConst(cfg, beam, aero, base)
%BUILDPARCONST Assemble the nonlinear parameter bundle used by the integrator.
%
% This routine is deliberately identical in content to the parConst blocks in
% ROMIntegrator and SimRunner.  Keeping it centralized prevents the scheduler,
% trim, plant and controller from silently using different Gamma tensors,
% force maps, scalings or thrust vectors.

forces0 = beam.eta_e + aero.DataMatrix.forces_aero_beam_dof;

if ~isfield(cfg,'SwTest'), cfg.SwTest = 0; end
if ~isfield(cfg,'trim') || ~isfield(cfg.trim,'thrust')
    cfg.trim.thrust = zeros(beam.Nm,1);
end
if ~isfield(cfg.flight,'Fscale')
    qInf = 0.5 * cfg.flight.rho * cfg.flight.U_inf^2;
    cfg.flight.Fscale = qInf * cfg.flight.b_ref^2;
end
if ~isfield(cfg.flight,'a'), cfg.flight.a = 1; end
if ~isfield(cfg.flight,'t_inf'), cfg.flight.t_inf = 1; end

parConst = struct( ...
    'Gamma1',   beam.Gamma1, ...
    'Gamma2',   beam.Gamma2, ...
    'Gamma_g',  base.Gamma_g, ...
    'Gamma_xi', base.Gamma_xi, ...
    'forces_0', forces0, ...
    'scaleAero', cfg.flight.a*cfg.flight.t_inf, ...
    't_inf', cfg.flight.t_inf, ...
    'Fscale', cfg.flight.Fscale, ...
    'scaleA', cfg.flight.a, ...
    'gustSet', cfg.gust, ...
    'Bw', aero.forceMap.Bw, ...
    'Dw', aero.forceMap.Dw, ...
    'Bdel',  aero.forceMap.B_delta, ...
    'Ddel',  aero.forceMap.D_delta, ...
    'Bddel', aero.forceMap.B_ddelta, ...
    'Dddel', aero.forceMap.D_ddelta, ...
    'gust_input', aero.gust_input, ...
    'dt', cfg.sim.dt, ...
    'Na', aero.Na, ...
    'SwTest', cfg.SwTest, ...
    'N_Thrust', cfg.trim.thrust);

if isfield(cfg,'trim') && isfield(cfg.trim,'useRateProjection') && cfg.trim.useRateProjection
    parConst.RateProject = struct('projSet',true,'Pz',beam.Pz);
else
    parConst.RateProject = struct('projSet',false,'Pz',beam.Pz);
end
end
