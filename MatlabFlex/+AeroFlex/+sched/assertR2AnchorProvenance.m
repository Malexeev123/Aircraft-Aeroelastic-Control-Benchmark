function assertR2AnchorProvenance(sched)
%ASSERTR2ANCHORPROVENANCE Reject mixed or validation-derived R2 anchors.

arguments
    sched (1,1) struct
end

if ~isfield(sched,'p5') || ~isfield(sched.p5,'r2') || ...
        ~isfield(sched.p5.r2,'anchor')
    error('AeroFlex:sched:R2AnchorMissing', ...
        'The package must contain an explicit R2 T2 anchor.');
end
if ~isfield(sched.p5,'t2AnchorSource')
    error('AeroFlex:sched:R2AnchorSourceMissing', ...
        'The package lacks its immutable T2 anchor-source identity.');
end
source = sched.p5.t2AnchorSource;
anchor = sched.p5.r2.anchor;
required = {'contract','provenanceCategory','construction','interpolated', ...
    'query','trimStateHash','trimCommandHash','structuralPackageHash', ...
    'rawLHash','recoveryMapHash','frame','referencePoint', ...
    'multiplicity','units','wrench'};
for k = 1:numel(required)
    if ~isfield(anchor,required{k})
        error('AeroFlex:sched:R2AnchorMetadataMissing', ...
            'R2 anchor metadata is missing field "%s".',required{k});
    end
end

category = string(anchor.provenanceCategory);
if category == "VALIDATION_TRUTH_T2_CLAMP"
    error('AeroFlex:sched:R2ValidationTruthLeakage', ...
        'Validation-truth T2 clamps are comparison-only.');
end
if ~ismember(category,["SOURCE_TRAINING_T2_ANCHOR", ...
        "MODEL_PREDICTED_QUERY_T2_ANCHOR"])
    error('AeroFlex:sched:R2AnchorProvenanceCategory', ...
        'R2 anchor provenance category is not permitted for model input.');
end
if logical(anchor.interpolated)
    error('AeroFlex:sched:R2InterpolatedAnchor', ...
        'A T2 anchor may not be interpolated directly.');
end
if string(anchor.contract) ~= "MATLAB_FULL_AIRCRAFT_T2"
    error('AeroFlex:sched:R2AnchorContract', ...
        'R2 absolute anchor must declare MATLAB_FULL_AIRCRAFT_T2.');
end
if isfield(sched.p5.r2,'validation') && ...
        isequaln(anchor.wrench, ...
        sched.p5.r2.validation.sharpyWingOnlySupportReaction)
    error('AeroFlex:sched:R2SharpyAnchorAssignment', ...
        'A SHARPy clamped-wing support reaction cannot be a T2 anchor.');
end
if norm(anchor.query(:)-sched.mu(:),inf) > 1e-12 || ...
        norm(anchor.query(:)-source.query(:),inf) > 1e-12
    error('AeroFlex:sched:R2AnchorQuery', ...
        'R2 anchor belongs to a different query.');
end
if ~isequal(string(anchor.trimStateHash),string(source.trimStateHash)) || ...
        ~isequal(string(anchor.trimCommandHash), ...
        string(source.trimCommandHash))
    error('AeroFlex:sched:R2AnchorTrimIdentity', ...
        'R2 anchor belongs to a different trim state or command.');
end
expectedStructural = contractHash(struct('Pz',sched.beam.Pz, ...
    'Pr',sched.beam.Pr,'eta_e',sched.beam.eta_e, ...
    'phi1_sA',sched.beam.red.phi1_sA));
expectedRecovery = contractHash(struct('Pr',sched.beam.Pr, ...
    'phi1_sA',sched.beam.red.phi1_sA));
if ~isequal(string(anchor.structuralPackageHash),expectedStructural) || ...
        ~isequal(string(anchor.structuralPackageHash), ...
        string(source.structuralPackageHash))
    error('AeroFlex:sched:R2AnchorStructuralIdentity', ...
        'R2 anchor structural package hash does not match the package.');
end
if ~isequal(string(anchor.rawLHash),string(source.rawLHash))
    error('AeroFlex:sched:R2AnchorRawLIdentity', ...
        'R2 anchor raw-L hash does not match the package.');
end
if ~isequal(string(anchor.recoveryMapHash),expectedRecovery) || ...
        ~isequal(string(anchor.recoveryMapHash), ...
        string(source.recoveryMapHash))
    error('AeroFlex:sched:R2AnchorRecoveryIdentity', ...
        'R2 anchor recovery-map hash does not match the package.');
end
if string(anchor.frame) ~= "body" || ...
        string(anchor.referencePoint) ~= "wing root" || ...
        string(anchor.multiplicity) ~= "full wing; no additional mirroring" || ...
        ~isequal(string(anchor.units(:)), ...
        ["N";"N";"N";"N m";"N m";"N m"])
    error('AeroFlex:sched:R2AnchorPhysicalConvention', ...
        'R2 anchor frame, reference, multiplicity, or units are invalid.');
end
end

function digest = contractHash(value)
engine = javaMethod('getInstance','java.security.MessageDigest','SHA-256');
engine.update(uint8(unicode2native(jsonencode(value),'UTF-8')));
bytes = typecast(engine.digest(),'uint8');
digest = lower(string(reshape(dec2hex(bytes,2).',1,[])));
end
