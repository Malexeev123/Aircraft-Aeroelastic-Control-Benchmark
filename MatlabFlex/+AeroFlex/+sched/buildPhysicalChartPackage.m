function wrench=recoveryAnchor(vertices,weights)
wrench=zeros(6,1);
for k=1:numel(vertices)
    sched=vertices(k).sched;
    if ~isfield(sched,'p5') || ~isfield(sched.p5,'r2') || ...
            ~isfield(sched.p5.r2,'anchor') || ...
            ~isfield(sched.p5.r2.anchor,'wrench')
        error('AeroFlex:sched:PhysicalRecoveryAnchor', ...
            'Source vertex %d has no certified T2 recovery anchor.',k);
    end
    sourceWrench=sched.p5.r2.anchor.wrench(:);
    if numel(sourceWrench)~=6 || any(~isfinite(sourceWrench))
        error('AeroFlex:sched:PhysicalRecoveryAnchor', ...
            'Source vertex %d has an invalid T2 recovery anchor.',k);
    end
    wrench=wrench+weights(k)*sourceWrench;
end
end

