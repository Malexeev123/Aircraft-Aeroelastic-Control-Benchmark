function digest = packageDigest(package)
payload = struct('mu',package.mu,'weights',package.weights, ...
    'LReal',real(full(package.L)),'LImag',imag(full(package.L)), ...
    'xEqReal',real(package.x_eq),'xEqImag',imag(package.x_eq), ...
    'forces0Real',real(package.parConst.forces_0), ...
    'forces0Imag',imag(package.parConst.forces_0), ...
    'affineReal',real(package.parConst.affineOffset), ...
    'affineImag',imag(package.parConst.affineOffset));
engine = javaMethod('getInstance','java.security.MessageDigest','SHA-256');
engine.update(uint8(unicode2native(jsonencode(payload),'UTF-8')));
bytes = typecast(engine.digest(),'uint8');
digest = lower(string(reshape(dec2hex(bytes,2).',1,[])));
end

function package = enforceRealPackage(package)
fields = {'L','Ldyn','parConst','base','aero','x_eq','u_eq'};
maxImaginary = 0;
maxField = "";
for k = 1:numel(fields)
    [package.(fields{k}),fieldMaximum] = realify(package.(fields{k}));
    if fieldMaximum > maxImaginary
        maxImaginary = fieldMaximum;
        maxField = fields{k};
    end
end
beamFields = {'Pz','Pr','eta_e','Gamma1','Gamma2'};
for k = 1:numel(beamFields)
    [package.beam.(beamFields{k}),fieldMaximum] = ...
        realify(package.beam.(beamFields{k}));
    if fieldMaximum > maxImaginary
        maxImaginary = fieldMaximum;
        maxField = "beam."+beamFields{k};
    end
end
redFields = {'phi1_sA'};
for k = 1:numel(redFields)
    [package.beam.red.(redFields{k}),fieldMaximum] = ...
        realify(package.beam.red.(redFields{k}));
    if fieldMaximum > maxImaginary
        maxImaginary = fieldMaximum;
        maxField = "beam.red."+redFields{k};
    end
end
discFields = {'phi0_local','phi1_local','etaVecExt', ...
    'Gamma1','Gamma2'};
for k = 1:numel(discFields)
    [package.beam.red.ModeVars_discrete.(discFields{k}),fieldMaximum] = ...
        realify(package.beam.red.ModeVars_discrete.(discFields{k}));
    if fieldMaximum > maxImaginary
        maxImaginary = fieldMaximum;
        maxField = "beam.red.ModeVars_discrete."+discFields{k};
    end
end
[package.p5.r2,fieldMaximum] = realify(package.p5.r2);
if fieldMaximum > maxImaginary
    maxImaginary = fieldMaximum;
    maxField = "p5.r2";
end
if maxImaginary > 1e-10
    error('AeroFlex:sched:PhysicalPackageComplex', ...
        'Query package field %s has imaginary content %.3e.', ...
        maxField,maxImaginary);
end
end

