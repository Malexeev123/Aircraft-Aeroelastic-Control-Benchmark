function package=installJointStructuralAerodynamicCoupling(package,joint)
idx=package.idx; Nm=numel(idx.q1); Na=numel(idx.qGam);
if isfield(joint,'subsystem')
    expected=2*Nm+Na;
    if ~isequal(size(joint.subsystem),[expected expected]) || ...
            any(~isfinite(joint.subsystem),'all')
        error('AeroFlex:sched:JointCouplingDimensions', ...
            'The joint structural-aerodynamic subsystem is incompatible.');
    end
    coupled=[idx.q1 idx.q2 idx.qGam];
    if isfield(joint,'coordinateTransport')
        coordinate=joint.coordinateTransport;
        if ~isequal(size(coordinate.coupledPhysicalToInternal), ...
                [numel(coupled) numel(coupled)])
            error('AeroFlex:sched:InternalCoupledDimensions', ...
                'The V8 coupled-coordinate transform is incompatible.');
        end
        package.L(coupled,coupled)=coordinate.coupledInternalToPhysical* ...
            joint.subsystem*coordinate.coupledPhysicalToInternal;
        fullTransform=eye(size(package.L));
        fullTransform(coupled,coupled)=coordinate.coupledPhysicalToInternal;
        package.internalCoupledCoordinate=struct('enabled',true, ...
            'architecture', jointArchitectureName(joint), ...
            'physicalToInternal',fullTransform, ...
            'internalToPhysical',fullTransform.', ...
            'Linternal',fullTransform*package.L*fullTransform.', ...
            'coupledIndices',coupled(:), ...
            'orthogonalityError',coordinate.orthogonalityError);
        package.p5.r2.Omega=-package.L(idx.q2,idx.q1);
    else
        package.L(coupled,coupled)=joint.subsystem;
    end
    package.info.mode='source_only_joint_structural_aerodynamic_common_realization';
    return
end
if isfield(joint,'couplingOnlySubsystem')
    expected=2*Nm+Na;
    if ~isequal(size(joint.couplingOnlySubsystem),[expected expected]) || ...
            any(~isfinite(joint.couplingOnlySubsystem),'all')
        error('AeroFlex:sched:JointCouplingDimensions', ...
            'The coupling-only structural-aerodynamic subsystem is incompatible.');
    end
    structural=[idx.q1 idx.q2]; gamma=idx.qGam;
    sourceStructural=1:(2*Nm); sourceGamma=2*Nm+(1:Na);
    package.L(structural,gamma)= ...
        joint.couplingOnlySubsystem(sourceStructural,sourceGamma);
    package.L(gamma,structural)= ...
        joint.couplingOnlySubsystem(sourceGamma,sourceStructural);
    package.info.mode='source_only_joint_structural_aerodynamic_coupling_realization';
    return
end
required={'q1q1','q1q2','q1Gamma','gammaQ1','gammaQ2','gammaGamma'};
if ~all(isfield(joint,required)) || ...
        ~isequal(size(joint.q1q1),[Nm Nm]) || ...
        ~isequal(size(joint.q1q2),[Nm Nm]) || ...
        ~isequal(size(joint.q1Gamma),[Nm Na]) || ...
        ~isequal(size(joint.gammaQ1),[Na Nm]) || ...
        ~isequal(size(joint.gammaQ2),[Na Nm]) || ...
        ~isequal(size(joint.gammaGamma),[Na Na])
    error('AeroFlex:sched:JointCouplingDimensions', ...
        'The direct structural-aerodynamic coupling blocks are incompatible.');
end
values=struct2cell(rmfield(joint,'assemblyRule'));
if any(cellfun(@(value)any(~isfinite(value),'all'),values))
    error('AeroFlex:sched:JointCouplingFinite', ...
        'The direct structural-aerodynamic coupling blocks must be finite.');
end
package.L(idx.q1,idx.q1)=joint.q1q1;
package.L(idx.q1,idx.q2)=joint.q1q2;
package.L(idx.q1,idx.qGam)=joint.q1Gamma;
package.L(idx.qGam,idx.q1)=joint.gammaQ1;
package.L(idx.qGam,idx.q2)=joint.gammaQ2;
package.L(idx.qGam,idx.qGam)=joint.gammaGamma;
package.info.mode='source_only_joint_structural_aerodynamic_common_realization';
end

