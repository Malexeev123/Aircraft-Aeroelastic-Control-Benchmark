function [value,maxImaginary] = realify(value)
maxImaginary = 0;
if isnumeric(value)
    if ~isreal(value), maxImaginary = max(abs(imag(value(:)))); end
    value = real(value);
elseif isstruct(value)
    names = fieldnames(value);
    for element = 1:numel(value)
        for k = 1:numel(names)
            [value(element).(names{k}),fieldMaximum] = ...
                realify(value(element).(names{k}));
            maxImaginary = max(maxImaginary,fieldMaximum);
        end
    end
elseif iscell(value)
    for k = 1:numel(value)
        [value{k},fieldMaximum] = realify(value{k});
        maxImaginary = max(maxImaginary,fieldMaximum);
    end
end
end

