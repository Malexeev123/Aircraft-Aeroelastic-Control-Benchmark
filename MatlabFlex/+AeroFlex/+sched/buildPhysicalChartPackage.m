function [package,chart] = buildPhysicalChartPackage( ...
        sources,weights,query,method,certifiedChart,atomicOptions)
%BUILDPHYSICALCHARTPACKAGE Build a centered query package from source data.

arguments
    sources (1,:) struct
    weights (:,1) double
    query (1,2) double
    method (1,1) string
    certifiedChart (1,1) struct = struct()
    atomicOptions (1,1) struct = struct()
end
weights = weights(:);
if numel(sources) ~= numel(weights) || any(weights < -1e-13) || ...
        abs(sum(weights)-1) > 1e-12
    error('AeroFlex:sched:PhysicalPackageWeights', ...
        'Query packages require nonnegative partition-of-unity weights.');
end
useCertifiedChart = ~isempty(fieldnames(certifiedChart));
useAtomic = ~isempty(fieldnames(atomicOptions)) && ...
    isfield(atomicOptions,'enabled') && logical(atomicOptions.enabled);
oneHot = find(abs(weights-1)<=1e-14,1);
forceCandidatePath=useAtomic && isfield(atomicOptions,'architecture') && ...
    ismember(string(atomicOptions.architecture), ...
    ["fixed_basis_full_operator_query_reduction", ...
    "full_coordinate_atomic_lift_interpolate_project", ...
    "physics_normalized_blockwise_full_operator", ...
    "joint_structural_aerodynamic_lift_interpolate_project", ...
    "joint_structural_aerodynamic_lift_interpolate_project_v2", ...
    "mixed_diagonal_offdiagonal_joint_coupling_lift_interpolate_project_v3", ...
    "full_coupled_common_coordinate_realization_diagnostic_v4", ...
    "branch_preserving_structural_common_realization_diagnostic_v6", ...
    "full_coupled_partition_preserving_branch_realization_diagnostic_v7", ...
    "unpartitioned_coupled_interface_realization_diagnostic_v8", ...
    "branch_aware_cross_coupling_realization_diagnostic_v9", ...
    "dual_structural_chart_biorthogonal_diagnostic_v12", ...
    "full_coupled_ordered_schur_invariant_subspace_diagnostic_v13", ...
    "selective_high_band_coupled_invariant_subspace_diagnostic_v14", ...
    "multiband_coupled_invariant_subspace_diagnostic_v15", ...
    "frequency_limited_global_parallel_transfer_function_diagnostic_v17", ...
    "invariant_cluster_biorthogonal", ...
    "ordered_real_schur_biorthogonal"]);
if ~useCertifiedChart && ~isempty(oneHot) && nnz(weights>1e-14)==1 && ...
        ~forceCandidatePath
    package = sources(oneHot);
    chart = AeroFlex.sched.buildPhysicalStructuralChart( ...
        sources(oneHot),1,method);
    if useAtomic
        package.p5.commonRealization = struct( ...
            'architecture',char(atomicArchitectureName(atomicOptions)), ...
            'oneHotIdentity',true,'sourceIndex',oneHot, ...
            'validationTruthUsedForConstruction',false);
    end
    return
end

physicalChartCacheStats = struct('enabled',false,'hits',0, ...
    'misses',0,'h5Reads',0,'wallSeconds',0);
if useCertifiedChart
    chart = validateCertifiedChart(certifiedChart,numel(sources));
else
    chartOptions = struct();
    if useAtomic && isfield(atomicOptions,'preparedRuntimeOwner') && ...
            logical(atomicOptions.preparedRuntimeOwner)
        preparedFields = {'preparedRuntimeOwner', ...
            'preparedRuntimeProfile','preparedRuntimeChangeId', ...
            'preparedRuntimeRegistrySha256','projectedTustinCondensation'};
        for fieldIndex = 1:numel(preparedFields)
            fieldName = preparedFields{fieldIndex};
            if isfield(atomicOptions,fieldName)
                chartOptions.(fieldName) = atomicOptions.(fieldName);
            end
        end
        chartOptions.registryPath = string(atomicOptions.registryPath);
    end
    [chart,physicalChartCacheStats] = ...
        AeroFlex.sched.buildPhysicalStructuralChart( ...
        sources,weights,method,useAtomic,chartOptions);
end
atomicCandidate = struct();
if useAtomic
    requiredAtomic = {'registryPath','ambientPath'};
    if isfield(atomicOptions,'architecture') && ...
            ismember(string(atomicOptions.architecture), ...
            ["full_coordinate_atomic_lift_interpolate_project", ...
            "physics_normalized_blockwise_full_operator", ...
            "joint_structural_aerodynamic_lift_interpolate_project", ...
            "joint_structural_aerodynamic_lift_interpolate_project_v2", ...
            "full_coupled_common_coordinate_realization_diagnostic_v4", ...
            "branch_preserving_structural_common_realization_diagnostic_v6", ...
            "full_coupled_partition_preserving_branch_realization_diagnostic_v7", ...
            "unpartitioned_coupled_interface_realization_diagnostic_v8", ...
            "branch_aware_cross_coupling_realization_diagnostic_v9", ...
            "dual_structural_chart_biorthogonal_diagnostic_v12", ...
            "full_coupled_ordered_schur_invariant_subspace_diagnostic_v13", ...
            "selective_high_band_coupled_invariant_subspace_diagnostic_v14", ...
            "multiband_coupled_invariant_subspace_diagnostic_v15", ...
            "frequency_limited_global_parallel_transfer_function_diagnostic_v17", ...
            "invariant_cluster_biorthogonal", ...
            "ordered_real_schur_biorthogonal"])
        requiredAtomic = {'registryPath','fieldRoot'};
    end
    missingAtomic = requiredAtomic(~isfield(atomicOptions,requiredAtomic));
    if ~isempty(missingAtomic)
        error('AeroFlex:sched:AtomicOptionField', ...
            'Atomic options are missing: %s.',strjoin(missingAtomic,', '));
    end
    architecture = "atomic_ambient";
    if isfield(atomicOptions,'architecture')
        architecture = string(atomicOptions.architecture);
    end
    switch architecture
        case "atomic_ambient"
            atomicCandidate = AeroFlex.sched.buildAtomicCommonRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.ambientPath));
        case "aligned_reduced_node27"
            atomicCandidate = AeroFlex.sched.buildAlignedReducedRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.ambientPath));
        case "fixed_basis_full_operator_query_reduction"
            atomicCandidate = AeroFlex.sched.buildFixedBasisQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath));
        case "full_coordinate_atomic_lift_interpolate_project"
            builderOptions = struct( ...
                'cacheImmutableMetadata', ...
                isfield(atomicOptions,'cacheImmutableMetadata') && ...
                logical(atomicOptions.cacheImmutableMetadata), ...
                'cacheImmutableSourceData', ...
                isfield(atomicOptions,'cacheImmutableSourceData') && ...
                logical(atomicOptions.cacheImmutableSourceData));
            preparedFields = {'preparedRuntimeOwner', ...
                'preparedRuntimeProfile','preparedRuntimeChangeId', ...
                'preparedRuntimeRegistrySha256','projectedTustinCondensation'};
            for fieldIndex = 1:numel(preparedFields)
                fieldName = preparedFields{fieldIndex};
                if isfield(atomicOptions,fieldName)
                    builderOptions.(fieldName) = atomicOptions.(fieldName);
                end
            end
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),builderOptions);
        case "physics_normalized_blockwise_full_operator"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'query',query));
        case "joint_structural_aerodynamic_lift_interpolate_project"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'jointCoupling',true,'query',query));
        case "joint_structural_aerodynamic_lift_interpolate_project_v2"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'jointDiscrete',true,'query',query));
        case "mixed_diagonal_offdiagonal_joint_coupling_lift_interpolate_project_v3"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'jointDiscreteCouplingOnly',true, ...
                'query',query));
        case "full_coupled_common_coordinate_realization_diagnostic_v4"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'fullCoupledCommonCoordinate',true, ...
                'query',query));
        case "branch_preserving_structural_common_realization_diagnostic_v6"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'branchPreservingStructural',true, ...
                'query',query));
        case "full_coupled_partition_preserving_branch_realization_diagnostic_v7"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'fullCoupledPartitionPreserving',true, ...
                'query',query));
        case "unpartitioned_coupled_interface_realization_diagnostic_v8"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'unpartitionedCoupledInterface',true, ...
                'query',query));
        case "branch_aware_cross_coupling_realization_diagnostic_v9"
            atomicCandidate = AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'branchAwareCrossCoupling',true, ...
                'query',query));
        case "dual_structural_chart_biorthogonal_diagnostic_v12"
            atomicCandidate = AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'fullCoupledCommonCoordinate',true, ...
                'query',query));
            atomicCandidate.architecture = ...
                'dual_structural_chart_biorthogonal_diagnostic_v12';
        case "full_coupled_ordered_schur_invariant_subspace_diagnostic_v13"
            atomicCandidate = AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'fullCoupledOrderedSchur',true, ...
                'query',query));
        case "selective_high_band_coupled_invariant_subspace_diagnostic_v14"
            atomicCandidate = AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'selectiveHighBandCoupled',true, ...
                'query',query));
        case "multiband_coupled_invariant_subspace_diagnostic_v15"
            atomicCandidate = AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'multiBandCoupled',true,'query',query));
        case "frequency_limited_global_parallel_transfer_function_diagnostic_v17"
            atomicCandidate = ...
                AeroFlex.sched.buildFrequencyLimitedGlobalParallelQueryRealization( ...
                sources,weights,string(atomicOptions.registryPath));
        case "invariant_cluster_biorthogonal"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'invariantCluster',true, ...
                'query',query));
        case "ordered_real_schur_biorthogonal"
            atomicCandidate = ...
                AeroFlex.sched.buildFullCoordinateQueryRealization( ...
                sources,weights,chart,string(atomicOptions.registryPath), ...
                string(atomicOptions.fieldRoot),struct( ...
                'physicsNormalized',true,'orderedSchur',true,'query',query));
        otherwise
            error('AeroFlex:sched:AtomicArchitecture', ...
                'Unknown atomic architecture %s.',architecture);
    end
    if ismember(architecture, ...
            ["full_coordinate_atomic_lift_interpolate_project", ...
            "physics_normalized_blockwise_full_operator", ...
            "joint_structural_aerodynamic_lift_interpolate_project", ...
            "joint_structural_aerodynamic_lift_interpolate_project_v2", ...
            "mixed_diagonal_offdiagonal_joint_coupling_lift_interpolate_project_v3", ...
            "full_coupled_common_coordinate_realization_diagnostic_v4", ...
            "branch_preserving_structural_common_realization_diagnostic_v6", ...
            "full_coupled_partition_preserving_branch_realization_diagnostic_v7", ...
            "unpartitioned_coupled_interface_realization_diagnostic_v8", ...
            "branch_aware_cross_coupling_realization_diagnostic_v9", ...
            "dual_structural_chart_biorthogonal_diagnostic_v12", ...
            "full_coupled_ordered_schur_invariant_subspace_diagnostic_v13", ...
            "selective_high_band_coupled_invariant_subspace_diagnostic_v14", ...
            "multiband_coupled_invariant_subspace_diagnostic_v15", ...
            "frequency_limited_global_parallel_transfer_function_diagnostic_v17", ...
            "invariant_cluster_biorthogonal", ...
            "ordered_real_schur_biorthogonal"])
        chart = installFullCoordinateQGammaPlaceholder( ...
            chart,atomicCandidate,sources);
    else
        chart = installAtomicQGammaTransforms(chart,atomicCandidate,sources);
    end
    if physicalChartCacheStats.enabled
        atomicCandidate.preparedPhysicalChartCache = ...
            physicalChartCacheStats;
    end
end

pointsCell = cell(size(sources));
vertices = repmat(struct('id',0,'sched',struct(), ...
    'xEq',[],'uEq',[]),1,numel(sources));
for k = 1:numel(sources)
    pointsCell{k} = AeroFlex.sched.transformPointByPhysicalChart( ...
        sources(k),chart.transforms(k));
    point = pointsCell{k};
    vertexState = point.x_eq(:);
    vertexInput = point.u_eq(:);
    if isfield(point,'physicalChartEquilibrium')
        vertexState = point.physicalChartEquilibrium.state(:);
        vertexInput = point.physicalChartEquilibrium.input(:);
    end
    vertices(k) = struct('id',sourceId(sources(k),k), ...
        'sched',point,'xEq',vertexState,'uEq',vertexInput);
end
points = [pointsCell{:}];

package = interpolatePoints(points,weights,query,chart);
if useAtomic
    package = installAtomicAerodynamics(package,atomicCandidate);
    if ismember(string(atomicCandidate.architecture), ...
            ["full_coordinate_atomic_lift_interpolate_project_v1", ...
            "physics_normalized_blockwise_full_operator_v1", ...
            "joint_structural_aerodynamic_lift_interpolate_project_v1", ...
            "joint_structural_aerodynamic_lift_interpolate_project_v2", ...
            "mixed_diagonal_offdiagonal_joint_coupling_lift_interpolate_project_v3", ...
            "full_coupled_common_coordinate_realization_diagnostic_v4", ...
            "branch_preserving_structural_common_realization_diagnostic_v6", ...
            "full_coupled_partition_preserving_branch_realization_diagnostic_v7", ...
            "unpartitioned_coupled_interface_realization_diagnostic_v8", ...
            "full_coupled_ordered_schur_invariant_subspace_diagnostic_v13", ...
            "selective_high_band_coupled_invariant_subspace_diagnostic_v14", ...
            "multiband_coupled_invariant_subspace_diagnostic_v15", ...
            "frequency_limited_global_parallel_transfer_function_diagnostic_v17", ...
            "invariant_cluster_biorthogonal_v1", ...
            "ordered_real_schur_biorthogonal_v1"])
        package = installFullCoordinateFields(package,atomicCandidate);
        if isfield(atomicCandidate,'jointCoupling') && ...
                isstruct(atomicCandidate.jointCoupling)
            package = installJointStructuralAerodynamicCoupling( ...
                package,atomicCandidate.jointCoupling);
        end
    end
end
xEq = zeros(size(package.L,1),1);
xEq(package.idx.q1) = chart.physicalEquilibrium.q1;
xEq(package.idx.q2) = chart.physicalEquilibrium.q2;
xEq(package.idx.qxi) = chart.physicalEquilibrium.qxi;
xEq(package.idx.chi) = 0;
uEq = weighted(arrayfun(@(v){v.uEq(:)},vertices),weights);
useFullCoordinate = useAtomic && ismember(string(atomicCandidate.architecture), ...
    ["full_coordinate_atomic_lift_interpolate_project_v1", ...
    "physics_normalized_blockwise_full_operator_v1", ...
    "joint_structural_aerodynamic_lift_interpolate_project_v1", ...
    "joint_structural_aerodynamic_lift_interpolate_project_v2", ...
    "mixed_diagonal_offdiagonal_joint_coupling_lift_interpolate_project_v3", ...
    "full_coupled_common_coordinate_realization_diagnostic_v4", ...
    "branch_preserving_structural_common_realization_diagnostic_v6", ...
    "full_coupled_partition_preserving_branch_realization_diagnostic_v7", ...
    "unpartitioned_coupled_interface_realization_diagnostic_v8", ...
    "branch_aware_cross_coupling_realization_diagnostic_v9", ...
    "dual_structural_chart_biorthogonal_diagnostic_v12", ...
    "full_coupled_ordered_schur_invariant_subspace_diagnostic_v13", ...
    "selective_high_band_coupled_invariant_subspace_diagnostic_v14", ...
    "multiband_coupled_invariant_subspace_diagnostic_v15", ...
    "frequency_limited_global_parallel_transfer_function_diagnostic_v17", ...
    "invariant_cluster_biorthogonal_v1", ...
    "ordered_real_schur_biorthogonal_v1"]);
if useFullCoordinate
    xEq(package.idx.qGam)=atomicCandidate.qGammaEquilibrium;
    package.x_eq=xEq; package.u_eq=uEq; package.parConst.u_ctrl=uEq;
    package.equilibriumCentered=struct('enabled',false, ...
        'endpointExact',~isempty(oneHot),'vertexIds',[vertices.id], ...
        'weights',weights.','form', ...
        'source-only full-coordinate equilibrium predictor; no pre-trim recenter', ...
        'recoveryVertices',fullCoordinateRecoveryVertices(vertices,weights), ...
        'recoveryAnchorWrench',recoveryAnchor(vertices,weights));
else
    package = AeroFlex.sched.buildEquilibriumCenteredPackage( ...
        package,vertices,weights,xEq,uEq);
end

% qGamma is model-owned and is solved in the assembled query realization.
package.parConst.u_ctrl = uEq;
if ~useFullCoordinate
    xEq(package.idx.qGam) = 0;
    nonlinear = AeroFlex.sim.nonlinear_terms( ...
        xEq,package.parConst,package.idx);
    rhs = package.L(package.idx.qGam,:)*xEq+nonlinear(package.idx.qGam);
    AGamma = package.L(package.idx.qGam,package.idx.qGam);
    if rcond(full(AGamma)) < 1e-12
        error('AeroFlex:sched:PhysicalPackageGammaCondition', ...
            'Query aerodynamic equilibrium operator is ill-conditioned.');
    end
    xEq(package.idx.qGam) = -(AGamma\rhs);
    package.x_eq = xEq;
    package.u_eq = uEq;
    package.parConst.u_ctrl = uEq;

    % Translate only the remaining query equilibrium defect.
    raw = package.L*xEq+AeroFlex.sim.nonlinear_terms( ...
        xEq,package.parConst,package.idx);
    package.parConst.affineOffset = package.parConst.affineOffset-raw;
    package.equilibriumCentered.rEqBeforeFinalTranslation = raw;
else
    % The full-coordinate operator is expressed about the source-only
    % weighted equilibrium. Translate only its affine term so that the
    % propagated query field has the same declared origin. Absolute root
    % reaction remains owned separately by recoveryAnchorWrench.
    pc = package.parConst;
    pc.u_ctrl = uEq;
    pc.gust = [];
    raw = package.L*xEq+AeroFlex.sim.nonlinear_terms( ...
        xEq,pc,package.idx);
    pc.affineOffset = pc.affineOffset(:)-raw;
    package.parConst = pc;
    package.equilibriumCentered.enabled = true;
    package.equilibriumCentered.rEqBeforeFinalTranslation = raw;
    package.equilibriumCentered.rEq = ...
        package.L*xEq+AeroFlex.sim.nonlinear_terms( ...
        xEq,package.parConst,package.idx);
    package.equilibriumCentered.form = ...
        'source-only full-coordinate affine translation';
end
package.equilibriumCentered.physicalChartMethod = char(method);
package.equilibriumCentered.physicalEquilibrium = ...
    chart.physicalEquilibrium;

package.Ldyn = package.L;
package.Ldyn(package.idx.q1,:) = ...
    package.beam.Pz*package.L(package.idx.q1,:);
gamma = (2-sqrt(2))/2;
implicitMatrix = speye(size(package.Ldyn))- ...
    gamma*package.time.runtimeDt*package.Ldyn;
[Lfac,Ufac,piv] = lu(implicitMatrix,'vector');
package.imex = struct('gamma',gamma,'Ldyn',package.Ldyn, ...
    'implicitMatrix',implicitMatrix,'Lfac',Lfac,'Ufac',Ufac,'piv',piv, ...
    'factorizationResidual',norm(implicitMatrix(piv,:)-Lfac*Ufac,'fro')/ ...
        max(1,norm(implicitMatrix,'fro')));

package = enforceRealPackage(package);
package.p5.r2.anchor = provisionalAnchor(package);
package.p5.r2.enabled = true;
package.p5.r2.diagnosticOnly = false;
package.p5.r2.feedsBackIntoDynamics = false;
package.p5.query = query;
package.p5.sourceArtifacts = arrayfun(@(p) string(p.p5.artifactPath),sources);
package.p5.physicalChart = rmfield(chart,'transforms');
if useFullCoordinate
    % Runtime schedule changes must transport persistent reduced states
    % through one shared physical/full coordinate.  Retain only the maps
    % required for that transport; the locked query dynamics are unchanged.
    package.scheduleStateCoordinate = struct( ...
        'schemaVersion',1, ...
        'owner','source_only_physical_and_full_coordinate', ...
        'query',double(query(:).'), ...
        'q1ToPhysical',chart.H1, ...
        'q1CenterToPhysical',package.beam.red.phi1_sA, ...
        'q2ToPhysical',chart.H2, ...
        'qxiToPhysical',chart.Hxi, ...
        'qxiCenterToPhysical',package.base.phiXi_sA, ...
        'qGammaToFull',atomicCandidate.V, ...
        'qGammaFromFull',atomicCandidate.W.', ...
        'equilibriumState',package.x_eq(:), ...
        'validationTruthUsedForConstruction',false);
end
package.p5.packageHash = packageDigest(package);
if useAtomic
    removable=intersect(fieldnames(atomicCandidate), ...
        {'A','B','C','D','Ad','Bd','Cd','Dd','V','W','full'});
    package.p5.commonRealization = rmfield(atomicCandidate,removable);
end
package.eigL = eig(full(package.L));
package.compatibleCoordinates = true;
package.physicalRecoveryCompatible = true;
if ~useFullCoordinate
    package = installProvisionalAnchor(package);
end
AeroFlex.sched.assertPackageConsistency(package);
end

function chart = installAtomicQGammaTransforms(chart,candidate,sources)
for k = 1:numel(sources)
    Tg = candidate.transforms(k).T;
    Sg = candidate.transforms(k).Tinv;
    chart.transforms(k).qGam = struct('T',Tg,'Tinv',Sg);
    idx = sources(k).idx;
    chart.transforms(k).T(idx.qGam,idx.qGam) = Tg;
    chart.transforms(k).Tinv(idx.qGam,idx.qGam) = Sg;
end
chart.method = "atomic_common_realization_"+string(chart.method);
chart.metrics.atomic = candidate.metrics;
chart.metrics.atomicReferenceSource = candidate.referenceSource;
end

function chart = installFullCoordinateQGammaPlaceholder(chart,candidate,sources)
% Source reduced qGamma fields are deliberately not transported. Identity
% placeholders keep structural charting dimensionally valid until every
% qGamma-dependent field is atomically replaced from the full realization.
for k=1:numel(sources)
    count=numel(sources(k).idx.qGam); identity=eye(count);
    chart.transforms(k).qGam=struct('T',identity,'Tinv',identity);
    idx=sources(k).idx;
    chart.transforms(k).T(idx.qGam,idx.qGam)=identity;
    chart.transforms(k).Tinv(idx.qGam,idx.qGam)=identity;
end
chart.method="full_coordinate_atomic_"+string(chart.method);
chart.metrics.atomic=candidate.metrics;
chart.metrics.atomicReferenceSource=candidate.referenceSource;
end

function package = installAtomicAerodynamics(package,candidate)
Nm = numel(package.idx.q1);
Na = numel(package.idx.qGam);
if ~isequal(size(candidate.A),[Na Na]) || ...
        ~isequal(size(candidate.B),[Na 2*Nm+5]) || ...
        ~isequal(size(candidate.C),[Nm Na]) || ...
        ~isequal(size(candidate.D),[Nm 2*Nm+5])
    error('AeroFlex:sched:AtomicTupleDimensions', ...
        'The projected atomic A/B/C/D tuple has incompatible dimensions.');
end
fm = package.aero.forceMap;
fm.A_Gamma = candidate.A;
fm.B0 = candidate.B(:,1:Nm);
fm.B1 = candidate.B(:,Nm+(1:Nm));
fm.Bw = candidate.B(:,2*Nm+1);
fm.B_delta = candidate.B(:,2*Nm+(2:3));
fm.B_ddelta = candidate.B(:,2*Nm+(4:5));
fm.C_Gamma = candidate.C;
fm.D0 = candidate.D(:,1:Nm);
fm.D1 = candidate.D(:,Nm+(1:Nm));
fm.Dw = candidate.D(:,2*Nm+1);
fm.D_delta = candidate.D(:,2*Nm+(2:3));
fm.D_ddelta = candidate.D(:,2*Nm+(4:5));
package.aero.forceMap = fm;

