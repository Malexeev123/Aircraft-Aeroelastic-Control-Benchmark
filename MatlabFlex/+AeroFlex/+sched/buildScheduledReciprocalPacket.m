function [packet,cache] = buildScheduledReciprocalPacket( ...
        queryPackage,manifestPath,cache,auditRequest)
%BUILDSCHEDULEDRECIPROCALPACKET Bind one V17A query to the source bank.
%   Source-local latent coordinates remain independent. The returned maps
%   transport only the native Artola state and source correction through the
%   scheduler's existing physical and full-coordinate charts.

arguments
    queryPackage (1,1) struct
    manifestPath (1,1) string
    cache (1,1) struct = struct()
    auditRequest (1,1) struct = struct()
end

requiredQuery = {'idx','x_eq','u_eq','scheduleStateCoordinate', ...
    'fullCoordinateRuntimeCandidate'};
assert(all(isfield(queryPackage,requiredQuery)), ...
    'AeroFlex:sched:ScheduledReciprocalQuery', ...
    'The scheduled reciprocal query package is incomplete.');
chart = queryPackage.scheduleStateCoordinate;
requiredChart = {'q1ToPhysical','q2ToPhysical','qxiToPhysical', ...
    'qGammaToFull','qGammaFromFull'};
assert(all(isfield(chart,requiredChart)), ...
    'AeroFlex:sched:ScheduledReciprocalChart', ...
    'The query package has no complete scheduled-state chart.');
assert(isfile(manifestPath), ...
    'AeroFlex:sched:ScheduledReciprocalManifest', ...
    'The scheduled reciprocal runtime-bank manifest is unavailable.');
manifestHash = localFileHash(manifestPath);
preparedRuntimeOwner = localPreparedRuntimeEnabled(auditRequest);
preparedRequestKey = localPreparedRequestKey( ...
    auditRequest,preparedRuntimeOwner);
if ~localCacheMatches( ...
        cache,manifestPath,manifestHash,preparedRequestKey)
    cache = localLoadBank(manifestPath,manifestHash,auditRequest, ...
        preparedRuntimeOwner,preparedRequestKey);
end

activeIds = string(queryPackage.fullCoordinateRuntimeCandidate.sourceIds(:));
activeWeights = double(queryPackage.weights(:));
assert(numel(activeIds)==numel(activeWeights) && ...
    all(isfinite(activeWeights)) && all(activeWeights>=-1e-14) && ...
    abs(sum(activeWeights)-1)<=1e-12 && ...
    numel(unique(activeIds))==numel(activeIds), ...
    'AeroFlex:sched:ScheduledReciprocalWeights', ...
    'The active V17A source weights are not a convex unique stencil.');
weights = zeros(cache.sourceCount,1);
for activeIndex = 1:numel(activeIds)
    bankIndex = find(cache.sourceIds==activeIds(activeIndex));
    assert(isscalar(bankIndex), ...
        'AeroFlex:sched:ScheduledReciprocalSource', ...
        'Active source %s is absent or duplicated in the reciprocal bank.', ...
        activeIds(activeIndex));
    weights(bankIndex) = max(activeWeights(activeIndex),0);
end
weights = weights/sum(weights);

idx = queryPackage.idx;
nativeCount = numel(queryPackage.x_eq);
assert(nativeCount==74 && numel(idx.q1)==10 && numel(idx.q2)==10 && ...
    numel(idx.qxi)==11 && numel(idx.qGam)==40 && numel(idx.chi)==3, ...
    'AeroFlex:sched:ScheduledReciprocalStateOrder', ...
    'The V17A native Artola state order changed.');
queryV = double(chart.qGammaToFull);
queryWTranspose = double(chart.qGammaFromFull);
assert(isequal(size(queryV),[size(cache.members(1).sourceV,1),40]) && ...
    isequal(size(queryWTranspose),[40,size(queryV,1)]) && ...
    norm(queryWTranspose*queryV-eye(40),'fro')<=1e-9, ...
    'AeroFlex:sched:ScheduledReciprocalAerodynamicChart', ...
    'The query aerodynamic lift/project pair is incompatible.');

bankMembers = cache.members;
members = repmat(struct('sourceId',"",'candidate',struct(), ...
    'trim',struct(),'queryToSourceNative',[], ...
    'sourceToQueryCorrection',[],'runtimeFromQueryState',[], ...
    'queryHiddenEquilibrium',[], ...
    'queryVisibleCorrection',[],'queryRuntimeDeparture',[], ...
    'queryInputDeparture',[],'queryRootWrench',[]), ...
    cache.sourceCount,1);
mapConditions = repmat(struct('sourceId',"",'q1',NaN,'qxi',NaN, ...
    'qGamma',NaN,'native',NaN,'roundTrip',NaN, ...
    'stateCenterResidual',NaN),cache.sourceCount,1);
queryTrim = localTrim(queryPackage,bankMembers,weights);
for memberIndex = 1:cache.sourceCount
    source = bankMembers(memberIndex).sourcePackage;
    if preparedRuntimeOwner
        prepared = bankMembers(memberIndex).prepared;
        sourceH1 = prepared.sourceH1;
        sourceHxi = prepared.sourceHxi;
    else
        sourceH1 = double(source.beam.red.ModeVars_discrete.phi1_local);
        sourceHxi = double(source.base.phi_xi_modes);
    end
    T1 = AeroFlex.sched.procrustesLocalToRef( ...
        sourceH1,double(chart.q1ToPhysical),'orthogonal');
    Tx = AeroFlex.sched.procrustesLocalToRef( ...
        sourceHxi,double(chart.qxiToPhysical),'orthogonal');
    T2 = T1;
    Tg = queryWTranspose*bankMembers(memberIndex).sourceV;
    S1 = T1.';
    S2 = T2.';
    Sx = Tx.';
    Sg = pinv(Tg);

    queryToSource = eye(nativeCount);
    queryToSource(idx.q1,idx.q1) = S1;
    queryToSource(idx.q2,idx.q2) = S2;
    queryToSource(idx.qxi,idx.qxi) = Sx;
    queryToSource(idx.qGam,idx.qGam) = Sg;

    candidate = bankMembers(memberIndex).candidate;
    if preparedRuntimeOwner
        sourceCenter = prepared.sourceCenter;
    else
        sourceCenter = zeros(nativeCount,1);
        sourceCenter(idx.q1) = candidate.base. ...
            correctionStateEquilibrium(candidate.visible.q1);
        sourceCenter(idx.q2) = candidate.base. ...
            correctionStateEquilibrium(candidate.visible.q2);
        sourceCenter(idx.qGam) = candidate.base. ...
            correctionStateEquilibrium(candidate.visible.qGam);
        sourceCenter(idx.qxi) = candidate.base. ...
            correctionStateEquilibrium(candidate.runtimeState.qxi);
        sourceCenter(idx.chi) = candidate.base. ...
            correctionStateEquilibrium(candidate.runtimeState.chi);
    end
    sourceToQuery = zeros(nativeCount,candidate.visible.count);
    sourceToQuery(idx.q1,candidate.visible.q1) = T1;
    sourceToQuery(idx.q2,candidate.visible.q2) = T2;
    sourceToQuery(idx.qGam,candidate.visible.qGam) = Tg;
    if preparedRuntimeOwner
        runtimeFromNative = prepared.runtimeFromNative;
        runtimeFromRigid = prepared.runtimeFromRigid;
        queryRuntimeToNative = prepared.queryRuntimeToNative;
        hiddenEquilibrium = prepared.hiddenEquilibrium;
        visibleEquilibriumCorrection = ...
            prepared.visibleEquilibriumCorrection;
    else
        runtimeFromNative = zeros( ...
            candidate.runtimeState.count,nativeCount);
        runtimeFromNative(candidate.runtimeState.sourceVisible(1:60), ...
            [idx.q1(:);idx.q2(:);idx.qGam(:)]) = eye(60);
        runtimeFromNative(candidate.runtimeState.qxi,idx.qxi) = ...
            eye(numel(idx.qxi));
        runtimeFromNative(candidate.runtimeState.chi,idx.chi) = ...
            eye(numel(idx.chi));
        runtimeFromRigid = zeros(candidate.runtimeState.count,9);
        runtimeFromRigid(candidate.visible.rigid,:) = eye(9);
        queryRuntimeToNative = zeros( ...
            nativeCount,candidate.runtimeState.count);
        queryRuntimeToNative(idx.q1,candidate.visible.q1) = ...
            eye(numel(idx.q1));
        queryRuntimeToNative(idx.q2,candidate.visible.q2) = ...
            eye(numel(idx.q2));
        queryRuntimeToNative(idx.qGam,candidate.visible.qGam) = ...
            eye(numel(idx.qGam));
        queryRuntimeToNative(idx.qxi,candidate.runtimeState.qxi) = ...
            eye(numel(idx.qxi));
        queryRuntimeToNative(idx.chi,candidate.runtimeState.chi) = ...
            eye(numel(idx.chi));
        hiddenEquilibrium = zeros(candidate.hidden.count,1);
        visibleEquilibriumCorrection = ...
            zeros(candidate.visible.count,1);
    end
    runtimeDeparture = runtimeFromNative*queryToSource* ...
        queryPackage.x_eq(:)+runtimeFromRigid*queryTrim.rigid- ...
        candidate.base.correctionStateEquilibrium(:);
    runtimeFromQueryState = runtimeFromNative*queryToSource* ...
        queryRuntimeToNative;
    runtimeFromQueryState(:,candidate.visible.rigid) = ...
        runtimeFromQueryState(:,candidate.visible.rigid)+runtimeFromRigid;
    localInput = [0;queryTrim.wing-bankMembers(memberIndex).trim.wing; ...
        queryTrim.elevator-bankMembers(memberIndex).trim.elevator; ...
        queryTrim.thrust-bankMembers(memberIndex).trim.thrust];
    inputDeparture = localInput-candidate.base.inputEquilibrium(:);
    rootWrenchEquilibrium = ...
        candidate.rootWrenchOutput.equilibrium(:)+ ...
        candidate.rootWrenchOutput.runtimeStateMap* ...
            [runtimeDeparture;hiddenEquilibrium]+ ...
        candidate.rootWrenchOutput.runtimeInputMap*inputDeparture;
    assert(all(isfinite([queryToSource(:);sourceToQuery(:)])), ...
        'AeroFlex:sched:ScheduledReciprocalFiniteMap', ...
        'A nonfinite scheduled reciprocal map was built for %s.', ...
        bankMembers(memberIndex).sourceId);

    members(memberIndex) = struct( ...
        'sourceId',bankMembers(memberIndex).sourceId, ...
        'candidate',candidate, ...
        'trim',bankMembers(memberIndex).trim, ...
        'queryToSourceNative',queryToSource, ...
        'sourceToQueryCorrection',sourceToQuery, ...
        'runtimeFromQueryState',runtimeFromQueryState, ...
        'queryHiddenEquilibrium',hiddenEquilibrium, ...
        'queryVisibleCorrection',visibleEquilibriumCorrection, ...
        'queryRuntimeDeparture',runtimeDeparture, ...
        'queryInputDeparture',inputDeparture, ...
        'queryRootWrench',rootWrenchEquilibrium);
    mapConditions(memberIndex) = struct( ...
        'sourceId',members(memberIndex).sourceId, ...
        'q1',cond(T1),'qxi',cond(Tx),'qGamma',cond(Tg), ...
        'native',cond(queryToSource), ...
        'roundTrip',norm(Tg*Sg-eye(40),'fro'), ...
        'stateCenterResidual',norm( ...
            queryToSource*queryPackage.x_eq(:)-sourceCenter,inf));
end

memoryCoordinateAudit = struct();
if preparedRuntimeOwner
    for memberIndex = 1:numel(members)
        members(memberIndex).candidate = ...
            bankMembers(memberIndex).prepared.candidate;
    end
    memoryCoordinateAudit = cache.preparedAudits.memoryCoordinate;
elseif localStableMemoryAuditEnabled(auditRequest)
    [members,memoryCoordinateAudit] = localStableMemoryMembers(members);
end
% Query root-wrench centers must use the final runtime realization.  The
% prepared stable-memory candidate changes the hidden-state realization and
% its dual root-wrench recovery map, so a center formed from the pre-transform
% candidate is not equivalent at an interior scheduled query.
for memberIndex = 1:numel(members)
    candidate = members(memberIndex).candidate;
    members(memberIndex).queryRootWrench = ...
        candidate.rootWrenchOutput.equilibrium(:)+ ...
        candidate.rootWrenchOutput.runtimeStateMap* ...
            [members(memberIndex).queryRuntimeDeparture(:); ...
             members(memberIndex).queryHiddenEquilibrium(:)]+ ...
        candidate.rootWrenchOutput.runtimeInputMap* ...
            members(memberIndex).queryInputDeparture(:);
end
sourceDomainAudit = struct();
if preparedRuntimeOwner
    sourceDomainAudit = cache.preparedAudits.sourceDomain;
elseif localSourceDomainAuditEnabled(auditRequest)
    [members,sourceDomainAudit] = localSourceDomainMembers( ...
        members,auditRequest.sourceDomainEnvelope);
end
recurrentMemoryAudit = struct();
if preparedRuntimeOwner
    recurrentMemoryAudit = cache.preparedAudits.recurrentMemory;
elseif localRecurrentMemoryCertificateEnabled(auditRequest)
    [members,recurrentMemoryAudit] = ...
        localRecurrentMemoryCertificateMembers(members,auditRequest);
end

packet = struct( ...
    'schemaVersion','phase18c-v17a-scheduled-reciprocal-packet-v1', ...
    'auditOnly',true,'defaultActive',false, ...
    'query',double(queryPackage.mu(:).'), ...
    'queryPackageHash',localPackageHash(queryPackage), ...
    'queryNativeEquilibrium',double(queryPackage.x_eq(:)), ...
    'queryTrim',queryTrim,'members',members, ...
    'schedule',struct('weights',weights,'activeSourceIds',activeIds, ...
        'activeWeights',activeWeights), ...
    'mapConditions',mapConditions, ...
    'bankManifestPath',manifestPath, ...
    'bankManifestSha256',manifestHash, ...
    'sourceIds',cache.sourceIds, ...
    'hiddenStateCount',sum(arrayfun( ...
        @(member)double(member.candidate.hidden.count),members)), ...
    'validationFittingUsed',false);
packet.plantCandidate = localPlantCandidate( ...
    queryPackage,members,weights,queryTrim,cache,preparedRuntimeOwner);
if preparedRuntimeOwner
    packet.preparedRuntimeOwner = struct('enabled',true, ...
        'profile',string(auditRequest.preparedRuntimeProfile), ...
        'changeId',string(auditRequest.preparedRuntimeChangeId), ...
        'requestKey',preparedRequestKey, ...
        'allFourteenMemoriesRetained',numel(members)==14);
end
if ~isempty(fieldnames(memoryCoordinateAudit))
    packet.memoryCoordinateAudit = memoryCoordinateAudit;
end
if ~isempty(fieldnames(sourceDomainAudit))
    packet.sourceDomainAudit = sourceDomainAudit;
end
if ~isempty(fieldnames(recurrentMemoryAudit))
    packet.recurrentMemoryCertificateAudit = recurrentMemoryAudit;
end
end

function enabled = localPreparedRuntimeEnabled(request)
enabled = isstruct(request) && isscalar(request) && ...
    isfield(request,'preparedRuntimeOwner') && ...
    logical(request.preparedRuntimeOwner);
if ~enabled
    return
end
required = {'enable','auditOnly','changeId','stableMemoryChart', ...
    'sourceDomainPrecommit','sourceDomainEnvelope', ...
    'preparedRuntimeProfile','preparedRuntimeChangeId'};
assert(all(isfield(request,required)) && logical(request.enable) && ...
    logical(request.auditOnly) && logical(request.stableMemoryChart) && ...
    logical(request.sourceDomainPrecommit) && ...
    string(request.changeId)== ...
        "phase18c-v17a-caseb-symmetric-longitudinal-reciprocal-runtime-domain-owner-v1" && ...
    ismember(string(request.preparedRuntimeProfile), ...
        ["formal_case_b","formal_case_c"]) && ...
    string(request.preparedRuntimeChangeId)== ...
        "phase18c-v17a-casebc-prepared-scheduled-runtime-owner-v1", ...
    'AeroFlex:sched:ScheduledReciprocalPreparedScope', ...
    ['Prepared reciprocal-bank data require the approved Case-B/C ', ...
     'runtime owner and both qualified reciprocal audits.']);
end

function key = localPreparedRequestKey(request,enabled)
if ~enabled
    key = "disabled";
    return
end
envelope = request.sourceDomainEnvelope;
memoryEnabled = localRecurrentMemoryCertificateEnabled(request);
memoryChangeId = "disabled";
if memoryEnabled
    memoryChangeId = string(request.recurrentMemoryCertificateChangeId);
end
key = strjoin([string(request.preparedRuntimeProfile), ...
    string(request.preparedRuntimeChangeId), ...
    string(request.changeId),string(envelope.artifactPath), ...
    lower(string(envelope.artifactSha256)),string(memoryEnabled), ...
    memoryChangeId],"|");
end

function enabled = localStableMemoryAuditEnabled(request)
enabled = false;
if isempty(fieldnames(request)) || ~isfield(request,"enable") || ...
        ~logical(request.enable) || ...
        ~isfield(request,"stableMemoryChart") || ...
        ~logical(request.stableMemoryChart)
    return
end
assert(isfield(request,"auditOnly") && logical(request.auditOnly) && ...
    isfield(request,"changeId") && string(request.changeId)== ...
    "phase18c-v17a-caseb-symmetric-longitudinal-reciprocal-runtime-domain-owner-v1", ...
    'AeroFlex:sched:ScheduledReciprocalStableMemoryApproval', ...
    'The stable scheduled-memory chart is outside the approved audit scope.');
enabled = true;
end

