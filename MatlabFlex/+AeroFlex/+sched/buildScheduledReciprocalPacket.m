function digest = localPackageHash(package)
fields = [package.mu(:);package.x_eq(:);package.u_eq(:); ...
    package.L(:);package.scheduleStateCoordinate.qGammaToFull(:); ...
    package.scheduleStateCoordinate.qGammaFromFull(:)];
bytes = typecast(double(fields(:)),'uint8');
engine = javaMethod('getInstance','java.security.MessageDigest','SHA-256');
engine.update(typecast(bytes(:),'int8'));
digest = lower(string(reshape(dec2hex( ...
    typecast(engine.digest(),'uint8'),2).',1,[])));
end

function digest = localFileHash(path)
engine = javaMethod('getInstance','java.security.MessageDigest','SHA-256');
fileId = fopen(path,'rb');
assert(fileId>=0,'AeroFlex:sched:ScheduledReciprocalHashOpen', ...
    'Cannot read %s.',path);
cleanup = onCleanup(@() fclose(fileId));
while ~feof(fileId)
    bytes = fread(fileId,1024*1024,'*uint8');
    if isempty(bytes), break, end
    engine.update(typecast(bytes(:),'int8'));
end
digest = lower(string(reshape(dec2hex( ...
    typecast(engine.digest(),'uint8'),2).',1,[])));
clear cleanup
end
