function [summary,plan] = runCustomBenchmarkCase(definition,options)
%RUNCUSTOMBENCHMARKCASE Plan or execute one continuous custom maneuver.
%   Execution is limited to the supported scheduled coupled-full speed/pitch
%   domain. Formal benchmark cases and their qualification records are never
%   modified by a custom run.

arguments
    definition (1,1) struct
    options.Execute (1,1) logical = false
    options.ControllerMode (1,1) string = "full"
    options.DiagnosticsLevel (1,1) double = 1
    options.FiguresVisible (1,1) logical = false
    options.SavePlots (1,1) logical = true
    options.PublicationMode (1,1) logical = false
    options.OutputRoot (1,1) string = ""
    options.RunId (1,1) string = "auto"
    options.NativeKernelPolicy (1,1) string = "auto"
    options.AllowUnqualified (1,1) logical = false
end

required = ["schemaVersion","caseId","modelRevision","bodyCase", ...
    "durationSeconds","reference","gust","initialCondition", ...
    "terminalTarget","controlMask","runtimeFamily","continuousRuntime", ...
    "stateResetAllowed","qualificationStatus","executionImplemented"];
missing = required(~isfield(definition,required));
assert(isempty(missing),"AeroFlex:CustomCaseDefinitionFields", ...
    "Custom definition is missing: %s",strjoin(missing,", "));
assert(string(definition.schemaVersion)== ...
    "pazy-custom-case-definition-v1", ...
    "AeroFlex:CustomCaseDefinitionSchema", ...
    "Unsupported custom-case definition schema.");

repositoryRoot = string(fileparts(fileparts(mfilename("fullpath"))));
outputRoot = options.OutputRoot;
if strlength(outputRoot)==0
    outputRoot = fullfile(repositoryRoot,"results","custom", ...
        lower(string(definition.name)));
end
executionImplemented = localExecutionImplemented(definition);
plan = struct( ...
    "schemaVersion","pazy-benchmark-execution-plan-v1", ...
    "requestedCaseId",string(definition.caseId), ...
    "caseId",string(definition.caseId), ...
    "modelRevision",string(definition.modelRevision), ...
    "bodyCase",string(definition.bodyCase), ...
    "durationSeconds",double(definition.durationSeconds), ...
    "controllerMode",options.ControllerMode, ...
    "diagnosticsLevel",options.DiagnosticsLevel, ...
    "diagnosticsEnabled",options.DiagnosticsLevel>0, ...
    "figuresVisible",options.FiguresVisible, ...
    "savePlots",options.SavePlots, ...
    "publicationMode",options.PublicationMode, ...
    "outputRoot",outputRoot, ...
    "runId",options.RunId, ...
    "nativeKernelPolicy",options.NativeKernelPolicy, ...
    "qualificationStatus","CUSTOM_VALIDATION_PENDING", ...
    "qualified",false, ...
    "allowUnqualified",options.AllowUnqualified, ...
    "runtimeFamily",string(definition.runtimeFamily), ...
    "continuousRuntime",logical(definition.continuousRuntime), ...
    "stateResetAllowed",logical(definition.stateResetAllowed), ...
    "reference",definition.reference, ...
    "terminalTarget",definition.terminalTarget, ...
    "gust",definition.gust, ...
    "initialCondition",definition.initialCondition, ...
    "controlMask",definition.controlMask, ...
    "executionAllowed",executionImplemented, ...
    "available",executionImplemented, ...
    "unavailableReason",string(definition.executionRequirement), ...
    "evidence","CUSTOM_CASE_SPECIFIC_EVIDENCE_REQUIRED", ...
    "runner","custom_scheduled_production", ...
    "runnerKind","custom_scheduled_v17a", ...
    "referenceType","custom_continuous_guidance", ...
    "subcase","custom", ...
    "commandEnabled",true, ...
    "gustEnabled",logical(definition.gust.enabled), ...
    "runtimeAcceleration",struct(), ...
    "protectedRuntime", ...
        AeroFlex.benchmark.internal.runtimeProfile("B1"), ...
    "innerLoopEnabled",options.ControllerMode=="full", ...
    "holdNmpcAtTrim",options.ControllerMode=="outer_only", ...
    "customScenario",definition, ...
    "executed",false, ...
    "formalCasesModified",false, ...
    "handoffPolicy","single_continuous_runtime_no_implicit_reset");
summary = struct("status","PLAN_ONLY","caseId",plan.caseId, ...
    "qualificationStatus",plan.qualificationStatus, ...
    "executed",false,"plan",plan);
if ~options.Execute
    return
end
assert(plan.executionAllowed,"AeroFlex:CustomCaseExecutionUnavailable", ...
    "The custom case is valid for planning but is outside the supported " + ...
    "scheduled coupled-full speed/pitch execution scope.");
assert(options.ControllerMode=="full", ...
    "AeroFlex:CustomCaseControllerMode", ...
    "The first custom scheduled adapter requires ControllerMode='full'.");

entryTimer = tic;
projectInfo = setupProject(ValidateEntryPoints=true);
if options.NativeKernelPolicy=="required"
    assert(projectInfo.scheduledCompiledControl.active, ...
        "AeroFlex:CustomCaseNativeKernelRequired", ...
        "The required scheduled native kernels are unavailable.");
end
layout = AeroFlex.benchmark.outputLayout(plan,Create=true);
plan.outputRoot = layout.runRoot;

oldVisibility = get(groot,"DefaultFigureVisible");
initialFigures = findall(groot,"Type","figure");
if plan.figuresVisible
    set(groot,"DefaultFigureVisible","on");
else
    set(groot,"DefaultFigureVisible","off");
end
figureCleanup = onCleanup(@()localRestoreFigures( ...
    oldVisibility,initialFigures));

AeroFlex.benchmark.printBanner(plan,"start");
preparationSeconds = toc(entryTimer);
wallTimer = tic;
executionError = [];
try
    summary = AeroFlex.benchmark.internal.executePlan(plan,layout.runRoot);
catch exception
    executionError = exception;
    artifact = AeroFlex.benchmark.internal.recoverExecutionArtifact( ...
        layout.runRoot);
    if artifact.available && ...
            string(exception.identifier)=="Phase18C:CaseBProfile"
        summary = artifact.summary;
        summary.status = "VALIDATION_PENDING_"+string(summary.status);
        summary.executionError = struct("identifier", ...
            string(exception.identifier),"message",string(exception.message));
    else
        summary = struct("status","ERROR","caseId",plan.caseId, ...
            "executionError",struct("identifier", ...
            string(exception.identifier),"message",string(exception.message)));
    end
end
wallSeconds = toc(wallTimer);

plan.executed = true;
plan.preparationSeconds = preparationSeconds;
summary.entryPlan = plan;
summary.wallSeconds = wallSeconds;
summary.preparationSeconds = preparationSeconds;
summary.outputLayout = layout;
products = AeroFlex.benchmark.finalizeResults( ...
    summary,plan,layout,wallSeconds);
summary.products = products;
summary.onlineWallSeconds = products.metrics.onlineWallSeconds;
summary.onlineRealTimeFactor = products.metrics.wallRealTimeFactor;
summary.totalEntryWallSeconds = toc(entryTimer);
summary.manifest = AeroFlex.benchmark.writeManifest( ...
    plan,layout,summary,projectInfo);
AeroFlex.benchmark.printBanner(plan,"complete",struct( ...
    "status",localSummaryStatus(summary), ...
    "onlineWallSeconds",summary.onlineWallSeconds, ...
    "runnerExecutionWallSeconds",wallSeconds, ...
    "preparationSeconds",preparationSeconds, ...
    "totalEntryWallSeconds",summary.totalEntryWallSeconds, ...
    "runRoot",layout.runRoot));
clear figureCleanup
if ~isempty(executionError)
    artifact = AeroFlex.benchmark.internal.recoverExecutionArtifact( ...
        layout.runRoot);
    if ~(artifact.available && ...
            string(executionError.identifier)=="Phase18C:CaseBProfile")
        rethrow(executionError)
    end
end
end

function status = localSummaryStatus(summary)
if isfield(summary,"status")
    status = string(summary.status);
else
    status = "COMPLETED";
end
end

function localRestoreFigures(oldVisibility,initialFigures)
currentFigures = findall(groot,"Type","figure");
newFigures = setdiff(currentFigures,initialFigures);
if ~isempty(newFigures)
    delete(newFigures);
end
set(groot,"DefaultFigureVisible",oldVisibility);
end

function implemented = localExecutionImplemented(definition)
initialStatus = AeroFlex.benchmark.internal. ...
    customInitialConditionStatus(definition.initialCondition);
implemented = logical(definition.executionImplemented) && ...
    string(definition.runtimeFamily)=="scheduled" && ...
    string(definition.bodyCase)=="coupled_full" && ...
    isempty(definition.reference.altitudeM) && ...
    ~logical(definition.controlMask.altitude) && ...
    ~logical(definition.controlMask.roll) && ...
    ~logical(definition.controlMask.yaw) && ...
    initialStatus.supported;
end
