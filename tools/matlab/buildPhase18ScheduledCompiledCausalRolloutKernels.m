function report = buildPhase18ScheduledCompiledCausalRolloutKernels(options)
%BUILDPHASE18SCHEDULEDCOMPILEDCAUSALROLLOUTKERNELS Build exact rollout MEX.

arguments
    options.Force (1,1) logical = false
    options.TimingRepetitions (1,1) double {mustBeInteger,mustBePositive} = 5
end

project = setupProject();
repoRoot = char(project.repositoryRoot);
changeId = "phase18c-v17a-casebc-high-leverage-runtime-audit-v1";
assert(~isempty(which('coder.config')), ...
    'Phase18ScheduledCausalRollout:MatlabCoderRequired', ...
    'MATLAB Coder is required; the exact per-interval fallback remains available.');
compiler = mex.getCompilerConfigurations('C++','Selected');
assert(~isempty(compiler), ...
    'Phase18ScheduledCausalRollout:CompilerRequired', ...
    'Configure a supported C++ compiler with mex -setup C++.');

[fixture,fixturePath] = loadBenchmarkNativeBuildFixture( ...
    "scheduled",string(repoRoot));
sourcePaths = [ ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalIntervalKernelAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalCausalRolloutCoreAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalEstimatorCausalRolloutAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalControllerCausalRolloutAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'buildScheduledReciprocalIntervalPacketAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'buildScheduledReciprocalHorizonPacketAudit.m')); ...
    fixturePath];
sourceRecords = localRecords(sourcePaths,repoRoot);
sourceSignature = localTextHash(strjoin( ...
    string({sourceRecords.sha256}),"|"));
releaseName = string(version('-release'));
architecture = string(computer('arch'));
cacheRoot = fullfile(repoRoot,'MatlabFlex','cache', ...
    'compiled_control_scheduled_causal_rollout',releaseName,architecture, ...
    extractBefore(sourceSignature,17));
if ~isfolder(cacheRoot), mkdir(cacheRoot); end
manifestPath = fullfile(cacheRoot, ...
    'PHASE18_SCHEDULED_COMPILED_CAUSAL_ROLLOUT_MANIFEST.json');
buildRoot = fullfile(tempdir,'AeroFlexScheduledCausalRolloutBuild', ...
    releaseName,architecture,extractBefore(sourceSignature,17));
if ~isfolder(buildRoot), mkdir(buildRoot); end

[context,state] = localFixture(fixture);
estimatorInputs = localInputs(context,state,8);
controllerInputs = localInputs(context,state,10);
entries = [ ...
    struct('label',"estimator_causal_rollout",'horizonLength',8, ...
        'entryName',"AeroFlex.ctrl."+ ...
            "scheduledReciprocalEstimatorCausalRolloutAudit", ...
        'mexName',"pazy_est_causal_rollout_mex", ...
        'inputs',{estimatorInputs}); ...
    struct('label',"controller_causal_rollout",'horizonLength',10, ...
        'entryName',"AeroFlex.ctrl."+ ...
            "scheduledReciprocalControllerCausalRolloutAudit", ...
        'mexName',"pazy_ctl_causal_rollout_mex", ...
        'inputs',{controllerInputs})];

startedUtc = localUtcNow();
recordCells = cell(numel(entries),1);
for index = 1:numel(entries)
    recordCells{index} = localBuildEntry(entries(index),cacheRoot, ...
        buildRoot,manifestPath,sourceSignature,releaseName,architecture, ...
        options,repoRoot);
end
records = vertcat(recordCells{:});
report = struct( ...
    'schemaVersion', ...
        "phase18-scheduled-compiled-causal-rollout-manifest-v1", ...
    'changeId',changeId,'passed',all([records.passed]), ...
    'startedUtc',startedUtc,'endedUtc',localUtcNow(), ...
    'matlabRelease',releaseName,'matlabVersion',string(version), ...
    'architecture',architecture,'mexExtension',string(mexext), ...
    'sourceSignature',sourceSignature,'sourceFiles',sourceRecords, ...
    'compiler',struct('name',string(compiler.Name), ...
        'version',string(compiler.Version), ...
        'location',string(compiler.Location)), ...
    'entries',records, ...
    'fallback',"exact scheduled per-interval compiled/MATLAB path", ...
    'timingExclusions',["setup","fixture load","build","hashing", ...
        "first call and JIT","serialization","plotting"]);
localWriteJson(manifestPath,report);
assert(report.passed,'Phase18ScheduledCausalRollout:Gate', ...
    'At least one causal-rollout entry failed its parity/speed gate.');
fprintf(['Scheduled causal-rollout kernels: PASS. Estimator/controller ', ...
    '%.2fx/%.2fx versus repeated interval MEX calls.\n'], ...
    records(1).timing.speedup,records(2).timing.speedup);
end

function record = localBuildEntry(entry,cacheRoot,buildRoot,manifestPath, ...
        sourceSignature,releaseName,architecture,options,repoRoot)
mexName = char(entry.mexName);
mexPath = fullfile(cacheRoot,[mexName,'.',mexext]);
buildMexPath = fullfile(buildRoot,[mexName,'.',mexext]);
cached = false;
if ~options.Force && isfile(mexPath) && isfile(manifestPath)
    prior = jsondecode(fileread(manifestPath));
    if isfield(prior,'entries')
        match = find(string({prior.entries.label})==entry.label,1);
        if ~isempty(match)
            old = prior.entries(match);
            cached = logical(old.passed) && ...
                string(prior.matlabRelease)==releaseName && ...
                string(prior.architecture)==architecture && ...
                string(prior.sourceSignature)==sourceSignature && ...
                string(old.binarySha256)==localFileHash(mexPath);
        end
    end
end

buildSeconds = 0;
if ~cached
    configuration = coder.config('mex');
    configuration.TargetLang = 'C++';
    configuration.GenerateReport = false;
    buildTimer = tic;
    previousFolder = pwd;
    folderCleanup = onCleanup(@() cd(previousFolder));
    cd(buildRoot);
    entryPath = resolveBenchmarkCodegenEntry(entry.entryName, ...
        struct("repositoryRoot",string(repoRoot)));
    codegen(char(entryPath),'-config',configuration, ...
        '-args',entry.inputs,'-o',mexName,'-d',buildRoot);
    clear folderCleanup
    cd(previousFolder);
    buildSeconds = toc(buildTimer);
    assert(isfile(buildMexPath), ...
        'Phase18ScheduledCausalRollout:LocalBinaryMissing', ...
        'Code generation did not produce %s.',buildMexPath);
    [copied,message] = copyfile(buildMexPath,mexPath,'f');
    assert(copied,'Phase18ScheduledCausalRollout:CacheCopy', ...
        'Cannot copy the compiled kernel: %s',message);
end
addpath(cacheRoot,'-begin');
clear(mexName);
[parity,timing] = localParityAndTiming(entry,mexName,options);
record = struct('label',entry.label, ...
    'horizonLength',double(entry.horizonLength), ...
    'entryName',entry.entryName,'functionName',entry.mexName, ...
    'passed',parity.passed && timing.speedup>1, ...
    'cached',cached,'buildSeconds',buildSeconds, ...
    'binaryPath',localRelative(mexPath,repoRoot), ...
    'binarySha256',localFileHash(mexPath), ...
    'parity',parity,'timing',timing);
end

function [parity,timing] = localParityAndTiming(entry,mexName,options)
inputs = entry.inputs;
reference = localRepeatedIntervalMex(inputs);
matlabValue = feval(char(entry.entryName),inputs{:});
actual = feval(mexName,inputs{:});
matlabError = norm(matlabValue-reference,inf);
mexError = norm(actual-reference,inf);
parity = struct('executed',true, ...
    'passed',matlabError<=2e-11 && mexError==0, ...
    'matlabToIntervalErrorInfinity',matlabError, ...
    'mexToIntervalErrorInfinity',mexError);

localRepeatedIntervalMex(inputs);
feval(mexName,inputs{:});
repetitions = double(options.TimingRepetitions);
intervalTimer = tic;
for index = 1:repetitions
    localRepeatedIntervalMex(inputs);
end
intervalSeconds = toc(intervalTimer)/repetitions;
rolloutTimer = tic;
for index = 1:repetitions
    feval(mexName,inputs{:});
end
rolloutSeconds = toc(rolloutTimer)/repetitions;
timing = struct('repetitions',repetitions, ...
    'repeatedIntervalMexSeconds',intervalSeconds, ...
    'causalRolloutMexSeconds',rolloutSeconds, ...
    'speedup',intervalSeconds/rolloutSeconds);
end

function endpoints = localRepeatedIntervalMex(inputs)
state = [inputs{1};inputs{2}];
disturbances = inputs{3};
wingTotal = inputs{4};
wingIncrement = inputs{5};
elevator = inputs{6};
thrust = inputs{7};
rigid = inputs{8};
packets = inputs{9};
horizonLength = numel(disturbances);
endpoints = zeros(620,horizonLength);
intervalMex = 'AeroFlex_ctrl_scheduledReciprocalIntervalKernelAudit_mex';
assert(~isempty(which(intervalMex)), ...
    'Phase18ScheduledCausalRollout:IntervalMexMissing', ...
    'The qualified scheduled interval MEX is required as the reference.');
for interval = 1:horizonLength
    state = feval(intervalMex,state,disturbances(interval), ...
        wingTotal(:,:,interval),wingIncrement(:,:,interval), ...
        elevator(:,:,interval),thrust(:,:,interval), ...
        rigid(:,:,interval),false,packets(interval));
    endpoints(:,interval) = state;
end
end

function inputs = localInputs(context,state,horizonLength)
contexts = repmat({context},1,horizonLength);
packets = AeroFlex.ctrl.buildScheduledReciprocalHorizonPacketAudit(contexts);
disturbances = linspace(0.013,0.017,horizonLength);
wingTotal = repmat(context.wingTotal,1,1,horizonLength);
wingIncrement = repmat(context.wingIncrement,1,1,horizonLength);
elevator = repmat(context.elevatorIncrement,1,1,horizonLength);
thrust = repmat(context.thrustIncrement,1,1,horizonLength);
rigid = repmat(context.rigidState,1,1,horizonLength);
inputs = {state(1:74),state(75:620),disturbances,wingTotal, ...
    wingIncrement,elevator,thrust,rigid,packets};
end

function [context,state] = localFixture(fixture)
context = fixture.context;
state = fixture.state;
end

function records = localRecords(paths,repoRoot)
records = repmat(struct('path',"",'sha256',""),numel(paths),1);
for index = 1:numel(paths)
    assert(isfile(paths(index)), ...
        'Phase18ScheduledCausalRollout:SourceMissing', ...
        'Required source file is missing: %s.',paths(index));
    records(index).path = localRelative(paths(index),repoRoot);
    records(index).sha256 = localFileHash(paths(index));
end
end

function localWriteJson(pathOut,value)
text = jsonencode(value,'PrettyPrint',true);
file = fopen(pathOut,'w');
assert(file>=0,'Phase18ScheduledCausalRollout:Manifest', ...
    'Cannot write %s.',pathOut);
cleanup = onCleanup(@() fclose(file));
fwrite(file,text,'char');
fwrite(file,newline,'char');
clear cleanup
end

function value = localFileHash(pathIn)
file = fopen(pathIn,'rb');
assert(file>=0,'Phase18ScheduledCausalRollout:HashRead', ...
    'Cannot read %s.',pathIn);
cleanup = onCleanup(@() fclose(file));
bytes = fread(file,inf,'*uint8');
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(bytes);
clear cleanup
value = lower(string(sprintf('%02x',typecast(engine.digest(),'uint8'))));
end

function value = localTextHash(input)
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(uint8(char(input)));
value = lower(string(sprintf('%02x',typecast(engine.digest(),'uint8'))));
end

function relative = localRelative(pathIn,repoRoot)
relative = string(pathIn);
prefix = string(repoRoot)+filesep;
if startsWith(relative,prefix)
    relative = extractAfter(relative,strlength(prefix));
end
relative = replace(relative,"\","/");
end

function value = localUtcNow()
value = string(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
