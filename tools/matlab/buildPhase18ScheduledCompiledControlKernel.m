function report = buildPhase18ScheduledCompiledControlKernel(options)
%BUILDPHASE18SCHEDULEDCOMPILEDCONTROLKERNEL Build scheduled interval MEX.

arguments
    options.Force (1,1) logical = false
    options.RunParity (1,1) logical = true
end

project = setupProject();
repoRoot = char(project.repositoryRoot);
changeId = ...
    "phase18c-v17a-casebc-scheduled-compiled-interval-kernel-audit-v1";
assert(~isempty(which('coder.config')), ...
    'Phase18ScheduledCompiledControl:MatlabCoderRequired', ...
    'MATLAB Coder is required; the exact MATLAB model bank remains available.');
compiler = mex.getCompilerConfigurations('C++','Selected');
assert(~isempty(compiler), ...
    'Phase18ScheduledCompiledControl:CompilerRequired', ...
    'Configure a supported C++ compiler with mex -setup C++.');

[fixture,fixturePath] = loadBenchmarkNativeBuildFixture( ...
    "scheduled",string(repoRoot));
sourcePaths = [ ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalIntervalKernelAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'buildScheduledReciprocalIntervalPacketAudit.m')); ...
    fixturePath];
sourceRecords = localRecords(sourcePaths,repoRoot);
sourceSignature = localTextHash(strjoin( ...
    string({sourceRecords.sha256}),"|"));
releaseName = string(version('-release'));
architecture = string(computer('arch'));
cacheRoot = fullfile(repoRoot,'MatlabFlex','cache', ...
    'compiled_control_scheduled',releaseName,architecture, ...
    extractBefore(sourceSignature,17));
if ~isfolder(cacheRoot), mkdir(cacheRoot); end
mexName = 'AeroFlex_ctrl_scheduledReciprocalIntervalKernelAudit_mex';
mexPath = fullfile(cacheRoot,[mexName,'.',mexext]);
manifestPath = fullfile(cacheRoot, ...
    'PHASE18_SCHEDULED_COMPILED_CONTROL_MANIFEST.json');
buildRoot = fullfile(tempdir,'AeroFlexScheduledCompiledControlBuild', ...
    releaseName,architecture,extractBefore(sourceSignature,17));
if ~isfolder(buildRoot), mkdir(buildRoot); end
buildMexPath = fullfile(buildRoot,[mexName,'.',mexext]);

[model,scheduledPacket,context,state] = localFixture(fixture);
packet = AeroFlex.ctrl.buildScheduledReciprocalIntervalPacketAudit( ...
    model,scheduledPacket);
cached = false;
if ~options.Force && isfile(mexPath) && isfile(manifestPath)
    prior = jsondecode(fileread(manifestPath));
    cached = isfield(prior,'passed') && logical(prior.passed) && ...
        string(prior.matlabRelease)==releaseName && ...
        string(prior.architecture)==architecture && ...
        string(prior.mexExtension)==string(mexext) && ...
        string(prior.sourceSignature)==sourceSignature && ...
        string(prior.binarySha256)==localFileHash(mexPath);
end

startedUtc = localUtcNow();
buildSeconds = 0;
if ~cached
    configuration = coder.config('mex');
    configuration.TargetLang = 'C++';
    configuration.GenerateReport = false;
    buildTimer = tic;
    previousFolder = pwd;
    folderCleanup = onCleanup(@() cd(previousFolder));
    cd(buildRoot);
    codegen('AeroFlex.ctrl.scheduledReciprocalIntervalKernelAudit', ...
        '-config',configuration,'-args',{state,0.013, ...
        context.wingTotal,context.wingIncrement, ...
        context.elevatorIncrement,context.thrustIncrement, ...
        context.rigidState,false,packet},'-o',mexName,'-d',buildRoot);
    clear folderCleanup
    cd(previousFolder);
    buildSeconds = toc(buildTimer);
    assert(isfile(buildMexPath), ...
        'Phase18ScheduledCompiledControl:LocalBinaryMissing', ...
        'Code generation did not produce %s.',buildMexPath);
    [copied,message] = copyfile(buildMexPath,mexPath,'f');
    assert(copied,'Phase18ScheduledCompiledControl:CacheCopy', ...
        'Cannot copy the compiled kernel into the cache: %s',message);
end

addpath(cacheRoot,'-begin');
clear(mexName);
parity = struct('executed',false,'passed',false, ...
    'stateErrorInfinity',nan,'sensitivityErrorInfinity',nan, ...
    'rootWrenchErrorInfinity',nan,'matlabSeconds',nan,'mexSeconds',nan, ...
    'speedup',nan);
if options.RunParity
    parity = localParity(model,scheduledPacket,context,state,packet,mexName);
    assert(parity.passed,'Phase18ScheduledCompiledControl:Parity', ...
        'The scheduled compiled kernel failed provider parity.');
end

report = struct( ...
    'schemaVersion',"phase18-scheduled-compiled-control-manifest-v1", ...
    'changeId',changeId,'passed',parity.passed || ~options.RunParity, ...
    'cached',cached,'startedUtc',startedUtc,'endedUtc',localUtcNow(), ...
    'buildSeconds',buildSeconds,'matlabRelease',releaseName, ...
    'matlabVersion',string(version),'architecture',architecture, ...
    'mexExtension',string(mexext),'sourceSignature',sourceSignature, ...
    'functionName',string(mexName),'sourceFiles',sourceRecords, ...
    'binaryPath',localRelative(mexPath,repoRoot), ...
    'binarySha256',localFileHash(mexPath), ...
    'compiler',struct('name',string(compiler.Name), ...
        'version',string(compiler.Version), ...
        'location',string(compiler.Location)), ...
    'command',"buildPhase18ScheduledCompiledControlKernel", ...
    'stateCount',620,'substepCount',14,'parity',parity, ...
    'fallback',"exact MATLAB scheduled reciprocal model bank");
localWriteJson(manifestPath,report);
fprintf(['Scheduled compiled control: ACTIVE (%s). Build %.3f s; ', ...
    'state/sensitivity/wrench %.3e/%.3e/%.3e; speedup %.2fx.\n'], ...
    string(compiler.Name),buildSeconds,parity.stateErrorInfinity, ...
    parity.sensitivityErrorInfinity,parity.rootWrenchErrorInfinity, ...
    parity.speedup);
end

function parity = localParity(model,packet,context,state,kernelPacket,mexName)
provider = AeroFlex.ctrl.ScheduledReciprocalControllerModelProvider( ...
    model,packet.members,packet.queryTrim);
provider.configureScheduledAggregateRuntime(struct( ...
    'enabled',true,'auditOnly',true,'changeId', ...
    "phase18c-v17a-casebc-scheduled-reciprocal-runtime-integration-v1"));
context.scheduledPacket = packet;
context.scheduledModel = model;
provider.applyScheduledPacket(model,packet);
[referenceState,referenceSensitivity] = provider.propagateInterval( ...
    state,0.013,context,true);
bank = AeroFlex.ctrl.ScheduledReciprocalControllerModelProvider( ...
    model,packet.members,packet.queryTrim);
[~,~,diagnostics] = bank.propagateInterval(state,0.013,context,true);
referenceWrench = zeros(6,14);
for substep = 1:14
    referenceWrench(:,substep) = diagnostics{substep}.sourceRootWrench;
end
[actualState,actualSensitivity,actualWrench] = feval(mexName, ...
    state,0.013,context.wingTotal,context.wingIncrement, ...
    context.elevatorIncrement,context.thrustIncrement, ...
    context.rigidState,true,kernelPacket);

matlabTimer = tic;
for repetition = 1:3
    AeroFlex.ctrl.scheduledReciprocalIntervalKernelAudit( ...
        state,0.013,context.wingTotal,context.wingIncrement, ...
        context.elevatorIncrement,context.thrustIncrement, ...
        context.rigidState,true,kernelPacket);
end
matlabSeconds = toc(matlabTimer)/3;
mexTimer = tic;
for repetition = 1:3
    feval(mexName,state,0.013,context.wingTotal,context.wingIncrement, ...
        context.elevatorIncrement,context.thrustIncrement, ...
        context.rigidState,true,kernelPacket);
end
mexSeconds = toc(mexTimer)/3;

stateError = norm(actualState-referenceState,inf);
sensitivityError = norm( ...
    actualSensitivity(:,1:621)-referenceSensitivity,inf);
wrenchError = norm(actualWrench-referenceWrench,inf);
parity = struct('executed',true, ...
    'passed',stateError<=2e-11 && sensitivityError<=2e-8 && ...
        wrenchError<=2e-9, ...
    'stateErrorInfinity',stateError, ...
    'sensitivityErrorInfinity',sensitivityError, ...
    'rootWrenchErrorInfinity',wrenchError, ...
    'matlabSeconds',matlabSeconds,'mexSeconds',mexSeconds, ...
    'speedup',matlabSeconds/mexSeconds);
end

function [model,packet,context,state] = localFixture(fixture)
model = fixture.model;
packet = fixture.packet;
context = fixture.context;
state = fixture.state;
end

function records = localRecords(paths,repoRoot)
records = repmat(struct('path',"",'sha256',""),numel(paths),1);
for index = 1:numel(paths)
    assert(isfile(paths(index)), ...
        'Phase18ScheduledCompiledControl:SourceMissing', ...
        'Required source file is missing: %s.',paths(index));
    records(index).path = localRelative(paths(index),repoRoot);
    records(index).sha256 = localFileHash(paths(index));
end
end

function localWriteJson(pathOut,value)
text = jsonencode(value,'PrettyPrint',true);
file = fopen(pathOut,'w');
assert(file>=0,'Phase18ScheduledCompiledControl:Manifest', ...
    'Cannot write %s.',pathOut);
cleanup = onCleanup(@() fclose(file));
fwrite(file,text,'char');
fwrite(file,newline,'char');
clear cleanup
end

function value = localFileHash(pathIn)
file = fopen(pathIn,'rb');
assert(file>=0,'Phase18ScheduledCompiledControl:HashRead', ...
    'Cannot read %s.',pathIn);
cleanup = onCleanup(@() fclose(file));
bytes = fread(file,inf,'*uint8');
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(bytes);
clear cleanup
digest = typecast(engine.digest(),'uint8');
value = lower(string(sprintf('%02x',digest)));
end

function value = localTextHash(text)
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(uint8(char(text)));
digest = typecast(engine.digest(),'uint8');
value = lower(string(sprintf('%02x',digest)));
end

function relative = localRelative(pathIn,repoRoot)
relative = string(pathIn);
prefix = string(repoRoot)+filesep;
if startsWith(relative,prefix)
    relative = extractAfter(relative,strlength(prefix));
end
relative = replace(relative,"\","/");
end

function value = localUtcNow()
value = string(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
