function report = buildPhase18CompiledControlKernels(options)
%BUILDPHASE18COMPILEDCONTROLKERNELS Build and verify control MEX kernels.
%   report = buildPhase18CompiledControlKernels() detects the active MATLAB
%   release, architecture, MATLAB Coder, and selected C++ compiler; builds
%   the fixed reciprocal interval kernel into an ignored deterministic
%   cache; and verifies it against the authoritative MATLAB provider.

arguments
    options.Force (1,1) logical = false
    options.RunParity (1,1) logical = true
end

project = setupProject();
repoRoot = char(project.repositoryRoot);
entryPath = resolveBenchmarkCodegenEntry( ...
    "AeroFlex.ctrl.fixedReciprocalIntervalKernelAudit",project);
changeId = ...
    "phase18c-v17a-condensed-rti-compiled-runtime-owner-promotion-v1";
assert(~isempty(which('coder.config')), ...
    'Phase18CompiledControl:MatlabCoderRequired', ...
    ['MATLAB Coder is required to build the accelerated control kernel. ', ...
     'The exact MATLAB provider remains available without it.']);
compiler = mex.getCompilerConfigurations('C++','Selected');
assert(~isempty(compiler), ...
    'Phase18CompiledControl:CompilerRequired', ...
    ['No supported C++ compiler is selected. Configure one with mex -setup ', ...
     'C++ and rerun buildPhase18CompiledControlKernels.']);

[fixture,fixturePath] = loadBenchmarkNativeBuildFixture( ...
    "fixed_interval",string(repoRoot));
sourcePaths = [ ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'fixedReciprocalIntervalKernelAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'buildFixedReciprocalIntervalPacketAudit.m')); ...
    fixturePath];
sourceRecords = localRecords(sourcePaths,repoRoot);
sourceSignature = localTextHash(strjoin( ...
    string({sourceRecords.sha256}),"|"));
releaseName = string(version('-release'));
architecture = string(computer('arch'));
cacheRoot = fullfile(repoRoot,'MatlabFlex','cache','compiled_control', ...
    releaseName,architecture,extractBefore(sourceSignature,17));
if ~isfolder(cacheRoot)
    mkdir(cacheRoot);
end
mexName = 'AeroFlex_ctrl_fixedReciprocalIntervalKernelProduction_mex';
mexPath = fullfile(cacheRoot,[mexName,'.',mexext]);
manifestPath = fullfile(cacheRoot,'PHASE18_COMPILED_CONTROL_MANIFEST.json');
buildRoot = fullfile(tempdir,'AeroFlexCompiledControlBuild', ...
    releaseName,architecture,extractBefore(sourceSignature,17));
if ~isfolder(buildRoot)
    mkdir(buildRoot);
end
buildMexPath = fullfile(buildRoot,[mexName,'.',mexext]);

provider = fixture.provider;
state = fixture.state;
disturbance = fixture.disturbance;
context = fixture.context;
packet = fixture.packet;

cached = false;
if ~options.Force && isfile(mexPath) && isfile(manifestPath)
    prior = jsondecode(fileread(manifestPath));
    cached = isfield(prior,'passed') && logical(prior.passed) && ...
        string(prior.matlabRelease)==releaseName && ...
        string(prior.architecture)==architecture && ...
        string(prior.mexExtension)==string(mexext) && ...
        string(prior.sourceSignature)==sourceSignature && ...
        string(prior.binarySha256)==localFileHash(mexPath);
end

startedUtc = localUtcNow();
buildSeconds = 0;
if ~cached
    configuration = coder.config('mex');
    configuration.TargetLang = 'C++';
    configuration.GenerateReport = false;
    buildTimer = tic;
    previousFolder = pwd;
    folderCleanup = onCleanup(@() cd(previousFolder));
    cd(buildRoot);
    codegen(char(entryPath), ...
        '-config',configuration,'-args',{state,disturbance, ...
        context.wingTotal,context.wingIncrement, ...
        context.elevatorIncrement,context.thrustIncrement, ...
        context.rigidState,false,packet},'-o',mexName,'-d',buildRoot);
    clear folderCleanup
    cd(previousFolder);
    buildSeconds = toc(buildTimer);
    assert(isfile(buildMexPath), ...
        'Phase18CompiledControl:LocalBinaryMissing', ...
        'Code generation did not produce %s.',buildMexPath);
    [copied,message] = copyfile(buildMexPath,mexPath,'f');
    assert(copied,'Phase18CompiledControl:CacheCopy', ...
        'Cannot copy the compiled kernel into the repository cache: %s', ...
        message);
end

assert(isfile(mexPath), ...
    'Phase18CompiledControl:BinaryMissing', ...
    'Code generation did not produce %s.',mexPath);
addpath(cacheRoot,'-begin');
clear(mexName);
parity = struct('executed',false,'passed',false, ...
    'stateErrorInfinity',nan,'sensitivityErrorInfinity',nan, ...
    'rootWrenchErrorInfinity',nan);
if options.RunParity
    parity = localParity(provider,state,disturbance,context,packet,mexName);
    assert(parity.passed,'Phase18CompiledControl:Parity', ...
        'The compiled control kernel failed its authoritative parity smoke.');
end

report = struct( ...
    'schemaVersion',"phase18-compiled-control-manifest-v1", ...
    'changeId',changeId,'passed',parity.passed || ~options.RunParity, ...
    'cached',cached,'startedUtc',startedUtc,'endedUtc',localUtcNow(), ...
    'buildSeconds',buildSeconds,'matlabRelease',releaseName, ...
    'matlabVersion',string(version),'architecture',architecture, ...
    'mexExtension',string(mexext),'sourceSignature',sourceSignature, ...
    'functionName',string(mexName), ...
    'sourceFiles',sourceRecords,'binaryPath',localRelative(mexPath,repoRoot), ...
    'binarySha256',localFileHash(mexPath), ...
    'compiler',struct('name',string(compiler.Name), ...
        'version',string(compiler.Version),'location',string(compiler.Location)), ...
    'command',"buildPhase18CompiledControlKernels",'parity',parity, ...
    'fallback',"exact MATLAB ReciprocalControllerModelProvider");
localWriteJson(manifestPath,report);
fprintf(['Compiled control acceleration: ACTIVE (%s, %s, %s). ', ...
    'Build %.3f s; state/sensitivity/wrench errors %.3e/%.3e/%.3e.\n'], ...
    releaseName,architecture,string(compiler.Name),buildSeconds, ...
    parity.stateErrorInfinity,parity.sensitivityErrorInfinity, ...
    parity.rootWrenchErrorInfinity);
end

function parity = localParity(provider,state,disturbance,context,packet,mexName)
[referenceState,referenceSensitivity,diagnostics] = ...
    provider.propagateInterval(state,disturbance,context,true);
referenceWrench = zeros(6,16);
for substep = 1:16
    referenceWrench(:,substep) = diagnostics{substep}.sourceRootWrench;
end
[actualState,actualSensitivity,actualWrench] = feval(mexName, ...
    state,disturbance,context.wingTotal,context.wingIncrement, ...
    context.elevatorIncrement,context.thrustIncrement, ...
    context.rigidState,true,packet);
stateError = norm(actualState-referenceState,inf);
sensitivityError = norm( ...
    actualSensitivity(:,1:122)-referenceSensitivity,inf);
wrenchError = norm(actualWrench-referenceWrench,inf);
parity = struct('executed',true, ...
    'passed',stateError<=1e-11 && sensitivityError<=1e-8 && ...
        wrenchError<=1e-9, ...
    'stateErrorInfinity',stateError, ...
    'sensitivityErrorInfinity',sensitivityError, ...
    'rootWrenchErrorInfinity',wrenchError);
end

function records = localRecords(paths,repoRoot)
records = repmat(struct('path',"",'sha256',""),numel(paths),1);
for index = 1:numel(paths)
    assert(isfile(paths(index)), ...
        'Phase18CompiledControl:SourceMissing', ...
        'Required source file is missing: %s.',paths(index));
    records(index).path = localRelative(paths(index),repoRoot);
    records(index).sha256 = localFileHash(paths(index));
end
end

function localWriteJson(pathOut,value)
text = jsonencode(value,'PrettyPrint',true);
file = fopen(pathOut,'w');
assert(file>=0,'Phase18CompiledControl:Manifest', ...
    'Cannot write %s.',pathOut);
cleanup = onCleanup(@() fclose(file));
fwrite(file,text,'char');
fwrite(file,newline,'char');
clear cleanup
end

function value = localFileHash(pathIn)
file = fopen(pathIn,'rb');
assert(file>=0,'Phase18CompiledControl:HashRead', ...
    'Cannot read %s for hashing.',pathIn);
cleanup = onCleanup(@() fclose(file));
bytes = fread(file,inf,'*uint8');
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(bytes);
clear cleanup
digest = typecast(engine.digest(),'uint8');
value = lower(string(sprintf('%02x',digest)));
end

function value = localTextHash(text)
engine = java.security.MessageDigest.getInstance('SHA-256');
engine.update(uint8(char(text)));
digest = typecast(engine.digest(),'uint8');
value = lower(string(sprintf('%02x',digest)));
end

function relative = localRelative(pathIn,repoRoot)
relative = string(pathIn);
prefix = string(repoRoot)+filesep;
if startsWith(relative,prefix)
    relative = extractAfter(relative,strlength(prefix));
end
relative = replace(relative,"\","/");
end

function value = localUtcNow()
value = string(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
