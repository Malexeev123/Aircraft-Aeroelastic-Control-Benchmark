function report = buildPhase18ScheduledCompiledHorizonKernels(options)
%BUILDPHASE18SCHEDULEDCOMPILEDHORIZONKERNELS Build exact Ne=8/Nc=10 MEX.

arguments
    options.Force (1,1) logical = false
    options.RunParity (1,1) logical = true
    options.TimingRepetitions (1,1) double {mustBeInteger,mustBePositive} = 3
end

project = setupProject();
repoRoot = char(project.repositoryRoot);
changeId = "phase18c-v17a-casebc-native-reduced-horizon-rti-audit-v1";
assert(~isempty(which('coder.config')), ...
    'Phase18ScheduledHorizon:MatlabCoderRequired', ...
    'MATLAB Coder is required; exact interval fallback remains available.');
compiler = mex.getCompilerConfigurations('C++','Selected');
assert(~isempty(compiler), ...
    'Phase18ScheduledHorizon:CompilerRequired', ...
    'Configure a supported C++ compiler with mex -setup C++.');

[fixture,fixturePath] = loadBenchmarkNativeBuildFixture( ...
    "scheduled",string(repoRoot));
sourcePaths = [ ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalIntervalKernelAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalHorizonKernelCoreAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalEstimatorHorizonKernelAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalControllerHorizonKernelAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'buildScheduledReciprocalIntervalPacketAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'buildScheduledReciprocalHorizonPacketAudit.m'))];
sourcePaths = [sourcePaths; ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalReducedTangentHorizonCoreAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalEstimatorReducedTangentHorizonAudit.m')); ...
    string(fullfile(repoRoot,'MatlabFlex','+AeroFlex','+ctrl', ...
        'scheduledReciprocalControllerReducedTangentHorizonAudit.m')); ...
    fixturePath];
sourceRecords = localRecords(sourcePaths,repoRoot);
sourceSignature = localTextHash(strjoin( ...
    string({sourceRecords.sha256}),"|"));
releaseName = string(version('-release'));
architecture = string(computer('arch'));
cacheRoot = fullfile(repoRoot,'MatlabFlex','cache', ...
    'compiled_control_scheduled_horizon',releaseName,architecture, ...
    extractBefore(sourceSignature,17));
if ~isfolder(cacheRoot), mkdir(cacheRoot); end
manifestPath = fullfile(cacheRoot, ...
    'PHASE18_SCHEDULED_COMPILED_HORIZON_MANIFEST.json');
buildRoot = fullfile(tempdir,'AeroFlexScheduledHorizonBuild', ...
    releaseName,architecture,extractBefore(sourceSignature,17));
if ~isfolder(buildRoot), mkdir(buildRoot); end

[context,state] = localFixture(fixture);
estimatorInputs = localInputs(context,state,8);
controllerInputs = localInputs(context,state,10);
[estimatorReducedInputs,controllerReducedInputs] = ...
    localReducedInputs(context,state);
entries = [ ...
    struct('label',"estimator_full",'kind',"full",'horizonLength',8, ...
        'entryName',"AeroFlex.ctrl."+ ...
            "scheduledReciprocalEstimatorHorizonKernelAudit", ...
        'mexName',"AeroFlex_ctrl_"+ ...
            "scheduledReciprocalEstimatorHorizonKernelAudit_mex", ...
        'inputs',{estimatorInputs}); ...
    struct('label',"controller_full",'kind',"full",'horizonLength',10, ...
        'entryName',"AeroFlex.ctrl."+ ...
            "scheduledReciprocalControllerHorizonKernelAudit", ...
        'mexName',"AeroFlex_ctrl_"+ ...
            "scheduledReciprocalControllerHorizonKernelAudit_mex", ...
        'inputs',{controllerInputs}); ...
    struct('label',"estimator_reduced_tangent",'kind',"reduced", ...
        'horizonLength',8,'entryName',"AeroFlex.ctrl."+ ...
            "scheduledReciprocalEstimatorReducedTangentHorizonAudit", ...
        'mexName',"AeroFlex_ctrl_"+ ...
            "scheduledReciprocalEstimatorReducedTangentHorizonAudit_mex", ...
        'inputs',{estimatorReducedInputs}); ...
    struct('label',"controller_reduced_tangent",'kind',"reduced", ...
        'horizonLength',10,'entryName',"AeroFlex.ctrl."+ ...
            "scheduledReciprocalControllerReducedTangentHorizonAudit", ...
        'mexName',"AeroFlex_ctrl_"+ ...
            "scheduledReciprocalControllerReducedTangentHorizonAudit_mex", ...
        'inputs',{controllerReducedInputs})];

startedUtc = localUtcNow();
recordCells = cell(numel(entries),1);
for index = 1:numel(entries)
    recordCells{index} = localBuildEntry(entries(index),cacheRoot, ...
        buildRoot,manifestPath,sourceSignature,releaseName,architecture, ...
        options,repoRoot);
end
records = vertcat(recordCells{:});

report = struct( ...
    'schemaVersion',"phase18-scheduled-compiled-horizon-manifest-v1", ...
    'changeId',changeId,'passed',all([records.passed]), ...
    'startedUtc',startedUtc,'endedUtc',localUtcNow(), ...
    'matlabRelease',releaseName,'matlabVersion',string(version), ...
    'architecture',architecture,'mexExtension',string(mexext), ...
    'sourceSignature',sourceSignature,'sourceFiles',sourceRecords, ...
    'compiler',struct('name',string(compiler.Name), ...
        'version',string(compiler.Version), ...
        'location',string(compiler.Location)), ...
    'entries',records, ...
    'fallback',"exact scheduled per-interval compiled/MATLAB path", ...
    'setupExcludedTiming',true);
localWriteJson(manifestPath,report);
assert(report.passed,'Phase18ScheduledHorizon:Gate', ...
    'At least one compiled horizon entry failed its parity gate.');
fprintf(['Scheduled horizon kernels: PASS. Full estimator/controller ', ...
    '%.2fx/%.2fx; reduced tangent %.2fx/%.2fx versus repeated compiled ', ...
    'interval calls and equivalent MATLAB recursion.\n'], ...
    records(1).timing.speedup,records(2).timing.speedup, ...
    records(3).timing.speedup,records(4).timing.speedup);
end

function record = localBuildEntry(entry,cacheRoot,buildRoot,manifestPath, ...
        sourceSignature,releaseName,architecture,options,repoRoot)
mexName = char(entry.mexName);
mexPath = fullfile(cacheRoot,[mexName,'.',mexext]);
buildMexPath = fullfile(buildRoot,[mexName,'.',mexext]);
cached = false;
if ~options.Force && isfile(mexPath) && isfile(manifestPath)
    prior = jsondecode(fileread(manifestPath));
    if isfield(prior,'entries')
        priorEntries = prior.entries;
        match = find(string({priorEntries.label})==entry.label,1);
        if ~isempty(match)
            old = priorEntries(match);
            cached = isfield(old,'passed') && logical(old.passed) && ...
                string(prior.matlabRelease)==releaseName && ...
                string(prior.architecture)==architecture && ...
                string(prior.sourceSignature)==sourceSignature && ...
                string(old.binarySha256)==localFileHash(mexPath);
        end
    end
end

buildSeconds = 0;
if ~cached
    configuration = coder.config('mex');
    configuration.TargetLang = 'C++';
    configuration.GenerateReport = false;
    buildTimer = tic;
    previousFolder = pwd;
    folderCleanup = onCleanup(@() cd(previousFolder));
    cd(buildRoot);
    codegen(char(entry.entryName),'-config',configuration, ...
        '-args',entry.inputs,'-o',mexName,'-d',buildRoot);
    clear folderCleanup
    cd(previousFolder);
    buildSeconds = toc(buildTimer);
    assert(isfile(buildMexPath), ...
        'Phase18ScheduledHorizon:LocalBinaryMissing', ...
        'Code generation did not produce %s.',buildMexPath);
    [copied,message] = copyfile(buildMexPath,mexPath,'f');
    assert(copied,'Phase18ScheduledHorizon:CacheCopy', ...
        'Cannot copy the compiled kernel: %s',message);
end
addpath(cacheRoot,'-begin');
clear(mexName);

parity = struct('executed',false,'passed',~options.RunParity);
timing = struct('repetitions',double(options.TimingRepetitions), ...
    'repeatedIntervalMexSeconds',nan,'horizonMexSeconds',nan, ...
    'speedup',nan);
if options.RunParity
    [parity,timing] = localParityAndTiming(entry,mexName,options);
end
record = struct('label',entry.label, ...
    'horizonLength',double(entry.horizonLength), ...
    'entryName',entry.entryName,'functionName',entry.mexName, ...
    'passed',parity.passed,'cached',cached,'buildSeconds',buildSeconds, ...
    'binaryPath',localRelative(mexPath,repoRoot), ...
    'binarySha256',localFileHash(mexPath), ...
    'parity',parity,'timing',timing);
end

function [parity,timing] = localParityAndTiming(entry,mexName,options)
inputs = entry.inputs;
[referenceEndpoint,referenceSensitivity,referenceWrench,referenceHistory] = ...
    feval(char(entry.entryName),inputs{:});
[actualEndpoint,actualSensitivity,actualWrench,actualHistory] = ...
    feval(mexName,inputs{:});
endpointError = norm(actualEndpoint-referenceEndpoint,inf);
sensitivityError = norm( ...
    actualSensitivity(:)-referenceSensitivity(:),inf);
wrenchError = norm(actualWrench(:)-referenceWrench(:),inf);
historyError = norm(actualHistory(:)-referenceHistory(:),inf);
passed = endpointError<=2e-11 && sensitivityError<=2e-8 && ...
    wrenchError<=2e-9 && historyError<=2e-11;
if entry.kind=="full"
    parity = struct('executed',true,'passed',passed, ...
        'endpointErrorInfinity',endpointError, ...
        'sensitivityErrorInfinity',sensitivityError, ...
        'rootWrenchErrorInfinity',wrenchError, ...
        'stateHistoryErrorInfinity',historyError);
else
    parity = struct('executed',true,'passed',passed, ...
        'endpointErrorInfinity',endpointError, ...
        'latentEndpointErrorInfinity',sensitivityError, ...
        'stateExpansionErrorInfinity',wrenchError, ...
        'stateOffsetErrorInfinity',historyError);
end

intervalMex = 'AeroFlex_ctrl_scheduledReciprocalIntervalKernelAudit_mex';
assert(~isempty(which(intervalMex)), ...
    'Phase18ScheduledHorizon:IntervalMexMissing', ...
    'The promoted scheduled interval MEX is required for timing comparison.');
if entry.kind=="full"
    referenceCall = @() localRepeatedIntervalMex(intervalMex,inputs);
else
    referenceCall = @() localReducedReferenceMex(intervalMex,entry,inputs);
end
referenceCall();
feval(mexName,inputs{:});
repetitions = double(options.TimingRepetitions);
intervalTimer = tic;
for index = 1:repetitions
    referenceCall();
end

function localReducedReferenceMex(intervalMex,entry,inputs)
nativeNodes = inputs{1};
latent = inputs{2};
if entry.horizonLength==8
    disturbances = inputs{3};
    wingTotal = inputs{4};
    wingIncrement = inputs{5};
    elevator = inputs{6};
    thrust = inputs{7};
    rigid = inputs{8};
    packets = inputs{9};
    reducedCount = 82;
    stateExpansion = [eye(74),zeros(74,8)];
    stateOffset = zeros(74,1);
    disturbanceExpansion = zeros(1,reducedCount,8);
    for interval = 1:8
        disturbanceExpansion(1,74+interval,interval) = 1;
    end
    wingExpansion = zeros(4,reducedCount,8);
else
    initialTarget = inputs{3};
    disturbances = inputs{4};
    wingTotal = inputs{5};
    wingIncrement = inputs{6};
    elevator = inputs{7};
    thrust = inputs{8};
    rigid = inputs{9};
    wingExpansion = inputs{10};
    packets = inputs{11};
    reducedCount = 10;
    stateExpansion = zeros(74,reducedCount);
    stateOffset = initialTarget(:)-nativeNodes(:,1);
    disturbanceExpansion = zeros(1,reducedCount,10);
end
directionCount = reducedCount+1;
stateDirections = zeros(620,directionCount);
stateDirections(1:74,1:reducedCount) = stateExpansion;
stateDirections(1:74,end) = stateOffset;
for interval = 1:double(entry.horizonLength)
    [endpoint,sensitivity] = feval(intervalMex, ...
        [nativeNodes(:,interval);latent],disturbances(interval), ...
        wingTotal(:,:,interval),wingIncrement(:,:,interval), ...
        elevator(:,:,interval),thrust(:,:,interval), ...
        rigid(:,:,interval),true,packets(interval));
    inputDirections = zeros(5,directionCount);
    inputDirections(1,1:reducedCount) = ...
        disturbanceExpansion(:,:,interval);
    inputDirections(2:5,1:reducedCount) = wingExpansion(:,:,interval);
    endpointDirections = sensitivity(:,1:620)*stateDirections+ ...
        sensitivity(:,621:625)*inputDirections;
    defect = nativeNodes(:,interval+1)-endpoint(1:74);
    stateExpansion = endpointDirections(1:74,1:reducedCount);
    stateOffset = endpointDirections(1:74,end)-defect;
    stateDirections(1:74,1:reducedCount) = stateExpansion;
    stateDirections(1:74,end) = stateOffset;
    stateDirections(75:620,:) = endpointDirections(75:620,:);
    latent = endpoint(75:620);
end
end
intervalSeconds = toc(intervalTimer)/repetitions;
horizonTimer = tic;
for index = 1:repetitions
    feval(mexName,inputs{:});
end
horizonSeconds = toc(horizonTimer)/repetitions;
timing = struct('repetitions',repetitions, ...
    'repeatedIntervalMexSeconds',intervalSeconds, ...
    'horizonMexSeconds',horizonSeconds, ...
    'speedup',intervalSeconds/horizonSeconds);
end

function localRepeatedIntervalMex(intervalMex,inputs)
nativeNodes = inputs{1};
latent = inputs{2};
disturbances = inputs{3};
wingTotal = inputs{4};
wingIncrement = inputs{5};
elevator = inputs{6};
thrust = inputs{7};
rigid = inputs{8};
packets = inputs{10};
for interval = 1:size(nativeNodes,2)
    [endpoint,~] = feval(intervalMex, ...
        [nativeNodes(:,interval);latent],disturbances(interval), ...
        wingTotal(:,:,interval),wingIncrement(:,:,interval), ...
        elevator(:,:,interval),thrust(:,:,interval), ...
        rigid(:,:,interval),true,packets(interval));
    latent = endpoint(75:620);
end
end

