    wingIncrement,elevator,thrust,rigid,true,packets};
end

function [estimatorInputs,controllerInputs] = localReducedInputs(context,state)
estimatorLength = 8;
estimatorContexts = repmat({context},1,estimatorLength);
estimatorPackets = AeroFlex.ctrl. ...
    buildScheduledReciprocalHorizonPacketAudit(estimatorContexts);
estimatorNodes = repmat(state(1:74),1,estimatorLength+1);
estimatorNodes(1,:) = estimatorNodes(1,:)+ ...
    linspace(0,3e-7,estimatorLength+1);
estimatorDisturbances = linspace(0.013,0.017,estimatorLength);
[estimatorWingTotal,estimatorWingIncrement,estimatorElevator, ...
    estimatorThrust,estimatorRigid] = ...
    localRepeatedContext(context,estimatorLength);
estimatorInputs = {estimatorNodes,state(75:620), ...
    estimatorDisturbances,estimatorWingTotal,estimatorWingIncrement, ...
    estimatorElevator,estimatorThrust,estimatorRigid,estimatorPackets};

controllerLength = 10;
controllerContexts = repmat({context},1,controllerLength);
controllerPackets = AeroFlex.ctrl. ...
    buildScheduledReciprocalHorizonPacketAudit(controllerContexts);
controllerNodes = repmat(state(1:74),1,controllerLength+1);
controllerNodes(2,:) = controllerNodes(2,:)+ ...
    linspace(0,-2e-7,controllerLength+1);
initialTarget = controllerNodes(:,1);
initialTarget(1:3) = initialTarget(1:3)+[1e-8;-2e-8;3e-8];
controllerDisturbances = linspace(0.009,0.012,controllerLength);
[controllerWingTotal,controllerWingIncrement,controllerElevator, ...
    controllerThrust,controllerRigid] = ...
    localRepeatedContext(context,controllerLength);
wingDirections = localSymmetricRateDirections(controllerLength,0.01,0.5);
controllerInputs = {controllerNodes,state(75:620),initialTarget, ...
    controllerDisturbances,controllerWingTotal,controllerWingIncrement, ...
    controllerElevator,controllerThrust,controllerRigid,wingDirections, ...
    controllerPackets};
end

function directions = localSymmetricRateDirections(horizonLength,Ts,alpha)
directions = zeros(4,horizonLength,horizonLength);
surfaceMap = [1;1];
for interval = 1:horizonLength
    for rate = 1:interval-1
        directions(1:2,rate,interval) = Ts*surfaceMap;
    end
    directions(1:2,interval,interval) = alpha*Ts*surfaceMap;
    directions(3:4,interval,interval) = surfaceMap;
end
end

function [wingTotal,wingIncrement,elevator,thrust,rigid] = ...
        localRepeatedContext(context,horizonLength)
wingTotal = repmat(context.wingTotal,1,1,horizonLength);
wingIncrement = repmat(context.wingIncrement,1,1,horizonLength);
elevator = repmat(context.elevatorIncrement,1,1,horizonLength);
thrust = repmat(context.thrustIncrement,1,1,horizonLength);
rigid = repmat(context.rigidState,1,1,horizonLength);
end

function [context,state] = localFixture(fixture)
