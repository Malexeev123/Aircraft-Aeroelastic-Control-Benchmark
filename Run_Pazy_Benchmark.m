%% Pazy Aeroelastic Control Benchmark
% Coupled nonlinear aeroelastic estimation and control in MATLAB.
%
% Project authors: Maxim Alexeev, Juan López Muro, Laurent Burlion
%
% Quick start:
%   1. Edit the settings below.
%   2. Leave EXECUTE_CASE=false to inspect the resolved plan.
%   3. Set EXECUTE_CASE=true when the plan and expected runtime are correct.

%% User settings
settings = struct();
settings.entryMode          = "benchmark"; % benchmark, custom, or model_workflow
settings.caseId             = "A1";    % A1, A2, A3, B1, or B2
settings.executeCase        = false;
settings.allowUnqualified   = false;   % Required for experimental B1/B2
settings.diagnosticsLevel   = 1;       % 0 (quiet) through 3 (detailed)
settings.figuresVisible     = true;
settings.savePlots          = true;
settings.publicationMode    = false;  % Title-free PNG/PDF journal figures
settings.nativeKernelPolicy = "auto";  % auto or required
settings.outputRoot         = "";      % Default: results/<case>/<run-id>

% General wing/coupled workflow settings (used only in model_workflow mode).
settings.bodyCase           = "wingOnly"; % wingOnly or coupledFull
settings.simulationMode     = "openloop"; % openloop or nmhe_nmpc
settings.gustEnabled        = true;
settings.prepareSetup       = true;
settings.setupDirectory     = "";

% Custom maneuver settings (used only in custom mode).
settings.customName         = "combined_maneuver";
settings.customDuration     = 10;
settings.customReference    = struct( ...
    "timeSeconds",[0,5,10], ...
    "speedMps",[15,17,20], ...
    "pitchRad",deg2rad([10,10.5,10]), ...
    "phaseLabel",["attitude","combined","speed"]);
settings.customGust         = struct("enabled",false,"type","none");

%% Configure and verify
fprintf("\nPAZY AEROELASTIC CONTROL BENCHMARK\n");
fprintf("Coupled nonlinear aeroelastic estimation and control\n\n");
project = setupProject(ChangeCurrentFolder=true);
fprintf("Repository revision: %s\n",project.gitRevision);
installation = verifyBenchmarkInstallation( ...
    RequireNativeKernels=settings.nativeKernelPolicy=="required", ...
    ProjectInfo=project);
assert(installation.passed,"AeroFlex:BenchmarkInstallation", ...
    "Installation verification did not pass. Review the summary above.");

%% Resolve and optionally execute
switch settings.entryMode
    case "benchmark"
        [summary,plan] = runBenchmarkCase(settings.caseId, ...
            Execute=settings.executeCase, ...
            DiagnosticsLevel=settings.diagnosticsLevel, ...
            FiguresVisible=settings.figuresVisible, ...
            SavePlots=settings.savePlots, ...
            PublicationMode=settings.publicationMode, ...
            OutputRoot=settings.outputRoot, ...
            NativeKernelPolicy=settings.nativeKernelPolicy, ...
            AllowUnqualified=settings.allowUnqualified);
    case "model_workflow"
        [summary,plan] = runPazyModelWorkflow( ...
            BodyCase=settings.bodyCase, ...
            SimulationMode=settings.simulationMode, ...
            GustEnabled=settings.gustEnabled, ...
            Execute=settings.executeCase, ...
            PrepareSetup=settings.prepareSetup, ...
            SetupDirectory=settings.setupDirectory, ...
            FiguresVisible=settings.figuresVisible);
    case "custom"
        definition = AeroFlex.benchmark.customCaseDefinition( ...
            Name=settings.customName, ...
            DurationSeconds=settings.customDuration, ...
            Reference=settings.customReference, ...
            Gust=settings.customGust);
        [summary,plan] = runCustomBenchmarkCase(definition, ...
            Execute=settings.executeCase, ...
            DiagnosticsLevel=settings.diagnosticsLevel, ...
            FiguresVisible=settings.figuresVisible, ...
            SavePlots=settings.savePlots, ...
            PublicationMode=settings.publicationMode, ...
            OutputRoot=settings.outputRoot, ...
            NativeKernelPolicy=settings.nativeKernelPolicy, ...
            AllowUnqualified=settings.allowUnqualified);
    otherwise
        error("AeroFlex:BenchmarkEntryMode", ...
            "Unknown entry mode: %s",settings.entryMode);
end

if ~settings.executeCase
    if settings.entryMode=="benchmark"
        AeroFlex.benchmark.printBanner(plan,"start");
    elseif settings.entryMode=="custom"
        fprintf("Custom maneuver: %s / %s runtime / %.3f s\n", ...
            plan.caseId,plan.runtimeFamily,plan.durationSeconds);
    else
        fprintf("Model workflow: %s / %s / gust %s\n", ...
            plan.bodyCase,plan.simulationMode,string(plan.gustEnabled));
    end
    fprintf("Plan only: no simulation or result directory was created.\n");
    fprintf("Set EXECUTE_CASE=true after reviewing variable 'plan'.\n\n");
else
    if settings.entryMode=="benchmark"
        fprintf("Completed case %s. Results: %s\n", ...
            plan.caseId,summary.outputLayout.runRoot);
    else
        fprintf("Completed %s / %s model workflow. Results: %s\n", ...
            plan.bodyCase,plan.simulationMode,summary.outputs.runRoot);
    end
end
